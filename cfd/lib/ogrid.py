# -*- coding: utf-8 -*-
"""Структурированная O-сетка вокруг замкнутого сечения.

Зачем она, когда есть `snappyHexMesh`. Тот режет тело из декартовой решётки, и
за это платится дважды. Первое: у обшивки ячейки не выстроены по ней, поверхность
идёт ступеньками, а сгустить слой у стенки нечем — измельчать можно только всё
вокруг разом. Второе: сгущение изотропно, поэтому «плоский» случай дробится и
ПОПЕРЁК размаха, хотя решение от этой координаты не зависит вовсе. Замер на
нашей тонкой NACA: 25 слоёв по размаху при одном нужном, то есть 25-кратная
переплата (у сечений генакера мягче — 2.9).

Эталонные сетки NASA устроены иначе и на порядок дешевле при лучшем разрешении:
14 336 ячеек против наших 306 698 в плоскости, и при этом y+ меньше единицы
против нашего 37. Там сетка построена ПО ТЕЛУ: линии обходят обшивку кольцами
и сгущаются к ней по нормали.

Здесь то же самое для произвольного замкнутого контура: кольцевая (O) топология,
геометрическое сгущение к стенке, ровно одна ячейка по размаху. Пишется в
формате PLOT3D — том же, в котором приходят сетки NASA, — чтобы дальше идти по
готовому пути `plot3dToFoam` без единой новой ступени в конвейере.

Почему O, а не C. У C-сетки лучше разрешается след, но она требует острой задней
кромки, чтобы разрез уходил от неё чисто. У нашего сечения кромка ОБРЕЗАНА
вертикально (`geometry.sail_section`: торец в полтора процента хорды), и разрез
пришлось бы начинать с торца — это лишний шов ровно там, где сходит вихрь.
Кольцо этой беды не имеет, а след разрешается тем, что радиальных ячеек много.
"""

import numpy as np

__all__ = ["ogrid", "write_plot3d"]


def _resample_loop(loop, n, curv_gain=12.0, max_ratio=4.0):
    """Пересемплировать замкнутый контур со СГУЩЕНИЕМ ПО КРИВИЗНЕ.

    Равномерно по длине дуги нельзя, и это выяснилось замером. У нашего сечения
    носок — полукруг радиусом в полтолщины (0.029 м при хорде 3.9), а торец
    высотой в толщину (0.0585 м). Равномерный шаг при 320 точках на периметр в
    восемь метров даёт 0.025 м, то есть на весь носок приходится три-четыре
    точки. Нормали там выходят случайными, и марш заворачивается на четвёртом
    же слое, в восемнадцати миллиметрах от тела: 258 вывернутых ячеек, все на
    носке и на торце.

    Плотность точек берётся как 1 + gain*|кривизна|*L, где L — характерный
    размер тела. Это не подгонка под ответ, а обычное правило: там, где контур
    поворачивает круче, точек нужно больше.
    """
    p = np.asarray(loop, dtype=np.float64)[:, :2]
    closed = np.vstack([p, p[:1]])
    seg = np.linalg.norm(np.diff(closed, axis=0), axis=1)
    s = np.concatenate([[0.0], np.cumsum(seg)])
    size = float(max(np.ptp(p[:, 0]), np.ptp(p[:, 1])))

    # Кривизна по трём соседним точкам: радиус описанной окружности.
    a = np.roll(p, 1, axis=0)
    c = np.roll(p, -1, axis=0)
    ab = np.linalg.norm(p - a, axis=1)
    bc = np.linalg.norm(c - p, axis=1)
    ca = np.linalg.norm(a - c, axis=1)
    cross = np.abs((p[:, 0] - a[:, 0]) * (c[:, 1] - a[:, 1])
                   - (p[:, 1] - a[:, 1]) * (c[:, 0] - a[:, 0]))
    denom = ab * bc * ca
    kappa = np.where(denom > 1e-14, 2.0 * cross / np.maximum(denom, 1e-14), 0.0)
    kappa = np.minimum(kappa, 1.0 / (1e-3 * size))     # потолок на изломах
    # Сглаженная плотность: резкий скачок плотности сам по себе портит сетку.
    dens = 1.0 + curv_gain * kappa * size
    # ПОТОЛОК на отношение плотностей, и он не косметический. Без него у
    # сечения с носком радиусом 0.029 м при хорде 3.9 плотность доходила до
    # полутора тысяч: шаг по обшивке выходил 0.0009 м против медианы 0.0028,
    # то есть в 69 раз мельче. Расплата не в числе ячеек, а в ШАГЕ ПО ВРЕМЕНИ:
    # у нестационарного счёта его диктует наихудшая ячейка, и горстка ячеек у
    # носка (где поток вдобавок разгоняется вдвое) посадила шаг на 8.2e-5 с
    # против 3.8e-3 у декартовой сетки — в 46 раз. Среднее число Куранта при
    # этом 2e-5 при максимуме единица: вся сетка простаивала ради нескольких
    # ячеек. Сорок секунд задачи потребовали бы двух недель счёта.
    dens = np.minimum(dens, max_ratio * float(np.median(dens)))
    # Сглаживание плотности — на длину ПОРЯДКА САМОЙ ОСОБЕННОСТИ, а не пары
    # точек. Плотность считается по кривизне, а торец сечения ПЛОСКИЙ: его два
    # угла получают максимум, а грань между ними минимум, и скачок плотности
    # приходится ровно туда, где геометрия теснее всего. Короткого сглаживания
    # (двадцать проходов, длина в две точки) не хватало, и марш заворачивался
    # у торца уже на третьем слое. Двести проходов дают длину около семи точек
    # — сравнимо с высотой торца.
    for _ in range(200):
        dens = dens + 0.25 * (np.roll(dens, 1) + np.roll(dens, -1) - 2 * dens)

    # Накопленная «плотностная длина» и обратное отображение.
    w = np.concatenate([[0.0], np.cumsum(0.5 * (dens + np.roll(dens, -1))[:-1]
                                         * seg[:-1])])
    w = np.concatenate([w, [w[-1] + dens[-1] * seg[-1]]])[:len(s)]
    want = np.linspace(0.0, w[-1], n, endpoint=False)
    s_at = np.interp(want, w, s)
    return np.column_stack([np.interp(s_at, s, closed[:, 0]),
                            np.interp(s_at, s, closed[:, 1])]), s[-1]


def _outward_normals(pts):
    """Внешние нормали замкнутого контура, обход против часовой стрелки."""
    nxt = np.roll(pts, -1, axis=0)
    prv = np.roll(pts, 1, axis=0)
    tang = nxt - prv
    tang /= np.linalg.norm(tang, axis=1)[:, None]
    n = np.column_stack([tang[:, 1], -tang[:, 0]])
    # Знак определяется по площади: у обхода против часовой стрелки она
    # положительна, и тогда (ty, -tx) смотрит НАРУЖУ. Проверять надо, а не
    # предполагать: контур приходит из `sail_section`, и порядок обхода там
    # свой.
    area = 0.5 * np.sum(pts[:, 0] * nxt[:, 1] - nxt[:, 0] * pts[:, 1])
    return n if area > 0 else -n


def _smooth_normals(n, passes=40):
    """Сгладить поле нормалей — иначе на изломах контура лучи разбегаются."""
    for _ in range(passes):
        n = n + 0.25 * (np.roll(n, 1, axis=0) + np.roll(n, -1, axis=0) - 2 * n)
        n /= np.linalg.norm(n, axis=1)[:, None]
    return n


def _laplace_ring(p, passes):
    """Сгладить кольцо точек по себе же. Концы замкнуты, поэтому просто roll."""
    for _ in range(passes):
        p = p + 0.5 * (np.roll(p, 1, axis=0) + np.roll(p, -1, axis=0) - 2 * p)
    return p


def _tangled(layer_a, layer_b):
    """Сколько ячеек между двумя слоями вывернуто."""
    p0, p3 = layer_a, layer_b
    p1, p2 = np.roll(p0, -1, axis=0), np.roll(p3, -1, axis=0)
    s = 0.5 * ((p0[:, 0] * p1[:, 1] - p1[:, 0] * p0[:, 1])
               + (p1[:, 0] * p2[:, 1] - p2[:, 0] * p1[:, 1])
               + (p2[:, 0] * p3[:, 1] - p3[:, 0] * p2[:, 1])
               + (p3[:, 0] * p0[:, 1] - p0[:, 0] * p3[:, 1]))
    return int((s * np.sign(np.median(s)) <= 0).sum())


def ogrid(loop, r_far, n_theta=320, n_radial=140, first_layer=None,
          growth=None, smooth_gain=0.6, normal_passes=240):
    """Точки O-сетки, массив (n_radial+1, n_theta, 2).

    Строится МАРШЕМ от тела наружу, а не отображением тела на окружность.
    Отображение пробовалось первым и не годится: у тонкой пластины длина дуги
    и геометрическое направление расходятся — точки верхней и нижней сторон
    лежат в полусантиметре друг от друга, а по длине дуги разнесены на пол-
    периметра, — поэтому лучи к окружности пересекаются. Замер: треть ячеек
    вывернута, и укорочение перехода к нормали её не лечит (2426 вывернутых
    даже при переходе в сотую долю хорды).

    Марш устроен так: очередной слой отодвигается от предыдущего по его же
    сглаженным нормалям, после чего САМ сглаживается по себе. Сглаживание тем
    сильнее, чем дальше слой: у стенки оно почти выключено (иначе теряется
    форма тела), вдали кольцо расплывается в окружность само собой. Именно это
    и не даёт лучам сойтись в вогнутых местах.
    """
    b, _perim = _resample_loop(loop, n_theta)
    size = float(max(np.ptp(b[:, 0]), np.ptp(b[:, 1])))
    h1 = first_layer if first_layer else 1e-3 * size

    # Знаменатель прогрессии: подбирается делением пополам так, чтобы сумма
    # шагов дала ровно радиус дальней границы.
    if growth is None:
        lo, hi = 1.0 + 1e-9, 1.5
        tgt = r_far / h1
        for _ in range(200):
            g = 0.5 * (lo + hi)
            if (g ** n_radial - 1.0) / (g - 1.0) < tgt:
                lo = g
            else:
                hi = g
        growth = g

    out = np.empty((n_radial + 1, n_theta, 2))
    out[0] = b
    layer, step = b, h1
    dist = 0.0
    for j in range(1, n_radial + 1):
        nrm = _smooth_normals(_outward_normals(layer), passes=normal_passes)
        nxt = layer + step * nrm
        dist += step
        # Сглаживание слоя. Число проходов растёт с удалением: у стенки нельзя
        # (потеряется форма), вдали нужно (иначе вогнутость схлопнет лучи).
        passes = int(smooth_gain * (dist / size) * n_theta)
        nxt = _laplace_ring(nxt, min(passes, 400))
        out[j] = nxt
        layer, step = nxt, step * growth
    # Дальняя граница приводится к точной окружности: марш подходит к ней
    # близко, но идеального круга не даёт, а патч должен быть ровным.
    centre = out[-1].mean(axis=0)
    ang = np.arctan2(out[-1][:, 1] - centre[1], out[-1][:, 0] - centre[0])
    out[-1] = centre + r_far * np.column_stack([np.cos(ang), np.sin(ang)])
    return out


def write_plot3d(path, pts, span=1.0, chord=None):
    """Записать сетку в формате PLOT3D: два одинаковых слоя, одна ячейка.

    Формат тот же, в котором приходят сетки NASA, поэтому дальше работает уже
    готовый путь `plot3dToFoam` и тот же шаблон — новой ступени в конвейере не
    появляется.

    Оси СРАЗУ наши: сечение в плоскости X-Y, размах по Z. И сразу носом к
    потоку: `sail_section` строит носок в нуле и кромку в хорде, а поток у нас
    идёт в минус X (`ax.onset_flow`), значит носок обязан смотреть в плюс X.
    Разворот делается здесь поворотом на 180° вокруг Z — то есть (x, y) ->
    (хорда - x, -y), — а не отражением: отражение меняет ориентацию, и все
    нормали ушли бы внутрь. Ровно на этом однажды попались с эталонной сеткой
    (§13.20), только там разворота не было вовсе и профиль обтекался задом
    наперёд.
    """
    # Кольцо ЗАМЫКАЕТСЯ повторением первого столбца. PLOT3D не знает о
    # периодичности по j: без повтора между последней и первой точками
    # остаётся щель в одну ячейку, её грани становятся граничными, и в сетке
    # недостаёт целого радиального столбца (67 060 ячеек вместо 67 200, у тела
    # 529 граней вместо 480). Совпавшие точки `plot3dToFoam` склеивает сам.
    pts = np.concatenate([pts, pts[:, :1, :]], axis=1)
    nk, nj, _ = pts.shape
    px = pts[:, :, 0].copy()
    py = pts[:, :, 1].copy()
    # Разворачивать НЕЧЕГО, и это выяснилось замером, а не чтением кода.
    # По описанию `sail_section` носок лежит в нуле, а торец в хорде; на деле
    # массивы идут в обратном порядке, и поверхности СХОДЯТСЯ при x = хорда
    # (разрыв 0.0000 м), а расходятся на толщину листа при x = 0 (0.0623 м при
    # толщине 0.0585). То есть носок и так смотрит в плюс X — навстречу потоку,
    # который идёт в минус X. Первая версия писателя честно поворачивала
    # сечение на 180°, «исправляя» то, что было верно, и ставила его задом
    # наперёд — ровно ту ошибку, что уже стоила прогонов на эталонной сетке
    # (§13.20), только зеркально. Поймано глазом по картинке и подтверждено
    # числом: расстояние между концами поверхностей у носка и у торца.
    # ПРАВАЯ тройка индексов обязательна: j вдоль обшивки, k наружу, i по
    # размаху. Если обход контура идёт не в ту сторону, блок выходит левым, и
    # `plot3dToFoam` строит сетку с отрицательными объёмами — у первой версии
    # их было 25 699 из 67 060, неортогональность 180°, и checkMesh честно
    # объявил все грани ориентированными неверно. Знак считается по самой
    # сетке, а не назначается: площадь ячейки у стенки обязана быть
    # положительной.
    t = np.roll(px, -1, axis=1) - px, np.roll(py, -1, axis=1) - py
    nx_, ny_ = px[1] - px[0], py[1] - py[0]
    cross = t[0][0] * ny_ - t[1][0] * nx_
    if np.median(cross) < 0.0:
        px = px[:, ::-1]
        py = py[:, ::-1]
    x = np.repeat(px[None], 2, axis=0)
    y = np.repeat(py[None], 2, axis=0)
    z = np.zeros_like(x)
    z[1] = span
    with open(path, "w", encoding="ascii") as f:
        f.write("%12d\n" % 1)
        f.write("%12d%12d%12d\n" % (2, nj, nk))
        for arr in (x, y, z):
            # Порядок обхода в PLOT3D: i быстрее всех, затем j, затем k.
            # Массив здесь сложен как (i, k, j), поэтому нужен (k, j, i).
            # Первая версия ставила (j, k, i) — то есть меняла местами обход
            # вдоль обшивки и наружу. Сетка при этом ЧИТАЕТСЯ, только выходит
            # перемешанной: 25 699 отрицательных объёмов из 67 060 и
            # неортогональность 179.9°. Молчаливая ошибка ровно того же рода,
            # что и все прочие в этом этапе.
            vals = arr.transpose(1, 2, 0).reshape(-1)
            for i in range(0, len(vals), 3):
                f.write("".join("%24.15f" % v for v in vals[i:i + 3]) + "\n")
    return path
