def gennaker_section(cases, sim_pts, strips):
    """Сечение генакера в рабочей точке, где модель упирается в потолок.

    Раздел устроен вокруг ОДНОГО сравнения: плоская пластина против сечения с
    проектным пузом на одном и том же угле. Модель сейчас считает первую —
    расчётное пузо у полосок генакера выходит нулевым, — а парус задуман
    вторым. Разность и есть цена этого нуля.
    """
    blocks = [{
        "kind": "text",
        "html": ("Карта (курс, шкот) из <code>tests/gennaker.test.mjs</code> "
                 "краснеет в бакштаге: при TWA 120° и шкоте 4.5—5.5 м "
                 "предохранитель по потолку сечения звенит по три десятка раз "
                 "за двадцать пять секунд. Считается именно эта точка, а не "
                 "удобная.")}]
    if strips:
        rows = [[g["strip"], g["alpha_deg"], g["camber"], g["design"],
                 g["slack"], g["cl"], g["ceiling"], g["at_ceiling"]]
                for g in strips.get("strips", [])]
        worst = max((g["at_ceiling"] for g in strips.get("strips", [])),
                    default=0)
        blocks.append({"kind": "tiles", "items": [
            _tile("предохранитель", strips.get("fuse_trips"), "раз", 0),
            _tile("Γ наибольшее", strips.get("gamma_max"), None, 1),
            _tile("ход", strips.get("speed_kn"), "уз", 2),
            _tile("наибольшая доля потолка", worst, None, 2)]})
        blocks.append({"kind": "note", "html":
                       "<b>Запас ткани есть, проектное пузо есть, а расчётное "
                       "выходит нулевым.</b> Полоски держатся на 33…37° угла "
                       "атаки и считаются ПЛОСКОЙ ПЛАСТИНОЙ: столбец «пузо» "
                       "весь в нулях при запасе 0.07…0.10 и проектном пузе "
                       "0.16…0.20. Плоская пластина на таком угле упирается в "
                       "потолок сечения неизбежно — доля потолка 1.10…1.15, — и "
                       "предохранитель звенит поделом. Причина ли это красных "
                       "клеток карты, отсюда не видно: пузо может входить в "
                       "силы другим путём, и разбираться в этом надо на стороне "
                       "симулятора. Но именно поэтому ниже считаются ОБЕ формы."})
        blocks.append({"kind": "table", "open": True,
                       "head": ["полоска", "угол, °", "пузо", "проектное",
                                "запас ткани", "cl", "потолок", "доля потолка"],
                       "rows": rows})
    if not cases:
        blocks.append({"kind": "note", "html":
                       "Ни одно сечение не посчитано — сравнивать нечего."})
        return {"title": "Генакер: сечение в рабочей точке", "blocks": blocks}

    flat = [c for c in cases if c["condition"].get("camber", 0) == 0]
    full = [c for c in cases if c["condition"].get("camber", 0) > 0]
    same = [(f, g) for f in flat for g in full
            if abs(f["condition"]["alpha_deg"] - g["condition"]["alpha_deg"]) < 1e-6]
    if same:
        f, g = same[0]
        df, dg = f["derived"], g["derived"]
        gain = (dg["Cl"] - df["Cl"]) / max(abs(df["Cl"]), 1e-9)
        blocks.append({"kind": "h3", "html":
                       "Цена нулевого пуза на угле %.0f°"
                       % f["condition"]["alpha_deg"]})
        blocks.append({"kind": "tiles", "items": [
            _tile("Cl плоской пластины", df["Cl"], None, 3),
            _tile("Cl с проектным пузом", dg["Cl"], None, 3),
            _tile("разница", 100 * gain, "%", 0),
            _tile("Cd плоской", df["Cd"], None, 4),
            _tile("Cd с пузом", dg["Cd"], None, 4)]})
        blocks.append({"kind": "bars", "rows": [
            {"label": "Cl, плоская пластина", "cfd": df["Cl"],
             "sim": sim_pts.get(("flat", round(f["condition"]["alpha_deg"], 3)), 0)},
            {"label": "Cl, проектное пузо", "cfd": dg["Cl"],
             "sim": sim_pts.get(("full", round(g["condition"]["alpha_deg"], 3)), 0)},
        ], "title": "CFD против polarCoeffs на том же угле",
            "text": ("Модель считает по таблице поляры, и таблица берёт пузо "
                     "как параметр. Слева — то, что модель считает сейчас "
                     "(пузо ноль), справа — то, чем парус задуман."),
            "caption": "Синий — CFD, оранжевый — polarCoeffs."})

    pts = [{"x": c["condition"]["alpha_deg"], "y": c["derived"]["Cl"],
            "label": c["case_id"],
            "sim": sim_pts.get(("full", round(c["condition"]["alpha_deg"], 3)))}
           for c in sorted(full, key=lambda c: c["condition"]["alpha_deg"])]
    curve = [{"x": a, "y": v} for (kind, a), v in sorted(sim_pts.items())
             if kind == "full"]
    if len(pts) >= 2 and curve:
        blocks.append({
            "kind": "polar", "pts": pts, "curve": curve,
            "xlab": "угол атаки, °", "ylab": "Cl", "opt": {"yd": 2},
            "title": "Поляра сечения с проектным пузом",
            "text": ("Здесь проверяется не только величина, но и ПОТОЛОК: "
                     "модель ограничивает подъёмную силу сечения сверху, и в "
                     "рабочей точке она в этот потолок упирается. Если CFD "
                     "даёт больше — потолок занижен и держит парус зря; если "
                     "меньше — он не спасает, а маскирует срыв."),
            "caption": "Наведите курсор, чтобы увидеть оба значения.",
            "table": {"head": ["угол, °", "Cl (CFD)", "Cl (модель)", "Δ, %"],
                      "rows": [[p["x"], p["y"], p["sim"],
                                None if not p["sim"] else
                                100 * (p["y"] - p["sim"]) / abs(p["sim"])]
                               for p in pts]}})
    for c in cases:
        s = (c.get("slices") or {}).get("sliceSpan")
        if s and s.get("nx"):
            blocks.append({"kind": "field", "slice": s,
                           "title": "Поле: " + c["case_id"],
                           "caption": ("Пузо %.3f, угол %.0f°. На таком угле "
                                       "интересен не столько сам отрыв, сколько "
                                       "то, где он начинается: от этого зависит "
                                       "и потолок, и то, что модель считает "
                                       "срывом."
                                       % (c["condition"].get("camber", 0),
                                          c["condition"].get("alpha_deg", 0)))})
    return {"title": "Генакер: сечение в рабочей точке", "blocks": blocks}


def mirror_section(pair, sim=None):
    """Зеркальная пара по дрейфу: разделить настоящую силу и паразитную.

    Изначально пара задумывалась проверкой знаков — что оси, геометрия и
    постобработка не переставили компоненты местами. Первый же посчитанный
    корпус превратил её в измерительный прибор: на НУЛЕВОМ дрейфе боковая сила
    оказалась не нулём, и значит у каждого случая с дрейфом в ответе сидит
    посторонняя добавка.

    Разделяются они однозначно. Симметричная часть (полусумма) при смене знака
    дрейфа не меняется — а физическая боковая сила обязана менять; значит вся
    полусумма посторонняя. Антисимметричная часть (полуразность) — то, что
    действительно вызвано дрейфом, и только её можно сравнивать с моделью.
    """
    if len(pair) != 2:
        return None
    a, b = pair                       # a — положительный дрейф, b — отрицательный
    da, db = a["derived"], b["derived"]
    beta = a["condition"].get("leeway_deg", 0.0)

    def split(key):
        return ((da[key] - db[key]) / 2.0, (da[key] + db[key]) / 2.0)

    fy_anti, fy_sym = split("Fy")
    mz_anti, mz_sym = split("Mz")
    rt_anti, rt_sym = split("Rt_n")

    scale = max(abs(fy_anti), 1e-9)
    pollution = abs(fy_sym) / scale
    rows = [["Fy, Н", da["Fy"], db["Fy"], fy_anti, fy_sym],
            ["Mz, Н·м", da["Mz"], db["Mz"], mz_anti, mz_sym],
            ["Rt, Н", da["Rt_n"], db["Rt_n"], rt_anti, rt_sym]]

    ok = pollution < 0.15
    tiles_items = [
        _tile("дрейф", beta, "°", 1),
        _tile("Fy настоящая (антисим.)", fy_anti, "Н", 1),
        _tile("Fy паразитная (сим.)", fy_sym, "Н", 1),
        _tile("доля паразитной", pollution * 100, "%", 0),
        _tile("Mz настоящий", mz_anti, "Н·м", 1),
    ]
    blocks = [
        {"kind": "text", "html":
         ("Два случая отличаются ровно знаком дрейфа. Физическая боковая сила "
          "обязана при этом поменять знак, а всё, что знака не меняет, "
          "физическим быть не может. Отсюда разделение: полуразность — "
          "настоящая сила от дрейфа, полусумма — посторонняя добавка от "
          "несимметричного отрыва за смоченным транцем.")},
        {"kind": "tiles", "items": tiles_items},
        {"kind": "note", "html":
         ("Пара служит здесь измерительным прибором, а не проверкой знаков. "
          "Проверка знаков — приятное следствие: если бы оси или постобработка "
          "переставили компоненты местами, антисимметричной части не вышло бы "
          "вовсе. Но главное измерение — доля паразитной силы: она говорит, "
          "насколько вообще можно доверять боковой силе из этой постановки."
          if not ok else
          "Паразитная часть мала, и боковую силу из этой постановки можно "
          "сравнивать с моделью напрямую.")},
        {"kind": "table", "open": True,
         "head": ["величина", "дрейф +%.0f°" % abs(beta),
                  "дрейф −%.0f°" % abs(beta),
                  "антисимметричная (настоящая)", "симметричная (паразитная)"],
         "rows": rows},
    ]
    if sim:
        blocks.append({
            "kind": "bars",
            "rows": [{"label": "Fy при дрейфе %.0f°" % abs(beta),
                      "cfd": fy_anti, "sim": sim.get("fy_n", 0.0)},
                     {"label": "Mz при дрейфе %.0f°" % abs(beta),
                      "cfd": mz_anti, "sim": sim.get("mz_nm", 0.0)}],
            "title": "Настоящая часть против hullLateral",
            "text": ("Сравнивается ТОЛЬКО антисимметричная часть — та, что "
                     "вызвана дрейфом. Паразитная добавка сюда не входит: она "
                     "и есть то, что мешало бы сравнивать сырые числа."),
            "caption": "Синий — CFD (антисимметричная часть), оранжевый — модель.",
            "table": {"head": ["величина", "CFD", "симулятор", "Δ, %"],
                      "rows": [["Fy, Н", fy_anti, sim.get("fy_n"),
                                None if not sim.get("fy_n") else
                                100 * (fy_anti - sim["fy_n"]) / abs(sim["fy_n"])],
                               ["Mz, Н·м", mz_anti, sim.get("mz_nm"),
                                None if not sim.get("mz_nm") else
                                100 * (mz_anti - sim["mz_nm"]) / abs(sim["mz_nm"])]]}})
    return {"title": "Зеркальная пара по дрейфу: что здесь настоящее",
            "badge": ("паразитная часть %.0f%%" % (pollution * 100)),
            "badgeKind": "ok" if ok else "look",
            "blocks": blocks}


def sensitivity_section(base, wide):
    """Чувствительность к размеру домена (§4.4).

    Разность двух ответов, отличающихся ТОЛЬКО границами, входит в
    неопределённость эталона. Если она велика, спорить с моделью рано: сначала
    надо перестать спорить с собственной границей.
    """
    if not base or not wide:
        return None
    db, dw = base["derived"], wide["derived"]
    d = (dw["Cl"] - db["Cl"]) / max(abs(db["Cl"]), 1e-12)
    rows = [["Cl", db["Cl"], dw["Cl"], 100 * d],
            ["Cd", db["Cd"], dw["Cd"],
             100 * (dw["Cd"] - db["Cd"]) / max(abs(db["Cd"]), 1e-12)],
            ["Fy, Н", db["Fy"], dw["Fy"],
             100 * (dw["Fy"] - db["Fy"]) / max(abs(db["Fy"]), 1e-12)],
            ["ячеек", base["cells"], wide["cells"], None]]
    big = abs(d) > 0.05
    return {
        "title": "Киль: сколько отнимает граница домена",
        "badge": ("Cl меняется на %.0f%%" % (100 * d)),
        "badgeKind": "look" if big else "ok",
        "blocks": [
            {"kind": "text", "html":
             ("Два случая отличаются только размером домена: у первого он "
              "задан в хордах (по три-четыре размаха), у второго растянут "
              "примерно до десяти размахов при тех же размерах ячеек у "
              "поверхности. Разность и есть влияние границы — она входит в "
              "неопределённость эталона (§4.4), а не выбирается по вкусу.")},
            {"kind": "tiles", "items": [
                _tile("Cl в тесном домене", db["Cl"], None, 4),
                _tile("Cl в широком", dw["Cl"], None, 4),
                _tile("разница", 100 * d, "%", 1)]},
            {"kind": "note", "html":
             ("Разница велика: значит тесный домен занижал подъёмную силу, и "
              "все прочие случаи киля посчитаны в нём же. Сравнивать их с "
              "моделью до пересчёта в широком домене нельзя."
              if big else
              "Разница мала: границей расхождение с моделью не объясняется, "
              "и подозрение переходит на сетку и на стык корня.")},
            {"kind": "table", "open": True,
             "head": ["величина", "тесный домен", "широкий", "Δ, %"],
             "rows": rows}]}


