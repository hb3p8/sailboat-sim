def _tile(k, v, unit=None, d=3):
    if v is None:
        return [k, "—", unit]
    if isinstance(v, str):
        return [k, v, unit]
    if d == 0:
        # Счётные величины — числом с разделителем разрядов. «3.00e+05» вместо
        # «299 566» в графе «ячеек» выглядит как оценка, а это точное число.
        return [k, "{:,}".format(int(round(v))).replace(",", " "), unit]
    if abs(v) >= 1e5 or (v != 0 and abs(v) < 1e-3):
        return [k, "%.2e" % v, unit]
    return [k, ("%%.%df" % d) % v, unit]


def _ar_from_slope(a_rad):
    """Какому удлинению отвечает наблюдаемый наклон кривой подъёмной силы.

    Обращение формулы несущей линии `a = 2π/(1 + 2/AR)`. Число это не измерение
    удлинения, а перевод наклона в единицы, в которых с ним можно спорить:
    «1.5 на радиан» ничего не говорит, «отвечает удлинению 0.6» говорит сразу.
    """
    import math
    if a_rad <= 0 or a_rad >= 2 * math.pi:
        return None
    return 2.0 / (2 * math.pi / a_rad - 1.0)


def _ittc(case):
    """Трение плоской пластины по ITTC-57 и то, что дал CFD.

    Смысл сравнения не в том, что корпус — пластина. Смысл в том, что эта
    формула известна независимо от расчёта, от симулятора и от лодки. Если
    вязкая часть CFD легла около неё с разумным коэффициентом формы,
    пограничный слой посчитан не бессмысленно. Если разошлась вдвое — дальше
    смотреть нечего, и это будет видно ДО любых выводов о модели.
    """
    import math
    f = case.get("force", {}).get("Fx", {})
    if f.get("viscous") is None:
        return None
    m, r = case["condition"], case["reference"]
    u = m.get("speed_ms")
    if not u:
        return None
    fl = case["fluid"]
    re = u * r["length_m"] / fl["nu"]
    if re <= 100:
        return None
    cf = 0.075 / (math.log10(re) - 2) ** 2
    rf = 0.5 * fl["rho"] * u * u * r["area_m2"] * cf
    visc = -f["viscous"]
    return {"re": re, "cf": cf, "friction_n": rf, "cfd_viscous_n": visc,
            "ratio": visc / rf if rf else None,
            "cfd_pressure_n": -(f.get("pressure") or 0.0)}


