        blocks.append({"kind": "convergence", "hist": ref["history"],
                       "keys": ["Rt", "Fy"],
                       "window": ref["force"]["Fx"]["window"][0],
                       "title": "Выход сил на плато: " + ref["case_id"],
                       "caption": "Полоса — размах внутри окна прореживания."})
