// Общие векторные примитивы кернелов.
//
// Вынесены в заголовок после второго модуля: копия этих двадцати строк в каждом
// — верный способ получить два по-разному округляющих кернела и потом сутки
// искать, почему сверка красная у одного и зелёная у другого.
//
// Ширина — две двойных: столько в wasm simd128 и столько же в NEON, то есть на
// телефоне это ровно нативная ширина, и ничего в переносе не теряется.
#ifndef SV20_VEC_H
#define SV20_VEC_H

#if defined(__wasm__)
#define KEXPORT(name) __attribute__((export_name(name)))
#else
#define KEXPORT(name)
#endif

typedef double f64x2 __attribute__((vector_size(16)));
typedef long long i64x2 __attribute__((vector_size(16)));

#define EPS     1e-10
#define FOURPI  12.566370614359172   // 4*Math.PI, ровно то же double

static inline f64x2 vsplat(double a) { return (f64x2){ a, a }; }

// Обнулить полосы, где маска ложна. Битовое И, а не умножение на ноль: в
// отброшенной полосе деление на нулевую длину даёт бесконечность, и 0·inf
// вернуло бы NaN.
static inline f64x2 vkeep(i64x2 mask, f64x2 v) {
  return (f64x2)(mask & (i64x2)v);
}

// Выбор целиком: где маска истинна — `a`, иначе `b`.
//
// Нужен там, где в образце стоит `if (условие) v += x`. Маскировать САМО
// СЛАГАЕМОЕ было бы почти правильно, но не совсем: `v + 0.0` превращает −0.0 в
// +0.0, а нетронутое `v` знак сохраняет. Разница видна только на нуле и почти
// никогда не важна — но сверка требует РАВЕНСТВА, и «почти» её не проходит.
static inline f64x2 vsel(i64x2 mask, f64x2 a, f64x2 b) {
  return (f64x2)((mask & (i64x2)a) | (~mask & (i64x2)b));
}

static inline f64x2 vsqrt(f64x2 v) {
  return (f64x2){ __builtin_sqrt(v[0]), __builtin_sqrt(v[1]) };
}

// Максимум без семантики NaN: аргументы здесь конечны и неотрицательны, а форма
// повторяет Math.max образца.
static inline f64x2 vmax(f64x2 a, f64x2 b) {
  return (f64x2){ a[0] > b[0] ? a[0] : b[0], a[1] > b[1] ? a[1] : b[1] };
}

#endif
