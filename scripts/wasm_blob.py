#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Блоб wasm в исходник: python3 scripts/wasm_blob.py

Симулятор собирается в один html и обязан открываться двойным кликом, поэтому
модуль не лежит отдельным файлом, а вклеивается в исходник строкой base64.

Заводится целью `make kernel` вместе с самим .wasm, и это не удобство: собранный
.wasm без пересобранного блоба означает симулятор со СТАРЫМ кернелом. Один раз
это уже стоило падения на не экспортированной функции — .wasm был новый, блоб
прошлый.
"""
import base64
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "kernel", "biot.wasm")
dst = os.path.join(ROOT, "sim", "biotwasm.js")

b64 = base64.b64encode(open(src, "rb").read()).decode()
lines = [b64[i:i + 96] for i in range(0, len(b64), 96)]

with open(dst, "w") as f:
    f.write(
        "// СГЕНЕРИРОВАНО `make kernel` из kernel/biot.wasm. Руками не правят.\n"
        "//\n"
        "// Блоб лежит в исходнике, а не отдельным файлом: симулятор собирается в один\n"
        "// html (scripts/build_sim.py) и обязан открываться двойным кликом, а отдельный\n"
        "// файл пришлось бы тянуть запросом. Три килобайта base64 дешевле развилки.\n"
        "//\n"
        "// Размер важен и по второй причине: браузеры запрещают синхронную компиляцию\n"
        "// wasm в главном потоке на буферах больше ЧЕТЫРЁХ килобайт. Пока модуль под\n"
        "// лимитом, загрузка остаётся синхронной и вопроса «что показывать, пока он не\n"
        "// готов» не возникает вовсе.\n"
        "export const BIOT_WASM_B64 =\n  '" + "' +\n  '".join(lines) + "';\n")

size = os.path.getsize(src)
print("sim/biotwasm.js — из %d байт wasm%s" %
      (size, "" if size < 4096 else "  ВНИМАНИЕ: больше 4 КБ, синхронная загрузка запрещена"))
