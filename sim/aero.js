// Ближайшая точка треугольника к точке и расстояние до неё. Обычная задача:
// проекция на плоскость, а если вышла за треугольник — ближайшая точка рёбер.
function triNear(px, py, pz, V, i0, i1, i2, out) {
  const ax = V[i0], ay = V[i0 + 1], az = V[i0 + 2];
  const e1x = V[i1] - ax, e1y = V[i1 + 1] - ay, e1z = V[i1 + 2] - az;
  const e2x = V[i2] - ax, e2y = V[i2 + 1] - ay, e2z = V[i2 + 2] - az;
  const dx = px - ax, dy = py - ay, dz = pz - az;
  const a = e1x * e1x + e1y * e1y + e1z * e1z;
  const bb = e1x * e2x + e1y * e2y + e1z * e2z;
  const cc = e2x * e2x + e2y * e2y + e2z * e2z;
  const d = e1x * dx + e1y * dy + e1z * dz;
  const e = e2x * dx + e2y * dy + e2z * dz;
  const det = a * cc - bb * bb;
  let u = 0, v = 0;
  if (det > 1e-12) { u = (cc * d - bb * e) / det; v = (a * e - bb * d) / det; }
  // Загон в треугольник: сперва по граням, потом по рёбрам.
  if (u < 0) u = 0; if (v < 0) v = 0;
  if (u + v > 1) { const k = u + v; u /= k; v /= k; }
  out[0] = ax + e1x * u + e2x * v;
  out[1] = ay + e1y * u + e2y * v;
  out[2] = az + e1z * u + e2z * v;
  return Math.hypot(px - out[0], py - out[1], pz - out[2]);
}

