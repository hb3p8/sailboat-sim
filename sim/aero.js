function fadeOf(alpha) {
  const a = Math.abs(alpha);
  return a <= IND_FADE0 ? 1
    : (a >= IND_FADE1 ? 0 : (IND_FADE1 - a) / (IND_FADE1 - IND_FADE0));
}

