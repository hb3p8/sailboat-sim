// Скамья: замороженная сцена и замер способов отражения.
//
// ЗАЧЕМ. Отражение отлаживалось на живой сцене, и это оказалось главным
// тормозом всей работы. Лодка идёт, волна бежит, камера догоняет — и два снимка
// никогда не об одном кадре. «Стало лучше или хуже» решалось на глаз по двум
// разным картинкам; «сколько это стоит» — по цифре, которая скакала вдвое от
// того, куда в этот миг смотрела камера. Настоящую ошибку — перевёрнутую по
// вертикали выборку — так и не нашли ни отладочными видами, ни рассуждением:
// она нашлась чтением кода.
//
// Скамья убирает ровно эту помеху. По адресу `?bench=<n>` симулятор
// останавливается: физика не шагает, время воды стоит, камера стоит там, где
// сказано, служебная разметка снята. Два запуска дают один и тот же кадр
// пиксель в пиксель — значит их МОЖНО вычитать, а не сравнивать впечатлением.
//
// Она же и мерная площадка. Способы отражения меряются по очереди на одном и том
// же кадре, и это единственный способ сравнить их честно: цена отражения зависит
// от того, сколько воды в кадре и подо что уходит луч, — то есть ровно от того,
// что на живой сцене меняется каждый миг.

// Случаи подобраны так, чтобы бить в разные слабости. Камера задаётся в осях
// ЛОДКИ — вперёд, вверх, вправо, — и точка, куда она смотрит, тоже. Начало этих
// осей у лодки на транце, а корпус тянется вперёд метров на шесть: середина
// корпуса это x ≈ 3, и цели наведения стоят около неё, а не в нуле.
const BENCH_CASES = [
  // 0. Лодка с борта, камера в полутора метрах над водой. Отражать есть что и
  //    всё оно в кадре — случай, в котором марш по экрану должен быть хорош.
  { name: 'борт', eye: [3.0, 1.6, 9.0], at: [3.0, 0.9, 0], wind: 6, fetch: 3000 },
  // 1. Камера у самой воды и близко. Луч идёт полого, шагов уходит много, а
  //    мачта вылезает за верхний край кадра — марш её теряет, зеркало нет. Это
  //    тот случай, ради которого зеркало и заводилось.
  { name: 'у воды', eye: [-3.5, 0.55, 4.0], at: [3.0, 1.6, 0], wind: 6, fetch: 3000 },
  // 2. От лодки в открытую воду: отражать нечего, и весь расход — впустую.
  //    Худший случай для марша и безразличный для зеркала.
  { name: 'в воду', eye: [3.0, 2.0, 7.0], at: [-25, 0.6, 40], wind: 6, fetch: 3000 },
  // 3. Крупная волна: поверхность перестаёт быть плоскостью, и это худший
  //    случай уже для зеркала — оно отражает в y = 0 и про гребни не знает.
  { name: 'волна', eye: [-5.0, 2.2, 7.0], at: [3.0, 0.8, 0], wind: 12, fetch: 30000 },
];

const BENCH_N = (() => {
  const v = new URLSearchParams(location.search).get('bench');
  if (v === null) return -1;
  const n = parseInt(v, 10);
  return Number.isFinite(n) && n >= 0 && n < BENCH_CASES.length ? n : 0;
})();

function benchFrozen() { return BENCH_N >= 0; }

// Состояние лодки ставится в известные числа и держится там. Ставится КАЖДЫЙ
// кадр, а не однажды: волну плавучести отдаёт проба, и без шага физики лодка бы
// всё равно медленно поехала от того, что ей эту волну кто-то подкладывает.
function benchPose(boat, prev) {
  const c = BENCH_CASES[BENCH_N];
  boat.x = 0; boat.y = 0; boat.psi = 0;
  boat.phi = 0.10; boat.th = -0.02; boat.zc = 0;
  boat.u = 0; boat.v = 0; boat.r = 0;
  boat.t = 12.5;                       // время воды: любое, лишь бы одно и то же
  boat.o.windSpeed = c.wind;
  boat.o.windDir = 0;
  boat.o.rudder = 0;
  boat.fetchM = c.fetch;
  boat.fetchOverride = true;
  boat.seaHs = seaState(c.wind, c.fetch).hs;
  if (boat.wind && boat.wind.o) {
    boat.wind.o.gust = 0;
    boat.wind.o.dir = 0;
    boat.wind.o.speed = c.wind;
  }
  prev.x = boat.x; prev.y = boat.y; prev.psi = boat.psi;
  prev.phi = boat.phi; prev.zc = boat.zc; prev.th = boat.th;
}

// Служебная разметка снимается вся. Не ради красоты: стрелки, сетка и след
// попадают и в снимок сцены, из которого марш берёт цвет, и во второй проход
// зеркала — то есть в самое отражение. На замере это чужая работа в обеих
// чашах весов, а на снимке — шум, по которому потом не отличить правку от
// стрелки, проехавшей на полпикселя.
function benchQuiet() {
  for (const o of [arrow, wake, track, grid, mark, streakMesh, seaProbeMarks,
                   curField, flowGroup]) {
    if (o) o.visible = false;
  }
}

// Камера случая. Оси лодки здесь совпадают с осями сцены — лодка стоит в начале
// координат носом на восток, — но пишется всё равно через орты: случай задан в
// её осях, и переносить его руками значило бы держать это соответствие в голове.
function benchAim(camera) {
  const c = BENCH_CASES[BENCH_N];
  const fx = bowSceneX(0), fz = bowSceneZ(0);
  const sx = stbdSceneX(0), sz = stbdSceneZ(0);
  const at = v => new Vector3(v[0] * fx + v[2] * sx, v[1], v[0] * fz + v[2] * sz);
  camera.position.copy(at(c.eye));
  camera.lookAt(at(c.at));
}

// --- замер ---------------------------------------------------------------------
//
// Что здесь меряется и почему именно так.
//
// Часы браузера привязаны к развёртке: rAF отдаёт кадр раз в 16.7 мс, и пока
// работа в этот срок укладывается, ЛЮБАЯ разница в цене показывает одно и то же
// число. Первый заход мерил таймстампами видеокарты и получил 0.26 мс с
// отражением и 0.27 без — то есть не измерил ничего и об этом не сказал.
//
// Здесь иначе: кадр рисуется подряд много раз, вне rAF, а в конце очередь
// видеокарты осушается. Тогда полное время делится на число кадров и даёт цену
// кадра под нагрузкой — уже без развёртки. Осушение обязательно: renderAsync
// возвращается, отдав команды, а не дождавшись их выполнения, и без него замер
// показал бы скорость записи команд.
const BENCH_WARM = 12;    // кадров на разогрев, в зачёт не идут
const BENCH_RUN = 60;     // кадров в зачёт

// Осушение очереди. Если до неё не дотянуться — замер меряет запись команд, а
// не работу, и об этом надо СКАЗАТЬ, а не показать красивое число. Прошлый заход
// на замер именно так и соврал: таймстампы отдавали 0.26 мс против 0.27, и
// разницу между «с отражением» и «без» было не отличить от шума.
let benchDrained = false;

async function benchDrain() {
  const dev = renderer.backend && renderer.backend.device;
  const q = dev && dev.queue;
  benchDrained = !!(q && q.onSubmittedWorkDone);
  if (benchDrained) await q.onSubmittedWorkDone();
}

async function benchOne(ssr, planar) {
  seaRefSsr.value = ssr;
  seaRefPlanar.value = planar;
  for (let i = 0; i < BENCH_WARM; i++) renderer.render(scene, camera);
  await benchDrain();
  // Число вызовов отрисовки за кадр — свидетель того, что проход вообще был.
  // Без него «зеркало дешевле неба» пришлось бы разгадывать: то ли замер врёт,
  // то ли второй проход не запускался. Оказалось второе, и разгадка нашлась
  // именно этим счётчиком: у обоих способов выходило поровну.
  //
  // Считается РАЗНОСТЬЮ на одном кадре: сбрасывает счётчики внутренний цикл
  // three по кадру развёртки, а не каждый render, — то есть само по себе
  // значение здесь накопленное и ничего не значит.
  const d0 = renderer.info.render.drawCalls;
  renderer.render(scene, camera);
  const draws = renderer.info.render.drawCalls - d0;
  const t0 = performance.now();
  for (let i = 0; i < BENCH_RUN; i++) renderer.render(scene, camera);
  await benchDrain();
  return { ms: (performance.now() - t0) / BENCH_RUN, draws };
}

let benchBusy = false;

// Пока идёт замер, обычный кадровый цикл не рисует. Иначе он подмешивал бы в
// измеряемое окно свои кадры — со своим прогоном БПФ и своей отрисовкой, — и
// разница между способами тонула бы в чужой работе тем сильнее, чем дольше шёл
// замер. Сам цикл при этом жив: остановленный rAF потом уже не завести.
function benchPaused() { return benchBusy; }

async function benchRun() {
  if (benchBusy) return;
  benchBusy = true;
  const out = document.getElementById('v-bench');
  const keep = [seaRefSsr.value, seaRefPlanar.value];
  try {
    const res = [];
    for (const [name, ssr, planar] of [['небо', 0, 0], ['SSR', 1, 0],
                                       ['зеркало', 0, 1]]) {
      if (out) out.textContent = name + '…';
      res.push([name, await benchOne(ssr, planar)]);
    }
    // Показывается не только время, но и НАДБАВКА над голым небом: полное время
    // кадра почти целиком состоит из всего остального, и по нему одному разницу
    // между способами не видно.
    const base = res[0][1].ms;
    const txt = res.map(([n, r], i) => i === 0
      ? n + ' ' + r.ms.toFixed(2)
      : n + ' ' + r.ms.toFixed(2) + ' (+' + (r.ms - base).toFixed(2) + ')').join(', ');
    if (out) out.textContent = benchDrained ? txt + ' мс' : txt + ' мс — БЕЗ ОСУШЕНИЯ';
    console.log('замер отражений:',
                Object.fromEntries(res.map(([n, r]) =>
                  [n, r.ms.toFixed(3) + ' мс, ' + r.draws + ' вызовов'])),
                'случай:', benchFrozen() ? BENCH_CASES[BENCH_N].name : 'живая сцена',
                'очередь осушалась:', benchDrained);
    if (!benchDrained) {
      console.warn('до очереди видеокарты не достучались: числа выше — это ' +
                   'скорость записи команд, а не цена кадра. Сравнивать нельзя.');
    }
  } finally {
    seaRefSsr.value = keep[0];
    seaRefPlanar.value = keep[1];
    benchBusy = false;
  }
}

{
  const b = document.getElementById('bench');
  if (b) b.addEventListener('click', benchRun);
  if (benchFrozen()) {
    const c = BENCH_CASES[BENCH_N];
    console.log('скамья: случай ' + BENCH_N + ' «' + c.name + '», ветер ' +
                c.wind + ' м/с, разгон ' + (c.fetch / 1000) + ' км');
  }
}
