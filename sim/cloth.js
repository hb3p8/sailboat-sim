// Полуугол дуги, у которой отношение длины к хорде равно `k`: sin θ / θ = 1/k.
// Делением пополам, без малоугольного приближения: при запасе в десятую долю оно
// врёт на проценты, а здесь от этого зависят длины шкаторин.
function arcHalfAngle(k) {
  if (!(k > 1 + 1e-9)) return 0;
  let lo = 1e-6, hi = Math.PI - 1e-6;
  for (let i = 0; i < 60; i++) {
    const m = 0.5 * (lo + hi);
    if (Math.sin(m) / m > 1 / k) lo = m; else hi = m;
  }
  return 0.5 * (lo + hi);
}

// Точка на дуге, у которой ЗАДАНА ВЫСОТА. Высота вдоль шкаторины монотонна —
// обе идут снизу вверх, — поэтому обращается делением пополам. Нужна затем,
// чтобы строки стояли по СТАНЦИЯМ ОБВОДА: ширина паруса объявлена на высоте, и
// снимать её надо там же, где она объявлена.
// Точка кромки с ОБЪЯВЛЕННЫМ СЕРПОМ на высоте z.
//
// Серп передней шкаторины задан в пакете двумя величинами: стрелкой
// (`luff_round_m`) и положением плеча (`luff_round_at`), и закон у него
// `amp · sin(π · f^pow)`, где показатель подобран так, чтобы максимум пришёлся
// ровно на плечо. Этим же законом сборщик считает длину `luff_m`, и этим же
// законом аэродинамика ставит провис (`sailSagAt` в `aero.js`).
//
// Ткань же строила кромку `arcAtZ` — ОКРУЖНОСТЬЮ, у которой горб всегда ровно
// на середине высоты. Замер: плечо объявлено на 62 %, ткань давала 50 %. То
// есть «плечо уехало вверх, куда §Б0.2 и просил» в крое не исполнялось, и одна
// кромка имела две формы — одну у аэродинамики, другую у ткани.
function roundAtZ(A, B, amp, at, n, z, out) {
  const pow = Math.log(0.5) / Math.log(at > 0 && at < 1 ? at : 0.5);
  const put = (f) => {
    const d = amp * Math.sin(Math.PI * Math.pow(Math.max(0, Math.min(1, f)), pow));
    out[0] = A[0] + (B[0] - A[0]) * f + n[0] * d;
    out[1] = A[1] + (B[1] - A[1]) * f + n[1] * d;
    out[2] = A[2] + (B[2] - A[2]) * f + n[2] * d;
    return out;
  };
  let lo = 0, hi = 1;
  const up = B[2] >= A[2];
  for (let i = 0; i < 40; i++) {
    const m = 0.5 * (lo + hi);
    put(m);
    if ((out[2] < z) === up) lo = m; else hi = m;
  }
  return put(0.5 * (lo + hi));
}

function arcAtZ(A, B, L, n, z, out) {
  let lo = 0, hi = 1;
  const up = B[2] >= A[2];
  for (let i = 0; i < 40; i++) {
    const m = 0.5 * (lo + hi);
    arcAt(A, B, L, n, m, out);
    if ((out[2] < z) === up) lo = m; else hi = m;
  }
  return arcAt(A, B, L, n, 0.5 * (lo + hi), out);
}

// --- ПРОФИЛЬ СЕЧЕНИЯ ------------------------------------------------------------
//
// Строка кроя была дугой окружности. У дуги постоянная кривизна, а значит место
// наибольшего пуза ровно посередине хорды, а углы входа и выхода равны. Обмер
// настоящего асимметрика (`data/sail/deparday_j80_2016.json`) даёт место пуза
// 41…49 % в рабочей части и вход вдвое-втрое круче выхода. Дугой такого не
// построить ни при каких длинах.
//
// Семейство взято у парусных мастеров: Sailcut CAD (R. & J. Lainé, GPL-2)
// задаёт сечение не формой, а РАСПРЕДЕЛЕНИЕМ КРИВИЗНЫ по хорде
//
//     z'' = −(a·(1−x)^kluff + kleech·x),   a = 1 + kluff/4,
//
// дважды проинтегрированным при z(0) = z(1) = 0. Код оттуда не взят — он под
// GPL-2 и в этот проект скопирован быть не может; переписано по уравнениям,
// которые в том исходнике выписаны комментарием.
//
// Два показателя и всё: `kluff` собирает кривизну у передней шкаторины,
// `kleech` у задней. При нуле обоих семейство вырождается в параболу с
// максимумом ровно на половине — то есть в то, что было.
//
// ПАРА (8, 0.5), и оба числа стоят на своих замерах.
//
// `kleech` держит МЕСТО ПУЗА. Обмер J/80 (столбец AWA 64°, ближайшая доступная
// замена проектной форме) даёт по шести сечениям 0.49 / 0.44 / 0.39 / 0.44 /
// 0.45 / 0.61; взвешенное по обмерной же ширине — 0.4525, и пара даёт 0.454.
// Прежде тут стояло 0.465 как «среднее по рабочим сечениям», но это среднее по
// ВСЕМ шести, вместе с фаловым 0.61 — а он не рабочее сечение, а конец.
//
// `kluff` держит ВХОД. Тот же обмер даёт вход 118 / 129 / 97° на сечениях,
// которые несут нагрузку, — и это больше, чем может дать любой профиль вида
// z(x): угол свыше 90° означает, что шкаторина завёрнута назад, то есть
// поверхность перестала быть однозначной по хорде. Достижимо тут одно —
// подойти как можно ближе, и при пузе 0.277 семейство даёт вход 51.6° при
// kluff = 1 и 65.6° при kluff = 8.
//
// Дальше упирается в СЕТКУ КРОЯ. Член передней шкаторины спадает как
// (1−x)^kluff, то есть его кривизна живёт на 1/kluff хорды; у полотна по хорде
// восемь панелей, и при kluff = 8 особенность занимает ровно одну. Просить
// мельче значит просить форму, которой в модели негде лежать: держать её будет
// не ткань, а частота выборки.
//
// Что это дало на летящем парусе (TWA 140°, шкот 5.5 м): вход 45…48° -> 56…59°,
// отношение входа к выходу 1.20 -> 1.39, тяга 329 -> 338 Н. Полотно при этом
// по-прежнему ложится на крой строка в строку.
const PROF_LUFF = 8;
const PROF_LEECH = 0.5;
const PROF_A = 1 + PROF_LUFF / 4;
const PROF_B = PROF_A / ((PROF_LUFF + 2) * (PROF_LUFF + 1));
const PROF_C = PROF_LEECH / 6 - PROF_B;
const PROF_N = 48;                       // шагов по хорде при интегрировании

function profZ(x) {
  return -PROF_A * Math.pow(1 - x, PROF_LUFF + 2) /
         ((PROF_LUFF + 1) * (PROF_LUFF + 2)) -
         PROF_LEECH / 6 * x * x * x + PROF_C * x + PROF_B;
}
function profDZ(x) {
  return PROF_A * Math.pow(1 - x, PROF_LUFF + 1) / (PROF_LUFF + 1) -
         PROF_LEECH / 2 * x * x + PROF_C;
}
const PROF_MAX = (() => {
  let m = 0;
  for (let x = 0; x <= 1; x += 0.0005) m = Math.max(m, profZ(x));
  return m;
})();

// Длина профиля в долях хорды при данной глубине, и заодно накопленная длина по
// шагам: по ней потом ищется точка на доле ДЛИНЫ.
// ПАРАМЕТРИЧЕСКИЙ ПРОФИЛЬ: кубическая кривая Безье с независимыми входом,
// выходом, пузом и местом пуза.
//
// ЗАЧЕМ. Семейство выше — это z(x), функция вдоль хорды, и у неё угол входа не
// может достичь 90°: производная в носке конечна. Замер: наш вход 58° при
// измеренных у J/80 84…90° на 1/6 и 2/6 высоты. Именно отсюда парус выглядел
// серпом, а не мешком: у настоящего спинакера передняя часть сечения
// ВОЗВРАЩАЕТСЯ НАЗАД относительно хорды, и Депардэ меряет там до 129°.
// Руководства по раскрою требуют того же: у ProSail сечение составляется из
// нескольких дуг с настраиваемыми долями длины и отношениями радиусов, потому
// что «одна величина глубины всю форму не описывает».
//
// КАК. Концы кривой стоят на хорде, а касательные в них задаются углами входа и
// выхода; длины ручек подбираются под объявленные пузо и место пуза. При входе
// больше 90° косинус отрицателен, ручка уходит за носок, и кривая честно
// заворачивает назад — того самого запрета, который отвергал измеренный парус,
// здесь просто нет.
const BEZ_N = 64;
const BEZ_CACHE = new Map();

function bezPts(a, b, fin, fex) {
  return [0, 0,
          a * Math.cos(fin), a * Math.sin(fin),
          1 - b * Math.cos(fex), b * Math.sin(fex),
          1, 0];
}
function bezAt(P, s, out) {
  const u = 1 - s, w0 = u * u * u, w1 = 3 * u * u * s, w2 = 3 * u * s * s, w3 = s * s * s;
  out[0] = w0 * P[0] + w1 * P[2] + w2 * P[4] + w3 * P[6];
  out[1] = w0 * P[1] + w1 * P[3] + w2 * P[5] + w3 * P[7];
  return out;
}
// Пузо, место пуза и длина кривой при данных ручках.
const BEZ_TMP = [0, 0];
function bezShape(P) {
  let cam = 0, at = 0.5, len = 0, px = P[0], pz = P[1];
  for (let i = 0; i <= BEZ_N; i++) {
    bezAt(P, i / BEZ_N, BEZ_TMP);
    const x = BEZ_TMP[0], z = BEZ_TMP[1];
    if (z > cam) { cam = z; at = x; }
    if (i) len += Math.hypot(x - px, z - pz);
    px = x; pz = z;
  }
  return { cam, at, len };
}
// Подбор ручек под объявленные пузо и место пуза: вложенные деления пополам.
// Пузо растёт с суммой ручек, место пуза уезжает назад с долей задней.
function bezSolve(cam, at, fin, fex) {
  const key = cam.toFixed(4) + ',' + at.toFixed(3) + ',' + fin.toFixed(3) + ',' + fex.toFixed(3);
  const hit = BEZ_CACHE.get(key);
  if (hit) return hit;
  let rLo = 0.05, rHi = 0.95, P = null, sh = null;
  for (let i = 0; i < 24; i++) {
    const r = 0.5 * (rLo + rHi);
    let kLo = 0.01, kHi = 6;
    for (let j = 0; j < 24; j++) {
      const k = 0.5 * (kLo + kHi);
      P = bezPts(k * (1 - r), k * r, fin, fex);
      sh = bezShape(P);
      if (sh.cam < cam) kLo = k; else kHi = k;
    }
    if (sh.at < at) rLo = r; else rHi = r;
  }
  const out = { P: P, ratio: sh.len, cam: sh.cam, at: sh.at };
  if (BEZ_CACHE.size > 512) BEZ_CACHE.clear();
  BEZ_CACHE.set(key, out);
  return out;
}
// Отношение длины сечения к хорде — то, чем задаётся длина строки.
function profRatio(cam, at, fin, fex) { return bezSolve(cam, at, fin, fex).ratio; }

// Точка сечения на доле `t` ЕГО ДЛИНЫ. Доля длины, а не хорды: узлы садятся
// поровну по материалу, как и у прежнего семейства.
const BEZ_CUM = new Float64Array(BEZ_N + 1);
function profAtPar(A, B, n, t, sol, out) {
  const ex = B[0] - A[0], ey = B[1] - A[1], ez = B[2] - A[2];
  const c = Math.hypot(ex, ey, ez);
  if (c < 1e-9) { out[0] = A[0]; out[1] = A[1]; out[2] = A[2]; return out; }
  const P = sol.P;
  let L = 0, px = P[0], pz = P[1];
  BEZ_CUM[0] = 0;
  for (let i = 1; i <= BEZ_N; i++) {
    bezAt(P, i / BEZ_N, BEZ_TMP);
    L += Math.hypot(BEZ_TMP[0] - px, BEZ_TMP[1] - pz);
    BEZ_CUM[i] = L; px = BEZ_TMP[0]; pz = BEZ_TMP[1];
  }
  const want = t * L;
  let sPar = t;
  for (let i = 1; i <= BEZ_N; i++) {
    if (BEZ_CUM[i] >= want) {
      const lo = BEZ_CUM[i - 1], hi = BEZ_CUM[i];
      sPar = (i - 1 + (hi > lo ? (want - lo) / (hi - lo) : 0)) / BEZ_N;
      break;
    }
  }
  bezAt(P, sPar, BEZ_TMP);
  const x = BEZ_TMP[0], z = BEZ_TMP[1] * c;
  out[0] = A[0] + ex * x + n[0] * z;
  out[1] = A[1] + ey * x + n[1] * z;
  out[2] = A[2] + ez * x + n[2] * z;
  return out;
}

const PROF_CUM = new Float64Array(PROF_N + 1);
function profLen(depth) {
  const k = depth / PROF_MAX;
  let L = 0, prev = Math.hypot(1, k * profDZ(0));
  PROF_CUM[0] = 0;
  for (let i = 1; i <= PROF_N; i++) {
    const cur = Math.hypot(1, k * profDZ(i / PROF_N));
    L += 0.5 * (prev + cur) / PROF_N;
    PROF_CUM[i] = L;
    prev = cur;
  }
  return L;
}

// Глубина, при которой профиль имеет заданную длину в долях хорды: длина растёт
// с глубиной монотонно, тридцати делений пополам хватает на шесть знаков.
function profDepth(k) {
  if (!(k > 1 + 1e-9)) return 0;
  let lo = 0, hi = 1.5;
  for (let i = 0; i < 30; i++) {
    const m = 0.5 * (lo + hi);
    if (profLen(m) < k) lo = m; else hi = m;
  }
  return 0.5 * (lo + hi);
}

// Точка профиля длиной `L` между A и B, выгнутого в сторону `n`. `t` — доля
// ДЛИНЫ, как и у дуги: узлы садятся поровну по материалу.
function profAt(A, B, L, n, t, out) {
  const ex = B[0] - A[0], ey = B[1] - A[1], ez = B[2] - A[2];
  const c = Math.hypot(ex, ey, ez);
  if (c < 1e-9) { out[0] = A[0]; out[1] = A[1]; out[2] = A[2]; return out; }
  const d = profDepth(L / c);
  const total = profLen(d);            // заполняет PROF_CUM под эту глубину
  const want = t * total;
  let x = t;
  for (let i = 1; i <= PROF_N; i++) {
    if (PROF_CUM[i] >= want) {
      const lo = PROF_CUM[i - 1], hi = PROF_CUM[i];
      x = (i - 1 + (hi > lo ? (want - lo) / (hi - lo) : 0)) / PROF_N;
      break;
    }
  }
  const z = d * profZ(x) / PROF_MAX * c;
  out[0] = A[0] + ex * x + n[0] * z;
  out[1] = A[1] + ey * x + n[1] * z;
  out[2] = A[2] + ez * x + n[2] * z;
  return out;
}

// Точка на дуге длиной `L` между A и B, выгнутой в сторону `n` (единичный,
// перпендикулярный хорде). `t` — доля ДЛИНЫ ДУГИ, а не хорды: узлы садятся
// поровну по материалу.
function arcAt(A, B, L, n, t, out) {
  const ex = B[0] - A[0], ey = B[1] - A[1], ez = B[2] - A[2];
  const c = Math.hypot(ex, ey, ez);
  if (c < 1e-9) { out[0] = A[0]; out[1] = A[1]; out[2] = A[2]; return out; }
  const th = arcHalfAngle(L / c);
  if (th < 1e-6) {
    out[0] = A[0] + ex * t; out[1] = A[1] + ey * t; out[2] = A[2] + ez * t;
    return out;
  }
  const R = c / (2 * Math.sin(th)), a = (2 * t - 1) * th;
  const along = R * (Math.sin(a) + Math.sin(th)) / c, bow = R * (Math.cos(a) - Math.cos(th));
  out[0] = A[0] + ex * along + n[0] * bow;
  out[1] = A[1] + ey * along + n[1] * bow;
  out[2] = A[2] + ez * along + n[2] * bow;
  return out;
}

export class Cloth {
  // `opts.bend` — жёсткость на излом. Наружу вынесена ради стенда: при нуле
  // натянутая строка обязана быть в точности равномерно нагруженной нитью, и
  // тогда решатель можно сверить с теорией, а не с самим собой.
  constructor(sail, si, opts) {
    this.sail = sail;
    this.si = si;
    this.bend = opts && opts.bend != null ? opts.bend : BEND;
    // Сетка и число проходов — у экземпляра, чтобы стенд мог их сгустить.
    this.rows = opts && opts.rows ? opts.rows : CLOTH_ROWS;
    this.cols = opts && opts.cols ? opts.cols : CLOTH_COLS;
    this.iter = opts && opts.iter ? opts.iter : ITER;
    this.freeClew = opts && opts.freeClew != null ? opts.freeClew : FREE_CLEW;
    this.cut3d = opts && opts.cut3d != null ? opts.cut3d : CUT3D;
    this.boardMaterial = opts && opts.boardMaterial === true;
    this.designSide = -1;
    this.rigRef = null;
    this.nRows = this.rows;
    const N = this.rows * this.cols;
    this.n = N;
    this.pos = new Float64Array(N * 3);
    this.prev = new Float64Array(N * 3);
    this.frc = new Float64Array(N * 3);
    this.w = new Float64Array(N);        // обратная масса; ноль — закреплён
    this.nrm = new Float64Array(N * 3);
    // Выкройка: плоский кусок ткани, из которого парус сшит. Все длины покоя
    // берутся из неё, и потому они между собой согласованы — что для куска
    // ткани и обязательно.
    this.px = new Float64Array(N);
    this.py = new Float64Array(N);
    // Проектная поверхность трёхмерного кроя: те же узлы, но в пространстве.
    this.dx = new Float64Array(N);
    this.dy = new Float64Array(N);
    this.dz = new Float64Array(N);
    this.area = new Float64Array(N);     // доля площади выкройки на узел
    this.mass = new Float64Array(N);
    this.rowW = new Float64Array(this.rows);   // ширина строки в выкройке
    this.rhoAir = 1.225;
    // Связи: пары узлов, длина покоя и жёсткость. Топология постоянна, длины
    // пересчитываются каждый шаг — запас ткани ходит за ползунком пуза.
    const ci = [], cj = [], ck = [];
    for (let r = 0; r < this.rows; r++)
      for (let c = 0; c + 1 < this.cols; c++) { ci.push(this.ix(r, c)); cj.push(this.ix(r, c + 1)); ck.push(1); }
    for (let r = 0; r + 1 < this.rows; r++)
      for (let c = 0; c < this.cols; c++) { ci.push(this.ix(r, c)); cj.push(this.ix(r + 1, c)); ck.push(1); }
    for (let r = 0; r + 1 < this.rows; r++)
      for (let c = 0; c + 1 < this.cols; c++) {
        ci.push(this.ix(r, c)); cj.push(this.ix(r + 1, c + 1)); ck.push(SHEAR);
        ci.push(this.ix(r, c + 1)); cj.push(this.ix(r + 1, c)); ck.push(SHEAR);
      }
    // ПОВОДКИ ОТ ЗАКРЕПЛЁННЫХ УГЛОВ. Не выдумка и не жёсткость: у нерастяжимой
    // ткани расстояние между двумя точками В ПРОСТРАНСТВЕ не может превысить
    // расстояние между ними В ВЫКРОЙКЕ. Выкройка выпукла (передняя шкаторина
    // выгнута вперёд, задняя в корму, нижняя прямая), поэтому по ней кратчайший
    // путь — прямая, и её длина и есть верхний предел. То есть поводок это то же
    // самое условие нерастяжимости, только записанное сразу, а не набранное
    // цепочкой рёбер.
    //
    // Без них сходимости нет, и это померено. У фала полотно сходится к
    // дощечке шириной 0.25 м, а соседняя строка шире метра: верхняя ячейка —
    // лучина, её рёбра по 3 см при вертикальных по метру. Гаусс — Зейдель на
    // таком отношении ползёт: за десять проходов верхняя строка растянута в
    // ШЕСТЬ раз, за сто двадцать проходов при вчетверо мельче подшаге — всё ещё
    // на 23 %, и стоит это шесть миллисекунд на шаг вместо трети. С поводками
    // хватает десяти (Kim и др., long-range attachments — тот же приём).
    // ЖЁСТКОСТЬ НА ИЗЛОМ. Связь через ячейку: расстояние между узлами c−1 и c+1
    // при сложенной вдвое ткани падает почти до нуля, при расправленной равно
    // длине по выкройке. Двусторонняя, в отличие от всех прочих: складку надо
    // распрямлять, а не только не давать тянуть.
    if (this.bend > 0) {
      for (let r = 0; r < this.rows; r++)
        for (let c = 1; c + 1 < this.cols; c++) {
          ci.push(this.ix(r, c - 1)); cj.push(this.ix(r, c + 1)); ck.push(-this.bend);
        }
      for (let r = 1; r + 1 < this.rows; r++)
        for (let c = 0; c < this.cols; c++) {
          ci.push(this.ix(r - 1, c)); cj.push(this.ix(r + 1, c)); ck.push(-this.bend);
        }
    }
    // Отвергнуто: поводки ещё и от ШКОТОВОГО угла. Он закреплён наравне с галсом
    // и фалом, условие нерастяжимости от него такое же, и на сходимость они
    // должны были работать — а не работают вовсе: летящая хорда на полувысоте
    // 3.18 м против 3.17 без них, при восьмипроцентном недоходе до сошедшегося
    // решения. Четверть лишних связей задаром (`docs/wake.md`, В1).
    for (let r = 0; r < this.rows; r++)
      for (let c = 0; c < this.cols; c++) {
        const i = this.ix(r, c);
        if (i !== this.ix(0, 0)) { ci.push(this.ix(0, 0)); cj.push(i); ck.push(1); }
        if (i !== this.ix(this.rows - 1, 0)) { ci.push(this.ix(this.rows - 1, 0)); cj.push(i); ck.push(1); }
      }
    this.ci = Int32Array.from(ci);
    this.cj = Int32Array.from(cj);
    this.ck = Float64Array.from(ck);
    // СВЯЗИ ВЕРХА — отдельным списком, для добавочных проходов по ним.
    //
    // Верх паруса сходится много медленнее низа, и это померено: при десяти
    // проходах задняя шкаторина у фала слаба на 2.2 %, верхние строки на 1.6 %,
    // и на этой слабине фаловая дощечка разворачивается к полотну на 49°. При
    // четырёхстах проходах всё натянуто в ноль, а залом падает до 19°.
    //
    // Причина — вырождение сетки: ширина строки падает с 4.29 м у нижней
    // шкаторины до 0.27 м у дощечки, рёбра строки становятся по 3.4 см при
    // вертикальных под метр, а масса узла — 117 г против 1684 г. По таким
    // связям Гаусс — Зейдель ползёт, и общие проходы тратятся в основном на
    // низ, который сошёлся давно.
    //
    // Поэтому верх доводится ОТДЕЛЬНО: те же связи, тот же проектор, просто
    // лишние проходы по четверти списка. Цена — доли миллисекунды вместо
    // сорокакратной.
    const top = this.rows - 1 - Math.max(2, Math.round((this.rows - 1) * 0.3));
    const ti = [];
    for (let k = 0; k < ci.length; k++) {
      const r = Math.max(Math.floor(ci[k] / this.cols), Math.floor(cj[k] / this.cols));
      if (r >= top) ti.push(k);
    }
    this.topIdx = Int32Array.from(ti);
    this.rest = new Float64Array(ci.length);
    this.luffAt = edgeFn(sail.luff);
    this.leechAt = edgeFn(sail.leech);
    this.zLo = Math.max(sail.tack[1], sail.clew[1]);
    this.zHi = Math.min(sail.head[1], sail.head_aft[1]);
    this.span = this.zHi - this.zLo;
    // Нормаль к прямой галс—фал в плоскости выкройки, наружу от паруса: по ней
    // откладывается серп передней шкаторины.
    const dx = sail.head[0] - sail.tack[0], dz = sail.head[1] - sail.tack[1];
    const L = Math.hypot(dx, dz) || 1;
    this.rnx = dz / L; this.rny = -dx / L;
    this.ready = false;
    this.tmpA = [0, 0, 0]; this.tmpB = [0, 0, 0]; this.tmpC = [0, 0, 0];
    this.clew = this.ix(0, this.cols - 1);
    this.tack = this.ix(0, 0);
    this.head = this.ix(this.rows - 1, 0);
  }

  // Высота строки над нижней шкаториной, в долях размаха.
  //
  // Отвергнуто: СГУЩАТЬ строки к фалу. Довод был хорош — у дощечки полотно
  // сходится к четверти метра, а шаг по высоте остаётся метровым, и верхняя
  // ячейка выходит лучиной 3 см на метр, на которой Гаусс — Зейдель ползёт.
  // Померено при `1 − (1 − u)^p`: недоход хорды на полувысоте до сошедшегося
  // решения 1.2 % при p = 1, 5 % при p = 1.5, 7 % при p = 2. Сгущение
  // сходимость УХУДШАЕТ: строк внизу становится меньше, а выигрыш наверху его не
  // окупает (`docs/wake.md`, В1).
  rowF(r) { return r / (this.rows - 1); }

  // Полоска, чьё давление и чей поток берёт строка. Тот же выбор ближайшей,
  // что у отрисовки: полосок шесть, строк одиннадцать.
  stripOf(r) { return Math.min(STRIPS - 1, Math.round(this.rowF(r) * (STRIPS - 1))); }

  // Выкройка.
  //
  // Плоский контур паруса и есть готовая выкройка — ломаные шкаторин сняты в
  // диаметральной плоскости, то есть уже плоские. К ней добавляются ровно две
  // вещи, и обе уже есть в модели:
  //
  //   * запас ткани по хорде — тот же `slack`, из которого мембрана считает
  //     пузо. Строка выкройки шире хорды ровно на него;
  //
  //   * серп передней шкаторины — уложенный в плоскость выкройки ПРЕДПИСАННЫЙ
  //     провис (`sailSagAt`). Это не совпадение и не хитрость: провис в полёте
  //     и есть та ткань, которой шкаторина длиннее прямой галс—фал, и другого
  //     источника длины у неё нет. Пока провис назначен постоянной 0.13, серп
  //     наследует это допущение целиком; шаг Б1 заменит его кроем, и тогда
  //     стрелка провиса станет СЛЕДСТВИЕМ, а не входом.
  //
  // Замер, ради которого это здесь и записано: 0.13 длины шкаторины провиса
  // дают дугу на 4.4 % длиннее прямой, то есть серп 0.134 её длины. План Б1
  // оценивает LUFF_ROUND_K в 0.10…0.12, ничего о провисе не зная, — два
  // независимых конца сошлись.
  // ТРЁХМЕРНЫЙ КРОЙ: длины покоя снимаются с ПРОЕКТНОЙ ПОВЕРХНОСТИ, а не с
  // плоского листа.
  //
  // Плоская выкройка не может держать всё сразу, и это померено: концы строк на
  // обводе, объявленные длины шкаторин и запас на пузо внутри строки —
  // одновременно невозможны. Запас в десятую часть при хорде 3.89 м требует в
  // плоскости стрелки 0.79 м, соседние строки выгибаются по-разному, и
  // расстояния по столбцам уезжают процентов на пять (`docs/wake.md`).
  //
  // Выход — тот, что и назван ревью: поверхность строится СРАЗУ В ПРОСТРАНСТВЕ,
  // с пузом, и метрика берётся с неё. Тогда двоякая кривизна не конфликтует с
  // нерастяжимостью: лист и не обязан быть разворачивающимся, он сшит.
  //
  // Поверхность задают три угла и три шкаторины СВОЕЙ ОБЪЯВЛЕННОЙ ДЛИНЫ:
  // передняя от галса к фалу, задняя от шкотового угла к задней кромке
  // дощечки, нижняя от галса к шкотовому углу. Строки идут между передней и
  // задней по равной доле их длины — так сшивают панели, — и каждая выгнута
  // своим проектным пузом. Нижняя строка и дощечка пузо не получают: это
  // границы, у них своя длина.
  //
  // Шкотовый угол берётся на ПРОЕКТНОМ шкоте (середина диапазона), а не на
  // рабочем: крой у паруса один, а тримов много. Отсюда же и та самая дуга
  // `gennakerClew` — на проектном триме обе шкаторины натянуты по определению,
  // и это ровно то место, где дуга верна.
  design3d(slack) {
    const g = this.sail.gennaker ? this.sail.gennaker : null;
    const gen = this.gen;
    const side = this.designSide;
    const T = [gen.tack[0], 0, gen.tack[1]];
    const H = [gen.head[0], 0, gen.head[1]];
    const HA = [gen.head_aft[0], 0, gen.head_aft[1]];
    const cc = gennakerClew({ genSheetLen: 0.5 * (gen.sheet_min_m + gen.sheet_max_m) }, gen);
    const C = [cc[0], Math.abs(cc[1]) * side, cc[2]];
    // КУДА ВЫГИБАЮТСЯ ШКАТОРИНЫ — и это, оказалось, главное число кроя.
    //
    // Серп шкаторины — это лишняя длина по сравнению с прямой между её концами.
    // Куда её деть, крой решает сам, и от решения зависит ВСЯ полнота паруса:
    // если обе шкаторины выгнуть в одну сторону поперёк (как стояло), их
    // расстояние друг от друга не меняется вовсе, и вся ширина обвода уходит в
    // пузо — на полувысоте 3.31 м ткани на хорду 1.99, то есть пузо 0.54. Если
    // же выгнуть их ВРОЗЬ, в плоскости паруса, хорда растёт, и пузо падает.
    //
    // Угол `bow` и есть эта развёртка: ноль — поперёк, как было; девяносто —
    // целиком врозь. Значение не назначается, а подбирается ниже под
    // ОБЪЯВЛЕННОЕ пузо (`sail.design`, те же 0.20/0.16, по которым считает
    // аэродинамика). Одно пузо на модель, а не два.
    const A = this.tmpA, B = this.tmpB, P = this.tmpC;
    const nOf = (E0, E1, other, bow) => {
      let ex = E1[0] - E0[0], ey = E1[1] - E0[1], ez = E1[2] - E0[2];
      const el = Math.hypot(ex, ey, ez) || 1;
      ex /= el; ey /= el; ez /= el;
      // Поперёк: борт постановки, очищенный от доли вдоль шкаторины.
      let ox = 0, oy = side, oz = 0;
      const d0 = ox * ex + oy * ey + oz * ez;
      ox -= d0 * ex; oy -= d0 * ey; oz -= d0 * ez;
      const ol = Math.hypot(ox, oy, oz) || 1;
      ox /= ol; oy /= ol; oz /= ol;
      // Второе направление той же плоскости: e × nOut. Знак берётся так, чтобы
      // плюс угла уводил шкаторину ПРОЧЬ от другой.
      let mx = ey * oz - ez * oy, my = ez * ox - ex * oz, mz = ex * oy - ey * ox;
      const ax = 0.5 * (E0[0] + E1[0]) - other[0], ay = 0.5 * (E0[1] + E1[1]) - other[1];
      if (mx * ax + my * ay < 0) { mx = -mx; my = -my; mz = -mz; }
      const cb = Math.cos(bow), sb = Math.sin(bow);
      return [ox * cb + mx * sb, oy * cb + my * sb, oz * cb + mz * sb];
    };
    const midL = [0.5 * (T[0] + H[0]), 0.5 * (T[1] + H[1])];
    const midB = [0.5 * (C[0] + HA[0]), 0.5 * (C[1] + HA[1])];
    const dsg = this.sail.design || [0.2];
    // Семейство сечения: пузо, место пуза, вход и выход. Все четыре — по
    // станциям высоты, из одной таблицы обмера (см. `aero.js`).
    const kind = this.sail.gennaker ? 'gennaker' : (this.sail.jib ? 'jib' : 'main');
    const dft = DESIGN_DRAFT[kind] || DESIGN_DRAFT.main;
    const ent = DESIGN_ENTRY[kind] || DESIGN_ENTRY.main;
    const exi = (DESIGN_EXIT[kind] || DESIGN_EXIT.main) * Math.PI / 180;
    const solAt = (f) => bezSolve(designAt(dsg, f), designAt(dft, f),
                                  designAt(ent, f) * Math.PI / 180, exi);
    // ЦЕЛЬ ПОДБОРА — ОБМЕРНАЯ ШИРИНА НА ПОЛУВЫСОТЕ. Пузо теперь задаёт длину
    // строки само, поэтому развёртке серпа осталось ровно одно дело: развести
    // шкаторины так, чтобы парус вышел нужной ШИРИНЫ. Каждое измерение
    // используется по одному разу — пузо на глубину строки, ширина на разнос
    // шкаторин.
    const want = this.luffAt(this.zLo + 0.5 * this.span) -
                 this.leechAt(this.zLo + 0.5 * this.span);
    // Ширина середины при данной развёртке: хорда между шкаторинами, растянутая
    // дугой объявленного пуза.
    const camAt = bow => {
      const nL = nOf(T, H, midB, bow), nB = nOf(C, HA, midL, bow);
      const z = Math.max(T[2], C[2]) +
                0.5 * (Math.min(H[2], HA[2]) - Math.max(T[2], C[2]));
      roundAtZ(T, H, gen.luff_round_m, gen.luff_round_at, nL, z, A);
      arcAtZ(C, HA, gen.leech_m, nB, z, B);
      const c = Math.max(0.02, Math.hypot(B[0] - A[0], B[1] - A[1], B[2] - A[2]));
      return c * solAt(0.5).ratio;
    };
    // Ширина растёт с углом монотонно: чем больше шкаторины врозь, тем длиннее
    // хорда и тем шире парус. Деление пополам, двадцати шагов хватает.
    let lo = 0, hi = Math.PI / 2;
    if (camAt(hi) < want) lo = hi;                  // врозь до упора и всё узко
    else if (camAt(lo) < want) {
      for (let k = 0; k < 20; k++) {
        const m = 0.5 * (lo + hi);
        if (camAt(m) < want) lo = m; else hi = m;
      }
      lo = 0.5 * (lo + hi);
    }
    this.cutBow = lo;
    const nL = nOf(T, H, midB, lo), nB = nOf(C, HA, midL, lo);
    // НИЖНЯЯ ШКАТОРИНА — ТРЕТЬЯ КРОМКА, А НЕ ОСОБЫЙ СЛУЧАЙ.
    //
    // Направление выгиба строки ниже берётся горизонтальной нормалью к хорде
    // (`nz = 0`): парус выгибается вбок, под ветер. Для нижней строки это
    // неверно — она не сечение, а КРОМКА, и её серп у настоящего паруса
    // провисает ВНИЗ, дугой между галсом и шкотовым углом. Пока выгиб был
    // горизонтальным, вся лишняя ткань низа уходила в боковое пузо, а обвод
    // оставался с прямой нижней.
    //
    // Нижняя кромка должна уйти ВНИЗ, но остаться на той же подветренной
    // стороне, что и соседние сечения. Прежний код брал `nOf(..., lo)`, а
    // затем переворачивал ВЕСЬ вектор, если его Z смотрел вверх. Тем самым он
    // действительно опускал нижнюю шкаторину, но одновременно переносил её на
    // наветренную сторону. В проектной поверхности получалось седло: середина
    // нижней кромки лежала на 1.55 м по другую сторону плоскости трёх углов,
    // тогда как все внутренние строки лежали на подветренней.
    //
    // Базис берём прямо из трёх углов. `nOut` — нормаль к их плоскости,
    // ориентированная к объёму остального паруса; `nDown` лежит в этой
    // плоскости, перпендикулярен нижней шкаторине и смотрит от фала, то есть
    // вниз. Их смесь тем же `cutBow` сохраняет у нижней кромки подветренную
    // составляющую объёма и одновременно даёт настоящий серп вниз.
    let fx = C[0] - T[0], fy = C[1] - T[1], fz = C[2] - T[2];
    const fl = Math.hypot(fx, fy, fz) || 1;
    fx /= fl; fy /= fl; fz /= fl;
    let nx = fy * (H[2] - T[2]) - fz * (H[1] - T[1]);
    let ny = fz * (H[0] - T[0]) - fx * (H[2] - T[2]);
    let nz = fx * (H[1] - T[1]) - fy * (H[0] - T[0]);
    if (ny * side < 0) { nx = -nx; ny = -ny; nz = -nz; }
    const nn = Math.hypot(nx, ny, nz) || 1;
    nx /= nn; ny /= nn; nz /= nn;
    const mx = 0.5 * (T[0] + C[0]) - H[0];
    const my = 0.5 * (T[1] + C[1]) - H[1];
    const mz = 0.5 * (T[2] + C[2]) - H[2];
    const md = mx * fx + my * fy + mz * fz;
    let dxF = mx - md * fx, dyF = my - md * fy, dzF = mz - md * fz;
    const dm = Math.hypot(dxF, dyF, dzF) || 1;
    dxF /= dm; dyF /= dm; dzF /= dm;
    const nF = [nx * Math.cos(lo) + dxF * Math.sin(lo),
                ny * Math.cos(lo) + dyF * Math.sin(lo),
                nz * Math.cos(lo) + dzF * Math.sin(lo)];
    for (let r = 0; r < this.rows; r++) {
      // СТРОКИ СТОЯТ ПО ВЫСОТЕ, а не по равной доле длины шкаторин. Ширина
      // паруса объявлена обводом НА ВЫСОТЕ, и снимать её надо там же: по доле
      // длины высоты передней и задней шкаторин расходятся, ширины берутся не
      // со своих станций, и площадь поверхности выходила 23.96 м² против
      // обмерных 27.0.
      //
      // Крайние строки — исключение, и не по недосмотру: нижняя идёт по нижней
      // шкаторине от галса к шкотовому углу, а они на РАЗНОЙ высоте; верхняя —
      // по дощечке. Это границы, и стоят они на своих углах, а не на станции.
      const edgeRow = r === 0 || r === this.rows - 1;
      if (r === 0) { A[0] = T[0]; A[1] = T[1]; A[2] = T[2];
                     B[0] = C[0]; B[1] = C[1]; B[2] = C[2]; }
      else if (r === this.rows - 1) {
        A[0] = H[0]; A[1] = H[1]; A[2] = H[2];
        B[0] = HA[0]; B[1] = HA[1]; B[2] = HA[2];
      } else {
        // СТАНЦИИ СЧИТАЮТСЯ ОТ УГЛОВ САМОГО КРОЯ, а не от `zLo`.
        //
        // `zLo` берётся у ПАКЕТНОГО шкотового угла, а крой строится при СРЕДНЕЙ
        // длине шкота, и угол там стоит выше. Станции, отсчитанные от `zLo`,
        // попадали ниже этого угла, `arcAtZ` не находила на задней шкаторине
        // такой высоты и возвращала сам угол — нижняя строка схлопывалась в
        // точку. Замер: связь длиной 4.6·10⁻¹² м, и растяжение на ней 2.6·10¹¹ %.
        // На прежнем, вдвое меньшем парусе угол вставал ниже, и это не вылезало.
        const zA = Math.max(T[2], C[2]), zB = Math.min(H[2], HA[2]);
        const z = zA + (r / (this.rows - 1)) * (zB - zA);
        roundAtZ(T, H, gen.luff_round_m, gen.luff_round_at, nL, z, A);  // передняя: по серпу
        arcAtZ(C, HA, gen.leech_m, nB, z, B);       // точка задней
      }
      const ex = B[0] - A[0], ey = B[1] - A[1], ez = B[2] - A[2];
      const chord = Math.max(0.02, Math.hypot(ex, ey, ez));
      // ДЛИНА СТРОКИ — ШИРИНА ПО ОБВОДУ, а не хорда с запасом.
      //
      // Ширина обвода на высоте — это и есть ширина сшитого паруса там, вместе с
      // серпом: `luffAt(z) − leechAt(z)` снято с чертежа. Запаса на пузо сверх
      // неё НЕ НАДО: пузо у трёхмерного кроя уже в самой поверхности, а не в
      // лишнем материале. Считать ширину от хорды между концами значило бы
      // потерять обвод: поверхность вышла бы узким треугольником (померено:
      // 18.5 м² против обмерных 27.0).
      //
      // Полнота при этом выходит спинакерная, и это не ошибка: на проектном
      // триме ширина 3.58 м приходится на хорду 1.95, то есть пузо около 0.5.
      // Спинакеры такими и бывают. У поляры сечения, однако, замеры есть до
      // 0.18 — это известный долг, и он записан.
      // ДЛИНА СТРОКИ — ИЗ ОБЪЯВЛЕННОГО ПУЗА, а не из ширины обвода.
      //
      // Два закона об одном и том же не уживаются. Ширина обвода по высоте и
      // пузо сечения по высоте — это одно и то же утверждение, связанное длиной
      // дуги: ширина = хорда · длина(пузо). Пока в крой шли ОБА, они спорили: у
      // верхних строк ширина обвода оказывалась не больше хорды, и крой там
      // выходил ПЛОСКИМ при объявленном пузе 0.15 (замер: строки 7…9 с пузом
      // ровно ноль, а у плоской строки сторона пуза не определена вовсе, и
      // свидетель стороны краснел на шуме).
      //
      // Первично ПУЗО: оно и измерено прямо (проектная форма асимметрика, шесть
      // станций), и нужно всем — ткани, решётке, поляре. Ширина же теперь
      // СЛЕДСТВИЕ и служит проверкой: обмерное распределение ширины по высоте
      // печатает стенд рядом с полученным.
      //
      // Крайние строки — исключение: у них длина объявлена шкаториной и дощечкой.
      // Нижняя строка берёт длину ПО ТКАНИ (`foot_cloth_m`), а не прямую
      // галс—шкот (`foot_m`): разница между ними и есть серп нижней шкаторины.
      // Без него строка выходила ровно прямой — пузо 0.001 при 0.31 у
      // измеренного J/80, вход 5° при 61°.
      const L = r === 0 ? (gen.foot_cloth_m || gen.foot_m)
              : (r === this.rows - 1 ? gen.head_width_m
                                     : chord * solAt(this.rowF(r)).ratio);
      if (edgeRow) { /* длина границы объявлена, пуза у неё нет */ }
      this.rowW[r] = L;
      // В КАКУЮ СТОРОНУ ВЫГНУТА СТРОКА. Сторону задаёт БОРТ ПОСТАНОВКИ, а не
      // поворот хорды, и это не мелочь: дважды уже оказывалось наоборот.
      //
      // У паруса наветренная сторона ВОГНУТАЯ, подветренная выпуклая, а
      // подветренная — это та, на которую парус вынесен: `side`. Поэтому из
      // двух нормалей к хорде берётся та, чья поперечная доля смотрит туда же.
      //
      // Брать знак от поворота хорды (`[ey, −ex]` или `[−ey, ex]`) нельзя:
      // азимут хорды ходит с курсом и с длиной шкота, и любая неподвижная
      // четвертьоборота рано или поздно даёт пузо не на ту сторону. Так и
      // вышло — после правки серпа шкаторин хорда развернулась, и парус стал
      // выгибаться ПРОТИВ ветра при том, что мешок целиком лежал под ветром.
      //
      // Проверяется это теперь прямо: аэродинамика знает свою сторону пуза
      // (`camberSign` в `aero.js`), и стенд ткани сверяет её с тканью по каждой
      // живой полоске. Считается и рисуется обязано быть одно и то же.
      let nx = ey, ny = -ex, nz = 0;
      if (ny * side < 0) { nx = -nx; ny = -ny; }
      const nl = Math.hypot(nx, ny, nz);
      if (nl < 1e-9) { nx = 0; ny = side; } else { nx /= nl; ny /= nl; }
      const nb = r === 0 ? nF : [nx, ny, 0];
      const sol = edgeRow ? null : solAt(this.rowF(r));
      for (let c = 0; c < this.cols; c++) {
        const t = c / (this.cols - 1), i = this.ix(r, c);
        if (sol) profAtPar(A, B, nb, t, sol, P); else profAt(A, B, L, nb, t, P);
        this.dx[i] = P[0]; this.dy[i] = P[1]; this.dz[i] = P[2];
      }
    }
  }

  pattern(slack) {
    const s = this.sail, N = this.n;
    for (let r = 0; r < this.rows; r++) {
      const f = this.rowF(r), z = this.zLo + f * this.span;
      const d = sailSagAt(s, z, this.zLo, this.span);
      const lx = this.luffAt(z) + d * this.rnx, ly = z + d * this.rny;
      const chord = Math.max(0.02, this.luffAt(z) - this.leechAt(z));
      const W = chord * (1 + Math.max(0, slack[this.stripOf(r)]));
      this.rowW[r] = W;
      for (let c = 0; c < this.cols; c++) {
        const u = c / (this.cols - 1), i = this.ix(r, c);
        this.px[i] = lx - u * W; this.py[i] = ly;
      }
    }
    // Длины покоя и площади — с ПРОЕКТНОЙ ПОВЕРХНОСТИ, если крой трёхмерный, и
    // с плоской выкройки иначе. Ниже всё одинаково: и то, и другое — набор
    // точек, между которыми меряются расстояния.
    if (this.cut3d) this.design3d(slack);
    const X = this.cut3d ? this.dx : this.px;
    const Y = this.cut3d ? this.dy : this.py;
    const Z = this.cut3d ? this.dz : null;
    const dist = (a, b) => Z
      ? Math.hypot(X[a] - X[b], Y[a] - Y[b], Z[a] - Z[b])
      : Math.hypot(X[a] - X[b], Y[a] - Y[b]);
    for (let k = 0; k < this.ci.length; k++)
      this.rest[k] = dist(this.ci[k], this.cj[k]);
    // Масса узла — по площади поверхности вокруг него. Треугольник по трём
    // сторонам, формулой Герона: она годится и в плоскости, и в пространстве.
    const tri = (a, b, c) => {
      const p = dist(a, b), q = dist(b, c), r2 = dist(c, a);
      const sp = 0.5 * (p + q + r2);
      return Math.sqrt(Math.max(0, sp * (sp - p) * (sp - q) * (sp - r2)));
    };
    this.area.fill(0);
    for (let r = 0; r + 1 < this.rows; r++)
      for (let c = 0; c + 1 < this.cols; c++) {
        const a = this.ix(r, c), b = this.ix(r, c + 1), e = this.ix(r + 1, c), g = this.ix(r + 1, c + 1);
        const q = (tri(a, b, e) + tri(g, e, b)) / 4;
        this.area[a] += q; this.area[b] += q; this.area[e] += q; this.area[g] += q;
      }
    // Масса узла — ткань ПЛЮС ВОЗДУХ, и второе слагаемое больше первого в
    // десятки раз.
    //
    // Это не поправка на устойчивость, а недостающая физика. Пластина шириной c,
    // движущаяся поперёк себя, тащит с собой присоединённую массу ρ·π·c²/4 на
    // единицу размаха, то есть ρ·π·c/4 на единицу площади (классика тонкого
    // тела, тот же множитель, что у качки судна). При хорде три метра это 2.9
    // кг/м² против 0.045 кг/м² самой ткани. Сухая ткань в знаменателе давала
    // ускорение узла под шестьсот м/с² — за кадр узел пролетал полметра, и вся
    // возня с подшагами и предохранителями была возня с последствиями пропущенного
    // слагаемого. С воздухом выходит семь м/с², и подшаг нужен один.
    //
    // Оговорка: присоединённая масса направленная — поперёк полотна она есть, а
    // вдоль его почти нет, — здесь же она взята одинаковой по всем осям. Вдоль
    // полотна ткань и так держат связи, так что цена упрощения — только чуть
    // ленивое скольжение узла по поверхности.
    const rho = this.rhoAir;
    for (let i = 0; i < N; i++) {
      const c = this.rowW[Math.floor(i / this.cols)];
      const m = Math.max(1e-4, this.area[i] * (AREAL_KG + rho * Math.PI * c / 4));
      this.w[i] = 1 / m;
      this.mass[i] = m;
    }
    this.w[this.tack] = 0;
    this.w[this.head] = 0;
    if (!this.freeClew) this.w[this.clew] = 0;
  }

  // Начальное положение: полотно ставится туда, где его до сих пор рисовали, —
  // передняя шкаторина на предписанном провисе, строки по хорде под своим углом
  // выноса, без пуза. Это НЕ вторая форма паруса, а только точка, из которой
  // ткань сходится: ненатянутая строка под давлением сама выгибается в дугу за
  // несколько десятков проходов.
  seed(b) {
    const rig = b.rig, calc = rig.stripCalc, base = this.si * STRIPS;
    const side = b.rigSide == null ? 1 : b.rigSide;
    // ЕСТЬ КРОЙ — САДИМСЯ НА НЕГО. Это не ускорение сходимости, а выбор ВЕТВИ.
    //
    // У нерастяжимой сетки с закреплёнными углами изометрий много: одна и та же
    // ткань ложится и гладкой поверхностью, и сложенной вдвое, и давление само
    // по себе между ними не выбирает — оно только удерживает ту, в которой
    // полотно оказалось. Плоская затравка тем глубже крой, тем дальше от
    // настоящей формы, и решателю приходится искать выпуклость с нуля; на
    // полных курсах, где давления почти нет (тяга полоски 3…22 Н), он её не
    // находит и складывает полотно.
    //
    // Замер: при крое с пузом 0.26 на полувысоте и TWA 160° летящая хорда
    // падала с 3.43 до 1.15 м, пузо доходило до 0.71, а сечение шло НАЗАД по
    // хорде на 61 %. При том же крое и TWA 120…140° всё было цело — то есть
    // ломалось не от глубины самой по себе, а от глубины ПРИ СЛАБОМ давлении.
    //
    // Проектная поверхность у нас уже построена и уже служит источником длин
    // покоя. Сажать на неё же и начальное положение — не новая сущность, а
    // отказ от второй.
    if (this.cut3d && this.dx) {
      for (let i = 0; i < this.n; i++) {
        const k = i * 3;
        this.pos[k] = this.dx[i]; this.pos[k + 1] = this.dy[i]; this.pos[k + 2] = this.dz[i];
      }
      this.prev.set(this.pos);
      return;
    }
    for (let r = 0; r < this.rows; r++) {
      const f = this.rowF(r), z = this.zLo + f * this.span;
      const g = calc[base + this.stripOf(r)] || {};
      const set = g.set == null ? 0.7 : g.set;
      const chord = Math.max(0.02, this.luffAt(z) - this.leechAt(z));
      const sag = sailSagAt(this.sail, z, this.zLo, this.span) * side;
      const ux = -Math.cos(set), uy = Math.sin(set) * side;
      for (let c = 0; c < this.cols; c++) {
        const u = c / (this.cols - 1), i = this.ix(r, c) * 3;
        this.pos[i] = this.luffAt(z) + chord * u * ux;
        this.pos[i + 1] = sag + chord * u * uy;
        this.pos[i + 2] = z;
      }
    }
    this.prev.set(this.pos);
  }

  // Нормали, по которым давит поток: одна на строку.
  //
  // Давление на полотно идёт по нормали к НЕМУ, а не по назначенному
  // направлению: так устроена мембрана, и это не выбор.
  //
  // Мёртвая нагрузка — давление по нормали ПОЛОСКИ, той самой, с которой решётка
  // его посчитала, — пробовалась и отложена по ДОВОДУ, а не по замеру; так это и
  // надо читать. Довод: хорда полоски на бакштаге отклонена от ДП на шестьдесят
  // с лишним градусов, значит её нормаль на столько же отклонена от траверза и на
  // девять десятых смотрит ВПЕРЁД. Приложенная ко ВСЕЙ хорде, она размазывает
  // подсос передней кромки по всему полотну. Замер сегодня двух нагрузок не
  // разводит — обе упираются в негодный обвод (docs/gennaker-sota-plan.md, §Б2), —
  // и после его починки это надо перемерить.
  //
  // ОДНА НА СТРОКУ, а не на узел, и вот это уже замер. Нагрузка следящая, у
  // мембраны под ней равновесие мягкое, и понодальная нормаль даёт полотну мелкую
  // степень свободы, которой нечем распорядиться: на поставленном парусе размах
  // узла за пять секунд при замороженном входе 42 / 27 / 109 мм против
  // 502 / 267 / 205 мм у понодальной, на курсах 120 / 140 / 160°.
  //
  // Довод к тому же числу: решётка знает нагрузку по трём панелям хорды и шести
  // полоскам размаха, и разрешать НАПРАВЛЕНИЕ силы мельче, чем известна сама
  // сила, значит разрешать шум.
  rowNormals(wx, wy) {
    const p = this.pos, nr = this.nrm;
    for (let r = 0; r < this.rows; r++) {
      // Летящая хорда строки и направление вдоль передней шкаторины: их
      // векторное произведение и есть нормаль сечения.
      const a = this.ix(r, 0) * 3, b = this.ix(r, this.cols - 1) * 3;
      const rLo = Math.max(0, r - 1), rHi = Math.min(this.rows - 1, r + 1);
      const e = this.ix(rHi, 0) * 3, g = this.ix(rLo, 0) * 3;
      const tx = p[b] - p[a], ty = p[b + 1] - p[a + 1], tz = p[b + 2] - p[a + 2];
      const sx = p[e] - p[g], sy = p[e + 1] - p[g + 1], sz = p[e + 2] - p[g + 2];
      let nx = ty * sz - tz * sy, ny = tz * sx - tx * sz, nz = tx * sy - ty * sx;
      const L = Math.hypot(nx, ny, nz);
      if (L < 1e-9) { nx = 0; ny = wy; nz = 0; }
      else { nx /= L; ny /= L; nz /= L; }
      if (nx * wx + ny * wy < 0) { nx = -nx; ny = -ny; nz = -nz; }
      for (let c = 0; c < this.cols; c++) {
        const k = this.ix(r, c) * 3;
        nr[k] = nx; nr[k + 1] = ny; nr[k + 2] = nz;
      }
    }
  }

  // Шаг. Всё, что нужно ткани, берётся у лодки: давление и поток — у полосок,
  // длина шкота — у настройки, крен — у самой лодки.
  step(b, dt) {
    const rig = b.rig;
    if (!rig || rig.sails[this.si] !== this.sail) return false;
    const calc = rig.stripCalc, base = this.si * STRIPS;
    const env = b.p.environment;
    const side = b.rigSide == null ? 1 : b.rigSide;
    // Запас ткани по полоскам — тот же, из которого мембрана считает пузо.
    // Запас ткани по полоскам — ПО КРОЮ, а не по летящей дуге. Летящую даёт сама
    // ткань, и кормить её собственным ответом значит замкнуть петлю, единственная
    // неподвижная точка которой — плоский парус.
    const slack = new Array(STRIPS);
    for (let i = 0; i < STRIPS; i++) {
      const g = calc[base + i] || {};
      slack[i] = g.slackCut || g.slack || 0;
    }
    // Выкройка пересчитывается только когда меняется запас ткани, то есть на
    // ползунке пуза. Она стоит около четверти всей цены шага, а между кадрами
    // не меняется вовсе.
    let same = this.rhoAir === env.rho_air;
    if (same && this.slackWas) {
      for (let i = 0; i < STRIPS; i++)
        if (this.slackWas[i] !== slack[i]) { same = false; break; }
    } else same = false;
    // Крою нужны обмеры генакера и борт постановки: поверхность строится по
    // углам и шкаторинам, а они в пакете.
    const genPack = b.p.rig.gennaker;
    if (this.cut3d && (!genPack || !(genPack.leech_m > 0))) this.cut3d = false;
    this.gen = genPack;
    const wantSide = Math.sign(side || -1);
    if (this.cut3d && this.designSide !== wantSide) { this.designSide = wantSide; same = false; }
    if (!same) {
      this.rhoAir = env.rho_air;
      this.slackWas = slack.slice();
      this.pattern(slack);
    }
    // ШКОТОВЫЙ УГОЛ БЕРЁТСЯ У МОДЕЛИ, а не ищется тканью, и это не уступка.
    //
    // Шкот — связь односторонняя: он говорит, ДАЛЬШЕ КУДА НЕЛЬЗЯ, и не говорит,
    // где угол стоит. Где он стоит, решают вместе шкот и обе шкаторины, а
    // шкаторины — не ткань вообще, а два вполне определённых отрезка: их концы
    // закреплены на галсе и на фале. Пересечение трёх этих условий и есть
    // `gennakerClew` — окружность вокруг оси галс—фал, на ней точка по длине
    // шкота (шаг Б0′).
    //
    // Ткань со свободным углом решает ту же задачу хуже, и это померено: у неё
    // шкаторины провисают, угол уезжает к галсу (3.1 м при нижней 3.9), а
    // полотно уходит в незатухающее колебание с размахом до двух метров. С
    // прибитым углом то же полотно стоит, а нижняя строка совпадает с точной
    // дугой до трёх процентов. Прибить — значит добавить натянутость шкаторин,
    // которую ткань из одного давления не выводит.
    //
    // Побочно и важно: картинка и решётка сходятся в углах. Полотно между
    // углами ткань по-прежнему находит сама — это и есть то, чего у полосок нет.
    if (!this.freeClew &&
        this.si === 2 && b.p.rig.gennaker && b.p.rig.gennaker.clew_arc_r > 0) {
      const c = gennakerClew(b.o, b.p.rig.gennaker), k = this.clew * 3;
      this.pos[k] = c[0];
      this.pos[k + 1] = Math.abs(c[1]) * Math.sign(side || -1);
      this.pos[k + 2] = c[2];
    }
    if (!this.ready || this.rigRef !== rig) {
      this.rigRef = rig; this.ready = true;
      this.seed(b);
      // Первый заход: полотно приходит к равновесию сразу, а не на глазах у
      // зрителя. Сорок подшагов — это две трети секунды по внутреннему времени
      // ткани, за них она сходится полностью.
      for (let k = 0; k < 40; k++) this.advance(b, SUB_DT, side, env);
      return true;
    }
    const nSub = Math.max(1, Math.min(SUB_MAX, Math.ceil(dt / SUB_DT)));
    const h = dt / nSub;
    for (let k = 0; k < nSub; k++) this.advance(b, h, side, env);
    return true;
  }

  // Поставить полотно из дампа: узлы, их прежние положения и признак того, что
  // САЖАТЬ УЖЕ НЕ НАДО.
  //
  // Последнее и есть вся суть метода. Первый шаг ткани, не видя `ready`, сажает
  // полотно на крой и доводит сорока подшагами до равновесия — то есть стирает
  // восстановленное и ставит на его место форму, какую крой даёт сам по себе.
  // Ловилось это не как «дамп не встал», а как расхождение по углу атаки
  // полосок генакера в пятнадцать-двадцать пять градусов на первом же шаге.
  restore(pos, prev, rig) {
    if (!pos || pos.length !== this.pos.length) return false;
    this.pos.set(pos);
    this.prev.set(prev && prev.length === this.prev.length ? prev : pos);
    this.ready = true;
    this.rigRef = rig;
    return true;
  }

  ix(r, c) { return r * this.cols + c; }

  // Расстояние между узлами ПО КРОЮ — та самая мера, из которой взяты длины
  // покоя. У плоской выкройки это расстояние в её плоскости, у трёхмерного
  // кроя — на проектной поверхности. Отдаётся наружу, чтобы свидетели мерили
  // ткань той же мерой, какой она скроена, а не той, какая была раньше.
  matDist(i, j) {
    return this.cut3d
      ? Math.hypot(this.dx[i] - this.dx[j], this.dy[i] - this.dy[j],
                   this.dz[i] - this.dz[j])
      : Math.hypot(this.px[i] - this.px[j], this.py[i] - this.py[j]);
  }

  // Площадь ячеек полотна В ПОЛЁТЕ, разнесённая по узлам. Считается тем же
  // способом, что площадь выкройки в `pattern()`, — двумя треугольниками на
  // ячейку, — но по текущим положениям.
  flyingAreas() {
    const A = this._areaNow || (this._areaNow = new Float64Array(this.n));
    const p = this.pos;
    A.fill(0);
    for (let r = 0; r + 1 < this.rows; r++)
      for (let c = 0; c + 1 < this.cols; c++) {
        const a = this.ix(r, c), b = this.ix(r, c + 1),
              e = this.ix(r + 1, c), g = this.ix(r + 1, c + 1);
        const tri = (i, j, k) => {
          const ux = p[j * 3] - p[i * 3], uy = p[j * 3 + 1] - p[i * 3 + 1],
                uz = p[j * 3 + 2] - p[i * 3 + 2];
          const vx = p[k * 3] - p[i * 3], vy = p[k * 3 + 1] - p[i * 3 + 1],
                vz = p[k * 3 + 2] - p[i * 3 + 2];
          return 0.5 * Math.hypot(uy * vz - uz * vy, uz * vx - ux * vz,
                                  ux * vy - uy * vx);
        };
        const q = (tri(a, b, e) + tri(g, e, b)) / 4;
        A[a] += q; A[b] += q; A[e] += q; A[g] += q;
      }
    return A;
  }

  // Та же нагрузка, что в штатном шаге, доступна экспериментальному
  // проектору без повторной формулы давления и без перемещения узлов.
  forcesAt(b, h, side, env) {
    const calc = b.rig.stripCalc, base = this.si * STRIPS;
    const p = this.pos, pv = this.prev, f = this.frc, N = this.n;
    // Поток берётся у средней полоски: направление давления по высоте меняется
    // мало, а вот сторона у всего паруса одна.
    const mid = calc[base + Math.floor(STRIPS / 2)] || {};
    let wx = mid.d1 || 0, wy = mid.d2 || 0;
    if (Math.hypot(wx, wy) < 1e-6) { wx = -1; wy = 0; }
    this.rowNormals(wx, wy);
    // Тяжесть в осях рига: вдоль мачты и поперёк неё, по крену.
    const cp = Math.cos(b.phi), sp = Math.sin(b.phi);
    const gy = -env.g * sp, gz = -env.g * cp;
    f.fill(0);
    // ПЛОЩАДЬ ПОД ДАВЛЕНИЕМ — ПО ЛЕТЯЩИМ ПОЛОЖЕНИЯМ, а не по выкройке.
    //
    // Масса узла остаётся по крою, и это верно: сколько ткани сшито, столько её
    // и весит, как бы полотно ни лежало. А вот воздух давит на ту площадь,
    // которую полотно подставляет СЕЙЧАС. У натянутой ткани разницы почти нет
    // (27.90 м² кроя против 27.77 в полёте), но на слабине летящая площадь
    // меньше, и по выкройке самая смятая часть паруса нагружалась полной — ровно
    // там, где ошибка дороже всего.
    const area = this.flyingAreas();
    const st = b.rig.stripState;
    // Раскладка нагрузки по полоскам: сумма формы, сумма модулей и площадь.
    const raw = this._raw || (this._raw = new Float64Array(STRIPS));
    const absRaw = this._absRaw || (this._absRaw = new Float64Array(STRIPS));
    const aSum = this._aSum || (this._aSum = new Float64Array(STRIPS));
    const kShape = this._kShape || (this._kShape = new Float64Array(STRIPS));
    const kFlat = this._kFlat || (this._kFlat = new Float64Array(STRIPS));
    raw.fill(0); absRaw.fill(0); aSum.fill(0); kShape.fill(0); kFlat.fill(0);
    for (let r = 0; r < this.rows; r++) {
      const si = this.stripOf(r), g = calc[base + si];
      if (!g || !g.live || !g.q) continue;
      for (let c = 0; c < this.cols; c++) {
        const i = this.ix(r, c), u = c / (this.cols - 1);
        const kp = Math.min(NCHORD - 1, Math.floor(u * NCHORD));
        raw[si] += g.q[kp] * area[i];
        absRaw[si] += Math.abs(g.q[kp]) * area[i];
        aSum[si] += area[i];
      }
    }
    for (let si = 0; si < STRIPS; si++) {
      const g = calc[base + si], d = st[base + si];
      if (!g || !g.live || !d || !(aSum[si] > 0)) continue;
      // НАГРУЗКА СТРОКИ — ТА ЖЕ, ЧТО УХОДИТ В ЛОДКУ, и это не уточнение, а
      // сведение двух путей в один.
      //
      // Способ здесь менялся трижды, и каждый раз по замеру. Сперва стоял
      // `qd·(q[k]/peak)` — форма нагрузки по хорде, поделённая на свой максимум:
      // перепад давления выходил ровно 0.5·ρ·V² в пике ВСЕГДА, при любом угле и
      // любой циркуляции. Следящая сила постоянной величины по нормали к
      // деформируемой поверхности неконсервативна, и полотно от неё
      // САМОВОЗБУЖДАЛОСЬ: на замороженной лодке размах пуза 0.0798 держался
      // ровным с 28-й секунды до 60-й, с порогом по скорости ветра, как
      // положено флаттеру.
      //
      // Потом — Кутта—Жуковский, `Δp = ρ·V·Γ/Δx`. Флаттер это сняло (размах
      // 0.0001), но остался долг: из одной Γ восстанавливается только
      // ЦИРКУЛЯЦИОННАЯ часть нагрузки. Аудит переноса (`tests/cloth.test.mjs`)
      // показал цену: на бакштаге пути сходились до 4 %, а на полных курсах
      // расходились в разы и МЕНЯЛИ ЗНАК — при силе полоски +316 Н вдоль корпуса
      // ткань получала −80 Н. То есть на фордевинде полотно придавливалось
      // назад ровно там, где лодку тянет вперёд.
      //
      // Теперь полоска отдаёт полотну свою НОРМАЛЬНУЮ СИЛУ — ту самую, что
      // уходит в лодку, — а форму вдоль хорды полотно по-прежнему берёт из Γ.
      // Совпадение сумм тогда не свойство, а тождество: сколько лодка получила
      // поперёк паруса, столько полотно и надуло. У решётки остаётся
      // РАСПРЕДЕЛЕНИЕ, и только оно; величину даёт поляра со всеми поправками,
      // наклоном и доводчиком.
      //
      // Берётся проекция на нормаль, а не модуль: касательная доля силы (трение
      // вдоль полотна) мембрану не надувает.
      //
      // И проекция берётся НА ТУ ЖЕ НОРМАЛЬ, ВДОЛЬ КОТОРОЙ СИЛА ПОТОМ И
      // ПРИКЛАДЫВАЕТСЯ, — на нормаль самого полотна. Стояло иначе: проекция
      // считалась на нормаль к ХОРДЕ полоски, `[−sin cd, cos cd]`, а
      // прикладывалась вдоль `nrm`, которую `rowNormals` разворачивает ПО
      // ПОТОКУ. На одном галсе эти два направления совпадали, на другом
      // оказывались противоположны — и полотно получало давление НАОБОРОТ,
      // втягиваясь в зеркальную ветвь и оставаясь в ней: сила сама её и
      // удерживала.
      //
      // Глаз это увидел раньше стенда («на другом галсе выглядит лучше»),
      // потому что стенд ходил только одним галсом. Замер: на TWA −140° пузо
      // ткани и пузо, с которым считает аэродинамика, расходились на 180° по
      // всем шести полоскам (совпадение −1.00), при том что сам крой на обоих
      // галсах зеркален до градуса.
      //
      // Нормаль берётся одна на полоску — средняя по её строкам: сила полоски
      // тоже одна, и раскладывать её по строкам подробнее, чем она известна,
      // значит разрешать шум (тот же довод, что у `rowNormals`).
      let snx = 0, sny = 0, snz = 0;
      for (let r = 0; r < this.rows; r++) {
        if (this.stripOf(r) !== si) continue;
        const k = this.ix(r, 0) * 3;
        snx += this.nrm[k]; sny += this.nrm[k + 1]; snz += this.nrm[k + 2];
      }
      const snl = Math.hypot(snx, sny, snz) || 1;
      snx /= snl; sny /= snl;
      // Сила полоски приходит двумя числами — вдоль корпуса и поперёк мачты, —
      // третьего у неё нет, поэтому в скалярном произведении третьего слагаемого
      // тоже нет. А нормаль единичная ТРЁХМЕРНАЯ: только тогда `fn` это ровно
      // проекция на то направление, вдоль которого сила и прикладывается.
      //
      // Нормировать по одной горизонтной доле (`hypot(snx, sny)`) пробовали:
      // карта от этого выходила зелёной целиком, но это завышение — у верхних
      // полосок |nz|/|n| доходит до 0.52, то есть нагрузка задиралась на
      // 10…17 %. Отвергнуто: зелёная карта от завышенной нагрузки не свидетель.
      const fn = ((d.drive || 0) * snx + (d.side || 0) * sny);
      // Знакопеременная нагрузка по хорде: когда сумма мала против суммы
      // модулей, делить на неё нельзя — распределение вырождается и один узел
      // получает всё. Тогда нормальная сила раскладывается РАВНОМЕРНО по
      // площади: это честное «формы не знаем», а не подгонка.
      if (Math.abs(raw[si]) > 0.05 * absRaw[si]) kShape[si] = fn / raw[si];
      else kFlat[si] = fn / aSum[si];
    }
    // Сохраняется именно приложенная скалярная нагрузка. Аудит читает этот
    // буфер, а не восстанавливает её из q, обновившегося после шага ткани.
    const pressureForce = this.pressureForce && this.pressureForce.length === N
      ? this.pressureForce : (this.pressureForce = new Float64Array(N));
    pressureForce.fill(0);
    for (let r = 0; r < this.rows; r++) {
      const si = this.stripOf(r), g = calc[base + si];
      if (!g || !g.live || !g.q) continue;
      for (let c = 0; c < this.cols; c++) {
        const kp = Math.min(NCHORD - 1, Math.floor(c / (this.cols - 1) * NCHORD));
        const i = this.ix(r, c);
        pressureForce[i] = (kShape[si] * g.q[kp] + kFlat[si]) * area[i];
      }
    }
    // Явно включаемый опыт: локальный тонкий лист с интегралом силы из поляры.
    // Общая вихревая система от него новых вихрей не получает. В решётке
    // действует прежняя раскладка. Неприменимость видна по причине в профиле.
    this.localPressureProfiles = null;
    if (this.si === 2 && b.o.localPressure) {
      const profiles = this.localPressureProfiles = [];
      for (let r = 0; r < this.rows; r++) {
        const si = this.stripOf(r), g = calc[base + si];
        if (!g?.live || !b.rig.latOn || b.rig.latOn[base + si]) {
          profiles.push({ ok: false, reason: 'inactive-or-lattice' }); continue;
        }
        const profile = localPressureForRow({ pos: p, normals: this.nrm,
          area, pressureForce, row: r, cols: this.cols, strip: g, rho: this.rhoAir,
          panels: b.o.localPressure.panels || 16 });
        profiles.push(profile);
        if (profile.ok) pressureForce.set(pressureToNodes(profile, this.cols), this.ix(r, 0));
      }
    }
    // Приложенная нагрузка отдаётся наружу — для аудита переноса
    // (`tests/cloth.test.mjs`). Считать её потом по формуле значило бы завести
    // второй источник правды ровно там, где проверяется единственность первого.
    const L = this.load || (this.load = { fx: 0, fy: 0, fz: 0, mx: 0 });
    L.fx = 0; L.fy = 0; L.fz = 0; L.mx = 0;
    const cgz = b.p.mass.cg_m[2];
    for (let r = 0; r < this.rows; r++) {
      const si = this.stripOf(r), g = calc[base + si] || {};
      const live = !!g.live;
      const q = g.q;
      // Затухание по нормали: полотно, идущее поперёк себя со скоростью v,
      // встречает сопротивление порядка ρ·V·v на единицу площади — та же
      // линеаризация нестационарной подъёмной силы пластины, что даёт затухание
      // качки крыла. Множителя при ней нет: единица, и та из формулы.
      const cd = live ? this.rhoAir * g.ve : 0;
      for (let c = 0; c < this.cols; c++) {
        const i = this.ix(r, c), k = i * 3;
        // Тяжесть — по массе ТКАНИ, а не по массе с воздухом: присоединённая
        // масса весит ровно ноль. Перепутать их стоило одного прогона, в котором
        // парус повис в диаметральной плоскости мокрой тряпкой.
        const mg = this.area[i] * AREAL_KG;
        f[k + 1] += mg * gy; f[k + 2] += mg * gz;
        if (!live) continue;
        const nx = this.nrm[k], ny = this.nrm[k + 1], nz = this.nrm[k + 2];
        if (cd > 0) {
          const vx = (p[k] - pv[k]) / h, vy = (p[k + 1] - pv[k + 1]) / h,
                vz = (p[k + 2] - pv[k + 2]) / h;
          const vn = vx * nx + vy * ny + vz * nz;
          const dmp = -cd * vn * area[i];
          f[k] += dmp * nx; f[k + 1] += dmp * ny; f[k + 2] += dmp * nz;
        }
        if (!q) continue;
        const pr = pressureForce[i];
        // Давление — вдоль нормали СТРОКИ, хотя разложена сила по средней
        // нормали ПОЛОСКИ. Несовпадение видно в аудите переноса (до 11 % по
        // силе) и выглядит как повод прикладывать тоже по средней — тогда
        // сумма стала бы тождеством. Пробовали, отвергнуто по замеру:
        // положение максимума тяги против ORC уезжает с 0° на −24°, то есть
        // ломается главная проверка формы кривой. Строки внутри полоски
        // смотрят в разные стороны не от шума, а от твиста, и усреднять их
        // значит терять его.
        f[k] += pr * nx; f[k + 1] += pr * ny; f[k + 2] += pr * nz;
        L.fx += pr * nx; L.fy += pr * ny; L.fz += pr * nz;
        // Момент крена — в горизонтных осях и вокруг ЦТ, той же формулой, что у
        // полоски: два плеча, сила разложена по крену.
        const fy = -pr * nz * sp + pr * ny * cp;
        const fz = pr * nz * cp + pr * ny * sp;
        const Y = -p[k + 2] * sp + p[k + 1] * cp;
        const Z = p[k + 2] * cp + p[k + 1] * sp;
        L.mx += Y * fz - (Z - cgz) * fy;
      }
    }
  }

  advance(b, h, side, env) {
    this.forcesAt(b, h, side, env);
    const p = this.pos, pv = this.prev, f = this.frc, N = this.n;
    const damp = Math.exp(-DAMP_HZ * h);
    for (let i = 0; i < N; i++) {
      const w = this.w[i];
      if (w === 0) continue;
      const k = i * 3;
      for (let d = 0; d < 3; d++) {
        let v = (p[k + d] - pv[k + d]) / h * damp + f[k + d] * w * h;
        if (v > VMAX) v = VMAX; else if (v < -VMAX) v = -VMAX;
        pv[k + d] = p[k + d];
        p[k + d] += v * h;
      }
    }
    this.project(b, side);
    // Скорость наружу не выводится: её роль здесь только в предсказании, а
    // берётся она разностью положений, как и положено позиционной динамике.
  }

  // Проходы по связям.
  //
  // Связь ОДНОСТОРОННЯЯ: ребро тянет, когда растянуто, и не делает ничего,
  // когда сжато. Это и есть ткань — она мнётся, а не пружинит. Из этого же
  // само собой выходит пузо: строка длиннее хорды, под давлением она
  // натягивается по дуге, и длина дуги равна длине ткани — ровно то уравнение,
  // которое решает мембрана для сечения.
  // ФАЛОВАЯ ДОЩЕЧКА — ЖЁСТКАЯ ПЛАНКА, а не девять узлов ткани.
  //
  // Верхняя строка идёт по дощечке шириной 0.27 м, и сетка кладёт на неё те же
  // девять узлов, что и на нижнюю шкаторину в четыре с лишним метра: рёбра по
  // 3.4 см при вертикальных почти в метр, масса узла 117 г против 1684 г внизу.
  // Семь лишних степеней свободы у детали, у которой их две — положение и
  // поворот, — и на них полотно заламывалось: поворот хорды между двумя
  // верхними строками 57° при 1…7° по всему остальному парусу.
  //
  // Дощечка настоящая и жёсткая: это планка, вшитая в фаловый угол. Поэтому её
  // узлы не решаются, а САЖАЮТСЯ на отрезок между концами, каждый на своём
  // месте по выкройке. Концы при этом решаются как прежде: фаловый закреплён,
  // задний тянут задняя шкаторина и полотно. Ни одной новой постоянной.
  board() {
    const p = this.pos, R = this.rows - 1;
    const a = this.ix(R, 0) * 3, z = this.ix(R, this.cols - 1) * 3;
    const w = this.rowW[R];
    if (!(w > 1e-9)) return;
    for (let c = 1; c + 1 < this.cols; c++) {
      // Диагностический вариант: крой дощечки задаёт равные материальные
      // доли. `px` относится к плоской проекции и на 33 столбцах даёт
      // t=1.021 у предпоследнего узла, за задним концом дощечки. Но прямая
      // замена без перенастройки всей связанной задачи дала 13 % размах тяги
      // в штатной клетке, поэтому пока только явное включение в стенде.
      const t = this.boardMaterial ? c / (this.cols - 1)
        : (this.px[this.ix(R, 0)] - this.px[this.ix(R, c)]) / w;
      const k = this.ix(R, c) * 3;
      p[k] = p[a] + (p[z] - p[a]) * t;
      p[k + 1] = p[a + 1] + (p[z + 1] - p[a + 1]) * t;
      p[k + 2] = p[a + 2] + (p[z + 2] - p[a + 2]) * t;
    }
  }

  // Один проход по списку связей. `list` — либо все подряд, либо выборка верха.
  sweep(list, M) {
    const p = this.pos, ci = this.ci, cj = this.cj, ck = this.ck, rest = this.rest;
    for (let n = 0; n < M; n++) {
      const k = list ? list[n] : n;
      const a = ci[k] * 3, c = cj[k] * 3;
      const wa = this.w[ci[k]], wb = this.w[cj[k]];
      const s = wa + wb;
      if (s === 0) continue;
      const dx = p[c] - p[a], dy = p[c + 1] - p[a + 1], dz = p[c + 2] - p[a + 2];
      const d = Math.hypot(dx, dy, dz);
      if (d < 1e-9) continue;
      // Отрицательная жёсткость — метка двусторонней связи (излом): она и
      // тянет, и распирает. Все прочие односторонние: ткань мнётся.
      const kk = ck[k];
      if (kk > 0 && d <= rest[k]) continue;
      const g = OMEGA * Math.abs(kk) * (d - rest[k]) / d / s;
      p[a] += wa * g * dx; p[a + 1] += wa * g * dy; p[a + 2] += wa * g * dz;
      p[c] -= wb * g * dx; p[c + 1] -= wb * g * dy; p[c + 2] -= wb * g * dz;
    }
    this.board();
  }

  // ШКОТ — ОДНОСТОРОННЯЯ СВЯЗЬ ДО ОБУХА, а не посадка угла на дугу.
  //
  // Шкот говорит «дальше нельзя» и ничего не говорит о том, где угол стоит:
  // верёвка тянет и не толкает. Где угол стоит, решают вместе шкот, обе
  // шкаторины и давление, и решать это должна ткань.
  //
  // Прежде угол сажался на `gennakerClew` — окружность вокруг оси галс—фал, на
  // ней точка по длине шкота. Это МНОЖЕСТВО, где обе шкаторины натянуты РОВНО
  // в струну, то есть край допустимой области, а не вся она: у гибкой шкаторины
  // длиной L условие цело́сти — |A − B| ≤ L. Дуга запрещала всю слабину, то есть
  // ровно те состояния, ради которых заводится заворот и сложение.
  sheet(b, side) {
    const gen = b.p && b.p.rig && b.p.rig.gennaker;
    if (!gen || !gen.sheet_lead_m) return;
    const L = gennakerSheetLen(b.o, gen), lead = gen.sheet_lead_m;
    const lx = lead[0], ly = Math.abs(lead[1]) * Math.sign(side || -1), lz = lead[2];
    const k = this.clew * 3, p = this.pos;
    const dx = p[k] - lx, dy = p[k + 1] - ly, dz = p[k + 2] - lz;
    const d = Math.hypot(dx, dy, dz);
    if (!(d > L) || d < 1e-9) return;      // слабина — шкот не работает
    const g = (d - L) / d;
    p[k] -= g * dx; p[k + 1] -= g * dy; p[k + 2] -= g * dz;
  }

  project(b, side) {
    for (let it = 0; it < this.iter; it++) {
      this.sweep(null, this.ci.length);
      // Добавочные проходы по верху: вырожденные ячейки у дощечки сходятся
      // много медленнее прочих, а список их вчетверо короче общего.
      for (let j = 0; j < TOP_SWEEPS; j++) this.sweep(this.topIdx, this.topIdx.length);
      if (this.freeClew) this.sheet(b, side);
    }
  }

  // --- что ткань может сказать о себе -----------------------------------

  // Нормаль строки — наружу от полотна, по потоку. Ею отрисовка отклоняет
  // заполаскивающий пузырь: бить он обязан поперёк ткани, а не куда попало.
  rowNormal(r) {
    const k = this.ix(r, 0) * 3;
    return [this.nrm[k], this.nrm[k + 1], this.nrm[k + 2]];
  }

  // Точка поверхности на строке `rf` и доле `t` вдоль полотна. Строка ДРОБНАЯ:
  // полосок решётки шесть, строк одиннадцать, и границы полосок между строк не
  // ложатся. Между строками и столбцами — билинейная выборка: полотно гладкое, и
  // разрешать его мельче сетки узлов всё равно нечем.
  sample(rf, t, out) {
    const b = this.biAt(rf, t);
    const p = this.pos, a3 = b.a * 3, b3 = b.b * 3, e3 = b.e * 3, f3 = b.f * 3;
    for (let k = 0; k < 3; k++) {
      const lo = p[a3 + k] + (p[b3 + k] - p[a3 + k]) * b.v;
      const hi = p[e3 + k] + (p[f3 + k] - p[e3 + k]) * b.v;
      out[k] = lo + (hi - lo) * b.u;
    }
    return out;
  }

  // Та же точка, но на ПОВЕРХНОСТИ КРОЯ. Нужна затем, чтобы летящую форму было
  // с чем сравнить: крой — единственный эталон формы, который у нас есть весь,
  // а не по трём числам с фотографии.
  cutAt(rf, t, out) {
    const b = this.biAt(rf, t);
    const X = this.cut3d ? this.dx : this.px;
    const Y = this.cut3d ? this.dy : this.py;
    const Z = this.cut3d ? this.dz : null;
    const m = (V, d) => {
      if (!V) return d;
      const lo = V[b.a] + (V[b.b] - V[b.a]) * b.v;
      const hi = V[b.e] + (V[b.f] - V[b.e]) * b.v;
      return lo + (hi - lo) * b.u;
    };
    out[0] = m(X, 0); out[1] = m(Y, 0); out[2] = m(Z, 0);
    return out;
  }

  // Место выборки: четыре узла и два веса. Одно на обе поверхности — летящую и
  // кроя, — чтобы они мерились ровно в одних и тех же точках полотна.
  biAt(rf, t) {
    const o = this._bi || (this._bi = { a: 0, b: 0, e: 0, f: 0, u: 0, v: 0 });
    const y = Math.min(this.rows - 1, Math.max(0, rf));
    const r = Math.min(this.rows - 2, Math.floor(y));
    const x = Math.min(this.cols - 1, Math.max(0, t * (this.cols - 1)));
    const c = Math.min(this.cols - 2, Math.floor(x));
    o.u = y - r; o.v = x - c;
    o.a = this.ix(r, c); o.b = this.ix(r, c + 1);
    o.e = this.ix(r + 1, c); o.f = this.ix(r + 1, c + 1);
    return o;
  }

  // --- ФОРМА РАСПРАВЛЕННОГО СЕЧЕНИЯ ---------------------------------------------
  //
  // Числа, которыми парус меряет парусный мастер, плюс три числа про то,
  // расправлен ли он вообще. Методология и обоснование — docs/sail-shape.md.
  //
  // Первые пять описывают форму и сравниваются с кроем: хорда, пузо, место
  // пуза, вход, выход, азимут хорды (из азимутов получается твист).
  //
  // Последние три не нуждаются в эталоне вовсе: это СВОЙСТВА расправленного
  // сечения, и нарушить их может только складка.
  //
  //   ход назад   доля хорды, которую сечение проходит В ОБРАТНУЮ сторону.
  //               У расправленного паруса сечение однозначно над хордой:
  //               каждый шаг идёт от передней шкаторины к задней. Складка —
  //               единственный способ пойти назад, и она даёт число сразу.
  //   вывернуто   доля длины сечения, лежащая по ДРУГУЮ сторону хорды, чем
  //               пузо. У дуги таких точек нет ни одной.
  //   залом       наибольший угол между соседними звеньями и где он стоит.
  //               У дуги из восьми звеньев поворот на звено ровно один и тот
  //               же; всё, что заметно больше, — перегиб, а не дуга.
  rowShape(rf, cut) {
    const n = this.cols, P = [];
    for (let k = 0; k < n; k++) {
      const o = [0, 0, 0];
      if (cut) this.cutAt(rf, k / (n - 1), o); else this.sample(rf, k / (n - 1), o);
      P.push(o);
    }
    const A = P[0], B = P[n - 1];
    const ex = B[0] - A[0], ey = B[1] - A[1], ez = B[2] - A[2];
    const chord = Math.hypot(ex, ey, ez);
    const nil = { chord, camber: 0, draft: 0.5, entry: 0, exit: 0, bearing: 0,
                  back: 0, flip: 0, kink: 0, kinkAt: 0, arc: 0 };
    if (chord < 1e-6) return nil;
    const ux = ex / chord, uy = ey / chord, uz = ez / chord;
    // Отступ каждой точки от хорды и сторона, в которую смотрит пузо.
    const off = [], along = [];
    let sx = 0, sy = 0, sz = 0;
    for (let k = 0; k < n; k++) {
      const vx = P[k][0] - A[0], vy = P[k][1] - A[1], vz = P[k][2] - A[2];
      const t = vx * ux + vy * uy + vz * uz;
      const ox = vx - t * ux, oy = vy - t * uy, oz = vz - t * uz;
      along.push(t); off.push([ox, oy, oz]);
      sx += ox; sy += oy; sz += oz;
    }
    const sl = Math.hypot(sx, sy, sz) || 1;
    const nx = sx / sl, ny = sy / sl, nz = sz / sl;   // куда смотрит пузо
    // Пузо и его место — ровно как их мерила `rowCamber`: наибольшее удаление
    // от хорды. Менять здесь нечего, иначе разойдутся старые числа стенда.
    let best = 0, at = 0.5;
    for (let k = 1; k + 1 < n; k++) {
      const d = Math.hypot(off[k][0], off[k][1], off[k][2]);
      if (d > best) { best = d; at = along[k] / chord; }
    }
    // Ход назад, вывернутость, залом и длина дуги — по звеньям.
    let back = 0, flip = 0, arc = 0, kink = 0, kinkAt = 0;
    const dir = [];
    for (let k = 0; k + 1 < n; k++) {
      const dx = P[k + 1][0] - P[k][0], dy = P[k + 1][1] - P[k][1], dz = P[k + 1][2] - P[k][2];
      const L = Math.hypot(dx, dy, dz);
      arc += L;
      dir.push(L > 1e-9 ? [dx / L, dy / L, dz / L] : [ux, uy, uz]);
      const step = along[k + 1] - along[k];
      if (step < 0) back -= step;
      const mid = 0.5 * ((off[k][0] + off[k + 1][0]) * nx +
                         (off[k][1] + off[k + 1][1]) * ny +
                         (off[k][2] + off[k + 1][2]) * nz);
      if (mid < 0) flip += L;
    }
    for (let k = 0; k + 1 < dir.length; k++) {
      const d = Math.max(-1, Math.min(1, dir[k][0] * dir[k + 1][0] +
                                         dir[k][1] * dir[k + 1][1] +
                                         dir[k][2] * dir[k + 1][2]));
      const a = Math.acos(d);
      if (a > kink) { kink = a; kinkAt = along[k + 1] / chord; }
    }
    // Вход и выход — знаковые, и знак тут главное. Положительный значит «в
    // сторону пуза», как у нормальной дуги; отрицательный — кромка завёрнута на
    // наветренную сторону, то есть ровно то, что на парусе видно глазом как
    // заворот передней шкаторины или крюк задней.
    const ang = (d, sgn) => Math.atan2(d[0] * nx + d[1] * ny + d[2] * nz,
                                       sgn * (d[0] * ux + d[1] * uy + d[2] * uz));
    return {
      chord, camber: best / chord, draft: at, arc,
      entry: ang(dir[0], 1),
      exit: ang([-dir[n - 2][0], -dir[n - 2][1], -dir[n - 2][2]], -1),
      bearing: Math.atan2(ey, ex),
      back: back / chord, flip: flip / (arc || 1), kink, kinkAt,
    };
  }

  // Пузо строки: наибольшее отклонение от хорды, в долях хорды. Меряется тем
  // же, чем меряет себя мембрана, — иначе сравнивать их было бы не с чем.
  // Отдельного счёта здесь больше нет: это три поля из `rowShape`.
  rowCamber(rf) {
    const sh = this.rowShape(rf);
    return { camber: sh.camber, draft: sh.draft, chord: sh.chord };
  }

  // Провис передней шкаторины: наибольшее удаление её узлов от прямой галс—фал.
  luffSag() {
    const p = this.pos, a = this.tack * 3, b = this.head * 3;
    const ex = p[b] - p[a], ey = p[b + 1] - p[a + 1], ez = p[b + 2] - p[a + 2];
    const L = Math.hypot(ex, ey, ez) || 1;
    let best = 0, at = 0;
    for (let r = 1; r + 1 < this.rows; r++) {
      const i = this.ix(r, 0) * 3;
      const vx = p[i] - p[a], vy = p[i + 1] - p[a + 1], vz = p[i + 2] - p[a + 2];
      const t = (vx * ex + vy * ey + vz * ez) / (L * L);
      const dx = vx - t * ex, dy = vy - t * ey, dz = vz - t * ez;
      const d = Math.hypot(dx, dy, dz);
      if (d > best) { best = d; at = t; }
    }
    return { sag: best, at: at };
  }

  // Высота шкотового угла над галсом: тот самый признак с фотографий, по
  // которому бакштаговый спинакер и отличается от натянутого в ДП стакселя.
  clewRise() { return this.pos[this.clew * 3 + 2] - this.pos[this.tack * 3 + 2]; }
}
