// Ткань генакера: форма летящего паруса из равновесия полотна, а не из полосок.
//
// До этого нарисованный генакер собирался построчно: на каждой высоте бралась
// хорда из обвода, поворачивалась на угол выноса со скруткой и выгибалась пузом
// из мембраны. Поперёк хорд кривизны при этом не было НИКАКОЙ — поверхность
// выходила цилиндрической, — а шкотовый угол лежал на высоте галса, потому что
// нижняя шкаторина была отрезком в горизонтальной плоскости. У летящего паруса
// ни того, ни другого: объём, по которому спинакер и узнают, идёт от поперечной
// дуги между галсом и фалом, а шкотовый угол на бакштаге висит на метр с
// лишним выше галса (docs/gennaker-sota-plan.md, §Б0.3 и §Б0.4).
//
// Здесь полотно считается как полотно: сетка узлов, нерастяжимость по рёбрам,
// три закреплённых угла — галс, фал и шкотовый, — и давление из решётки. Где
// стоит шкотовый, решает не ткань, а геометрия шкаторин со шкотом; почему
// именно так, см. `step`. Форму находит позиционная динамика (Müller и др., 2007): предсказали
// положения по скорости и силам, потом несколько проходов подтянули каждое
// ребро к его длине. Она устойчива при любом шаге и не требует ни матрицы, ни
// жёсткости — а жёсткости у ткани и нет.
//
// ТКАНЬ ИДЁТ И В СИЛЫ (шаг Б3): по этому полотну решётка строит панели генакера,
// его точками схода сходит пелена, и его хорда задаёт угол атаки. Связь слабая,
// без итераций внутри шага — ткань берёт вчерашнее давление, решётка сегодняшнюю
// форму.
//
// Ради чего это всё. У прежнего горизонтального веера полосок задняя шкаторина
// выходила 10.7 м при скроенных 9.1 — на 17 % длиннее, чем на парусе есть ткани,
// то есть поверхность, на которой считались силы, сшить было нельзя. По ткани она
// выходит 8.7 м, и скрутка получается сама, обратного знака: верхние сечения
// приходят к диаметральной, потому что фал сидит на мачте, а шкотовый угол
// вынесен вбок. Промах модели по тяге против продувок падает при этом с 69 % до
// 39 % (docs/gennaker-sota-plan.md, «Б3 сделан»).

import { edgeFn, sailSagAt, STRIPS, NCHORD, gennakerClew,
         gennakerSheetLen } from './aero.js';

// Сетка ткани. Строк — как у отрисовки (SAIL_ROWS), чтобы полотно и обвод резались
// по одним и тем же высотам; столбцов девять при трёх панелях решётки, то есть
// по три узла на панель давления. Больше не нужно: нагрузка по хорде известна с
// точностью до трёх ступенек, и сгущать сетку значит уточнять то, чего во входе
// нет.
// Сетка ПО УМОЛЧАНИЮ. У экземпляра она своя (`opts.rows`, `opts.cols`), и
// вынесена наружу ровно затем же, ради чего вынесена жёсткость на излом: пока
// статическая форма не проверена на сгущении сетки, она не свойство модели, а
// свойство разрешения.
export const CLOTH_ROWS = 11;
export const CLOTH_COLS = 9;

// Проходов по связям за подшаг. Десять — из ряда 8…12, названного планом; на
// двадцати установившаяся форма отличается меньше чем на миллиметр.
// Проходов Гаусса — Зейделя за подшаг, и ПЕРЕСЛАБЛЕНИЕ при них.
//
// Десяти проходов НЕ ХВАТАЕТ, и это померено на неподвижной задаче: у решателя
// при каждом числе проходов своя неподвижная точка, потому что баланс встаёт
// там, где поправка за проход равна силе за подшаг. Летящая хорда на полувысоте
// выходит 3.39 м против 3.47 у вчетверо более густых проходов и 3.45 у
// сошедшегося решения; у фала 1.86 против 2.03 и 2.07.
//
// Видно это и глазом: у фала полотно ЗАЛАМЫВАЕТСЯ. Верхняя строка — дощечка в
// четверть метра — развёрнута к соседней на 57°, тогда как по всему остальному
// полотну поворот идёт по 1…7° на строку. На фотографиях настоящего SV20
// никакого залома нет, парус гладкий до самого фала. Залом уходит вместе с
// недоходом: 57° при десяти проходах, 42° при восьмидесяти, 32° при четырёхстах,
// 17.5° при четырёхстах с переслаблением 1.9 — и твист самого полотна падает с
// 27° до 2°.
//
// ПОЧЕМУ ЗДЕСЬ ВСЁ ЖЕ ДЕСЯТЬ И ЕДИНИЦА. Сходимость стоит не только времени.
// Переслабление 1.9 (устойчиво, вдвое сокращает проходы, улучшает все
// собственные числа ткани: растяжение 0.32 -> 0.15 %, дуга/ткань 0.984 -> 0.990,
// совпадение с точной дугой 4.4 -> 2.9 %) РАЗНОСИТ связанную систему на
// TWA 110°: клетка карты 99 % против нуля, качка 4.7°. Двадцать проходов с ним
// же — 58 %, и боковая к тяге у эталона ORC уезжает с 0.46 на 0.58.
//
// То есть нынешняя связка «ткань — решётка» устойчива только на НЕСОШЕДШЕЙСЯ
// ткани, и это куда более серьёзное утверждение, чем сам недоход. Менять
// настройку, не разобравшись с этим, значит менять видимый залом на невидимую
// раскачку. Оба числа — ворота стенда (`tests/cloth.test.mjs`), оба сейчас
// красные, и оба держат шаг В1 открытым.
export const CLOTH_ITER = 10;
// СВОБОДНЫЙ ШКОТОВЫЙ УГОЛ — вариант шага В2, и пока он ВЫКЛЮЧЕН.
//
// Сам шкот сделан как ему и положено: односторонняя связь до обуха (`sheet`
// ниже), длина выдерживается в точности при натяжении, слабина разрешена. Это
// половина ворот В2, и она взята.
//
// Со свободным углом полотно, однако, разваливается ровно так же, как в первом
// заходе: шкотовый угол уходит к оси галс—фал (1.22 м при шкоте 7.5 против
// 3.61 у дуги), на замороженной лодке ткань не приходит в покой (размах пуза
// 0.122 при пороге 0.01, отношение конца к началу 0.90), карта даёт 24 красных
// клетки из 36 при худшей 275 % и качке до 75.7°, эталон ORC разваливается по
// спаду к фордевинду (0.30 против 0.57).
//
// Причина на этот раз НАЙДЕНА И ПОМЕРЕНА, и она не в шкоте. У полотна
// шкаторины не той длины, что объявлены в крое:
//
//     шкаторина   у выкройки   в крое   расхождение
//     нижняя        4.292      3.890     +10.3 %
//     задняя        8.668      9.141      −5.2 %
//     передняя      9.783      9.787      −0.0 %
//
// Пока угол был прибит к дуге, это ничего не решало — его ставила дуга. Свободный
// угол держат ровно шкот и две шкаторины, и с нижней на десятую часть длиннее
// настоящей ему и вправду некуда деваться, кроме как уехать к галсу.
//
// Поэтому В2 упирается в В1: «шкаторины — гибкие границы С ДЛИНОЙ ПО ТКАНИ».
// Пока длины не сойдутся, свободный угол включать нельзя. Ворота на это заведены
// (`tests/cloth.test.mjs`), и они красные.
const FREE_CLEW = false;
const TOP_SWEEPS = 4;
const ITER = CLOTH_ITER;
const OMEGA = 1;

// Жёсткость диагоналей относительно рёбер. Ткань тянется вдоль нитей плохо, а
// перекашивается легко — на этом и держится крой парусов: одно и то же полотно
// по косой ложится совсем иначе, чем по основе. Величина — ОЦЕНКА; ноль
// оставил бы строки независимыми друг от друга, то есть вернул бы цилиндр,
// единица сделала бы полотно жестью.
const SHEAR = 0.3;

// Жёсткость на излом, в долях от жёсткости рёбер. Записывается ОТРИЦАТЕЛЬНОЙ
// жёсткостью — так помечена двусторонняя связь.
//
// Без неё ткань складывается, и это не мелочь картинки: лишняя длина строки
// уходила не в пузо, а в гармошку — дуга/ткань 0.85…0.91 по всем средним
// строкам, а сверху полотно читалось зигзагом. Настоящая ткань так не делает:
// у неё есть своя жёсткость на изгиб, малая, но не нулевая, и складка у
// спинакера получается плавной.
//
// Величина — ОЦЕНКА, и порог у неё пологий: 0.02 уже распрямляет (дуга/ткань
// 0.99), 0.05 доводит до 1.000, 0.4 ничего не добавляет. Взята наименьшая из
// уверенно работающих.
const BEND = 0.05;

// Поверхностная плотность, кг/м². Спинакерный нейлон 0.75 унции на квадратный
// ярд это 25 г/м²; со швами, лентами и усилениями берётся вдвое.
const AREAL_KG = 0.045;

// Затухание скорости, 1/с. Затухание от воздуха считается отдельно и по формуле
// (см. ниже, поперёк полотна); это — общее, по всем осям, и оно назначено. Без
// него полотно не стоит: размах узла за пять секунд 4.4 м и растяжение 3.05 %
// против 0.75 м и 0.55 % при шестёрке. Двадцатка не лучше шестёрки (0.56 м,
// 0.50 %), так что величина взята наименьшей из работающих.
const DAMP_HZ = 6;

// Наибольший шаг подшага, с. С присоединённой массой воздуха ускорение узла
// порядка десятка м/с², и хватило бы одного подшага на кадр; два берутся по
// замеру на ходу: размах узла за пять секунд 7.6 см при одном подшаге против
// 3.1 см при двух, а стоит это 0.13 против 0.23 мс на шаг.
const SUB_DT = 1 / 60;
const SUB_MAX = 4;

// Наибольшая скорость узла, м/с. Предохранитель, а не модель: он срабатывает
// только на разрыве — подъём паруса, перекладка, — и на установившемся режиме
// молчит.
const VMAX = 12;


export class Cloth {
  // `opts.bend` — жёсткость на излом. Наружу вынесена ради стенда: при нуле
  // натянутая строка обязана быть в точности равномерно нагруженной нитью, и
  // тогда решатель можно сверить с теорией, а не с самим собой.
  constructor(sail, si, opts) {
    this.sail = sail;
    this.si = si;
    this.bend = opts && opts.bend != null ? opts.bend : BEND;
    // Сетка и число проходов — у экземпляра, чтобы стенд мог их сгустить.
    this.rows = opts && opts.rows ? opts.rows : CLOTH_ROWS;
    this.cols = opts && opts.cols ? opts.cols : CLOTH_COLS;
    this.iter = opts && opts.iter ? opts.iter : ITER;
    this.freeClew = opts && opts.freeClew != null ? opts.freeClew : FREE_CLEW;
    this.rigRef = null;
    this.nRows = this.rows;
    const N = this.rows * this.cols;
    this.n = N;
    this.pos = new Float64Array(N * 3);
    this.prev = new Float64Array(N * 3);
    this.frc = new Float64Array(N * 3);
    this.w = new Float64Array(N);        // обратная масса; ноль — закреплён
    this.nrm = new Float64Array(N * 3);
    // Выкройка: плоский кусок ткани, из которого парус сшит. Все длины покоя
    // берутся из неё, и потому они между собой согласованы — что для куска
    // ткани и обязательно.
    this.px = new Float64Array(N);
    this.py = new Float64Array(N);
    this.area = new Float64Array(N);     // доля площади выкройки на узел
    this.mass = new Float64Array(N);
    this.rowW = new Float64Array(this.rows);   // ширина строки в выкройке
    this.rhoAir = 1.225;
    // Связи: пары узлов, длина покоя и жёсткость. Топология постоянна, длины
    // пересчитываются каждый шаг — запас ткани ходит за ползунком пуза.
    const ci = [], cj = [], ck = [];
    for (let r = 0; r < this.rows; r++)
      for (let c = 0; c + 1 < this.cols; c++) { ci.push(this.ix(r, c)); cj.push(this.ix(r, c + 1)); ck.push(1); }
    for (let r = 0; r + 1 < this.rows; r++)
      for (let c = 0; c < this.cols; c++) { ci.push(this.ix(r, c)); cj.push(this.ix(r + 1, c)); ck.push(1); }
    for (let r = 0; r + 1 < this.rows; r++)
      for (let c = 0; c + 1 < this.cols; c++) {
        ci.push(this.ix(r, c)); cj.push(this.ix(r + 1, c + 1)); ck.push(SHEAR);
        ci.push(this.ix(r, c + 1)); cj.push(this.ix(r + 1, c)); ck.push(SHEAR);
      }
    // ПОВОДКИ ОТ ЗАКРЕПЛЁННЫХ УГЛОВ. Не выдумка и не жёсткость: у нерастяжимой
    // ткани расстояние между двумя точками В ПРОСТРАНСТВЕ не может превысить
    // расстояние между ними В ВЫКРОЙКЕ. Выкройка выпукла (передняя шкаторина
    // выгнута вперёд, задняя в корму, нижняя прямая), поэтому по ней кратчайший
    // путь — прямая, и её длина и есть верхний предел. То есть поводок это то же
    // самое условие нерастяжимости, только записанное сразу, а не набранное
    // цепочкой рёбер.
    //
    // Без них сходимости нет, и это померено. У фала полотно сходится к
    // дощечке шириной 0.25 м, а соседняя строка шире метра: верхняя ячейка —
    // лучина, её рёбра по 3 см при вертикальных по метру. Гаусс — Зейдель на
    // таком отношении ползёт: за десять проходов верхняя строка растянута в
    // ШЕСТЬ раз, за сто двадцать проходов при вчетверо мельче подшаге — всё ещё
    // на 23 %, и стоит это шесть миллисекунд на шаг вместо трети. С поводками
    // хватает десяти (Kim и др., long-range attachments — тот же приём).
    // ЖЁСТКОСТЬ НА ИЗЛОМ. Связь через ячейку: расстояние между узлами c−1 и c+1
    // при сложенной вдвое ткани падает почти до нуля, при расправленной равно
    // длине по выкройке. Двусторонняя, в отличие от всех прочих: складку надо
    // распрямлять, а не только не давать тянуть.
    if (this.bend > 0) {
      for (let r = 0; r < this.rows; r++)
        for (let c = 1; c + 1 < this.cols; c++) {
          ci.push(this.ix(r, c - 1)); cj.push(this.ix(r, c + 1)); ck.push(-this.bend);
        }
      for (let r = 1; r + 1 < this.rows; r++)
        for (let c = 0; c < this.cols; c++) {
          ci.push(this.ix(r - 1, c)); cj.push(this.ix(r + 1, c)); ck.push(-this.bend);
        }
    }
    // Отвергнуто: поводки ещё и от ШКОТОВОГО угла. Он закреплён наравне с галсом
    // и фалом, условие нерастяжимости от него такое же, и на сходимость они
    // должны были работать — а не работают вовсе: летящая хорда на полувысоте
    // 3.18 м против 3.17 без них, при восьмипроцентном недоходе до сошедшегося
    // решения. Четверть лишних связей задаром (`docs/wake.md`, В1).
    for (let r = 0; r < this.rows; r++)
      for (let c = 0; c < this.cols; c++) {
        const i = this.ix(r, c);
        if (i !== this.ix(0, 0)) { ci.push(this.ix(0, 0)); cj.push(i); ck.push(1); }
        if (i !== this.ix(this.rows - 1, 0)) { ci.push(this.ix(this.rows - 1, 0)); cj.push(i); ck.push(1); }
      }
    this.ci = Int32Array.from(ci);
    this.cj = Int32Array.from(cj);
    this.ck = Float64Array.from(ck);
    // СВЯЗИ ВЕРХА — отдельным списком, для добавочных проходов по ним.
    //
    // Верх паруса сходится много медленнее низа, и это померено: при десяти
    // проходах задняя шкаторина у фала слаба на 2.2 %, верхние строки на 1.6 %,
    // и на этой слабине фаловая дощечка разворачивается к полотну на 49°. При
    // четырёхстах проходах всё натянуто в ноль, а залом падает до 19°.
    //
    // Причина — вырождение сетки: ширина строки падает с 4.29 м у нижней
    // шкаторины до 0.27 м у дощечки, рёбра строки становятся по 3.4 см при
    // вертикальных под метр, а масса узла — 117 г против 1684 г. По таким
    // связям Гаусс — Зейдель ползёт, и общие проходы тратятся в основном на
    // низ, который сошёлся давно.
    //
    // Поэтому верх доводится ОТДЕЛЬНО: те же связи, тот же проектор, просто
    // лишние проходы по четверти списка. Цена — доли миллисекунды вместо
    // сорокакратной.
    const top = this.rows - 1 - Math.max(2, Math.round((this.rows - 1) * 0.3));
    const ti = [];
    for (let k = 0; k < ci.length; k++) {
      const r = Math.max(Math.floor(ci[k] / this.cols), Math.floor(cj[k] / this.cols));
      if (r >= top) ti.push(k);
    }
    this.topIdx = Int32Array.from(ti);
    this.rest = new Float64Array(ci.length);
    this.luffAt = edgeFn(sail.luff);
    this.leechAt = edgeFn(sail.leech);
    this.zLo = Math.max(sail.tack[1], sail.clew[1]);
    this.zHi = Math.min(sail.head[1], sail.head_aft[1]);
    this.span = this.zHi - this.zLo;
    // Нормаль к прямой галс—фал в плоскости выкройки, наружу от паруса: по ней
    // откладывается серп передней шкаторины.
    const dx = sail.head[0] - sail.tack[0], dz = sail.head[1] - sail.tack[1];
    const L = Math.hypot(dx, dz) || 1;
    this.rnx = dz / L; this.rny = -dx / L;
    this.ready = false;
    this.tmpA = [0, 0, 0]; this.tmpB = [0, 0, 0]; this.tmpC = [0, 0, 0];
    this.clew = this.ix(0, this.cols - 1);
    this.tack = this.ix(0, 0);
    this.head = this.ix(this.rows - 1, 0);
  }

  // Высота строки над нижней шкаториной, в долях размаха.
  //
  // Отвергнуто: СГУЩАТЬ строки к фалу. Довод был хорош — у дощечки полотно
  // сходится к четверти метра, а шаг по высоте остаётся метровым, и верхняя
  // ячейка выходит лучиной 3 см на метр, на которой Гаусс — Зейдель ползёт.
  // Померено при `1 − (1 − u)^p`: недоход хорды на полувысоте до сошедшегося
  // решения 1.2 % при p = 1, 5 % при p = 1.5, 7 % при p = 2. Сгущение
  // сходимость УХУДШАЕТ: строк внизу становится меньше, а выигрыш наверху его не
  // окупает (`docs/wake.md`, В1).
  rowF(r) { return r / (this.rows - 1); }

  // Полоска, чьё давление и чей поток берёт строка. Тот же выбор ближайшей,
  // что у отрисовки: полосок шесть, строк одиннадцать.
  stripOf(r) { return Math.min(STRIPS - 1, Math.round(this.rowF(r) * (STRIPS - 1))); }

  // Выкройка.
  //
  // Плоский контур паруса и есть готовая выкройка — ломаные шкаторин сняты в
  // диаметральной плоскости, то есть уже плоские. К ней добавляются ровно две
  // вещи, и обе уже есть в модели:
  //
  //   * запас ткани по хорде — тот же `slack`, из которого мембрана считает
  //     пузо. Строка выкройки шире хорды ровно на него;
  //
  //   * серп передней шкаторины — уложенный в плоскость выкройки ПРЕДПИСАННЫЙ
  //     провис (`sailSagAt`). Это не совпадение и не хитрость: провис в полёте
  //     и есть та ткань, которой шкаторина длиннее прямой галс—фал, и другого
  //     источника длины у неё нет. Пока провис назначен постоянной 0.13, серп
  //     наследует это допущение целиком; шаг Б1 заменит его кроем, и тогда
  //     стрелка провиса станет СЛЕДСТВИЕМ, а не входом.
  //
  // Замер, ради которого это здесь и записано: 0.13 длины шкаторины провиса
  // дают дугу на 4.4 % длиннее прямой, то есть серп 0.134 её длины. План Б1
  // оценивает LUFF_ROUND_K в 0.10…0.12, ничего о провисе не зная, — два
  // независимых конца сошлись.
  pattern(slack) {
    const s = this.sail, N = this.n;
    for (let r = 0; r < this.rows; r++) {
      const f = this.rowF(r), z = this.zLo + f * this.span;
      const d = sailSagAt(s, z, this.zLo, this.span);
      const lx = this.luffAt(z) + d * this.rnx, ly = z + d * this.rny;
      const chord = Math.max(0.02, this.luffAt(z) - this.leechAt(z));
      const W = chord * (1 + Math.max(0, slack[this.stripOf(r)]));
      this.rowW[r] = W;
      for (let c = 0; c < this.cols; c++) {
        const u = c / (this.cols - 1), i = this.ix(r, c);
        this.px[i] = lx - u * W; this.py[i] = ly;
      }
    }
    for (let k = 0; k < this.ci.length; k++) {
      const a = this.ci[k], b = this.cj[k];
      this.rest[k] = Math.hypot(this.px[a] - this.px[b], this.py[a] - this.py[b]);
    }
    // Масса узла — по площади выкройки вокруг него.
    this.area.fill(0);
    for (let r = 0; r + 1 < this.rows; r++)
      for (let c = 0; c + 1 < this.cols; c++) {
        const a = this.ix(r, c), b = this.ix(r, c + 1), e = this.ix(r + 1, c), g = this.ix(r + 1, c + 1);
        const ax = this.px[b] - this.px[a], ay = this.py[b] - this.py[a];
        const bx = this.px[e] - this.px[a], by = this.py[e] - this.py[a];
        const s1 = Math.abs(ax * by - ay * bx) / 2;
        const cx = this.px[b] - this.px[g], cy = this.py[b] - this.py[g];
        const dx2 = this.px[e] - this.px[g], dy2 = this.py[e] - this.py[g];
        const s2 = Math.abs(cx * dy2 - cy * dx2) / 2;
        const q = (s1 + s2) / 4;
        this.area[a] += q; this.area[b] += q; this.area[e] += q; this.area[g] += q;
      }
    // Масса узла — ткань ПЛЮС ВОЗДУХ, и второе слагаемое больше первого в
    // десятки раз.
    //
    // Это не поправка на устойчивость, а недостающая физика. Пластина шириной c,
    // движущаяся поперёк себя, тащит с собой присоединённую массу ρ·π·c²/4 на
    // единицу размаха, то есть ρ·π·c/4 на единицу площади (классика тонкого
    // тела, тот же множитель, что у качки судна). При хорде три метра это 2.9
    // кг/м² против 0.045 кг/м² самой ткани. Сухая ткань в знаменателе давала
    // ускорение узла под шестьсот м/с² — за кадр узел пролетал полметра, и вся
    // возня с подшагами и предохранителями была возня с последствиями пропущенного
    // слагаемого. С воздухом выходит семь м/с², и подшаг нужен один.
    //
    // Оговорка: присоединённая масса направленная — поперёк полотна она есть, а
    // вдоль его почти нет, — здесь же она взята одинаковой по всем осям. Вдоль
    // полотна ткань и так держат связи, так что цена упрощения — только чуть
    // ленивое скольжение узла по поверхности.
    const rho = this.rhoAir;
    for (let i = 0; i < N; i++) {
      const c = this.rowW[Math.floor(i / this.cols)];
      const m = Math.max(1e-4, this.area[i] * (AREAL_KG + rho * Math.PI * c / 4));
      this.w[i] = 1 / m;
      this.mass[i] = m;
    }
    this.w[this.tack] = 0;
    this.w[this.head] = 0;
    if (!this.freeClew) this.w[this.clew] = 0;
  }

  // Начальное положение: полотно ставится туда, где его до сих пор рисовали, —
  // передняя шкаторина на предписанном провисе, строки по хорде под своим углом
  // выноса, без пуза. Это НЕ вторая форма паруса, а только точка, из которой
  // ткань сходится: ненатянутая строка под давлением сама выгибается в дугу за
  // несколько десятков проходов.
  seed(b) {
    const rig = b.rig, calc = rig.stripCalc, base = this.si * STRIPS;
    const side = b.rigSide == null ? 1 : b.rigSide;
    for (let r = 0; r < this.rows; r++) {
      const f = this.rowF(r), z = this.zLo + f * this.span;
      const g = calc[base + this.stripOf(r)] || {};
      const set = g.set == null ? 0.7 : g.set;
      const chord = Math.max(0.02, this.luffAt(z) - this.leechAt(z));
      const sag = sailSagAt(this.sail, z, this.zLo, this.span) * side;
      const ux = -Math.cos(set), uy = Math.sin(set) * side;
      for (let c = 0; c < this.cols; c++) {
        const u = c / (this.cols - 1), i = this.ix(r, c) * 3;
        this.pos[i] = this.luffAt(z) + chord * u * ux;
        this.pos[i + 1] = sag + chord * u * uy;
        this.pos[i + 2] = z;
      }
    }
    this.prev.set(this.pos);
  }

  // Нормали, по которым давит поток: одна на строку.
  //
  // Давление на полотно идёт по нормали к НЕМУ, а не по назначенному
  // направлению: так устроена мембрана, и это не выбор.
  //
  // Мёртвая нагрузка — давление по нормали ПОЛОСКИ, той самой, с которой решётка
  // его посчитала, — пробовалась и отложена по ДОВОДУ, а не по замеру; так это и
  // надо читать. Довод: хорда полоски на бакштаге отклонена от ДП на шестьдесят
  // с лишним градусов, значит её нормаль на столько же отклонена от траверза и на
  // девять десятых смотрит ВПЕРЁД. Приложенная ко ВСЕЙ хорде, она размазывает
  // подсос передней кромки по всему полотну. Замер сегодня двух нагрузок не
  // разводит — обе упираются в негодный обвод (docs/gennaker-sota-plan.md, §Б2), —
  // и после его починки это надо перемерить.
  //
  // ОДНА НА СТРОКУ, а не на узел, и вот это уже замер. Нагрузка следящая, у
  // мембраны под ней равновесие мягкое, и понодальная нормаль даёт полотну мелкую
  // степень свободы, которой нечем распорядиться: на поставленном парусе размах
  // узла за пять секунд при замороженном входе 42 / 27 / 109 мм против
  // 502 / 267 / 205 мм у понодальной, на курсах 120 / 140 / 160°.
  //
  // Довод к тому же числу: решётка знает нагрузку по трём панелям хорды и шести
  // полоскам размаха, и разрешать НАПРАВЛЕНИЕ силы мельче, чем известна сама
  // сила, значит разрешать шум.
  rowNormals(wx, wy) {
    const p = this.pos, nr = this.nrm;
    for (let r = 0; r < this.rows; r++) {
      // Летящая хорда строки и направление вдоль передней шкаторины: их
      // векторное произведение и есть нормаль сечения.
      const a = this.ix(r, 0) * 3, b = this.ix(r, this.cols - 1) * 3;
      const rLo = Math.max(0, r - 1), rHi = Math.min(this.rows - 1, r + 1);
      const e = this.ix(rHi, 0) * 3, g = this.ix(rLo, 0) * 3;
      const tx = p[b] - p[a], ty = p[b + 1] - p[a + 1], tz = p[b + 2] - p[a + 2];
      const sx = p[e] - p[g], sy = p[e + 1] - p[g + 1], sz = p[e + 2] - p[g + 2];
      let nx = ty * sz - tz * sy, ny = tz * sx - tx * sz, nz = tx * sy - ty * sx;
      const L = Math.hypot(nx, ny, nz);
      if (L < 1e-9) { nx = 0; ny = wy; nz = 0; }
      else { nx /= L; ny /= L; nz /= L; }
      if (nx * wx + ny * wy < 0) { nx = -nx; ny = -ny; nz = -nz; }
      for (let c = 0; c < this.cols; c++) {
        const k = this.ix(r, c) * 3;
        nr[k] = nx; nr[k + 1] = ny; nr[k + 2] = nz;
      }
    }
  }

  // Шаг. Всё, что нужно ткани, берётся у лодки: давление и поток — у полосок,
  // длина шкота — у настройки, крен — у самой лодки.
  step(b, dt) {
    const rig = b.rig;
    if (!rig || rig.sails[this.si] !== this.sail) return false;
    const calc = rig.stripCalc, base = this.si * STRIPS;
    const env = b.p.environment;
    const side = b.rigSide == null ? 1 : b.rigSide;
    // Запас ткани по полоскам — тот же, из которого мембрана считает пузо.
    // Запас ткани по полоскам — ПО КРОЮ, а не по летящей дуге. Летящую даёт сама
    // ткань, и кормить её собственным ответом значит замкнуть петлю, единственная
    // неподвижная точка которой — плоский парус.
    const slack = new Array(STRIPS);
    for (let i = 0; i < STRIPS; i++) {
      const g = calc[base + i] || {};
      slack[i] = g.slackCut || g.slack || 0;
    }
    // Выкройка пересчитывается только когда меняется запас ткани, то есть на
    // ползунке пуза. Она стоит около четверти всей цены шага, а между кадрами
    // не меняется вовсе.
    let same = this.rhoAir === env.rho_air;
    if (same && this.slackWas) {
      for (let i = 0; i < STRIPS; i++)
        if (this.slackWas[i] !== slack[i]) { same = false; break; }
    } else same = false;
    if (!same) {
      this.rhoAir = env.rho_air;
      this.slackWas = slack.slice();
      this.pattern(slack);
    }
    // ШКОТОВЫЙ УГОЛ БЕРЁТСЯ У МОДЕЛИ, а не ищется тканью, и это не уступка.
    //
    // Шкот — связь односторонняя: он говорит, ДАЛЬШЕ КУДА НЕЛЬЗЯ, и не говорит,
    // где угол стоит. Где он стоит, решают вместе шкот и обе шкаторины, а
    // шкаторины — не ткань вообще, а два вполне определённых отрезка: их концы
    // закреплены на галсе и на фале. Пересечение трёх этих условий и есть
    // `gennakerClew` — окружность вокруг оси галс—фал, на ней точка по длине
    // шкота (шаг Б0′).
    //
    // Ткань со свободным углом решает ту же задачу хуже, и это померено: у неё
    // шкаторины провисают, угол уезжает к галсу (3.1 м при нижней 3.9), а
    // полотно уходит в незатухающее колебание с размахом до двух метров. С
    // прибитым углом то же полотно стоит, а нижняя строка совпадает с точной
    // дугой до трёх процентов. Прибить — значит добавить натянутость шкаторин,
    // которую ткань из одного давления не выводит.
    //
    // Побочно и важно: картинка и решётка сходятся в углах. Полотно между
    // углами ткань по-прежнему находит сама — это и есть то, чего у полосок нет.
    if (!this.freeClew &&
        this.si === 2 && b.p.rig.gennaker && b.p.rig.gennaker.clew_arc_r > 0) {
      const c = gennakerClew(b.o, b.p.rig.gennaker), k = this.clew * 3;
      this.pos[k] = c[0];
      this.pos[k + 1] = Math.abs(c[1]) * Math.sign(side || -1);
      this.pos[k + 2] = c[2];
    }
    if (!this.ready || this.rigRef !== rig) {
      this.rigRef = rig; this.ready = true;
      this.seed(b);
      // Первый заход: полотно приходит к равновесию сразу, а не на глазах у
      // зрителя. Сорок подшагов — это две трети секунды по внутреннему времени
      // ткани, за них она сходится полностью.
      for (let k = 0; k < 40; k++) this.advance(b, SUB_DT, side, env);
      return true;
    }
    const nSub = Math.max(1, Math.min(SUB_MAX, Math.ceil(dt / SUB_DT)));
    const h = dt / nSub;
    for (let k = 0; k < nSub; k++) this.advance(b, h, side, env);
    return true;
  }

  ix(r, c) { return r * this.cols + c; }

  // Площадь ячеек полотна В ПОЛЁТЕ, разнесённая по узлам. Считается тем же
  // способом, что площадь выкройки в `pattern()`, — двумя треугольниками на
  // ячейку, — но по текущим положениям.
  flyingAreas() {
    const A = this._areaNow || (this._areaNow = new Float64Array(this.n));
    const p = this.pos;
    A.fill(0);
    for (let r = 0; r + 1 < this.rows; r++)
      for (let c = 0; c + 1 < this.cols; c++) {
        const a = this.ix(r, c), b = this.ix(r, c + 1),
              e = this.ix(r + 1, c), g = this.ix(r + 1, c + 1);
        const tri = (i, j, k) => {
          const ux = p[j * 3] - p[i * 3], uy = p[j * 3 + 1] - p[i * 3 + 1],
                uz = p[j * 3 + 2] - p[i * 3 + 2];
          const vx = p[k * 3] - p[i * 3], vy = p[k * 3 + 1] - p[i * 3 + 1],
                vz = p[k * 3 + 2] - p[i * 3 + 2];
          return 0.5 * Math.hypot(uy * vz - uz * vy, uz * vx - ux * vz,
                                  ux * vy - uy * vx);
        };
        const q = (tri(a, b, e) + tri(g, e, b)) / 4;
        A[a] += q; A[b] += q; A[e] += q; A[g] += q;
      }
    return A;
  }

  advance(b, h, side, env) {
    const calc = b.rig.stripCalc, base = this.si * STRIPS;
    const p = this.pos, pv = this.prev, f = this.frc, N = this.n;
    // Поток берётся у средней полоски: направление давления по высоте меняется
    // мало, а вот сторона у всего паруса одна.
    const mid = calc[base + Math.floor(STRIPS / 2)] || {};
    let wx = mid.d1 || 0, wy = mid.d2 || 0;
    if (Math.hypot(wx, wy) < 1e-6) { wx = -1; wy = 0; }
    this.rowNormals(wx, wy);
    // Тяжесть в осях рига: вдоль мачты и поперёк неё, по крену.
    const cp = Math.cos(b.phi), sp = Math.sin(b.phi);
    const gy = -env.g * sp, gz = -env.g * cp;
    f.fill(0);
    // ПЛОЩАДЬ ПОД ДАВЛЕНИЕМ — ПО ЛЕТЯЩИМ ПОЛОЖЕНИЯМ, а не по выкройке.
    //
    // Масса узла остаётся по крою, и это верно: сколько ткани сшито, столько её
    // и весит, как бы полотно ни лежало. А вот воздух давит на ту площадь,
    // которую полотно подставляет СЕЙЧАС. У натянутой ткани разницы почти нет
    // (27.90 м² кроя против 27.77 в полёте), но на слабине летящая площадь
    // меньше, и по выкройке самая смятая часть паруса нагружалась полной — ровно
    // там, где ошибка дороже всего.
    const area = this.flyingAreas();
    const st = b.rig.stripState;
    // Раскладка нагрузки по полоскам: сумма формы, сумма модулей и площадь.
    const raw = this._raw || (this._raw = new Float64Array(STRIPS));
    const absRaw = this._absRaw || (this._absRaw = new Float64Array(STRIPS));
    const aSum = this._aSum || (this._aSum = new Float64Array(STRIPS));
    const kShape = this._kShape || (this._kShape = new Float64Array(STRIPS));
    const kFlat = this._kFlat || (this._kFlat = new Float64Array(STRIPS));
    raw.fill(0); absRaw.fill(0); aSum.fill(0); kShape.fill(0); kFlat.fill(0);
    for (let r = 0; r < this.rows; r++) {
      const si = this.stripOf(r), g = calc[base + si];
      if (!g || !g.live || !g.q) continue;
      for (let c = 0; c < this.cols; c++) {
        const i = this.ix(r, c), u = c / (this.cols - 1);
        const kp = Math.min(NCHORD - 1, Math.floor(u * NCHORD));
        raw[si] += g.q[kp] * area[i];
        absRaw[si] += Math.abs(g.q[kp]) * area[i];
        aSum[si] += area[i];
      }
    }
    for (let si = 0; si < STRIPS; si++) {
      const g = calc[base + si], d = st[base + si];
      if (!g || !g.live || !d || !(aSum[si] > 0)) continue;
      // НАГРУЗКА СТРОКИ — ТА ЖЕ, ЧТО УХОДИТ В ЛОДКУ, и это не уточнение, а
      // сведение двух путей в один.
      //
      // Способ здесь менялся трижды, и каждый раз по замеру. Сперва стоял
      // `qd·(q[k]/peak)` — форма нагрузки по хорде, поделённая на свой максимум:
      // перепад давления выходил ровно 0.5·ρ·V² в пике ВСЕГДА, при любом угле и
      // любой циркуляции. Следящая сила постоянной величины по нормали к
      // деформируемой поверхности неконсервативна, и полотно от неё
      // САМОВОЗБУЖДАЛОСЬ: на замороженной лодке размах пуза 0.0798 держался
      // ровным с 28-й секунды до 60-й, с порогом по скорости ветра, как
      // положено флаттеру.
      //
      // Потом — Кутта—Жуковский, `Δp = ρ·V·Γ/Δx`. Флаттер это сняло (размах
      // 0.0001), но остался долг: из одной Γ восстанавливается только
      // ЦИРКУЛЯЦИОННАЯ часть нагрузки. Аудит переноса (`tests/cloth.test.mjs`)
      // показал цену: на бакштаге пути сходились до 4 %, а на полных курсах
      // расходились в разы и МЕНЯЛИ ЗНАК — при силе полоски +316 Н вдоль корпуса
      // ткань получала −80 Н. То есть на фордевинде полотно придавливалось
      // назад ровно там, где лодку тянет вперёд.
      //
      // Теперь полоска отдаёт полотну свою НОРМАЛЬНУЮ СИЛУ — ту самую, что
      // уходит в лодку, — а форму вдоль хорды полотно по-прежнему берёт из Γ.
      // Совпадение сумм тогда не свойство, а тождество: сколько лодка получила
      // поперёк паруса, столько полотно и надуло. У решётки остаётся
      // РАСПРЕДЕЛЕНИЕ, и только оно; величину даёт поляра со всеми поправками,
      // наклоном и доводчиком.
      //
      // Берётся проекция на нормаль, а не модуль: касательная доля силы (трение
      // вдоль полотна) мембрану не надувает.
      const cd0 = g.chordDir || 0;
      const fn = (d.drive || 0) * -Math.sin(cd0) + (d.side || 0) * Math.cos(cd0);
      // Знакопеременная нагрузка по хорде: когда сумма мала против суммы
      // модулей, делить на неё нельзя — распределение вырождается и один узел
      // получает всё. Тогда нормальная сила раскладывается РАВНОМЕРНО по
      // площади: это честное «формы не знаем», а не подгонка.
      if (Math.abs(raw[si]) > 0.05 * absRaw[si]) kShape[si] = fn / raw[si];
      else kFlat[si] = fn / aSum[si];
    }
    // Приложенная нагрузка отдаётся наружу — для аудита переноса
    // (`tests/cloth.test.mjs`). Считать её потом по формуле значило бы завести
    // второй источник правды ровно там, где проверяется единственность первого.
    const L = this.load || (this.load = { fx: 0, fy: 0, fz: 0, mx: 0 });
    L.fx = 0; L.fy = 0; L.fz = 0; L.mx = 0;
    const cgz = b.p.mass.cg_m[2];
    for (let r = 0; r < this.rows; r++) {
      const si = this.stripOf(r), g = calc[base + si] || {};
      const live = !!g.live;
      const q = g.q;
      // Затухание по нормали: полотно, идущее поперёк себя со скоростью v,
      // встречает сопротивление порядка ρ·V·v на единицу площади — та же
      // линеаризация нестационарной подъёмной силы пластины, что даёт затухание
      // качки крыла. Множителя при ней нет: единица, и та из формулы.
      const cd = live ? this.rhoAir * g.ve : 0;
      for (let c = 0; c < this.cols; c++) {
        const i = this.ix(r, c), k = i * 3;
        // Тяжесть — по массе ТКАНИ, а не по массе с воздухом: присоединённая
        // масса весит ровно ноль. Перепутать их стоило одного прогона, в котором
        // парус повис в диаметральной плоскости мокрой тряпкой.
        const mg = this.area[i] * AREAL_KG;
        f[k + 1] += mg * gy; f[k + 2] += mg * gz;
        if (!live) continue;
        const nx = this.nrm[k], ny = this.nrm[k + 1], nz = this.nrm[k + 2];
        if (cd > 0) {
          const vx = (p[k] - pv[k]) / h, vy = (p[k + 1] - pv[k + 1]) / h,
                vz = (p[k + 2] - pv[k + 2]) / h;
          const vn = vx * nx + vy * ny + vz * nz;
          const dmp = -cd * vn * area[i];
          f[k] += dmp * nx; f[k + 1] += dmp * ny; f[k + 2] += dmp * nz;
        }
        if (!q) continue;
        const u = c / (this.cols - 1);
        const kp = Math.min(NCHORD - 1, Math.floor(u * NCHORD));
        const pr = (kShape[si] * q[kp] + kFlat[si]) * area[i];
        f[k] += pr * nx; f[k + 1] += pr * ny; f[k + 2] += pr * nz;
        L.fx += pr * nx; L.fy += pr * ny; L.fz += pr * nz;
        // Момент крена — в горизонтных осях и вокруг ЦТ, той же формулой, что у
        // полоски: два плеча, сила разложена по крену.
        const fy = -pr * nz * sp + pr * ny * cp;
        const fz = pr * nz * cp + pr * ny * sp;
        const Y = -p[k + 2] * sp + p[k + 1] * cp;
        const Z = p[k + 2] * cp + p[k + 1] * sp;
        L.mx += Y * fz - (Z - cgz) * fy;
      }
    }
    const damp = Math.exp(-DAMP_HZ * h);
    for (let i = 0; i < N; i++) {
      const w = this.w[i];
      if (w === 0) continue;
      const k = i * 3;
      for (let d = 0; d < 3; d++) {
        let v = (p[k + d] - pv[k + d]) / h * damp + f[k + d] * w * h;
        if (v > VMAX) v = VMAX; else if (v < -VMAX) v = -VMAX;
        pv[k + d] = p[k + d];
        p[k + d] += v * h;
      }
    }
    this.project(b, side);
    // Скорость наружу не выводится: её роль здесь только в предсказании, а
    // берётся она разностью положений, как и положено позиционной динамике.
  }

  // Проходы по связям.
  //
  // Связь ОДНОСТОРОННЯЯ: ребро тянет, когда растянуто, и не делает ничего,
  // когда сжато. Это и есть ткань — она мнётся, а не пружинит. Из этого же
  // само собой выходит пузо: строка длиннее хорды, под давлением она
  // натягивается по дуге, и длина дуги равна длине ткани — ровно то уравнение,
  // которое решает мембрана для сечения.
  // ФАЛОВАЯ ДОЩЕЧКА — ЖЁСТКАЯ ПЛАНКА, а не девять узлов ткани.
  //
  // Верхняя строка идёт по дощечке шириной 0.27 м, и сетка кладёт на неё те же
  // девять узлов, что и на нижнюю шкаторину в четыре с лишним метра: рёбра по
  // 3.4 см при вертикальных почти в метр, масса узла 117 г против 1684 г внизу.
  // Семь лишних степеней свободы у детали, у которой их две — положение и
  // поворот, — и на них полотно заламывалось: поворот хорды между двумя
  // верхними строками 57° при 1…7° по всему остальному парусу.
  //
  // Дощечка настоящая и жёсткая: это планка, вшитая в фаловый угол. Поэтому её
  // узлы не решаются, а САЖАЮТСЯ на отрезок между концами, каждый на своём
  // месте по выкройке. Концы при этом решаются как прежде: фаловый закреплён,
  // задний тянут задняя шкаторина и полотно. Ни одной новой постоянной.
  board() {
    const p = this.pos, R = this.rows - 1;
    const a = this.ix(R, 0) * 3, z = this.ix(R, this.cols - 1) * 3;
    const w = this.rowW[R];
    if (!(w > 1e-9)) return;
    for (let c = 1; c + 1 < this.cols; c++) {
      const t = (this.px[this.ix(R, 0)] - this.px[this.ix(R, c)]) / w;
      const k = this.ix(R, c) * 3;
      p[k] = p[a] + (p[z] - p[a]) * t;
      p[k + 1] = p[a + 1] + (p[z + 1] - p[a + 1]) * t;
      p[k + 2] = p[a + 2] + (p[z + 2] - p[a + 2]) * t;
    }
  }

  // Один проход по списку связей. `list` — либо все подряд, либо выборка верха.
  sweep(list, M) {
    const p = this.pos, ci = this.ci, cj = this.cj, ck = this.ck, rest = this.rest;
    for (let n = 0; n < M; n++) {
      const k = list ? list[n] : n;
      const a = ci[k] * 3, c = cj[k] * 3;
      const wa = this.w[ci[k]], wb = this.w[cj[k]];
      const s = wa + wb;
      if (s === 0) continue;
      const dx = p[c] - p[a], dy = p[c + 1] - p[a + 1], dz = p[c + 2] - p[a + 2];
      const d = Math.hypot(dx, dy, dz);
      if (d < 1e-9) continue;
      // Отрицательная жёсткость — метка двусторонней связи (излом): она и
      // тянет, и распирает. Все прочие односторонние: ткань мнётся.
      const kk = ck[k];
      if (kk > 0 && d <= rest[k]) continue;
      const g = OMEGA * Math.abs(kk) * (d - rest[k]) / d / s;
      p[a] += wa * g * dx; p[a + 1] += wa * g * dy; p[a + 2] += wa * g * dz;
      p[c] -= wb * g * dx; p[c + 1] -= wb * g * dy; p[c + 2] -= wb * g * dz;
    }
    this.board();
  }

  // ШКОТ — ОДНОСТОРОННЯЯ СВЯЗЬ ДО ОБУХА, а не посадка угла на дугу.
  //
  // Шкот говорит «дальше нельзя» и ничего не говорит о том, где угол стоит:
  // верёвка тянет и не толкает. Где угол стоит, решают вместе шкот, обе
  // шкаторины и давление, и решать это должна ткань.
  //
  // Прежде угол сажался на `gennakerClew` — окружность вокруг оси галс—фал, на
  // ней точка по длине шкота. Это МНОЖЕСТВО, где обе шкаторины натянуты РОВНО
  // в струну, то есть край допустимой области, а не вся она: у гибкой шкаторины
  // длиной L условие цело́сти — |A − B| ≤ L. Дуга запрещала всю слабину, то есть
  // ровно те состояния, ради которых заводится заворот и сложение.
  sheet(b, side) {
    const gen = b.p && b.p.rig && b.p.rig.gennaker;
    if (!gen || !gen.sheet_lead_m) return;
    const L = gennakerSheetLen(b.o, gen), lead = gen.sheet_lead_m;
    const lx = lead[0], ly = Math.abs(lead[1]) * Math.sign(side || -1), lz = lead[2];
    const k = this.clew * 3, p = this.pos;
    const dx = p[k] - lx, dy = p[k + 1] - ly, dz = p[k + 2] - lz;
    const d = Math.hypot(dx, dy, dz);
    if (!(d > L) || d < 1e-9) return;      // слабина — шкот не работает
    const g = (d - L) / d;
    p[k] -= g * dx; p[k + 1] -= g * dy; p[k + 2] -= g * dz;
  }

  project(b, side) {
    for (let it = 0; it < this.iter; it++) {
      this.sweep(null, this.ci.length);
      // Добавочные проходы по верху: вырожденные ячейки у дощечки сходятся
      // много медленнее прочих, а список их вчетверо короче общего.
      for (let j = 0; j < TOP_SWEEPS; j++) this.sweep(this.topIdx, this.topIdx.length);
      if (this.freeClew) this.sheet(b, side);
    }
  }

  // --- что ткань может сказать о себе -----------------------------------

  // Нормаль строки — наружу от полотна, по потоку. Ею отрисовка отклоняет
  // заполаскивающий пузырь: бить он обязан поперёк ткани, а не куда попало.
  rowNormal(r) {
    const k = this.ix(r, 0) * 3;
    return [this.nrm[k], this.nrm[k + 1], this.nrm[k + 2]];
  }

  // Точка поверхности на строке `rf` и доле `t` вдоль полотна. Строка ДРОБНАЯ:
  // полосок решётки шесть, строк одиннадцать, и границы полосок между строк не
  // ложатся. Между строками и столбцами — билинейная выборка: полотно гладкое, и
  // разрешать его мельче сетки узлов всё равно нечем.
  sample(rf, t, out) {
    const y = Math.min(this.rows - 1, Math.max(0, rf));
    const r = Math.min(this.rows - 2, Math.floor(y)), u = y - r;
    const x = Math.min(this.cols - 1, Math.max(0, t * (this.cols - 1)));
    const c = Math.min(this.cols - 2, Math.floor(x)), v = x - c;
    const p = this.pos;
    const a = this.ix(r, c) * 3, b = this.ix(r, c + 1) * 3;
    const e = this.ix(r + 1, c) * 3, f = this.ix(r + 1, c + 1) * 3;
    for (let k = 0; k < 3; k++) {
      const lo = p[a + k] + (p[b + k] - p[a + k]) * v;
      const hi = p[e + k] + (p[f + k] - p[e + k]) * v;
      out[k] = lo + (hi - lo) * u;
    }
    return out;
  }

  // Пузо строки: наибольшее отклонение от хорды, в долях хорды. Меряется тем
  // же, чем меряет себя мембрана, — иначе сравнивать их было бы не с чем.
  rowCamber(rf) {
    const A = this.tmpA, B = this.tmpB, C = this.tmpC;
    this.sample(rf, 0, A); this.sample(rf, 1, B);
    const ex = B[0] - A[0], ey = B[1] - A[1], ez = B[2] - A[2];
    const c = Math.hypot(ex, ey, ez);
    if (c < 1e-6) return { camber: 0, draft: 0.5, chord: c };
    let best = 0, at = 0.5;
    for (let k = 1; k + 1 < this.cols; k++) {
      this.sample(rf, k / (this.cols - 1), C);
      const vx = C[0] - A[0], vy = C[1] - A[1], vz = C[2] - A[2];
      const t = (vx * ex + vy * ey + vz * ez) / (c * c);
      const dx = vx - t * ex, dy = vy - t * ey, dz = vz - t * ez;
      const d = Math.hypot(dx, dy, dz);
      if (d > best) { best = d; at = t; }
    }
    return { camber: best / c, draft: at, chord: c };
  }

  // Провис передней шкаторины: наибольшее удаление её узлов от прямой галс—фал.
  luffSag() {
    const p = this.pos, a = this.tack * 3, b = this.head * 3;
    const ex = p[b] - p[a], ey = p[b + 1] - p[a + 1], ez = p[b + 2] - p[a + 2];
    const L = Math.hypot(ex, ey, ez) || 1;
    let best = 0, at = 0;
    for (let r = 1; r + 1 < this.rows; r++) {
      const i = this.ix(r, 0) * 3;
      const vx = p[i] - p[a], vy = p[i + 1] - p[a + 1], vz = p[i + 2] - p[a + 2];
      const t = (vx * ex + vy * ey + vz * ez) / (L * L);
      const dx = vx - t * ex, dy = vy - t * ey, dz = vz - t * ez;
      const d = Math.hypot(dx, dy, dz);
      if (d > best) { best = d; at = t; }
    }
    return { sag: best, at: at };
  }

  // Высота шкотового угла над галсом: тот самый признак с фотографий, по
  // которому бакштаговый спинакер и отличается от натянутого в ДП стакселя.
  clewRise() { return this.pos[this.clew * 3 + 2] - this.pos[this.tack * 3 + 2]; }
}
