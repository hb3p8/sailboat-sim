// Сопротивление корпуса по скорости И КРЕНУ.
//
// У этой лодки крен меняет обводы сильно: днище плоское и мелкое, и
// наветренная скула выходит из воды уже на десяти градусах. Смоченная
// поверхность падает с 6.8 до 5.3 кв.м на двадцати градусах — считано по
// геометрии, поворотом корпуса при постоянном водоизмещении
// (scripts/build_physics.py). Волновая часть по крену не меняется, и почему —
// объяснено там же: интеграл Мичелла на накренённом корпусе выходит за
// пределы своей применимости.
// `mods` — множители на трение и на волновое по отдельности. Их приносит
// глиссирование: смоченная поверхность сокращается (трение падает), корпус
// всплывает и вытесняет меньше (волновое уходит). Без них ветка тождественна
// прежней и читает готовое `rt_n`, поэтому вытесняющий режим не может сдвинуться
// ни на разряд — не «не должен», а не может: другой арифметики там не появляется.
export function hullResistance(P, u, heelDeg, mods) {
  const R = P.resistance, H = R.heel;
  const at = (curve) => {
    if (!mods) return lerpTable(curve, 'v_ms', u, 'rt_n');
    return lerpTable(curve, 'v_ms', u, 'rf_n') * mods.friction +
           lerpTable(curve, 'v_ms', u, 'rr_n') * mods.wave;
  };
  if (!H || H.length < 2) return at(R.curve);
  const a = Math.abs(heelDeg);
  for (let i = 0; i < H.length - 1; i++) {
    if (a <= H[i + 1].heel_deg) {
      const lo = H[i].heel_deg, hi = H[i + 1].heel_deg;
      const t = Math.max(0, Math.min(1, (a - lo) / (hi - lo)));
      return at(H[i].curve) * (1 - t) + at(H[i + 1].curve) * t;
    }
  }
  return at(H[H.length - 1].curve);
}

// --- глиссирование --------------------------------------------------------------
//
// Метод Савицкого (1964): эмпирика по буксировкам призматических глиссирующих
// пластин. Это НЕ расчёт обтекания, и записать это надо прямо: формулы получены
// подгонкой к замерам шестидесятых, область их применимости — плоское днище с
// постоянной килеватостью, а у нас корпус с седловатостью и скулой. Здесь он
// стоит как разумная опора, а не как истина.
//
// Что берётся из геометрии, а не назначается:
//   килеватость 12.65° и седловатость — из шпангоутов (build_physics.py);
//   смоченная поверхность и вытесненный объём — живые, с каждого шага;
//   ширина глиссирующей поверхности — ширина по ватерлинии из пакета.
//
// Не назначено НИ ОДНОГО подгоняемого числа, и это важно: у глиссирования ручек
// много, и любой красивой кривой можно добиться. Пока наблюдений нет, единственная
// защита — не заводить чисел, которые нечем оправдать.

// Окно по числу Фруда, в котором глиссирование включается.
//
// Ниже FN0 не считается ВООБЩЕ — там лежит всё, что откалибровано по наблюдению
// владельца, и трогать это нельзя. Верх окна — там, где вытесняющая теория уже
// заведомо не про то.
const PLANE_FN0 = 0.5;
const PLANE_FN1 = 0.9;

// Верхний предел доли смоченной длины от транца, на которой стоит центр
// давления. У Савицкого Cp = 0.75 − 1/(5.21·Cv²/λ² + 2.39): к 0.75 на больших
// скоростях, к трети на малых.
const PLANE_CP = 0.75;

// Плавная ступенька: у окна обязана быть нулевая производная на концах, иначе
// на входе в него скачком меняется дифферент.
function smoothstep(x, a, b) {
  const t = Math.max(0, Math.min(1, (x - a) / (b - a)));
  return t * t * (3 - 2 * t);
}

// Насколько открыто окно глиссирования. Ниже FN0 ноль, и это тот самый
// инвариант: вытесняющий режим не может сдвинуться, потому что там ничего и не
// считается.
export function planingWindow(P, v) {
  const H = P.hydrostatics, env = P.environment;
  if (H.deadrise_deg == null || H.rocker_deg == null) return 0;
  return smoothstep(v / Math.sqrt(env.g * H.lwl_m), PLANE_FN0, PLANE_FN1);
}

// Собственная волновая система корпуса: профиль воды вдоль борта.
//
// Это и есть просадка кормы на горбе — недостающий источник ходового
// дифферента. Лодка на ходу сидит не на ровной воде, а на волне, которую сама
// же и развела: гребень у форштевня, а корма — во впадине. Корма проседает,
// нос встаёт, и днище получает тот положительный угол, с которого начинается
// глиссирование. На воде это видят как «лодка упёрлась в горб и присела кормой».
//
// Оба числа ВЫВОДЯТСЯ, ручек здесь нет:
//
//   • длина волны — из дисперсии глубокой воды: λ = 2π·v²/g. Отсюда сразу
//     следует, где просадка сильнее всего: наибольший дифферент — когда корма
//     попадает ровно во впадину, то есть при λ = 2·LWL, что для SV20 даёт
//     Fn 0.57 — самый горб. Дальше волна длиннее корпуса, корма выбирается из
//     впадины, и просадка сама сходит на нет — ровно там, где её должно
//     сменить днище.
//
//   • амплитуда — из ВОЛНОВОГО СОПРОТИВЛЕНИЯ, которое уже посчитано Мичеллом и
//     лежит в таблице (rr_n). Связь — поток энергии: работа сопротивления
//     уходит в волну, R_w·c = E·c_g·B, а у глубокой воды c_g = c/2, откуда
//     R_w = ¼·ρ·g·A²·B и A = √(4·R_w/(ρ·g·B)). Приближение здесь одно и
//     названо: ближнее поле считается той же амплитуды, что уносимая волна
//     шириной в корпус.
//
// Крутизна ограничена обрушением (k·A ≤ 0.44, то же H/λ = 1/7): волна круче
// просто не живёт. Ниже окна по Фруду — ровно ноль, тем же `planingWindow`:
// в откалиброванном вытесняющем режиме просадка мала и уже сидит в калибровке.
export function humpSquat(P, v) {
  const w = planingWindow(P, v);
  if (!(w > 0) || !(v > 0.1)) return null;
  const env = P.environment, H = P.hydrostatics;
  const rr = lerpTable(P.resistance.curve, 'v_ms', v, 'rr_n');
  if (!(rr > 0)) return null;
  const k = env.g / (v * v);
  let amp = Math.sqrt(4 * rr / (env.rho_water * env.g * H.bwl_m));
  amp = Math.min(amp, 0.44 / k);
  // Гребень — у форштевня. Настоящий гребень стоит чуть позади носа (давление
  // строит волну не мгновенно), но двигать его — уже ручка, а этой модели
  // хватает фазы «гребень на носу, впадина по дисперсии».
  return { amp: amp * w, k, xf: H.lwl_fwd_x_m };
}

// Подъёмная сила глиссирующего днища, её точка приложения и множители на
// таблицу сопротивления.
//
//   v      — ход через воду, м/с
//   thRad  — дифферент, рад; плюс — нос кверху
//   hyd    — живая гидростатика с этого шага (`Buoyancy.at`)
//
// Возвращает `null`, когда глиссирования нет вовсе: ниже окна по Фруду или при
// неположительном угле днища. Пустой ответ — это не «ошибка», а «здесь считает
// вытеснение», и вызывающая сторона обязана уметь его прочесть.
export function planing(P, v, thRad, hyd) {
  const H = P.hydrostatics, env = P.environment;
  if (!hyd || H.deadrise_deg == null || H.rocker_deg == null) return null;
  const fn = v / Math.sqrt(env.g * H.lwl_m);
  const w = smoothstep(fn, PLANE_FN0, PLANE_FN1);
  if (w <= 0) return null;

  // Угол днища — по хорде смоченной части линии киля в текущей посадке
  // (`Buoyancy.at` отдаёт его четвёртым полем). Дифферент от конструктивной
  // ватерлинии минус средняя седловатость — прежняя версия — занижала угол на
  // три градуса: линия киля кривая, и хорда её смоченной части почти
  // горизонтальна, пока смочен весь корпус, а на короткой корме сама ложится
  // на крутой участок. Запас на случай отсутствия шпангоутов — прежний.
  const tau = hyd.tauChordDeg != null
    ? hyd.tauChordDeg
    : thRad * 180 / Math.PI - H.rocker_deg;
  const b = H.bwl_m;
  // Смоченная поверхность и объём — живые. Отношения к стояночным и есть то,
  // чем глиссирование гасит вытесняющую таблицу.
  const sRatio = H.wetted_m2 > 1e-6 ? hyd.wetted / H.wetted_m2 : 1;
  // Волновое сопротивление у Мичелла — квадрат по силе источников, то есть по
  // вытесненному объёму. Всплыла вдвое — волновое вчетверо меньше.
  const vRatio = H.volume_m3 > 1e-9 ? hyd.volume / H.volume_m3 : 1;
  const mods = {
    friction: 1 + w * (sRatio - 1),
    wave: 1 + w * (vRatio * vRatio - 1),
  };

  if (!(tau > 0) || !(v > 0.1)) {
    return { lift: 0, xcp: 0, tau, w, mods, lambda: 0 };
  }

  // Смоченная длина — ЧЕСТНАЯ, из геометрии текущей посадки, а не из площади
  // ватерлинии. Первая версия брала λ = awp/b², и это была длина, которая не
  // знает угла: у Савицкого смоченная длина по килю и по скуле РАЗНЫЕ, и
  // разница задана подъёмом брызговой пелены — Lk − Lc = b·tg(β)/(π·tg(τ)).
  // Средняя из них и есть длина, которой работает днище. При τ → 0 поправка
  // растёт, скула сохнет, и подъёмная сила гаснет сама — естественный конец
  // применимости вместо обрыва.
  //
  // Длина по килю — из тех же шпангоутов, что и плавучесть: от кормового до
  // носового края смоченной части нынешней посадки.
  const aft = hyd.wetAft != null && hyd.wetAft > 0 ? hyd.wetAft : H.lwl_aft_x_m;
  const fwd = hyd.wetFwd > aft ? hyd.wetFwd : H.lwl_fwd_x_m;
  const lk = fwd - aft;
  // Нет смоченной длины — нет и поверхности, которой нести. Нижнего зажима у λ
  // не бывает: он создавал бы подъёмную силу из ничего, и первый же решатель
  // посадки это нашёл — выпрыгнувшая из воды лодка продолжала «нести» и
  // разлеталась до 450% веса на сухом корпусе.
  if (!(lk > 0.05)) return { lift: 0, xcp: 0, tau, w, mods, lambda: 0 };
  const tanTau = Math.tan(tau * Math.PI / 180);
  const lc = Math.max(0, lk - b * Math.tan(H.deadrise_deg * Math.PI / 180) /
                            (Math.PI * Math.max(1e-3, tanTau)));
  const lambda = Math.min(8, 0.5 * (lk + lc) / b);
  if (!(lambda > 0.01)) return { lift: 0, xcp: 0, tau, w, mods, lambda: 0 };
  const cv = v / Math.sqrt(env.g * b);
  // Подъёмная сила — ТОЛЬКО динамический член Савицкого, τ^1.1·0.012·√λ.
  //
  // Его второе слагаемое, 0.0055·λ^2.5/Cv², — эмпирическая ПЛАВУЧЕСТЬ
  // глиссирующего клина, и здесь ей не место: настоящая плавучесть погружённого
  // объёма уже стоит в сумме сил, посчитанная по шпангоутам точнее всякой
  // эмпирики. Первая версия несла оба слагаемых и учитывала плавучесть дважды —
  // на горбе это давало до сорока процентов лишней подъёмной силы.
  const cl0 = Math.pow(tau, 1.1) * 0.0120 * Math.sqrt(lambda);
  const clb = Math.max(0, cl0 - 0.0065 * H.deadrise_deg * Math.pow(cl0, 0.60));
  const lift = w * clb * 0.5 * env.rho_water * v * v * b * b;
  // Центр давления — по Савицкому, а не назначенной долей: доля средней
  // смоченной длины от транца Cp = 0.75 − 1/(5.21·Cv²/λ² + 2.39). На больших
  // скоростях она идёт к 0.75, на малых — к трети, как у крыла малого
  // удлинения. С короткой смоченной длиной центр давления сам уезжает к корме —
  // это и есть та обратная связь, которой глиссирующая посадка держится.
  const cp = PLANE_CP - 1 / (5.21 * (cv * cv) / (lambda * lambda) + 2.39);
  const xcp = aft + Math.max(0.1, cp) * lambda * b;
  return { lift, xcp, tau, w, mods, lambda };
}

// Поперечная сила корпуса по полоскам. Заменяет два прежних слагаемых —
// «сопротивление дрейфу» и «демпфирование рыскания», — потому что на самом
// деле это одно и то же явление: каждая полоска обтекается поперёк со своей
// местной скоростью v + r·x, и сумма даёт сразу и силу, и момент, и связь
// между ними. Раздельные подгоняемые коэффициенты для этого не нужны.
export function hullLateral(P, phi, v, r, n) {
  const env = P.environment, hs = P.hydrostatics;
  const xa = hs.lwl_aft_x_m != null ? hs.lwl_aft_x_m : 0.55;
  const xf = hs.lwl_fwd_x_m != null ? hs.lwl_fwd_x_m : 6.02;
  const cgx = P.mass.cg_m[0];
  const steps = n || 12;
  const dx = (xf - xa) / steps;
  // На ровном киле поперёк потока стоит только осадка корпуса — пятнадцать
  // сантиметров. На крене лодка подставляет потоку днище, и высота растёт до
  // половины ширины. Без этого положенная набок лодка ничем не держится
  // и уезжает боком со скоростью, которой на воде не бывает.
  const c = Math.abs(Math.cos(phi)), s2 = Math.abs(Math.sin(phi));
  const depth = hs.draft_canoe_m * c + 0.5 * hs.bwl_m * s2;
  const q = 0.5 * env.rho_water * HULL_CROSSFLOW_CD * depth * dx;
  let fy = 0, mz = 0;
  for (let i = 0; i < steps; i++) {
    const arm = xa + (i + 0.5) * dx - cgx;
    const vi = v + r * arm;
    const f = -q * Math.abs(vi) * vi;
    fy += f;
    mz += f * arm;
  }
  // Глубина отдаётся наружу: по ней отладочный вид баланса ставит точку
  // приложения боковой силы корпуса, а считать её второй раз значило бы
  // завести второй источник правды.
  return { fy: fy, mz: mz, depth: depth };
}

// Приводящий момент накренённого корпуса.
//
// Накренённый корпус несимметричен относительно своего пути, и погружённая
// скула гонит его на ветер. Величина подобрана по наблюдениям владельца лодки —
// одна из двух подгоняемых в модели.
export function hullHeelYaw(P, u, phi) {
  const hs = P.hydrostatics;
  return HULL_HEEL_YAW * 0.5 * P.environment.rho_water * u * u *
         hs.lwl_m * hs.draft_canoe_m * Math.sin(2 * phi);
}

// --- крылья -------------------------------------------------------------------


// Сила крыла сразу в связанных осях. Так не нужно отдельно решать, куда
// смотрит подъёмная сила: она просто перпендикулярна скорости крыла, а
// сопротивление направлено против неё, и все четверти получаются сами.
export function foilForce(env, foil, ux, vy, deflect, extraCd) {
  const V = Math.hypot(ux, vy);
  if (V < 0.05) return { fx: 0, fy: 0, side: 0, alpha: 0 };
  const heading = Math.atan2(vy, ux);            // куда движется крыло
  const alpha = wrapPi(heading - (deflect || 0));
  const k = foilCoeffs(alpha, foil.effective_ar, foil.stall_deg,
                       0.008 + (extraCd || 0));
  const q = 0.5 * env.rho_water * foil.area_m2 * V * V;
  const L = q * k.cl, Dg = q * k.cd;
  const ex = ux / V, ey = vy / V;                // вдоль движения
  const px = -ey, py = ex;                       // поперёк движения
  return { fx: -Dg * ex - L * px, fy: -Dg * ey - L * py,
           side: -L * py, alpha: alpha, cl: k.cl };
}
