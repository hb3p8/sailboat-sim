// WebGPU. Если его нет, рендерер сам откатывается на WebGL2 — код при этом один
// и тот же, TSL компилируется и туда и туда. Но не весь: волна считается
// вычислительным шейдером с рабочей памятью группы, а этого в WebGL2 нет
// вовсе, и падает там не вода, а вся страница.
//
// Сообщение при этом получается про `getScopedArray` — то есть про следствие,
// на четыре слоя ниже причины. Причин же всего две, и обе снаружи страницы:
// адрес не защищённый или браузер не умеет. Разбирается это здесь, чтобы
// человек с телефона читал, что ему делать, а не имя метода в сборщике шейдеров.
// `trackTimestamp` — В КОНСТРУКТОР, а не свойством после. Свойство ставится на
// рендерер, а метки времени заводит СЛОЙ ПОД ним, и он читает свой флаг один
// раз, из этих же параметров. Поставленное потом свойство он не видит вовсе:
// метки молча не собираются, и на экране стоит ровный ноль.
// `?noaa` — поднять рендерер без сглаживания. Не настройка на каждый день, а
// способ его ЗАМЕРИТЬ: число проб входит в описание конвейера, и переключить его
// посреди работы нельзя — скамья на такой попытке выдала отрицательную цену
// (sim/bench.js). Два прогона сравниваются по строке «как есть».
const renderer = new WebGPURenderer({
  antialias: !location.search.includes('noaa'),
  trackTimestamp: true,
});

function gpuTrouble() {
  if (navigator.gpu) return null;
  if (!window.isSecureContext) {
    return 'WebGPU не выдаётся по этому адресу: браузер даёт его только в ' +
      'защищённом контексте — по https или на localhost. Откройте страницу с ' +
      'сервера, поднятого с --lan (он включает https сам), либо по localhost.';
  }
  return 'Этот браузер не умеет WebGPU. На iOS до 26 его включают руками: ' +
    'Настройки → Safari → Дополнения → Экспериментальные функции → WebGPU, ' +
    'потом закрыть и открыть Safari заново.';
}
// Плотность пикселей. Потолок два — и на телефоне тоже.
//
// Вода занимает почти весь кадр, и её цена — это цена пикселя, помноженная на их
// число, так что рычаг это самый прямой из всех. На телефоне он был опущен до
// полутора, когда видеокарта тратила 16.5 мс из 17.6-миллисекундного кадра
// (docs/perf.md, §3.4) и запаса не было никакого.
//
// ВОЗВРАЩЕНО ОБРАТНО. После разложения волны по кадрам (§9.2г) телефон вышел на
// частоту развёртки с запасом: 13.4 мс работы видеокарты из 16.7 доступных.
// Запас на то и запас, чтобы тратить его на картинку, а не хранить; полтора
// вместо двух — это заметная лестница на вантах и кромке паруса.
//
// Ставится это на замер, а не насовсем: пикселей становится в 1.78 раза больше,
// а вода — половина цены отрисовки. Не влезет — вернуть полтора, и уже с числом
// в руках, а не «на всякий случай».
const PIXELS_MAX = 2;
// `?dpr=<число>` — потолок на один запуск, чтобы мерить лестницу по двум
// прогонам одной сборкой.
const PIXELS_WANT = (() => {
  const v = parseFloat(new URLSearchParams(location.search).get('dpr'));
  return isFinite(v) && v > 0 ? Math.min(v, 4) : PIXELS_MAX;
})();
renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, PIXELS_WANT));
// Тени — только от лодки и только на воду. Карту акватории они не трогают
// нарочно: пятнадцать километров в одну карту теней не влезают ничем полезным,
// а лодка со своим ригом влезает целиком, и тень от паруса на воде — это то, по
// чему видно, куда стоит солнце.
renderer.shadowMap.enabled = true;
// Фон задаётся сценой, а не setClearColor: у WebGPU-рендерера очистка цветом
// до неба не доходит, и небо остаётся чёрным.
scene.background = SKY;

// Контрастный вид пелены: сцена снята, нити жирные. Переключает его debug.js, а
// объявлено здесь нарочно. Сборка вклеивает файлы в общую область в порядке
// main, debug, controls, и `let` из debug.js для main.js — временная мёртвая
// зона: паруса прячутся в `updateSails`, а она успевает отработать при постройке
// сцены, до того как debug.js вообще будет прочитан. Читалось это как
