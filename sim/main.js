const ms = v => v.toFixed(1);

// Номер сборки на экран. По порядковому номеру коммита, а не по хэшу: с
// телефона хэши глазом не сравнить, а «r742 против r741» читается сразу — и
// отвечает ровно на тот вопрос, ради которого спрашивают: свежее ли то, что я
// вижу, того, что я видел минуту назад. Шестимегабайтную страницу браузер
// кэширует охотно, и без этого числа «правка не подействовала» и «открыто
// вчерашнее» неразличимы.
//
// Звёздочка — сборка с несохранёнными правками: такой номер ничего не
// обозначает, и знать об этом надо сразу.
//
// Читается лениво, при первом же выводе: `BUILD` вклеивается в общую область
// вместе с разметкой, и трогать его на верхнем уровне модуля — та самая
// временная мёртвая зона, на которой страница уже однажды падала целиком.
let revText = null;
function rev() {
  if (revText === null) {
    revText = (typeof BUILD !== 'undefined' && BUILD && BUILD.rev)
      ? 'r' + BUILD.rev + (BUILD.dirty ? '*' : '') : 'r?';
  }
  return revText;
}

function updatePerf() {
  const gpu = perf.gpu + perf.gpuCompute;
  if (perfEl) {
    perfEl.textContent =
      rev() + '\n' +
      // «ЦП» в подписи не для красоты: это время работы процессора от входа в
      // кадр до постановки следующего, без ожидания развёртки и без работы
      // видеокарты. Полный кадр виден по к/с рядом, и они НЕ обязаны сходиться:
      // 16.4 мс при 46 к/с — это не противоречие, а ровно эта разница.
      'кадр ЦП ' + ms(perf.frame) + ' мс   ' + perf.fps.toFixed(0) + ' к/с\n' +
      'физика ' + ms(perf.phys) + '   шагов ' + perf.steps.toFixed(1) +
        (perf.dropped > 0.05 ? '   брошено ' + perf.dropped.toFixed(1) + ' с' : '') + '\n' +
      'сцена  ' + ms(perf.scene) + '\n' +
      'рисов. ' + ms(perf.draw) + '\n' +
      'приб.  ' + ms(perf.hud) + '\n' +
      // Счёт — СРЕДНИЙ на показанный кадр; в скобках цена одного пакета, а
      // пакет идёт раз в OCEAN_EVERY кадров. Складывать с отрисовкой можно
      // только первое.
      'ГП     ' + ms(gpu) + '   (счёт ' + ms(perf.gpuCompute) +
        ', пакет ' + ms(perf.gpuBatch) + ')\n' +
      'вызовов ' + perf.calls + '   тр. ' + (perf.tris / 1000).toFixed(0) + 'к';
  }
  if (gperfEl) {
    // Двумя строками, а не одной: одна не помещается на телефоне поперёк, а
    // ломать её посередине числа нельзя — читать становится нечего.
    gperfEl.textContent =
      rev() + ' · ' + perf.fps.toFixed(0) + ' к/с · кадр ЦП ' + ms(perf.frame) + ' мс\n' +
      'физ ' + ms(perf.phys) + ' · сцена ' + ms(perf.scene) +
      ' · рис ' + ms(perf.draw) +
      (perf.dropped > 0.05 ? ' · брошено ' + perf.dropped.toFixed(1) + ' с' : '') + '\n' +
      'ГП ' + ms(perf.gpu) + ' + счёт ' + ms(perf.gpuCompute);
  }
}

function updateHud(t) {
  if (!t) return;
  const rows = HUD_ROWS.map(([k, label, unit, prec]) =>
    '<tr><td>' + label + '</td><td class="v">' +
    (t[k] == null ? '—' : (+t[k]).toFixed(prec)) +
    '</td><td class="u">' + unit + '</td></tr>').join('') +
    // Расстояние до берега — прибор, а не наказание. Дно у нас выдумано, и мель
    // ведёт себя мягко: цепляет, но не останавливает. Предупреждает именно эта
    // цифра, и на реке умение читать берег — половина дела.
    (t.shoreM == null ? '' :
      '<tr><td>До берега' +
      (t.aground ? ' <em>на мели</em>' : t.shoalK > 0.02 ? ' <em>мель</em>' : '') +
      '</td><td class="v">' + (t.shoreM >= 127 ? '&gt;127' : t.shoreM.toFixed(0)) +
      '</td><td class="u">м</td></tr>') +
    // Течение и скорость над грунтом. Большая цифра наверху — скорость ЧЕРЕЗ
    // ВОДУ: ею меряется лодка, её чувствуют корпус, киль и руль. А доедешь ты
    // с той, что здесь, и на реке между ними узел с лишним. Угол — от курса:
    // ноль в нос, сто восемьдесят в корму.
    (!t.curKn ? '' :
      '<tr><td>Течение <em>' + relBearing(t) + '°</em></td><td class="v">' +
      t.curKn.toFixed(2) + '</td><td class="u">уз</td></tr>' +
      '<tr><td>Над грунтом</td><td class="v">' + t.sogKn.toFixed(2) +
      '</td><td class="u">уз</td></tr>');
  // «Перебрано» имеет смысл только на острых курсах: на полных парус работает
  // сорванным, и это норма, а не ошибка настройки.
  const al = t.alphaDeg || 0;
  const luff = al < 3 ? ' <em>полощет</em>'
             : ((t.awaDeg || 0) < 80 && al > 24 ? ' <em>перебрано</em>' : '');
  hud.innerHTML =
    '<div class="big">' + (t.speedKn || 0).toFixed(2) + ' <span>уз</span></div>' +
    '<table>' + rows + '</table>' +
    '<div class="ctl">руль ' + (boat.o.rudder / D).toFixed(0) +
    '°&nbsp;&nbsp;грот ' + (boat.o.sheet / D).toFixed(0) + '°' +
    '&nbsp;&nbsp;стаксель ' + (jibSheetOf(boat.o) / D).toFixed(0) + '°' + luff +
    (autopilot ? '&nbsp;&nbsp;<b>авторулевой</b>' : '') + '</div>';
}

