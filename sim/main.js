// --- струи ветра ---------------------------------------------------------------
//
// Не прибор, а ощущение. Отладочные стрелки отвечают на вопрос «сколько и куда»,
// и отвечают точно; но пока смотришь на воду, а не на них, ветра не видно вовсе —
// он ровный, и глазу не за что зацепиться. Струи дают то, чего числа не дают:
// движение воздуха мимо лодки.
//
// Возле парусов струи ведут себя как линии тока: ускоряются, замедляются и
// гнутся. Это не подражание — они и считаются той же решёткой, тем же вызовом
// `induced`, что и линии тока, только по шести точкам вместо полусотни и с
// приглушённым возмущением. Одна физика, две подробности.
//
// Показывают они ТОТ ЖЕ ветер, что и линии тока, — кажущийся, а не истинный.
// Это одна величина, показанная двумя способами: линиями тока подробно, у самого
// паруса, и струями казуально, по всей воде вокруг. Кажущийся, а не истинный,
// потому что именно его чувствует лодка и именно он объясняет, почему на ходу
// «поддувает в лицо», а на стоянке нет. Показывать рядом две разные величины,
// обе назвав ветром, значит сбивать с толку — это мы уже проходили.
//
// Три вещи, которые пришлось сделать не самым коротким способом, и каждая по
// своей причине.
//
// **Разворот к камере — в вершинном узле.** Лента, лежащая в фиксированной
// плоскости, с половины ракурсов видна с ребра и пропадает. Поэтому поперечное
// смещение считается не здесь, а в шейдере: `нормаль = dir × (камера − точка)`.
// Тогда лента всегда стоит лицом к глазу, как это делают с толстыми линиями.
// А вот ширина остаётся НАСТОЯЩЕЙ, в метрах: экранно-постоянная делала дальние
// струи одинаково жирными, и они читались наклейками поверх кадра.
//
// **Веретено, а не прямоугольник.** Три станции вдоль струи с шириной 0 — макс —
// 0: оба конца сходятся в остриё. Прямоугольник давал срезанные торцы, и хвост
// обрывался ножом.
//
// **Прозрачность по вершинам, а не цвет.** Гасить хвост цветом означает уводить
// его в чёрный — на светлой воде это грязный след, а не растворение. Альфа
// приходит отдельным атрибутом и уходит в `opacityNode`.

const STREAK_N = 70;
const STREAK_R = 70;                     // радиус, в котором держатся, м
const STREAK_LO = 0.4, STREAK_HI = 14;   // высоты, м
// Струя летит медленнее ветра: с его настоящей скоростью пучок превращается в
// мельтешение, которое читается как помеха, а не как движение воздуха.
const STREAK_SPEED = 0.45;
// Нижний предел скорости сноса, м/с. Нужен на полных курсах: там кажущийся
// ветер падает почти до нуля — лодка убегает вместе с воздухом, — и струи
// перестают догонять лодку, повисая рядом неподвижными лентами. Физически это
// верно, а на экране читается как поломка: украшение, которое замерло.
// Поэтому снос не опускается ниже этого, а честность возвращается яркостью:
// чем слабее кажущийся ветер, тем бледнее струи, вплоть до полного исчезновения.
// Полуширина в МЕТРАХ. Экранно-постоянная толщина держала дальние струи
// одинаково жирными, и они читались наклейками поверх кадра, а не воздухом в
// нём; настоящий размер возвращает им место в перспективе.
const STREAK_W = 0.04;
// Станции вдоль струи: доля длины и полуширина в долях максимальной.
//
// Их одиннадцать. Тремя выходил ромб с изломом на плечах; шестью — капля, но
// ломаная гнулась в потоке заметными коленями. Станции ведь работают дважды:
// задают форму и служат точками, по которым струя изгибается, — и для второго
// их нужно больше, чем для первого.
//
// Ставятся они гуще к голове: там и профиль круче, и поток у паруса меняется
// быстрее, а к хвосту всё равно всё сходит на нет.
const STREAK_ST = (() => {
  const n = 10, head = 0.13, out = [];
  for (let k = 0; k <= n; k++) {
    const t = Math.pow(k / n, 1.35);
    // Капля: скруглённый нос до `head`, длинный сходящий хвост после.
    const w = t < head ? Math.sqrt(t / head)
                       : Math.pow((1 - t) / (1 - head), 1.3);
    out.push([t, w]);
  }
  return out;
})();

// Насколько струи слушаются возмущения от парусов. Единица — как у линий тока,
// один в один; но струи живут по всей воде и на виду постоянно, поэтому берётся
// меньше: нужен намёк на обтекание, а не второй экземпляр отладочного слоя.
const STREAK_HEED = 0.55;
// Дальше этого от центра парусности решётка не опрашивается вовсе: там её
// возмущение всё равно тонет в свободном потоке, а вызовов набегает много.
const STREAK_NEAR = 26;
// Насколько быстро форма догоняет расчётную, 1/с. Хвост строится опросом потока
// на каждой станции, а поток у паруса шумит: порывы, качка, перекладка. Без
// памяти струя от кадра к кадру дёргается — и чем больше станций, тем заметнее,
// потому что дрожание накапливается вдоль ломаной. Здесь она догоняет расчётную
// форму по экспоненте: медленные изменения проходят целиком, быстрые гасятся.
const STREAK_EASE = 7;

const streaks = [];
const STREAK_V = STREAK_ST.length * 2;
const streakGeo = new BufferGeometry();
{
  const n = STREAK_N * STREAK_V;
  streakGeo.setAttribute('position', new Float32BufferAttribute(new Float32Array(n * 3), 3));
  // Направление струи и знаковая полуширина: из них шейдер и строит ленту.
  streakGeo.setAttribute('aDir', new Float32BufferAttribute(new Float32Array(n * 3), 3));
  streakGeo.setAttribute('aWide', new Float32BufferAttribute(new Float32Array(n), 1));
  streakGeo.setAttribute('aFade', new Float32BufferAttribute(new Float32Array(n), 1));
  const idx = [];
  for (let i = 0; i < STREAK_N; i++) {
    const b = i * STREAK_V;
    for (let k = 0; k < STREAK_ST.length - 1; k++) {
      const a = b + k * 2;
      idx.push(a, a + 1, a + 2, a + 1, a + 3, a + 2);
    }
  }
  streakGeo.setIndex(idx);
}

const streakMat = new MeshBasicNodeMaterial({
  color: 0xffffff, transparent: true, depthWrite: false, side: DoubleSide });
{
  const centre = positionGeometry;
  const dir = attribute('aDir', 'vec3');
  const wide = attribute('aWide', 'float');
  // Нормаль к струе, всегда лицом к глазу. Вырождение — когда смотришь вдоль
  // струи — гасится тем, что длина векторного произведения там стремится к нулю
  // вместе с видимой шириной: лента честно исчезает, а не дёргается.
  const toEye = cameraPosition.sub(centre);
  const side = cross(dir, toEye).normalize();
  streakMat.positionNode = centre.add(side.mul(wide));
  streakMat.opacityNode = attribute('aFade', 'float');
}
if (typeof streakMat.positionNode !== 'object' || !streakMat.positionNode) {
  throw new Error('TSL: выражение струй собралось не в узел');
}
const streakMesh = new Mesh(streakGeo, streakMat);
streakMesh.frustumCulled = false;
streakMesh.renderOrder = 2;
scene.add(streakMesh);

// Посадить струю: первый раз — равномерно по всему кругу, потом — на
// противоположный край от того места, где она вышла.
//
// Раздача менялась дважды. Сперва круг с посадкой у наветренного края: струи
// выходили оттуда пучком, а с подветра и с бортов было пусто. Потом полоса
// поперёк потока, сносимая насквозь: покрытие выровнялось, но осталась
// зависимость от скорости сноса. На полном курсе она и подвела: лодка идёт
// быстрее воздуха, струи отстают, и то, что подсеивается сзади, вперёд уже не
// доходит — впереди пусто. Поднять снос до порога не помогает: он всё равно
// меньше хода лодки.
//
// Круг привязан к лодке, поэтому важен не снос сам по себе, а снос ОТНОСИТЕЛЬНО
// неё. Струя, ушедшая за край, переносится в точку, симметричную относительно
// лодки, — и попадает ровно туда, откуда относительный поток идёт. Отставая, она
// вернётся спереди; обгоняя — сзади; вбок — с наветра. Плотность держится сама:
// поток равномерен, вход равен выходу, а перенос через центр сохраняет и
// распределение по краю (входов больше там, где поток входит отвеснее).
//
// Перенос годится, только когда струя ТОЛЬКО ЧТО пересекла край. Лодка умеет
// перескакивать: сброс, приход разметки через сеть, смена стартовой точки. Тогда
// за краем оказываются разом все и с одной стороны — перенос сложил бы их в одну
// точку, откуда они уже не разойдутся, потому что дальше сдвиг у всех общий.
// Так и было: после загрузки разметки все семьдесят стояли одним комком в
// семидесяти метрах от лодки, а в сцене не было видно ни одной. Поэтому далёкий
// выход — это не выход, а повод раздать заново.
//
// Разброс по радиусу квадратный: иначе все скучиваются у центра, где площади мало.
function seedStreak(st, ix, iy, ox, oz) {
  const d = ox === undefined ? 0 : Math.hypot(ox, oz);
  if (d > STREAK_R && d < STREAK_R * 1.1) {
    st.x = ix - ox / d * STREAK_R * 0.995;
    st.z = iy - oz / d * STREAK_R * 0.995;
  } else {
    const a = Math.random() * Math.PI * 2;
    const r = STREAK_R * Math.sqrt(Math.random());
    st.x = ix + Math.cos(a) * r;
    st.z = iy + Math.sin(a) * r;
  }
  st.y = STREAK_LO + Math.random() * (STREAK_HI - STREAK_LO);
  st.len = 6 + Math.random() * 15;
  st.w = STREAK_W * (0.6 + Math.random() * 0.9);
  st.k = 0.75 + Math.random() * 0.5;    // своя скорость: пучок не идёт стенкой
  st.fade = 0;                          // проявляется, а не возникает
  if (!st.pts) st.pts = new Float32Array(STREAK_ST.length * 2);
  st.warm = false;                      // первую форму ставим без сглаживания
}

// Местный поток в точке струи: свободный кажущийся ветер плюс возмущение от
// парусов, взятое у той же решётки, что кормит линии тока.
//
// Возвращает орт в осях СЦЕНЫ и множитель скорости. Дальше STREAK_NEAR от
// центра парусности решётка не опрашивается: там её возмущение всё равно тонет,
// а вызовов набегает много — струй семь десятков, станций по шесть у каждой.
const streakFree = { dx: 0, dz: 0, s: 1 };
const streakOut = { dx: 0, dz: 0, s: 1 };
const streakV = [0, 0, 0];
function streakFlow(sx, sz, h, ux, uy, aw, cpsi, spsi) {
  const lat = boat.rig.lattice;
  if (!lat) return streakFree;
  // Сцена → мир → оси лодки. Крен не учитывается, как и в линиях тока: решётка
  // живёт в горизонтной системе.
  const wx = toWorldX(sx) - boat.x, wy = toWorldY(sz) - boat.y;
  const bx = wx * cpsi + wy * spsi, by = -wx * spsi + wy * cpsi;
  const rig = boat.p.rig;
  const dcx = bx - (rig.ce_x_m != null ? rig.ce_x_m : rig.mast_x_m);
  const dch = h - rig.ce_height_m;
  if (dcx * dcx + by * by + dch * dch > STREAK_NEAR * STREAK_NEAR) return streakFree;

  lat.induced(bx, by, h, ux, uy, 0, true, streakV);
  // Возмущение приглушается: нужен намёк на обтекание, а не второй отладочный
  // слой. Полная величина у линий тока, здесь — доля.
  const vx = aw.x + streakV[0] * STREAK_HEED;
  const vy = aw.y + streakV[1] * STREAK_HEED;
  const sp = Math.hypot(vx, vy);
  if (!(sp > 1e-3)) return streakFree;
  // Обратно в мир и в сцену. Знаки — через тот же перевод, что у всего прочего.
  const wvx = (vx * cpsi - vy * spsi) / sp, wvy = (vx * spsi + vy * cpsi) / sp;
  streakOut.dx = toSceneX(wvx);
  streakOut.dz = toSceneZ(wvy);
  // Множитель скорости к свободному потоку — ограничен, чтобы у самой шкаторины
  // струя не выстреливала: решётка там даёт большие числа, а нам нужен намёк.
  streakOut.s = Math.max(0.35, Math.min(1.9, sp / Math.hypot(aw.x, aw.y)));
  return streakOut;
}

function updateStreaks(ix, iy, dt) {
  // Яркость — по КАЖУЩЕМУСЯ ветру, а не по истинному: показывают струи именно
  // его, и на полном курсе, где лодка уходит вместе с воздухом, им положено
  // бледнеть. В штиль их нет вовсе: рисовать движение воздуха там, где его нет,
  // значит врать ровно о том, ради чего они и заведены.
  const aw0 = boat.apparentWind();
  const amp = Math.max(0, Math.min(1, (Math.hypot(aw0.x, aw0.y) - 1.0) / 5));

  // Направление и скорость — КАЖУЩЕГОСЯ ветра, тем же способом, что у линий
  // тока. Он приходит в осях лодки, поэтому сначала разворачивается по курсу в
  // мир, а уже потом в сцену.
  const aw = aw0;
  const V = Math.hypot(aw.x, aw.y);
  streakMesh.visible = !wakeDark && amp > 0.01 && V > 0.3;
  topView.on = streakMesh.visible;
  if (!streakMesh.visible) return;
  const awDir = Math.atan2(aw.y, aw.x) + boat.psi;       // куда дует, в мире
  const dx = dirSceneX(awDir), dz = dirSceneZ(awDir);
  // Снос — настоящий, без нижнего предела. Порог тут стоял, пока струи
  // подсеивались с наветра и им приходилось догонять лодку; с переносом через
  // центр в этом нужды нет, а движение мимо камеры на полном курсе даёт сам ход
  // лодки — как и в жизни, где воздух почти неподвижен, а идёшь сквозь него.
  const v = V * STREAK_SPEED;
  // Всё, что нужно, чтобы спросить решётку: орт свободного потока в осях лодки
  // и синус с косинусом курса для перевода туда и обратно.
  const ux = aw.x / V, uy = aw.y / V;
  const cpsi = Math.cos(boat.psi), spsi = Math.sin(boat.psi);
  streakFree.dx = dx; streakFree.dz = dz; streakFree.s = 1;
  topView.x = ix; topView.z = iy;
  topView.dx = dx; topView.dz = dz; topView.v = v;

  const p = streakGeo.attributes.position.array;
  const ad = streakGeo.attributes.aDir.array;
  const awide = streakGeo.attributes.aWide.array;
  const af = streakGeo.attributes.aFade.array;

  for (let i = 0; i < STREAK_N; i++) {
    let st = streaks[i];
    if (!st) { st = streaks[i] = {}; seedStreak(st, ix, iy); }
    // Голова идёт с МЕСТНОЙ скоростью: над парусом поток разгоняется, перед ним
    // тормозит, и струи это показывают — тем же способом, что линии тока цветом.
    const hf = streakFlow(st.x, st.z, st.y, ux, uy, aw, cpsi, spsi);
    st.x += hf.dx * v * st.k * hf.s * dt;
    st.z += hf.dz * v * st.k * hf.s * dt;
    st.fade = Math.min(1, st.fade + dt * 0.8);
    const ox = st.x - ix, oz = st.z - iy;
    const away = Math.hypot(ox, oz);
    if (away > STREAK_R) seedStreak(st, ix, iy, ox, oz);

    // Гаснут к краю круга — с обеих сторон одинаково, потому что край теперь и
    // выход, и вход: где струя пропадает, там же другая и появляется.
    const edge = Math.max(0, Math.min(1, (STREAK_R - away) / (STREAK_R * 0.3)));
    // Плотность держится низкой нарочно: струи должны читаться боковым
    // зрением и не спорить с парусами, когда смотришь на них.
    const A = 0.62 * amp * st.fade * edge;
    st.A = A;                             // для вида сверху: рисуем что видно
    const L = st.len * (0.6 + 0.6 * amp);

    // Хвост строится ЛОМАНОЙ НАЗАД ПО ПОТОКУ, а не отрезком: на каждой станции
    // спрашивается местная скорость, и струя гнётся там, где гнётся поток.
    // Вдали от рига решётка не опрашивается, и ломаная вырождается в прямую —
    // ровно то, чем она и была.
    // Хвост считается ломаной назад по потоку, а потом СГЛАЖИВАЕТСЯ к прежней
    // форме: без этого он дрожит вслед за порывами и качкой, и дрожание тем
    // заметнее, чем больше станций.
    const ease = st.warm ? 1 - Math.exp(-STREAK_EASE * dt) : 1;
    let cx = st.x, cz = st.z;
    for (let k = 0; k < STREAK_ST.length; k++) {
      const t = STREAK_ST[k][0];
      if (k) {
        const seg = L * (t - STREAK_ST[k - 1][0]);
        const f = streakFlow(cx, cz, st.y, ux, uy, aw, cpsi, spsi);
        cx -= f.dx * seg; cz -= f.dz * seg;
      }
      st.pts[k * 2] += (cx - st.pts[k * 2]) * ease;
      st.pts[k * 2 + 1] += (cz - st.pts[k * 2 + 1]) * ease;
      // Считать дальше надо от СГЛАЖЕННОЙ точки, иначе память есть у каждой
      // станции по отдельности, а у ломаной как целого — нет, и она рвётся.
      cx = st.pts[k * 2]; cz = st.pts[k * 2 + 1];
    }
    st.warm = true;

    for (let k = 0; k < STREAK_ST.length; k++) {
      const [t, wk] = STREAK_ST[k];
      // Направление ленты — по самой ломаной, а не по потоку: лента обязана
      // стоять поперёк того, что нарисовано, иначе на изгибе её перекашивает.
      const j = k < STREAK_ST.length - 1 ? k : k - 1;
      let sdx = st.pts[j * 2] - st.pts[(j + 1) * 2];
      let sdz = st.pts[j * 2 + 1] - st.pts[(j + 1) * 2 + 1];
      const m = Math.hypot(sdx, sdz) || 1;
      sdx /= m; sdz /= m;
      // Хвост растворяется: альфа падает к нулю вместе с длиной.
      const fade = A * (1 - t) * (1 - t) * (1 - t);
      for (let e = 0; e < 2; e++) {
        const q = (i * STREAK_V + k * 2 + e);
        p[q * 3] = st.pts[k * 2]; p[q * 3 + 1] = st.y; p[q * 3 + 2] = st.pts[k * 2 + 1];
        ad[q * 3] = sdx; ad[q * 3 + 1] = 0; ad[q * 3 + 2] = sdz;
        awide[q] = (e ? -1 : 1) * wk * st.w;
        af[q] = fade;
      }
    }
  }
  streakGeo.attributes.position.needsUpdate = true;
  streakGeo.attributes.aDir.needsUpdate = true;
  streakGeo.attributes.aWide.needsUpdate = true;
  streakGeo.attributes.aFade.needsUpdate = true;
}

// --- запись состояния ---------------------------------------------------------
//
// Кнопка «сдампать» пишет в файл всё, что нужно, чтобы воспроизвести момент:
// состояние лодки, настройки, поле ветра — и запись последних двадцати секунд
// по шагам физики. Запись важнее снимка: жалобы на воде звучат как «дрожит»
// или «понемногу разгоняется», а это про поведение во времени, а не про одно
// мгновение.
//
// Поле ветра собственного состояния не имеет: оно однозначно задаётся
// скоростью, направлением, порывистостью и парой (положение, время). Значит
// восстановления лодки достаточно, чтобы получить тот же самый ветер.
//
// Проигрывается дамп без браузера: scripts/replay.mjs.
const TRACE_SECONDS = 20;
const recorder = new Recorder(TRACE_SECONDS, HZ);

function dumpState() {
  const t = boat.telemetry || {};
  return {
    build: typeof BUILD !== 'undefined' ? BUILD : null,
    // Отпечаток полей акватории. Запись, сделанная на ней, без неё не
    // воспроизводится — и об этом надо сказать вслух, а не разойтись молча.
    terrain: terrain.ready ? { hash: TERRAIN_PACK.hash } : null,
    saved: new Date().toISOString(),
    boat: {
      x: boat.x, y: boat.y, psi: boat.psi, u: boat.u, v: boat.v, r: boat.r,
      phi: boat.phi, p_: boat.p_, t: boat.t, rigSide: boat.rigSide,
      zc: boat.zc, w: boat.w, th: boat.th, q: boat.q,
    },
    controls: Object.assign({}, boat.o),
    wind: Object.assign({}, boat.wind.o),
    scene: {
      camera: CAMS[camMode], autopilot: autopilot, apHeading: apHeading,
      debug: debugOn,
    },
    telemetry: Object.assign({}, t, { strips: undefined }),
    strips: (t.strips || []).map(s => Object.assign({}, s)),
    rig: boat.rig.strips.map(s => ({
      h: s.h, area: s.area, chord: s.chord, xLuff: s.xLuff,
      ar: s.ar, twistF: s.twistF,
    })),
    trace: recorder.dump(),
    // Свободная пелена — короткой сводкой, а не целиком: узлов пятьсот с
    // лишним, и в дампе они заняли бы больше всего остального. Для разбора
    // хватает того, сколько её и куда она уехала.
    wake: boat.rig.wake && boat.rig.wake.n > 1 ? (() => {
      const w = boat.rig.wake, L = w.len;
      let far = 0, zlo = 1e9, zhi = -1e9;
      for (let f = 0; f < w.fil; f++) {
        for (let i = 0; i < w.n; i++) {
          far = Math.max(far, Math.hypot(w.x[f * L + i] - w.x[f * L],
                                         w.y[f * L + i] - w.y[f * L]));
          zlo = Math.min(zlo, w.z[f * L + i]);
          zhi = Math.max(zhi, w.z[f * L + i]);
        }
      }
      // Заодно — что реально лежит в буфере отрисовки: сколько вершин, куда
      // они разъехались и виден ли объект. Без этого «пелены не видно»
      // разбирается перебором догадок. Координаты тут МИРОВЫЕ, поэтому рядом
      // кладётся и место лодки: без него «max = 380» ни о чём не говорит.
      const gp = wakeGeo.attributes.position;
      let vmin = 1e9, vmax = -1e9;
      if (gp) for (let i = 0; i < gp.count * 3; i++) {
        vmin = Math.min(vmin, gp.array[i]); vmax = Math.max(vmax, gp.array[i]);
      }
      return { fil: w.fil, nodes: w.n, far: +far.toFixed(2),
               at: [+boat.x.toFixed(1), +boat.y.toFixed(1)],
               zlo: +zlo.toFixed(2), zhi: +zhi.toFixed(2),
               g: Array.from(w.g, v => +v.toFixed(3)),
               draw: gp ? { vert: gp.count, min: +vmin.toFixed(2), max: +vmax.toFixed(2),
                            vis: wakeLines.visible,
                            r: wakeGeo.boundingSphere ? +wakeGeo.boundingSphere.radius.toFixed(1) : null }
                        : null };
    })() : null,
  };
}

// Загрузка дампа: файл бросают в окно.
//
// Восстанавливается то, из чего складывается положение дел: состояние лодки,
// органы управления, ветер и вид. Не восстанавливается запись (`trace`) — она
// нужна проигрывателю, а не живому симулятору, — и не восстанавливается режим
// физики паруса: дамп читается безусловно на измеренной поляре, иначе один и
// тот же файл давал бы разный ответ в зависимости от галочки.
//
// Акватория при этом НЕ подменяется: если дамп снят на другой, лодка встанет в
// те же координаты на нынешней, и об этом говорится вслух. Тень берега и
// поворот ветра долиной зависят от места, и молча разойтись тут проще всего.
function loadDump(d) {
  if (!d || !d.boat || !d.controls) throw new Error('это не дамп симулятора');
  Object.assign(boat.o, d.controls);
  // Старый дамп знает шкот стакселя поправкой к гроту, новый — своим углом.
  if (d.controls.jibSheet == null) {
    boat.o.jibSheet = d.controls.sheet + (d.controls.jibTrim || 0);
  }
  if (d.controls.jibTwist == null) boat.o.jibTwist = null;
  if (d.controls.jibDraft == null) boat.o.jibDraft = null;
  boat.o.mainUp = d.controls.mainUp !== false;
  boat.o.jibUp = d.controls.jibUp !== false;
  Object.assign(boat, d.boat);
  Object.assign(boat.wind.o, d.wind || {});
  if (d.scene) {
    autopilot = !!d.scene.autopilot;
    apHeading = d.scene.apHeading != null ? d.scene.apHeading : boat.psi;
  }
  setSailPhysics(false);
  syncPanelFromBoat();
  wake.clear();
  trackN = 0;
  const mine = terrain.ready ? TERRAIN_PACK.hash : null;
  const theirs = d.terrain ? d.terrain.hash : null;
  return theirs === mine ? '' : (theirs && mine ? ' (снят на другой акватории)'
                               : theirs ? ' (снят с акваторией, у нас её нет)'
                                        : ' (снят без акватории)');
}

// Панель после загрузки обязана показывать то, что в лодке, а не то, что на ней
// стояло. Иначе первый же кадр `readControls` вернёт всё обратно с ползунков.
function syncPanelFromBoat() {
  const o = boat.o, set = (id, v) => {
    const el = ui[id];
    if (!el) return;
    if (el.type === 'checkbox') el.checked = !!v; else el.value = v;
    el.dispatchEvent(new Event('input'));
  };
  set('wind', o.windSpeed);
  set('winddir', Math.round(((o.windDir / D) % 360 + 360) % 360));
  set('hike', o.crewHike);
  set('sailscale', o.sailScale);
  set('gust', boat.wind.o.gust);
  set('mainsheet', Math.round(o.sheet / D));
  set('twist', Math.round(o.twist / D));
  set('draft', Math.round(o.draft * 100));
  set('jibsheet', Math.round(jibSheetOf(o) / D));
  set('jibtwist', Math.round((o.jibTwist != null ? o.jibTwist : o.twist) / D));
  set('jibdraft', Math.round((o.jibDraft != null ? o.jibDraft : o.draft) * 100));
  set('mainup', o.mainUp !== false);
  set('jibup', o.jibUp !== false);
  set('oldsail', false);
  set('fetch', o.fetch / 1000);
  set('fetchover', o.fetchOverride);
  if (ui.cur) set('cur', o.current);
}

// Бросить файл можно куда угодно в окне: целиться в кнопку — лишняя работа для
// того, кто разбирается с застрявшей лодкой.
addEventListener('dragover', e => { e.preventDefault(); document.body.classList.add('drop'); });
addEventListener('dragleave', e => {
  if (e.relatedTarget === null) document.body.classList.remove('drop');
});
addEventListener('drop', e => {
  e.preventDefault();
  document.body.classList.remove('drop');
  const f = e.dataTransfer && e.dataTransfer.files && e.dataTransfer.files[0];
  if (!f) return;
  const btn = document.getElementById('dump');
  f.text().then(txt => {
    const note = loadDump(JSON.parse(txt));
    if (btn) {
      btn.textContent = 'загружено: ' + f.name.slice(0, 28) + note;
      setTimeout(() => { btn.textContent = 'Сдампать состояние'; }, 4000);
    }
  }).catch(err => {
    if (btn) {
      btn.textContent = 'не дамп: ' + err.message;
      setTimeout(() => { btn.textContent = 'Сдампать состояние'; }, 4000);
    }
  });
});

function saveDump() {
  const name = 'sv20-' + new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  const blob = new Blob([JSON.stringify(dumpState(), null, 1)],
                        { type: 'application/json' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name + '.json';
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 2000);
  const btn = document.getElementById('dump');
  if (btn) {
    btn.textContent = 'записано: ' + recorder.frames.length + ' кадров';
    setTimeout(() => { btn.textContent = 'Сдампать состояние'; }, 2200);
  }
}

// --- акватория: рельеф, покров, дальняя вода ----------------------------------
//
// Всё, что ниже, включается только когда есть пакет акватории. Без него ничего
// не создаётся вовсе, и сцена остаётся прежней — бесконечная вода со знаками.
//
// Оси: земля кладётся в правую сцену — three = (x, высота, -y), X на восток,
// Y мира на север. Ошибка знака по Y отражает участок зеркально, и
// глазом это не ловится совершенно: река на месте, берега на месте. Ловится
