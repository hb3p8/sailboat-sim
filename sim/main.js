// Отбрасывает тень только лодка. Всё остальное в сцене тень не отбрасывает и не
// принимает: карта акватории снята с этого нарочно (см. загрузку GLB), а вода
// только принимает.
//
// Зовётся это НЕ ЗДЕСЬ, а после того, как лодка собрана, и ещё раз — когда
// приедут фигурки. Первый заход стоял ровно тут, сразу за `scene.add`, и флаг не
// достался ни одной части: корпус добавляется тридцатью строками ниже, паруса
// полутора сотнями, экипаж вообще приходит с сервера. Обход пустой группы
// отработал молча, теней не было, и выглядело это как «тени не поддерживаются».
function boatCastsShadow() {
  // И ОТБРАСЫВАЕТ, И ПРИНИМАЕТ. Второе я забыл, и это стоило ещё одного круга:
  // лодка исправно отбрасывала тень, но принять её было некому — палубе никто
  // не разрешал. Тень фигурки падала на поверхность, которая её не смотрит, и
  // выглядело это опять как «теней нет». Самозатенение — это ровно пара флагов,
  // и нужны оба.
  boatGroup.traverse(o => {
    if (!o.isMesh) return;
    o.castShadow = true;
    o.receiveShadow = true;
  });
}

function meshFrom(data, colour, rough, metal) {
  const g = new BufferGeometry();
  g.setAttribute('position', new Float32BufferAttribute(data.positions, 3));
  g.setIndex(data.indices);
  g.computeVertexNormals();
  return new Mesh(g, new MeshStandardMaterial({
    color: new Color(colour), roughness: rough == null ? 0.45 : rough,
    metalness: metal == null ? 0.05 : metal, side: DoubleSide,
  }));
}

