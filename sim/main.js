// --- экипаж -------------------------------------------------------------------
//
// Фигурка сидит — значит и сажать её надо на борт, а не ставить на палубу.
// Поэтому поперёк она стоит не по плечу откренивания, а прямо на линии борта:
// зад над кромкой, ноги внутрь. Борт — наветренный, то есть противоположный
// парусу, и во время поворота экипаж переползает через лодку вместе с ним.
//
// Само плечо при этом никуда не делось, его показывает подпись ползунка. Физика
// откренивает не по ползунку, а против кренящего момента (physics.js, `hike`):
// в слабый ветер экипаж сидит спокойно, в порыв выкладывается, и делает это с
// запаздыванием. Ползунок задаёт лишь верхний предел, и без подписи сто
// процентов на нём читались бы как враньё.
//
// Модель приходит с сервера: ровно на этом месте страница перестала быть
// самодостаточной. Без сервера фигурок не будет, всё остальное работает как
// прежде — поэтому загрузка и не мешает ничему стартовать.

const CREW_H = 0.92;                 // габарит фигурки по высоте, м
// Фигурка занимает вдоль лодки метр с небольшим — отсюда и шаг станций. Ноги у
// неё разнесены поперёк почти на полтора метра, и это удачно: так сидит на борту
// откренивающий экипаж, ступни внутрь.
const CREW_X = [1.15, 2.20, 3.25];   // станции вдоль лодки, м от транца
// Линия борта на этих станциях — из самой сетки корпуса, а не числом в коде:
// фигурка сидит, и сажать её надо на борт, а он и по высоте, и по ширине на
// каждой станции свой. Берётся полуширина по верхней кромке и её высота.
const CREW_SHEER = CREW_X.map(x0 => {
  const p = MESH.hull.positions;
  let top = -1e9;
  for (let i = 0; i < p.length; i += 3)
    if (Math.abs(p[i] - x0) < 0.12 && p[i + 1] > top) top = p[i + 1];
  let half = 0;
  for (let i = 0; i < p.length; i += 3)
    if (Math.abs(p[i] - x0) < 0.12 && p[i + 1] > top - 0.03)
      half = Math.max(half, Math.abs(p[i + 2]));
  return [half, top];
});

// Середина посадки и высота сиденья — для физики: вес экипажа приложен там же,
// где стоят фигурки. Высота берётся по линии борта, а не по палубе: сидят на
// борту, и центр тяжести сидящего примерно на треть роста выше сиденья.
const CREW_MID = CREW_X.reduce((a, b) => a + b, 0) / CREW_X.length;
const CREW_SEAT = CREW_SHEER.reduce((a, s) => a + s[1], 0) / CREW_SHEER.length
                  + CREW_H * 0.33;

const crewFigs = [];
let crewLegs = 0;                    // куда вытянуты ноги в осях модели, рад
const crewGroup = new Group();
boatGroup.add(crewGroup);

new GLTFLoader()
  .setDRACOLoader(new DRACOLoader().setDecoderPath('../viewer/vendor/draco/'))
  .load('../assets/crew.glb', gltf => {
    // Рост и посадка берутся из самой модели, а не из числа в коде: заменят
    // фигурку — и всё сойдётся само.
    const box = new Box3().setFromObject(gltf.scene);
    const size = new Vector3(); box.getSize(size);
    const k = CREW_H / size.y;
    // Габарит не говорит, где у сидящей фигурки зад, а где носки, — а сажать её
    // надо задом на борт и ногами внутрь. Поэтому ось тела и направление ног
    // берутся из самих вершин: центр верхней половины — это торс с головой,
    // центр нижней пятой — ступни. Разность и есть «куда вытянуты ноги».
    let geo = null;
    gltf.scene.traverse(o => { if (!geo && o.isMesh) geo = o.geometry; });
    const pa = geo.attributes.position;
    const midY = (box.min.y + box.max.y) / 2, lowY = box.min.y + size.y * 0.2;
    let tx = 0, tz = 0, tn = 0, fx = 0, fz = 0, fn = 0;
    for (let i = 0; i < pa.count; i++) {
      const y = pa.getY(i);
      if (y > midY) { tx += pa.getX(i); tz += pa.getZ(i); tn++; }
      else if (y < lowY) { fx += pa.getX(i); fz += pa.getZ(i); fn++; }
    }
    tx /= tn || 1; tz /= tn || 1; fx /= fn || 1; fz /= fn || 1;
    crewLegs = Math.atan2(fz - tz, fx - tx);
    for (let i = 0; i < CREW_X.length; i++) {
      const g = new Group();
      const fig = i ? gltf.scene.clone() : gltf.scene;
      fig.scale.setScalar(k);
      // Начало группы — ось тела на уровне низа фигурки: вокруг неё и разворот,
      // и посадка на борт.
      fig.position.set(-tx * k, -box.min.y * k, -tz * k);
      g.add(fig);
      crewGroup.add(g);
      crewFigs.push(g);
    }
  }, undefined, err => console.warn('фигурка экипажа не загрузилась:', err));

// Плечо: какой момент экипаж создаёт сейчас, делённый на его вес. Груз на левом
// борту (+Y) даёт момент отрицательный, отсюда знак. Не ограничивается ничем:
// фигурки обязаны стоять там, где физика держит экипаж, и если он окажется за
// бортом — это и надо увидеть, а не спрятать.
//
// Считается в одном месте: то же плечо ставит фигурки и рисует стрелку их веса
// в отладке баланса, и разъезжаться этим двум нельзя.
function crewArm() {
  const m = boat.o.crewMass;
  return m > 0 ? boat.hike / (m * PACK.environment.g) : 0;
}

function updateCrew() {
  if (!crewFigs.length) return;
  const arm = crewArm();
  // Поперёк фигурки двигает плечо, а разворачивает — борт паруса. Знак плеча
  // для разворота не годится: у оси он вырождается в ноль, и фигурки принялись
  // бы крутиться на месте. Борт берётся тем же выражением, каким рисуется
  // парус, с обратным знаком: экипаж на наветренном борту по определению есть
  // «не там, где парус». Величина непрерывна, и в повороте, пока гик идёт через
  // лодку, доворот сам собой уходит в ноль.
  const side = -rigSideZ(boat.rigSide != null ? boat.rigSide : 1);
  for (let i = 0; i < crewFigs.length; i++) {
    const f = crewFigs[i], sheer = CREW_SHEER[i];
    f.position.set(bodyPointLocalX(CREW_X[i]), bodyPointLocalY(sheer[1]),
                   bodyPointLocalZ(-arm));
    // Разворот зависит от того, где человек сидит. У оси лодки сидеть боком
    // не с чего — там садятся лицом по курсу; на борту разворачиваются ногами
    // внутрь. Между этими двумя положениями переход по тому же плечу, каким
    // фигурки и двигаются, со сглаживанием на концах: без него на самом борту
    // виден излом, а у оси — рывок с места.
    //
    // Поворот three вокруг Y уменьшает угол в плоскости XZ, поэтому нулевой
    // доворот оставляет ноги смотреть вперёд, а полный уводит их к -side.
    const t = Math.min(1, Math.abs(arm) / sheer[0]);
    f.rotation.y = crewLegs + t * t * (3 - 2 * t) * side * Math.PI / 2;
  }
  if (capHike) capHike.textContent =
    (boat.o.crewHike * 100).toFixed(0) + '% · плечо ' + Math.abs(arm).toFixed(2) + ' м';
}

// --- сетка на воде ------------------------------------------------------------
//
// Однородная вода не даёт ощущения хода: лодка будто висит. Сетка привязана к
// миру, а не к лодке, и переставляется шагами по ячейке — получается
// бесконечное поле, по которому видно и скорость, и снос, и поворот.
//
// Прибор, а не обстановка: сетка мерит ход в метрах, и на воде её нет. Поэтому
// она включается вместе с остальной отладкой, а не живёт всегда.

// Дробление вдоль линии измельчено с двух до восьми вместе с переходом волны на
// БПФ: сетка лежит НА воде, а лечь на волну она может только там, где сама эту
// волну разрешает. С двухметровым звеном она резала гребни хордами и висела над
// подошвами — прибор врал ровно тем, что мерил.
const GRID_STEP = 5, GRID_HALF = 11, GRID_SUB = 8;
const gridLines = [];
{
  const n = GRID_HALF * 2, m = n * GRID_SUB;
  for (let i = 0; i <= n; i++) {
    const a = (i - GRID_HALF) * GRID_STEP;
    for (let j = 0; j < m; j++) {
      const b0 = (j / GRID_SUB - GRID_HALF) * GRID_STEP;
      const b1 = ((j + 1) / GRID_SUB - GRID_HALF) * GRID_STEP;
      gridLines.push([a, b0], [a, b1]);          // вдоль Z
      gridLines.push([b0, a], [b1, a]);          // вдоль X
    }
  }
}
const gridGeo = new BufferGeometry();
gridGeo.setAttribute('position',
  new Float32BufferAttribute(new Float32Array(gridLines.length * 3), 3));
gridGeo.setAttribute('color',
  new Float32BufferAttribute(new Float32Array(gridLines.length * 3), 3));
const gridMat = new LineBasicNodeMaterial({
  vertexColors: true, transparent: true, opacity: 0.5, depthWrite: false });
// Сетку на волну кладёт та же выборка, что и воду. Не «та же формула», а
// буквально тот же узел из ocean.js: две реализации одной поверхности разошлись
// бы, и разошлись бы незаметно — прибор поехал бы вместе с тем, что мерит.
//
// Веса каскадов здесь постоянные: звено сетки везде одно и то же, и считать их
// на вершину незачем. Считаются они той же формулой, что у воды, — сетка обязана
// не разрешать ровно то же, чего не разрешает вода под ней, иначе она либо
// провалится в гребень, либо повиснет над ним.
{
  const cell = GRID_STEP / GRID_SUB;
  const w = OCEAN_TILES.map(tile => {
    const a = tile / 3, b = tile / 12;
    const x = Math.max(0, Math.min(1, (cell - a) / (b - a)));
    return x * x * (3 - 2 * x);
  });
  const ref = modelWorldMatrix.mul(vec4(positionGeometry, 1.0)).xyz;
  const d = ocean.displace(vec2(ref.x, ref.z.negate()), i => float(w[i]));
  gridMat.positionNode = positionLocal.add(vec3(d.x, d.z, d.y.negate()));
}
const grid = new LineSegments(gridGeo, gridMat);
grid.frustumCulled = false;
scene.add(grid);
const GRID_FADE = GRID_HALF * GRID_STEP;

// Плоская заготовка: высоту сетке даёт шейдер, здесь только положение в мире и
// цвет. Пересчитывать её каждый кадр незачем — она переставляется шагами по
// ячейке и между шагами не меняется.
const gridAt = { x: NaN, z: NaN };
function updateGrid(cx, cz) {
  const ox = Math.round(cx / GRID_STEP) * GRID_STEP;
  const oz = Math.round(cz / GRID_STEP) * GRID_STEP;
  if (gridAt.x === ox && gridAt.z === oz) return;
  gridAt.x = ox; gridAt.z = oz;
  const p = gridGeo.attributes.position.array;
  const c = gridGeo.attributes.color.array;
  for (let i = 0; i < gridLines.length; i++) {
    p[i * 3] = ox + gridLines[i][0];
    p[i * 3 + 1] = 0.03;
    p[i * 3 + 2] = oz + gridLines[i][1];
    const d = Math.max(Math.abs(gridLines[i][0]), Math.abs(gridLines[i][1]));
    const f = Math.max(0, 1 - d / GRID_FADE);
    const v = 0.35 + 0.45 * f * f;
    c[i * 3] = v; c[i * 3 + 1] = v * 1.05; c[i * 3 + 2] = v * 1.1;
  }
  gridGeo.attributes.position.needsUpdate = true;
  gridGeo.attributes.color.needsUpdate = true;
}

