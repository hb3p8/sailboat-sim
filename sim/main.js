let wakeDark = false;
stage.appendChild(renderer.domElement);

// Полусферический свет остался, но приглушён впятеро: он был подпоркой на месте
// неба, а теперь небо есть настоящее и светит само — картой окружения. Оставлять
// обоих в полную силу значит светить сцену дважды, что и вышло на первом заходе:
// лодка выбелилась до потери обводов, борт с парусом слились в одно белое пятно.
const skyFill = new HemisphereLight(0xe8f4ff, 0x2b4a63, 0.5);
scene.add(skyFill);
const sun = new DirectionalLight(0xfff2dc, 1.5);
// Куда светит солнце. Есть два честных ответа, и стоит по умолчанию среднее.
//
// ПО КАРТЕ НЕБА. Направление снято с самого файла при сборке
// (scripts/build_sky.py) и вклеено сюда числом — нарисованный диск и источник
// света должны совпасть, иначе блик на воде лежит не под солнцем, а это глаз
// ловит мгновенно, даже не понимая, что именно не так. Беда в том, что небо на
// карте закатное: солнце в четырёх градусах над горизонтом. Светит оно
// скользяще, палуба прямого света почти не получает, теням падать некуда —
// лодка выходит плоской.
//
// ПОДНЯТОЕ к полудню даёт и объём, и тени, но с нарисованным диском расходится
// уже вопиюще: солнце у горизонта, а свет сверху.
//
// СРЕДНЕЕ между ними — двадцать шесть градусов. Что делает эту середину не
// компромиссом наполовину, а почти бесплатной: у обоих направлений ПОЧТИ ОДИН
// АЗИМУТ, 216 и 221 градус. Значит по компасу солнце остаётся там же, где
// нарисовано, и блик ложится в правильную СТОРОНУ; расходится только высота. А
// глаз ловит именно сторону — «блик не оттуда» видно сразу, «блик выше, чем
// должен» не видно вовсе.
//
// Оба конца остались доступны: `?sunmap` — ровно как на карте, `?sunhigh` — как
// в полдень. Первым проверяют совпадение с небом, вторым — тени. Без карты
// остаётся прежнее положение: сцена должна светиться и когда сервера нет.
const SUN_MAP = (SKY_PACK && SKY_PACK.sun)
  ? new Vector3(SKY_PACK.sun[0], SKY_PACK.sun[1], SKY_PACK.sun[2]).normalize()
  : new Vector3(toSceneX(-70), 80, toSceneZ(50)).normalize();
const SUN_HIGH = new Vector3(-0.5, 0.75, -0.43).normalize();
const SUN_DIR = location.search.includes('sunmap') ? SUN_MAP.clone()
  : location.search.includes('sunhigh') ? SUN_HIGH.clone()
  : SUN_MAP.clone().add(SUN_HIGH).normalize();

// Как далеко ставится источник. Ближе — точнее глубина у теневой карты, дальше
// — не влезает коробка; шестьдесят метров держат и то, и другое.
const SHADOW_LIGHT = 60;
sun.position.copy(SUN_DIR).multiplyScalar(SHADOW_LIGHT);
sun.castShadow = true;
// Коробка теней размером с лодку с запасом, а не со сцену. Размер тут спорит сам
// с собой: солнце над горизонтом на четыре градуса, и тень девятиметровой мачты
// вытягивается на сто тридцать метров. Коробка в лодку такую тень обрезает у
// самого борта — первый заход так и кончился, тени не было видно вовсе. Коробка
// во всю тень размазывает карту так, что от паруса остаётся серое пятно.
//
// Взято среднее: восемьдесят метров и сдвиг коробки ПО ТЕНИ, а не по лодке.
// Лодка стоит у ближнего края, тень уходит вглубь, и её читаемая часть — первые
// полсотни метров, где ещё различимы мачта и парус, — попадает целиком.
// КОРОБКА ТЕНЕЙ ПОДОГНАНА ПОД ЛОДКУ, и ни подо что больше. Тени тут нужны от
// паруса на палубу и от фигурки на банку — то есть внутри двенадцати метров.
// Всё остальное теней не отбрасывает и не принимает: карта акватории снята с
// этого нарочно, вода тоже.
//
// Прежняя коробка тянулась на восемьдесят метров — ловила стосорокаметровую тень
// мачты при закатном солнце. Ловила напрасно: падает она на воду, а вода теней
// не показывает. Зато карту размазывало так, что на фигурку приходилось
// полтексела, и её тень не могла бы появиться ни при каком солнце.
//
// Двенадцать метров на две тысячи текселов — это сантиметр на тексель. Пуговицу
// не разглядеть, а руку видно.
const SHADOW_BOX = 12;
// Карта теней. Тысяча на телефоне: тень тут одна, от лодки, и коробка под неё
// маленькая — на мелком экране разницы не видно, а это отдельный проход по всей
// геометрии каждый кадр.
sun.shadow.mapSize.set(MOBILE_UI ? 1024 : 2048, MOBILE_UI ? 1024 : 2048);
sun.shadow.camera.left = -SHADOW_BOX;
sun.shadow.camera.right = SHADOW_BOX;
sun.shadow.camera.top = SHADOW_BOX;
sun.shadow.camera.bottom = -SHADOW_BOX;
// Ближняя и дальняя плоскости вплотную вокруг лодки. Это не экономия, а
// точность: у теневой карты глубина хранится в долях диапазона камеры.
sun.shadow.camera.near = SHADOW_LIGHT - SHADOW_BOX * 2;
sun.shadow.camera.far = SHADOW_LIGHT + SHADOW_BOX * 2;

// Смещение задаётся normalBias, В МЕТРАХ, а не bias в долях глубины. Стояло
// bias = −0.0012 при диапазоне в девятьсот метров — то есть смещение больше
// метра в мире, и фигурка ростом полтора метра проваливалась в него целиком.
sun.shadow.bias = 0;
sun.shadow.normalBias = 0.02;
scene.add(sun);
// Источник светит НА ЛОДКУ: коробка теней едет вместе с ней, иначе лодка из неё
// выходит на первых же ста метрах и тень пропадает.
scene.add(sun.target);

// Отладка теней: «тень чёрная». Смысл в том, чтобы вопрос «есть тень или нет»
// перестал быть вопросом вкуса. При низком солнце скользящий свет сам по себе
// кладёт на палубу тёмное, и отличить его от тени на глаз нельзя — я на этом
// уже ошибся, приняв одно за другое.
//
// Режим гасит ВСЁ, кроме солнца: небо как источник, полусферический свет, фон.
// Что не освещено солнцем напрямую — становится чёрным. Тень тогда не «темнее»,
// а именно чёрная, и её край видно с точностью до пикселя.
//
// Первое же включение и окупило затею: чёрной стала вся лодка целиком. Значит
// дело не в мягкости тени, а в том, что с этой стороны на неё вообще не падает
// солнце, — и заодно нашлось, что флаг «отбрасывает тень» не достался ни одной
// части лодки (см. boatCastsShadow). Вместе с `?sunhigh` это вопрос одного кадра.
let hardShadow = false;
let skyTex = null;

function setHardShadow(on) {
  hardShadow = on;
  skyFill.intensity = on ? 0 : 0.5;
  sun.intensity = on ? 3.2 : 1.5;
  scene.environmentIntensity = on ? 0 : 0.9;
  // Фон ровным серым: на снимке неба чёрную тень не разглядеть у горизонта, а
  // серое даёт ей опору для глаза.
  scene.background = on ? new Color(0x6a7480) : (skyTex || SKY);
  scene.fog = on ? null : sceneFog;
}

// Небо картой, а не одним цветом. Грузится с сервера, как экипаж и карта
// акватории: полтораста килобайт незачем нести в файле, который открывают
// двойным кликом. Пока не пришло — фон остаётся ровным цветом, и это не
// заглушка, а полноправный вид: страница без сервера так и работает.
//
// Карта идёт и в ОКРУЖЕНИЕ. Отражение воды считает зеркальный проход, но всё,
// что он не поймал, — и матовые поверхности корпуса с парусом — берут свет
// отсюда, а не из ровной полусферы. Ради этого небо и снималось.
new TextureLoader().load('../assets/sky.jpg', tex => {
  tex.mapping = EquirectangularReflectionMapping;
  tex.colorSpace = SRGBColorSpace;
  skyTex = tex;
  scene.background = tex;
  scene.environment = tex;
  scene.environmentIntensity = 0.9;
  if (hardShadow) setHardShadow(true);   // режим включили до загрузки неба
}, undefined, () => {
  console.warn('assets/sky.jpg не открылся — небо остаётся ровным цветом');
});

// ------------------------------------------------------------------- вода
//
// Вода одна на всё: и та, что под лодкой, и та, что до самого тумана. Второй,
// плоской, для дали нет и не будет — а значит нет и шва между ними, и нет
// второй реализации цвета. Это то же правило, что уже записано ниже про поле
// порывов: одно поле — одна реализация. Стоило нарушить его один раз, и вода
// пошла полосами, а физика при этом была права.
//
// Сетка при этом РАВНОМЕРНОЙ быть не может. Волны должны читаться в метре от
// борта, а вода — доставать до берега в километре; равномерная сетка на такой
// размах это девять тысяч ячеек в ряду. Поэтому она сгущается к лодке:
//
//     x = A·u + B·u³,   u ∈ [−1, 1]
//
// Кубическая часть растягивает край, линейная держит середину. A подобрано так,
// чтобы у лодки ячейка была полметра, A + B даёт нужный радиус. У SV20 с
// акваторией это полметра под бортом и сто на семи километрах — при
// четырёхстах делениях.
//
// Делений вчетверо прибавлено вместе с переходом волны на БПФ (ocean.js), и
// прибавлено не для красоты. Ячейка растёт как квадрат удаления, и на прежних
// ста пятидесяти делениях она добиралась до семи метров уже в полусотне метров
// от борта — то есть основная волна, та самая, которой лодку и качает, дальше
// тридцати метров просто не рисовалась. Теперь она держится до сотни.
//
// Стоить это стало не дороже, а дешевле: смещение вершин ушло с процессора на
// видеокарту, и сто шестьдесят тысяч вершин там считаются быстрее, чем двадцать
// две тысячи считались здесь. Нормали, которые раньше пересчитывались через
// кадр по всей сетке, не считаются вовсе — они приходят из карты.
//
// Сетка ездит за лодкой шагами по ЦЕНТРАЛЬНОЙ ячейке, чтобы сгущение всегда
// приходилось на лодку, а волна и цвет считались по мировым координатам и
// оттого не ползли.

// Дробление сетки воды. На телефоне вдвое реже: 200×200 это вчетверо меньше
// вершин, а ячейка под лодкой остаётся полуметровой (CELL ниже) — мельче неё
// волна всё равно рисуется рябью в шейдере, а не геометрией.
const SEG = MOBILE_UI ? 200 : 400;

// Цвет воды — ПАРА цветов, а не один.
//
// Одним цветом вода не красится ни в природе, ни на картинке. Глубина уносит
// свет: смотришь в толщу — видишь почти чёрное. А на гребне слой тонкий, свет
// проходит его насквозь и рассеивается — гребень светится, и цвет у него
// совсем другой, зеленоватый или бирюзовый. Ровно по этому свечению глаз и
// читает, где гребень: с одним цветом волна опознаётся только по бликам, а на
// пологой волне бликов почти нет.
//
// Наборы взяты из чужой готовой воды (threejswaterpro), где они подобраны
// художником и проверены на глазах: свои три числа тут подбирались бы неделю и
// вышли бы хуже. Первый — арктический, холодный и тёмный; он и стоит по
// умолчанию, потому что здешнее небо серо-голубое и тёплая вода под ним
// выглядит крашеной. «Река» — прежний цвет этого симулятора, разложенный на ту
// же пару.
const SEA_LOOKS = [
  { id: 'arctic', name: 'Арктика', deep: 0x162731, scatter: 0x719cb8 },
  { id: 'river', name: 'Река', deep: 0x1d3d52, scatter: 0x4a86ab },
  { id: 'storm', name: 'Шторм', deep: 0x1b2a32, scatter: 0x346565 },
  { id: 'dusk', name: 'Сумерки', deep: 0x112a37, scatter: 0x1e675c },
];
const seaDeep = uniform(new Color(SEA_LOOKS[0].deep));
const seaScatter = uniform(new Color(SEA_LOOKS[0].scatter));
// Цвет пены оттуда же и один на все виды: взбитая вода везде одинаково белая.
const SEA_FOAM_COLOUR = 0xedf9fd;
// Докуда стелется вода. С акваторией — до тумана, чтобы река доходила до
// берега; без неё дальше двухсот метров всё равно ничего нет.
const SEA_FAR = FAR_WATER ? 7000 : 260;
const CELL = 0.5;                       // ячейка под лодкой, м
const SEA_A = CELL * (SEG / 2);
const SEA_B = SEA_FAR - SEA_A;
const seaGeo = new PlaneGeometry(2, 2, SEG, SEG);
seaGeo.rotateX(-Math.PI / 2);
// Размер ячейки в каждой вершине. По нему в шейдере гасятся каскады волны:
// далёкая ячейка в сотни метров волну не разрешает, и считать её там значит не
// рисовать волну, а разводить муар из ошибок дискретизации. Гасится по размеру
// ячейки, а не по расстоянию: размер и есть то, из-за чего гасить.
//
// Раньше это был один вес на вершину, посчитанный на процессоре. Теперь в
// атрибут кладётся сам размер, а решение, какой каскад на нём ещё жив,
// принимается там же, где известны размеры плиток, — в шейдере.
const seaCell = new Float32Array((SEG + 1) * (SEG + 1));
{
  const p = seaGeo.attributes.position.array;
  const warp = u => SEA_A * u + SEA_B * u * u * u;
  const du = 2 / SEG;
  for (let i = 0, v = 0; i < p.length; i += 3, v++) {
    // производная кубической растяжки в этой точке и есть размер ячейки
    const cx = (SEA_A + 3 * SEA_B * p[i] * p[i]) * du;
    const cz = (SEA_A + 3 * SEA_B * p[i + 2] * p[i + 2]) * du;
    seaCell[v] = Math.max(cx, cz);
    p[i] = warp(p[i]);
    p[i + 2] = warp(p[i + 2]);
  }
}
seaGeo.setAttribute('seaCell', new Float32BufferAttribute(seaCell, 1));
const seaMat = new MeshStandardNodeMaterial({ roughness: 0.28, metalness: 0.12 });
const sea = new Mesh(seaGeo, seaMat);
// Вода теней не принимает. Не по забывчивости: её вид держит отражение, а оно
// сидит в свечении, куда тень по устройству не попадает, — и тень на воде
// оказывалась бы посчитанной и невидимой. Когда понадобится, её придётся
// заводить внутрь самого выражения воды, а не флагом.
sea.frustumCulled = false;
// Вода рисуется ПОСЛЕДНЕЙ из непрозрачных. Отражения экранного пространства
// (ниже) читают снимок уже нарисованной сцены, и вода в этом снимке оказаться не
// должна — иначе она отразит сама себя. По умолчанию непрозрачные идут спереди
// назад, и вода, накрывающая камеру, уходила бы в самое начало.
sea.renderOrder = 1;
scene.add(sea);

// Море. Считается целиком на видеокарте, каждый кадр; здесь только заводится и
// раз в кадр получает состояние моря от физики — см. `frame`.
const ocean = new Ocean(renderer, 1);

// --- поверхность под корпусом --------------------------------------------------
//
// То, что плавучесть считает водой. Пять проб по корпусу — центр, нос, корма и
// оба борта, — и по ним подгоняется плоскость: высота и два наклона.
//
// Плоскость, а не точка, и не ради точности, а потому что иначе получается не
// лодка. В поле волны живут длины от сантиметров до десятков метров;
// шестиметровый корпус коротких не чувствует вовсе — он их перекрывает, и
// давление под ним усредняется само. Проба точкой отдаёт всё подряд, и лодка
// начинает отыгрывать каждую рябь: на замере это три с половиной метра в
// секунду вертикальной скорости на волне в семнадцать сантиметров, то есть
// лодку подбрасывает. С плоскостью по корпусу — восемь десятых.
//
// База берётся по ВАТЕРЛИНИИ, и по ней же — середина. Ноль модели у SV20 стоит
// у транца: ватерлиния идёт от 0.55 до 6.02 м, и её середина в трёх с лишним
// метрах от начала координат. Раскладывать пробы вокруг нуля значит увести
// половину креста за корму — что и было видно на отладочном виде, оттуда это и
// нашлось.
//
// Не «чтобы сгладить посильнее», а потому что фильтрует именно корпус, и
// фильтрует он ровно на своей длине.
const SEA_PROBE = {
  x0: (PACK.hydrostatics.lwl_aft_x_m + PACK.hydrostatics.lwl_fwd_x_m) / 2,
  l: PACK.hydrostatics.lwl_m / 2,
  b: PACK.hydrostatics.bwl_m / 2,
};
const seaPlane = { z: 0, se: 0, sn: 0 };

// След за кормой — поле, а не геометрия; читает его сама вода. Обводы берутся
// по ватерлинии из того же пакета, что и пробы: полоса впрыска идёт от транца к
// форштевню и потому накрывает не только след, но и сам корпус.
const wake = new Wake(renderer, ocean);
wakeSetHull(SEA_PROBE.b, PACK.hydrostatics.lwl_aft_x_m,
            PACK.hydrostatics.lwl_fwd_x_m);

// Разложить пробы под корпусом: их читает СЛЕДУЮЩИЙ кадр.
//
// Раскладка берётся из ocean.js — оттуда же, откуда её берёт подгонка плоскости.
// Смещения даются в долях полудлины и полуширины, здесь превращаются в метры,
// сносятся на середину ватерлинии и поворачиваются по курсу.
function seaProbeOffset(i, c, s, out) {
  const p = OCEAN_PROBE[i];
  const bx = SEA_PROBE.x0 + p[0] * SEA_PROBE.l, by = p[1] * SEA_PROBE.b;
  out.x = bx * c - by * s;
  out.y = bx * s + by * c;
  return out;
}
const seaProbeAt = { x: 0, y: 0 };
function placeSeaProbes(x, y, psi) {
  const c = Math.cos(psi), s = Math.sin(psi);
  for (let i = 0; i < OCEAN_PROBE.length; i++) {
    seaProbeOffset(i, c, s, seaProbeAt);
    ocean.setProbe(i, x + seaProbeAt.x, y + seaProbeAt.y);
  }
}

// Собрать из проб плоскость воды. Курс тот же, с которым пробы раскладывались:
// за кадр лодка поворачивается на доли градуса, и брать текущий незачем.
//
// Саму подгонку делает ocean.js: там она под тестом. Здесь остаётся только
// гашение по ветру — тем же множителем, каким гасит волну шейдер.
const seaProbeH = new Float64Array(OCEAN_PROBE.length);
function readSeaPlane(psi, damp) {
  for (let i = 0; i < seaProbeH.length; i++) seaProbeH[i] = ocean.probeHeight(i);
  oceanPlaneFit(seaProbeH, psi, SEA_PROBE.l, SEA_PROBE.b, SEA_PROBE.x0, seaPlane);
  seaPlane.z *= damp; seaPlane.se *= damp; seaPlane.sn *= damp;
}

// Рябь от порывов. На воде усиление ветра видно раньше, чем оно доходит до
// парусов, — тёмными языками, ползущими по ветру. Это не украшение: без них
// порыв приходит из ниоткуда, и понять, что произошло, невозможно.
//
// Красится это в шейдере, по мировым координатам фрагмента. Раньше цвет
// раскладывался по вершинам на процессоре: сетка воды переставляется вслед за
// лодкой шагами по ячейке каждый кадр, а цвета пересчитывались через кадр, и
// картинка отставала от геометрии — языки мельтешили. В шейдере отставать
// нечему, заодно исчезла и зернистость от полутораметровой сетки вершин.
//
// Само поле здесь НЕ считается. Оно посчитано один раз в sim/wind.js — тем же
// кодом, по которому идут силы, — и лежит в текстуре размером в один период.
// Шейдеру остаётся перевести мировые координаты в систему, связанную с ветром,
// и взять выборку.
//
// Так сделано после того, как две реализации одного поля разошлись: множитель
// сглаживания в шейдерном шуме оказался переписан с ошибкой, поле рвалось на
// границах ячеек решётки, вода шла полосами — а физика при этом считала
// правильное поле. Ни тестом, ни консолью такое не ловится, потому что тесты
// до шейдера не достают. Теперь реализация одна, и расходиться нечему.
//
// Период поля — тысяча метров вдоль ветра и триста поперёк; текстура кроется
// с повторением, поэтому вода бесконечная. Байта на тексел хватает: на яркость
// приходится меньше процента на шаг, а вывод и так восьмибитный.
const GUST_TEX = { w: 512, h: 256 };
const seaGustMap = new DataTexture(
  gustTexture(GUST_TEX.w, GUST_TEX.h), GUST_TEX.w, GUST_TEX.h, RedFormat);
seaGustMap.wrapS = RepeatWrapping;
seaGustMap.wrapT = RepeatWrapping;
seaGustMap.minFilter = LinearFilter;
seaGustMap.magFilter = LinearFilter;
seaGustMap.needsUpdate = true;

const seaGust = uniform(0);
// Рваность в тени — тот же ползунок, что у сил. Единообразие тут не роскошь:
// подбирается он по картинке, и если картинка живёт по своему числу, подбор
// подбирает не то.
const seaShadeGust = uniform(1.5);
const seaWindDir = uniform(0);
const seaWindSpeed = uniform(6);
const seaTime = uniform(0);

// Те же две строки, что и в WindField.frame: вдоль потока и поперёк, поле едет
// по ветру со скоростью потока.
const svGust = Fn(([p]) => {
  const c = seaWindDir.cos(), s = seaWindDir.sin();
  const along = p.x.mul(c).add(p.y.mul(s)).negate().sub(seaWindSpeed.mul(seaTime));
  const across = p.x.mul(s).negate().add(p.y.mul(c));
  const uv = vec2(along.div(GUST_PERIOD.along), across.div(GUST_PERIOD.across));
  return texture(seaGustMap, uv).r.mul(2.0).sub(1.0);
});

// Карта ветра над акваторией: разгон после берега и тень берега, в одном байте
// на ячейку в сто метров. Считает её terrain.js — той же формулой, по которой
// идут силы на лодке, — а здесь она только читается.
//
// Без неё тень берега осталась бы числом в телеметрии. Проверить это число
// нечем: подгоняется оно глазом, а глазу нужна картинка. С картой под
// подветренным берегом ложится гладкая полоса, ровно та, по которой на реке и
// читают ветер, — и подбирать D₀ с k становится занятием, а не гаданием.
const windMapData = terrain.ready ? new Uint8Array(2 * terrain.cells) : new Uint8Array(2);
const windMapTex = new DataTexture(windMapData,
  terrain.ready ? TERRAIN_PACK.cnx : 1, terrain.ready ? TERRAIN_PACK.cny : 1, RGFormat);
windMapTex.wrapS = ClampToEdgeWrapping;
windMapTex.wrapT = ClampToEdgeWrapping;
windMapTex.minFilter = LinearFilter;
windMapTex.magFilter = LinearFilter;
windMapTex.needsUpdate = true;
// Пересчитывается только когда меняется то, от чего она зависит: направление
// ветра и два ползунка тени. Восемнадцать тысяч ячеек — не то чтобы дорого, но
// и каждый кадр незачем.
const windMapAt = { dir: NaN, d0: NaN, k: NaN };
function updateWindMap() {
  if (!terrain.ready) return;
  const d = boat.o.windDir, d0 = boat.o.shadeD0, k = boat.o.shadeK;
  if (windMapAt.dir === d && windMapAt.d0 === d0 && windMapAt.k === k) return;
  windMapAt.dir = d; windMapAt.d0 = d0; windMapAt.k = k;
  terrain.windMap(d, { a: WIND_SHORE_A, l: WIND_SHORE_L, d0: d0, k: k }, windMapData);
  windMapTex.needsUpdate = true;
}
// Та же карта, но с процессора: по ней идут стрелки поля ветра. Ближайший узел,
// без интерполяции — сто метров на ячейку, а стрелка и так стоит в узле.
//
// Высоту волны она больше не гасит: гашение ушло в шейдер вместе с самой
// волной (ocean.js), и выборка там идёт из той же текстуры, что и цвет.
const WM = terrain.ready
  ? { x0: TERRAIN_PACK.x0, y0: TERRAIN_PACK.y0, c: TERRAIN_PACK.coarse,
      nx: TERRAIN_PACK.cnx, ny: TERRAIN_PACK.cny }
  : null;
function windMapCell(x, z) {
  if (!WM) return -1;
  const i = Math.round((toWorldX(x) - WM.x0) / WM.c),
        j = Math.round((toWorldY(z) - WM.y0) / WM.c);
  if (i < 0 || j < 0 || i >= WM.nx || j >= WM.ny) return -1;
  return 2 * (j * WM.nx + i);
}
// Тот же множитель ветра, что берёт шейдер воды, но с процессора: им плавучести
// гасится волна там, где её гасит и картинка. Без этого лодка качалась бы на
// волне, которой под подветренным берегом не нарисовано.
//
// Берётся только УСТОЙЧИВАЯ часть, без порыва. Порыв поднимает мелкий каскад, а
// его плоскость по корпусу всё равно усредняет: лодка длиной в шесть метров ряби
// не чувствует, и подмешивать её сюда значило бы качать лодку тем, чего она не
// замечает.
function windMapSample(x, z) {
  const c = windMapCell(x, z);
  return c < 0 ? 1 : windMapData[c] / 255;
}

// Ветер в точке сцены С УЧЁТОМ АКВАТОРИИ — ровно тот же, что чувствует лодка.
// Через него идут все стрелки поля: если бы они показывали чистое поле порывов,
// они врали бы именно там, где на них и смотрят, — под берегом.
const windSceneOut = { x: 0, y: 0, speed: 0, dir: 0 };
const windSceneAxis = { x: 0, y: 0 };
function windScene(x, z, h, t) {
  const c = windMapCell(x, z);
  const wk = c < 0 ? 1 : windMapData[c] / 255;
  const sh = c < 0 ? 1 : windMapData[c + 1] / 255;
  const w = boat.wind.sample(toWorldX(x), toWorldY(z), h, t,
                             1 + boat.o.shadeGust * (1 - sh));
  // Ось долины у каждой стрелки своя, и поворот считается на месте, а не берётся
  // от лодки: над стрелкой ветра эта разница и есть всё содержание канализации.
  // На стрелках у берега видно, как поток ложится вдоль реки, а на середине нет.
  terrain.channel(toWorldX(x), toWorldY(z), windSceneAxis);
  const r = channelTurn(windSceneAxis.x, windSceneAxis.y, boat.o.windDir, boat.o.chan);
  const cr = Math.cos(r), sr = Math.sin(r);
  windSceneOut.x = toSceneX((w.x * cr - w.y * sr) * wk);
  windSceneOut.y = toSceneZ((w.x * sr + w.y * cr) * wk);
  windSceneOut.speed = w.speed * wk; windSceneOut.dir = w.dir + r;
  return windSceneOut;
}

// Тот же множитель в шейдере. Мировые метры → доли текстуры; за краем участка
// выборка прижимается к кромке, но там уже нет ни воды, ни берега.
//
// Рябь гасится вдвое слабее, чем падает ветер: полоса под берегом обязана
// читаться гладкой, но не мёртвой — вода там всё-таки не зеркало.
//
// Без акватории выражение цвета не трогается вовсе, ни на один узел: вода на
// бесконечной воде обязана быть той же самой, а «умножить на единицу» — это уже
// другой шейдер.
const svWind = WM && Fn(([p]) => {
  const u = p.x.sub(WM.x0).div(WM.c * (WM.nx - 1));
  const v = p.y.sub(WM.y0).div(WM.c * (WM.ny - 1));
  return texture(windMapTex, vec2(u, v)).rg;
});
// Опорная точка на НЕВОЗМУЩЁННОЙ воде: мировые XY вершины до того, как её
// сдвинула волна.
//
// Брать `positionWorld` здесь больше нельзя, и не только из-за волны. В
// вершинном шейдере positionWorld считается из положения, которое вот этим же
// выражением и назначается, — вышел бы круг. А в пиксельном оно уже сдвинуто
// волной, и выборка каскадов пошла бы не в той точке, что смещение: рябь
// поехала бы относительно гребня, на который села.
//
// Сцена -> мир: X сцены есть X мира, Z сцены есть -Y мира. TSL-узел пишется
// явно, потому что числовой адаптер осей к узлам неприменим.
const seaRefWorld = modelWorldMatrix.mul(vec4(positionGeometry, 1.0)).xyz;
const seaRefXY = vec2(seaRefWorld.x, seaRefWorld.z.negate());
const seaWorldXY = varying(seaRefXY);
const svWindV = svWind && svWind(seaWorldXY);
// Рябь гаснет со скоростью ветра, но в тени она же и резче — тем самым
// множителем рваности, что в физике. Гашение вдвое слабее падения ветра:
// полоса под берегом обязана читаться гладкой, но не мёртвой.
const seaWindK = svWindV && svWindV.x.mul(0.5).add(0.5);
const seaRough = svWindV && svWindV.y.oneMinus().mul(seaShadeGust).add(1.0);

// --- волна ------------------------------------------------------------------
//
// Само поле считает ocean.js; здесь оно только кладётся на сетку. Гасится оно
// дважды и по разным причинам, и обе важны:
//
//   * по ветру. Под подветренным берегом волны нет, и вода там обязана быть
//     плоской не только на вид. Множитель — тот же, что у сил (карта одна на
//     физику и картинку), в квадрате: энергия волны идёт как квадрат ветра;
//
//   * по разрешению. Каскад с плиткой в три метра на ячейке в двести метров —
//     это не волна, а муар. Но геометрия и затенение упираются в РАЗНЫЕ
//     пределы, и потому гасятся порознь. Вершина не может нести волну короче
//     своей ячейки — это предел сетки. Пиксель может: на то и карта нормалей,
//     и мелкая рябь живёт в затенении там, где в геометрии её давно нет.
//     Предел здесь — размер пикселя в метрах, а не размер ячейки.
const seaCellAttr = attribute('seaCell', 'float');
// Метры на пиксель на единицу дальности: 2·tg(fov/2)/высота экрана. Ставится в
// кадре, потому что зависит от размера окна.
const seaPerPixel = uniform(0.001);
const seaFootprint = positionWorld.sub(cameraPosition).length().mul(seaPerPixel);
// Множитель ветра берётся в каждой стадии своей выборкой: в вершинной —
// напрямую из опорной точки, в пиксельной — через интерполированную. Смешивать
// нельзя: varying в вершинном шейдере ещё не существует.
//
// Волна гасится ЧИСТЫМ множителем карты, в квадрате, — тем же выражением, что
// стояло в прежнем счёте на процессоре. Не тем, что у ряби в цвете: у той
// множитель поднят до половины (`x·0.5 + 0.5`) нарочно, чтобы вода под берегом
// читалась гладкой, но не мёртвой. Волне такая поблажка не нужна и вредна: в
// мёртвой тени берега волны нет, и она обязана быть плоской.
const svWindVert = svWind && svWind(seaRefXY);
const seaSteadyVert = svWindVert ? svWindVert.x : float(1.0);
const seaSteadyFrag = svWindV ? svWindV.x : float(1.0);

// --- порыв поднимает рябь -----------------------------------------------------
//
// Поле порывов до сих пор красило воду и только. Но тёмный язык на воде — это
// не тень и не пятно краски: это участок, где ветер на несколько секунд стал
// сильнее и НАПОДНИМАЛ РЯБИ. Темнее он именно потому, что шершавее — рябь
// рассеивает свет вместо того, чтобы отражать небо. Красить, не трогая
// поверхность, значит показывать следствие без причины: на статичной картинке
// сходится, а стоит посмотреть под низким солнцем — блик по языку идёт ровно
// такой же, как по гладкой воде рядом.
//
// Поэтому местный ветер входит в амплитуду. Но не всей волны, а только МЕЛКОГО
// каскада, и это не упрощение:
//
//   * длинная волна набирается часами с разгона. Порыв в десять секунд её не
//     меняет вовсе, и приподнимать её на языке значило бы врать грубее, чем
//     не поднимать ничего;
//
//   * рябь короче трёх метров приходит в равновесие с ветром за секунды. Она и
//     есть то, что на воде видно как порыв.
//
// Квадрат — потому что этим же квадратом гасится волна по карте берега:
// множитель один, и применяется он одинаково.
//
// ГЕЙН. Само поле порывов размахом не единица: у него СКО 0.265, а к краям
// диапазона (−0.84…0.73) оно заглядывает редко. Ползунок «порывистость ±18%»
// поэтому означает не восемнадцать процентов на воде, а типичные пять, и в
// амплитуде ряби это множитель 0.91…1.10 — то есть ничего. Первый заход так и
// вышел: сделано верно, а на воде не видно.
//
// КРАЙ. Поле — гладкий шум, и переход от затишья к порыву растянут у него на
// десятки метров: язык выходит облаком без границы. На воде он резче — порыв
// приходит фронтом, и край его видно как черту. Поэтому величина пропускается
// через S-образную кривую: середина растягивается, хвосты садятся в упор.
//
// Это ПЕРЕДАТОЧНАЯ кривая показа, а не второе поле. Само поле остаётся тем
// же, каким его считает wind.js для сил, — здесь меняется не оно, а то, как оно
// ложится на воду. Ровно на тех же правах, что и гейн ниже.
//
// Полширины взята чуть больше СКО поля (0.265): при меньшей язык вырождается в
// пятно с обрубленным краем, при большей края опять нет.
const SEA_GUST_EDGE = 0.32;
const seaGustShape = f => f.smoothstep(-SEA_GUST_EDGE, SEA_GUST_EDGE)
  .mul(2.0).sub(1.0);

// ГЕЙН. После кривой величина ходит уже от −1 до 1, и гейн отвечает только за
// то, во сколько раз порыв меняет воду. Двойка при ползунке ±18% даёт множитель
// ряби от 0.64 до 1.36 — с кубом ниже это от четверти до двух с половиной.
//
// Число одно на оба проявления НАРОЧНО: где темнее, там и шершавее, и ровно во
// столько же — иначе язык расслаивается на тёмное пятно и отдельно от него
// взъерошенную воду.
const SEA_GUST_GAIN = 2.0;
// Само поле берётся один раз на стадию: два вызова — две выборки из текстуры за
// один и тот же ответ.
const seaGustRaw = seaGustShape(svGust(seaWorldXY));
const seaGustRawVert = seaGustShape(svGust(seaRefXY));
const seaRipple = seaGustRaw.mul(seaGust);
const seaGustVert = seaGustRawVert.mul(seaGust).mul(SEA_GUST_GAIN)
  .add(1.0).clamp(0.35, 1.5);
const seaGustFrag = seaRipple.mul(SEA_GUST_GAIN).add(1.0).clamp(0.35, 1.5);

// --- отладка воды -------------------------------------------------------------
//
// Порыв на воде — вещь, которую нельзя проверить, глядя на воду: он подмешан в
// ту же поверхность, что несёт волну, рябь и блики, и «вижу — не вижу»
// оказывается спором о вкусах. Поэтому его можно посмотреть отдельно.
//
//   «только порывы» — волны нет вовсе, вокруг зеркало, и рябь поднята ровно
//     там, где поле положительно. Видно форму языков, их размер и как они едут
//     по ветру. Ради этого режим и заведён: спор о том, видно порыв или нет,
//     кончается тем, что на него смотрят в упор;
//
//   «поле порывов» — та же величина прямо цветом, без всякого затенения.
//     Последняя инстанция: если языки и здесь не те, дело не в воде, а в поле,
//     то есть в sim/wind.js, по которому идут и силы.
//
// Режимы живут в uniform, а не в пересборке материала: переключаются они мышью,
// и ждать компиляции шейдера на каждый щелчок незачем.
//
// Флага два, и это ЧИСЛА 0/1, а переключение — через mix, а не через select.
// Условный узел на цветовом выражении даёт чёрное: тип у него сходится к vec4,
// ветки отдают vec3, и в альфу попадает ноль. Ошибка тихая — вода просто гаснет,
// и ни строчки в консоли; полчаса на неё ушло. Через mix такого не бывает,
// а стоит он на воде ровно ничего.
const seaDbgOnly = uniform(0);     // 1 — только порывы
const seaDbgField = uniform(0);    // 1 — поле порывов цветом
const seaDbgRefl = uniform(0);     // 1 — отражённая сцена сама по себе
const seaDbgWake = uniform(0);     // 1 — поле следа цветом
// Доля ряби в отладке: от нуля вне языка до единицы в его сердцевине. Величина
// уже прошла кривую края и ходит от −1 до 1, так что растягивать нечего.
const dbgOnlyVert = seaGustRawVert.max(0.0);

// --- след за кормой ------------------------------------------------------------
//
// Поле считает wake.js; здесь оно только читается — двумя выборками, как и всё
// остальное на этой воде: в вершинной стадии из опорной точки, в пиксельной из
// интерполированной. Смешивать нельзя, varying в вершинном шейдере ещё нет.
const seaWakeVert = wake.sample(seaRefXY);
const seaWakeFrag = wake.sample(seaWorldXY);
// Насколько гладкая дорожка гасит рябь. Не в ноль: за кормой вода взбита, а не
// залита маслом, и совсем зеркальная полоса читается прорехой в воде.
const SEA_WAKE_SMOOTH = 0.85;
// Пена следа входит в общую пену воды, и оттого сама собой делается и белой, и
// шершавой, и неотражающей: на этом узле уже висят цвет, шероховатость и
// Френель. Отдельного «цвета следа» нет нарочно — он разошёлся бы с пеной
// гребня, и на одной воде оказались бы две разные белизны.
//
// СЕЙЧАС ОНА ВЫКЛЮЧЕНА, и это осознанно, а не забыто. Белое в следе получалось
// убедительным на кромке и однородным у транца, и пока оно есть, судить о том,
// как читается сама форма — приглаженный конус и две волны по его краям, —
// нельзя: белизна перетягивает взгляд на себя. Поле пены при этом считается и
// показывается отладочным видом «поле следа»; чтобы вернуть её в воду, довольно
// поставить здесь 0.55.
const SEA_WAKE_FOAM = 0.0;

// Множитель амплитуды каскада по ветру и следу: длинным — только берег, мелкому
// ещё порыв и след.
function seaWindOn(i, steady, gust, slick) {
  // Берег входит КВАДРАТОМ — как энергия волны от ветра.
  const s2 = steady.mul(steady);
  if (i < OCEAN_TILES.length - 1) return s2;
  // Порыв — КУБОМ, и это не подгонка под глаз. Короткая волна несимметрична по
  // времени: в порыве она поднимается за секунды, а в затишье гаснет вязкостью
  // ещё быстрее, и потому затишье на воде выглядит зеркалом, а не «чуть глаже».
  // Квадрат такой несимметрии не даёт: при типичном порыве он менял рябь на
  // треть, а видно её становится примерно с двух раз.
  //
  // След гасит тот же самый каскад и по той же причине, только в другую
  // сторону: корпус сбивает капиллярную рябь, и дорожка за кормой остаётся
  // зеркальнее воды вокруг. Механизм один — амплитуда мелкой волны; поэтому
  // след и порыв не спорят друг с другом, а перемножаются.
  return s2.mul(gust).mul(gust).mul(gust)
    .mul(slick.mul(SEA_WAKE_SMOOTH).oneMinus());
}

// Мелкий каскад — последний в списке; в отладке «только порывы» живёт он один.
const seaFine = OCEAN_TILES.length - 1;

// Границы у smoothstep всюду идут по возрастанию, а разворот делается oneMinus.
// Не ради единообразия: у WGSL при low ≥ high результат НЕ ОПРЕДЕЛЁН. То, что
// сегодняшний компилятор считает его по той же формуле с переставленными
// концами, — везение, которое незачем закладывать в основание воды.
function seaGeomWeight(i) {
  const tile = OCEAN_TILES[i];
  const res = seaCellAttr.smoothstep(tile / 12, tile / 3).oneMinus();
  const only = i === seaFine ? res.mul(dbgOnlyVert) : float(0);
  const norm = res.mul(seaWindOn(i, seaSteadyVert, seaGustVert, seaWakeVert.y));
  return mix(mix(norm, only, seaDbgOnly), float(0), seaDbgField);
}
function seaShadeWeight(i) {
  const t = OCEAN_TILES[i] / 16;
  const res = seaFootprint.smoothstep(t, t * 2.5).oneMinus();
  const only = i === seaFine ? res.mul(seaGustRaw.max(0.0)) : float(0);
  const norm = res.mul(seaWindOn(i, seaSteadyFrag, seaGustFrag, seaWakeFrag.y));
  return mix(mix(norm, only, seaDbgOnly), float(0), seaDbgField);
}

// Смещение приходит в осях мира (восток, север, вверх) — в сцену оно
// переводится тем же отображением, что и точка.
//
// Узел считается ОДИН раз и переиспользуется: из него берётся и положение
// вершины, и высота гребня для цвета. Позвать `displace` второй раз значило бы
// выбрать все каскады заново — двенадцать лишних выборок на вершину.
const seaDisp = ocean.displace(seaRefXY, seaGeomWeight);
// Корабельная волна поднимает вершину вместе с ветровой: усы — это рельеф, и
// никаким цветом их не изобразить. Складываются высоты, а не смешиваются:
// кельвинова волна идёт ПОВЕРХ волнения, а не вместо него.
seaMat.positionNode = positionLocal.add(
  vec3(seaDisp.x, seaDisp.z.add(seaWakeVert.z), seaDisp.y.negate()));
// Нормаль — из тех же каскадов, но на пиксель, а не на вершину. Материалу она
// нужна в осях вида; сетка воды только двигается, не вращаясь, так что оси
// объекта и мира у неё совпадают и перевод сводится к одной матрице.
//
// Уклон усов подмешивается сюда же, и именно уклоном, а не нормалью. Складывать
// две нормали нельзя — сумма единичных векторов не единичный вектор и не
// нормаль ни к чему; складываются УКЛОНЫ, то есть отношения n.xy/n.z, а из суммы
// нормаль собирается обратно. Без этого усы поднимались бы геометрией, а свет по
// ним шёл бы как по гладкой воде: рельеф есть, блика нет.
const seaSurf = ocean.surface(seaWorldXY, seaShadeWeight);
const seaWakeSlope = wake.slope(seaWorldXY, seaWakeFrag.z);
const seaNrm = vec3(
  seaSurf.xy.div(seaSurf.z.abs().max(1e-3)).sub(seaWakeSlope), 1.0).normalize();
seaMat.normalNode = transformNormalToView(
  vec3(seaNrm.x, seaNrm.z, seaNrm.y.negate()));

// Пена на заворачивающемся гребне. На здешней воде она появляется только в
// свежий ветер, и это правильно: барашки на реке при пяти метрах в секунду не
// бывают. Оттого она и не подкрашена «в белое» жёстко, а осветляет воду:
// зачаток барашка — это ещё не барашек, а взбитая вода.
// Пена гребня и пена следа — одна и та же пена, и берётся МАКСИМУМ, а не сумма:
// вода за кормой белее не становится оттого, что там же завернулся гребень.
const seaFoam = seaSurf.w.max(seaWakeFrag.x.mul(SEA_WAKE_FOAM)).clamp(0, 1);
// Свечение гребня.
//
// Мерится оно не в метрах, а в долях СВОЕЙ волны: на штилевой ряби в сантиметр
// гребень обязан светиться так же, как на полуметровой волне, иначе в слабый
// ветер вода делается однотонной клеёнкой. Отсюда деление на текущую высоту
// волнения — то самое hs, что пришло от физики.
//
// Считается оно по КРУПНЫМ каскадам, без мелкого. Светится не всякая
// поднявшаяся вода, а гребень волны: сквозь него слой тонкий. Рябь под бортом
// в пару сантиметров ничего не просвечивает, и когда она входила в эту сумму,
// вода шла светлыми пятнами по каждой мелкой морщине — не свечением, а сыпью.
const seaCrest = varying(
  ocean.displace(seaRefXY, i => i < OCEAN_TILES.length - 1 ? seaGeomWeight(i) : null).z)
  .div(ocean.uHs.mul(0.8).max(0.03)).smoothstep(0.0, 1.0).mul(0.55);
// Цвет порыва остаётся, и теперь он не сам по себе: языки на воде и темнее, и
// шершавее разом — как и бывает, потому что темнее они именно от шершавости.
const seaBody = mix(seaDeep, seaScatter, seaCrest).mul(
  (seaWindK ? seaRipple.mul(seaWindK).mul(seaRough) : seaRipple)
    .mul(SEA_GUST_GAIN).oneMinus().clamp(0.25, 1.8));
// mix берётся ФУНКЦИЕЙ, а не методом. У метода первым аргументом идёт доля, а
// не первый цвет: `a.mix(b, t)` во вклеенной сборке значит mix(b, t, a). Вода
// от этого выходила кремовой — смешивались пена с белилами, а долей служил цвет
// воды, — и ни одной ошибки в консоли при этом не было. Та же ловушка, что с
// clamp ниже, только тише.
// В отладке «поле порывов» вода красится прямо величиной поля: тёмное — затишье,
// светлое — порыв. Ни волны, ни бликов, ни пены — только форма языков.
// Показывается величина ПОСЛЕ кривой края — та самая, что ложится на воду. Она
// уже от −1 до 1, и шкала ложится на неё целиком.
const seaDbgColour = mix(color(0x0d1a26), color(0xffd48a),
                         seaGustRaw.mul(0.5).add(0.5).clamp(0, 1));
seaMat.colorNode = mix(seaBody, color(SEA_FOAM_COLOUR), seaFoam.mul(0.85));
// Гладкая вода и блестит иначе: в тени она ближе к зеркалу. Пена не блестит
// вовсе — она шершавая, и без этого барашек выглядит куском полированного льда.
{
  const base = seaWindK ? seaWindK.mul(0.20).add(0.08) : float(0.28);
  seaMat.roughnessNode = mix(base, float(0.9), seaFoam);
}

// Отражение неба по Френелю.
//
// Без него волна не читается вовсе, и это не вкусовщина. Рассеянная
// составляющая почти не зависит от наклона: у полуметровой волны длиной в
// десять метров склон около десятой, и освещённость на нём меняется на
// проценты — правильно посчитанная волна выглядит листом бумаги. У отражения
// же зависимость от угла резкая: там, где склон подставлен глазу, воды почти
// не видно, видно небо. Этим вода и читается на любой картинке, от фотографии
// до мультфильма.
//
// Кладётся оно в СВЕЧЕНИЕ, а не в цвет: отражение не освещается лампами, оно
// само и есть свет. В цвете его пришлось бы домножать на освещённость, и на
// ярком небе вода уходила бы в белое.
//
// Небо здесь одного цвета, картой окружения сцена не пользуется. Но кроме неба
// над водой стоит ещё и сцена, и её отражение считается ниже.

// --- отражение сцены в воде: только зеркало ------------------------------------
//
// Способов было два, остался один. Марш по экрану (SSR) искал отражение в уже
// нарисованном кадре; зеркало рисует сцену второй раз камерой, отражённой в
// плоскости воды. Марш убран целиком — и вот почему, чтобы его не завели заново.
//
// ИЗЪЯН У НЕГО НЕ В КАЧЕСТВЕ, А В УСТРОЙСТВЕ. Главное, что должна отражать вода
// у берега, — сам берег и мачта, — в кадр не попадает: мачта уходит за верхний
// край раньше всего остального. О том, чего в кадре нет, марш знать не может, и
// никакой настройкой это не лечится. Отладочный вид «исход SSR» показывал это
// прямо: ближняя вода почти сплошь красная, весь запас шагов выбран впустую.
//
// И дешевле он не был. Скамья (`?bench=0`, замороженный кадр, осушение очереди):
// небо 4.84 мс, марш 6.20 (+1.36), зеркало 4.98 (+0.15). Зеркало со вторым
// проходом по ВСЕЙ сцене стоило вдесятеро меньшей добавки, чем марш по пикселям
// воды, — и отражало то, чего марш не видел.
//
// Вместе с маршем ушли снимки цвета и глубины кадра (`viewportSharedTexture` и
// `viewportDepthTexture`): они снимались каждый кадр ради него одного.
//
// Сила отражения осталась ползунком: ноль — вода отражает одно небо.
const seaReflect = uniform(1.0);
// 1 — зеркальный проход работает. Ноль оставлен не для симметрии: это дешёвый
// запасной вид для слабого устройства, и он же используется на замерах.
const seaRefPlanar = uniform(1.0);

// --- зеркало: тот же вопрос, решённый вторым проходом --------------------------
//
// Марш по экрану не умеет отражать то, чего в кадре нет, и на воде это не
// мелочь: мачта уходит за верхний край раньше всего остального, а именно её
// отражение и связывает лодку с водой. Зеркало этой болезни лишено по устройству
// — сцена рисуется ЗАНОВО, камерой, отражённой в плоскости воды. Что попадёт в
// отражение, решает не кадр, а сама зеркальная камера.
//
// Цена другая по природе: не выборки глубины на пиксель воды, а второй проход по
// всей сцене. Он идёт в половинном разрешении (четверть пикселей) и без самой
// воды — материал на время прохода гасится, иначе зеркало отражало бы зеркало.
//
// Чем расплачиваемся:
//
//   * плоскость одна, y = 0. Волна поднимает поверхность на десятки сантиметров,
//     и отражение на гребне встаёт не совсем там, где должно. Искажение нормалью
//     это маскирует, но не исправляет: физически верное отражение волнистой
//     поверхности зеркалом не считается вовсе;
//
//   * отражается ВСЯ сцена, включая отладочные стрелки и сетку. У марша по
//     экрану они тоже попадают в снимок, так что разницы между способами тут
//     нет, но на замерах их всё равно надо гасить — см. bench.js;
//
//   * проход идёт каждый кадр целиком, независимо от того, сколько воды в кадре.
//     Марш, наоборот, платит ровно за видимую воду. Где проходит граница выгоды —
//     вопрос замера, а не рассуждения.
// bounces: true — не ради отражения в отражении, его тут нет и быть не может
// (вода на зеркальном проходе погашена). Дело в том, ЧЕМ отмеряется «уже
// рисовали»: при false проход привязан к номеру кадра, а номер кадра двигает
// внутренний цикл three по requestAnimationFrame — не наш render. Замер,
// рисующий кадр шестьдесят раз подряд вне rAF, получал зеркало ОДИН раз и
// показывал, что оно дешевле неба. При true отметка идёт по номеру отрисовки, и
// проход честно повторяется столько раз, сколько его попросили.
// Доля от кадра, в которой рисуется зеркальный проход. Половина линейно — то
// есть вчетверо меньше пикселей, чем в кадре. Вынесена в имя, потому что её
// меряет скамья: «а если ещё вдвое мельче» — вопрос замера (§9, docs/perf.md).
const MIRROR_SCALE = 0.5;
const seaMirrorTex = reflector({ resolutionScale: MIRROR_SCALE, bounces: true });
if (seaMirrorTex) {
  // Цель задаёт плоскость: её местная ось Z — нормаль зеркала. Вода лежит в
  // XZ мира, нормаль вверх, значит цель повёрнута на четверть оборота.
  seaMirrorTex.target.rotateX(-Math.PI / 2);
  scene.add(seaMirrorTex.target);
  // Выключатель самого прохода: при выборе «только небо» зеркало не должно
  // рисовать сцену в никуда. Это же и запасной вид для слабого устройства.
  const base = seaMirrorTex.reflector;
  const draw = base.updateBefore.bind(base);
  base.updateBefore = frame => {
    if (seaRefPlanar.value > 0) return draw(frame);
  };
}
// Искажение волной. Плоское зеркало даёт зеркально гладкую картинку — на воде
// это читается стеклом; рябь берётся отсюда. Смещение по экрану пропорционально
// НАКЛОНУ поверхности, а гасится с дальностью: у горизонта пиксель отражения
// стоит десятки метров, и там же смещение размазало бы берег в кашу.
const SEA_MIRROR_WOBBLE = 0.055;
const seaMirror = seaMirrorTex ? Fn(() => {
  // Наклон поверхности в МИРОВОЙ горизонтали: насколько нормаль волны отклонилась
  // от вертикали и куда.
  const tiltWorld = vec3(normalWorld.x, 0.0, normalWorld.z).toVar();
  // ...и он же в осях КАМЕРЫ: x вправо по экрану, y вверх. Без этого поворота
  // смещение было бы в мировых осях, а прибавлялось бы к экранным, и ошибка шла
  // бы ровно на угол рыскания камеры: та же волна, снятая с востока и с севера,
  // гнула бы отражение в направлениях, различающихся на прямой угол. Смотрелось
  // это правдоподобно только потому, что дрожание мелкое, а при какой-то одной
  // ориентации оси случайно совпадают.
  const tiltView = cameraViewMatrix.mul(vec4(tiltWorld, 0.0)).xy.toVar();
  const k = float(SEA_MIRROR_WOBBLE)
    .div(positionView.length().mul(0.06).add(1.0)).toVar();
  // Горизонтальная составляющая идёт со ЗНАКОМ МИНУС. Выборка зеркала берётся
  // по flipX(screenUV), то есть горизонтальная ось у неё перевёрнута: сдвинуть
  // отражение вправо по экрану значит взять из текстуры левее. Пока базис был
  // перепутан, знак ничего не значил.
  const off = vec2(tiltView.x.negate(), tiltView.y).mul(k).toVar();
  return seaMirrorTex.sample(screenUV.flipX().add(off)).xyz;
})() : null;

{
  const cosView = normalView.dot(positionViewDirection.normalize())
    .abs().clamp(0, 1);
  // 0.02 — отражение воды в упор, дальше растёт пятой степенью до единицы.
  const fres = cosView.oneMinus().pow(5).mul(0.9).add(0.02);
  // Подложка — небо, поверх неё зеркало. У зеркала попадание есть везде по
  // устройству, поэтому его уверенность — сам выключатель прохода, помноженный
  // на силу отражения с ползунка.
  const mirror = mix(color(SKY), seaMirror, seaRefPlanar.mul(seaReflect));
  // Пена отражает как шершавое, а не как зеркало: на барашке Френеля нет.
  const lit = mirror.mul(fres).mul(seaFoam.oneMinus().mul(0.75));

  // --- отладочные виды отражения ---------------------------------------------
  //
  // Смотреть на итог бесполезно: отражение помножено на Френеля, подмешано к
  // небу и разбито волной, и «выглядит неправильно» никуда не ведёт. Поэтому
  // зеркало показывается само по себе, отдельным видом: по нему видно, совпадает
  // ли отражённая сцена с настоящей.
  //
  // Видов было три: к этому шли ещё «шаги SSR» (карта цены марша) и «исход SSR»
  // (чем марш кончился, шестью цветами). Оба ушли вместе с маршем — показывать
  // им теперь нечего.
  //
  // Вид кладётся в СВЕЧЕНИЕ, а альбедо гасится: свечение не освещается лампами
  // и показывает ровно посчитанное число. Через альбедо смотреть на отладку
  // нельзя — оно домножается на свет и врёт.
  const dbgReflView = mix(color(0xff00ff), seaMirror, seaRefPlanar);
  // Поле следа прямо цветом: красное — гладкость, зелёное — пена, синее — усы
  // по модулю. Три канала порознь и в разные стороны видно только так; в самой
  // воде они уже смешаны с пеной гребня, с рябью и с волной, и «след не тот»
  // никуда бы не вело. Усы взяты по модулю и с запасом яркости: величина там
  // сантиметры, и в своём масштабе она была бы чёрной.
  const dbgWakeView = vec3(seaWakeFrag.y, seaWakeFrag.x,
                           seaWakeFrag.z.abs().mul(8.0).clamp(0, 1));
  const dbgAny = seaDbgField.max(seaDbgRefl).max(seaDbgWake).toVar();
  const dbgView = mix(mix(seaDbgColour, dbgReflView, seaDbgRefl),
                      dbgWakeView, seaDbgWake);
  seaMat.emissiveNode = mix(lit, dbgView, dbgAny);
  seaMat.colorNode = mix(seaMat.colorNode, vec3(0.0), dbgAny);
}

// Имена TSL живут в одной области видимости с вклеенным three, и какое-нибудь
// из них может оказаться перекрыто одноимённой обычной функцией — так уже
// вышло с clamp: в ядре есть числовой clamp, он молча вернул число вместо
// узла, и вода стала чёрной без единой ошибки в консоли. Проверять по списку
// имён незачем: достаточно убедиться, что собранное выражение — узел.
for (const [name, node] of [['цвета', seaMat.colorNode],
                            ['положения', seaMat.positionNode],
                            ['нормали', seaMat.normalNode],
                            ['отражения', seaMat.emissiveNode]]) {
  if (!node || typeof node.mul !== 'function') {
    throw new Error('TSL: выражение ' + name + ' воды собралось не в узел — ' +
                    'какое-то имя перекрыто вклеенной сборкой three');
  }
}

