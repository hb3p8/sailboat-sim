function buoy(x, z, colour) {
  const g = new Group();
  const mat = new MeshStandardMaterial({ color: colour, roughness: 0.6 });
  const body = new Mesh(new CylinderGeometry(0.34, 0.42, 1.5, 12), mat);
  body.position.y = 0.55;
  const top = new Mesh(new ConeGeometry(0.34, 0.7, 12), mat);
  top.position.y = 1.6;
  g.add(body, top);
  g.position.set(x, 0, z);
  scene.add(g);
  return g;
}
// Знаки берутся из разметки акватории, если она есть: их расставили руками по
// настоящей реке, глядя на настоящий берег. Свои четыре остаются на бесконечной
// воде — там их роль другая, они там единственная привязка взгляда, и без них
// не понять даже, движешься ты или стоишь.
//
