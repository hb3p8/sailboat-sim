const TELL_SEG = 4;               // звеньев в ленточке
const TELL_LEN = 0.34;            // длина, м
const TELL_OFF = 0.03;            // отступ от полотна, м
const TELL_W = 0.018;             // полуширина ленты, м
const SAIL_STALL = 13;            // градусов, как в physics.sailCoeffs

// Ленточка — не линия, а узкая полоса: линия толщиной в пиксель на воде не
// читается, а тут ещё и не утолщается (WebGL везде рисует её в один пиксель).
// Полосу разворачиваем в плоскости паруса — тогда с наветра, откуда на них и
// смотрят, она видна плашмя.
//
// Тест глубины включён. Раньше ленточки рисовались поверх всего, чтобы
// подветренный колдунчик было видно сквозь полотно, — но за это платили тем,
// что они светились и сквозь корпус, и сквозь дальний парус, и с любого ракурса
// путались между собой. Пусть лучше подветренный прячется за полотном, как и на
// воде: там его видно, только когда ткань тонкая и солнце сзади.
const TELL_VERT = TELL_SEG * 6;   // два треугольника на звено

const TELL_PORT = [0.98, 0.36, 0.30];    // левый борт — красный
const TELL_STBD = [0.35, 0.88, 0.58];    // правый — зелёный

// Перекрасить: `lee` — знак локальной Z подветренной стороны (Z вправо).
// Первая половина вершин наветренная, вторая подветренная.
function telltaleColours(mesh, lee) {
  const col = mesh.geometry.attributes.color.array;
  const n = col.length / 3;
  const leeC = lee > 0 ? TELL_STBD : TELL_PORT;
  const winC = lee > 0 ? TELL_PORT : TELL_STBD;
  for (let i = 0; i < n; i++) {
    const c = i >= n / 2 ? leeC : winC;
    col[i * 3] = c[0]; col[i * 3 + 1] = c[1]; col[i * 3 + 2] = c[2];
  }
  mesh.geometry.attributes.color.needsUpdate = true;
}

