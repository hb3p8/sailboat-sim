// --- струи ветра ---------------------------------------------------------------
//
// Не прибор, а ощущение. Отладочные стрелки отвечают на вопрос «сколько и куда»,
// и отвечают точно; но пока смотришь на воду, а не на них, ветра не видно вовсе —
// он ровный, и глазу не за что зацепиться. Струи дают то, чего числа не дают:
// движение воздуха мимо лодки.
//
// Возле парусов струи ведут себя как линии тока: ускоряются, замедляются и
// гнутся. Это не подражание — они и считаются той же решёткой, тем же вызовом
// `induced`, что и линии тока, только по шести точкам вместо полусотни и с
// приглушённым возмущением. Одна физика, две подробности.
//
// Показывают они ТОТ ЖЕ ветер, что и линии тока, — кажущийся, а не истинный.
// Это одна величина, показанная двумя способами: линиями тока подробно, у самого
// паруса, и струями казуально, по всей воде вокруг. Кажущийся, а не истинный,
// потому что именно его чувствует лодка и именно он объясняет, почему на ходу
// «поддувает в лицо», а на стоянке нет. Показывать рядом две разные величины,
// обе назвав ветром, значит сбивать с толку — это мы уже проходили.
//
// Три вещи, которые пришлось сделать не самым коротким способом, и каждая по
// своей причине.
//
// **Разворот к камере — в вершинном узле.** Лента, лежащая в фиксированной
// плоскости, с половины ракурсов видна с ребра и пропадает. Поэтому поперечное
// смещение считается не здесь, а в шейдере: `нормаль = dir × (камера − точка)`.
// Тогда лента всегда стоит лицом к глазу, как это делают с толстыми линиями.
// А вот ширина остаётся НАСТОЯЩЕЙ, в метрах: экранно-постоянная делала дальние
// струи одинаково жирными, и они читались наклейками поверх кадра.
//
// **Веретено, а не прямоугольник.** Три станции вдоль струи с шириной 0 — макс —
// 0: оба конца сходятся в остриё. Прямоугольник давал срезанные торцы, и хвост
// обрывался ножом.
//
// **Прозрачность по вершинам, а не цвет.** Гасить хвост цветом означает уводить
// его в чёрный — на светлой воде это грязный след, а не растворение. Альфа
// приходит отдельным атрибутом и уходит в `opacityNode`.

const STREAK_N = 70;
const STREAK_R = 70;                     // радиус, в котором держатся, м
const STREAK_LO = 0.4, STREAK_HI = 14;   // высоты, м
// Струя летит медленнее ветра: с его настоящей скоростью пучок превращается в
// мельтешение, которое читается как помеха, а не как движение воздуха.
const STREAK_SPEED = 0.45;
// Нижний предел скорости сноса, м/с. Нужен на полных курсах: там кажущийся
// ветер падает почти до нуля — лодка убегает вместе с воздухом, — и струи
// перестают догонять лодку, повисая рядом неподвижными лентами. Физически это
// верно, а на экране читается как поломка: украшение, которое замерло.
// Поэтому снос не опускается ниже этого, а честность возвращается яркостью:
// чем слабее кажущийся ветер, тем бледнее струи, вплоть до полного исчезновения.
// Полуширина в МЕТРАХ. Экранно-постоянная толщина держала дальние струи
// одинаково жирными, и они читались наклейками поверх кадра, а не воздухом в
// нём; настоящий размер возвращает им место в перспективе.
const STREAK_W = 0.04;
// Станции вдоль струи: доля длины и полуширина в долях максимальной.
//
// Их одиннадцать. Тремя выходил ромб с изломом на плечах; шестью — капля, но
// ломаная гнулась в потоке заметными коленями. Станции ведь работают дважды:
// задают форму и служат точками, по которым струя изгибается, — и для второго
// их нужно больше, чем для первого.
//
// Ставятся они гуще к голове: там и профиль круче, и поток у паруса меняется
// быстрее, а к хвосту всё равно всё сходит на нет.
const STREAK_ST = (() => {
  const n = 10, head = 0.13, out = [];
  for (let k = 0; k <= n; k++) {
    const t = Math.pow(k / n, 1.35);
    // Капля: скруглённый нос до `head`, длинный сходящий хвост после.
    const w = t < head ? Math.sqrt(t / head)
                       : Math.pow((1 - t) / (1 - head), 1.3);
    out.push([t, w]);
  }
  return out;
})();

// Насколько струи слушаются возмущения от парусов. Единица — как у линий тока,
// один в один; но струи живут по всей воде и на виду постоянно, поэтому берётся
// меньше: нужен намёк на обтекание, а не второй экземпляр отладочного слоя.
const STREAK_HEED = 0.55;
// Дальше этого от центра парусности решётка не опрашивается вовсе: там её
// возмущение всё равно тонет в свободном потоке, а вызовов набегает много.
const STREAK_NEAR = 26;
// Насколько быстро форма догоняет расчётную, 1/с. Хвост строится опросом потока
// на каждой станции, а поток у паруса шумит: порывы, качка, перекладка. Без
// памяти струя от кадра к кадру дёргается — и чем больше станций, тем заметнее,
// потому что дрожание накапливается вдоль ломаной. Здесь она догоняет расчётную
// форму по экспоненте: медленные изменения проходят целиком, быстрые гасятся.
const STREAK_EASE = 7;

const streaks = [];
const STREAK_V = STREAK_ST.length * 2;
const streakGeo = new BufferGeometry();
{
  const n = STREAK_N * STREAK_V;
  streakGeo.setAttribute('position', new Float32BufferAttribute(new Float32Array(n * 3), 3));
  // Направление струи и знаковая полуширина: из них шейдер и строит ленту.
  streakGeo.setAttribute('aDir', new Float32BufferAttribute(new Float32Array(n * 3), 3));
  streakGeo.setAttribute('aWide', new Float32BufferAttribute(new Float32Array(n), 1));
  streakGeo.setAttribute('aFade', new Float32BufferAttribute(new Float32Array(n), 1));
  const idx = [];
  for (let i = 0; i < STREAK_N; i++) {
    const b = i * STREAK_V;
    for (let k = 0; k < STREAK_ST.length - 1; k++) {
      const a = b + k * 2;
      idx.push(a, a + 1, a + 2, a + 1, a + 3, a + 2);
    }
  }
  streakGeo.setIndex(idx);
}

const streakMat = new MeshBasicNodeMaterial({
  color: 0xffffff, transparent: true, depthWrite: false, side: DoubleSide });
{
  const centre = positionGeometry;
  const dir = attribute('aDir', 'vec3');
  const wide = attribute('aWide', 'float');
  // Нормаль к струе, всегда лицом к глазу. Вырождение — когда смотришь вдоль
  // струи — гасится тем, что длина векторного произведения там стремится к нулю
  // вместе с видимой шириной: лента честно исчезает, а не дёргается.
  const toEye = cameraPosition.sub(centre);
  const side = cross(dir, toEye).normalize();
  streakMat.positionNode = centre.add(side.mul(wide));
  streakMat.opacityNode = attribute('aFade', 'float');
}
if (typeof streakMat.positionNode !== 'object' || !streakMat.positionNode) {
  throw new Error('TSL: выражение струй собралось не в узел');
}
