// Колдунчики.
//
// Тряска показывает, что парус УЖЕ полощет; колдунчик — что вот-вот начнёт, и
// в какую сторону править. Это то, по чему на воде и держат настройку, и стоит
// он дешевле всего: всё нужное уже посчитано.
//
// Наветренный поднимается, когда угол атаки падает ниже идеального, то есть
// когда лодка приведена или шкот перетравлен. Подветренный виснет и мечется,
// когда угол атаки подходит к срыву — перебран шкот или лодка увалена. Оба
// стелются по потоку, когда парус настроен.
//
// Цвет держится за БОРТ, а не за роль. Красный на левом, зелёный на правом —
// как ходовые огни, так их и вяжут. Значит на одном галсе наветренный красный,
// на другом зелёный, и меняются они ролями сами при перекладке. Пока цвет был
// привязан к роли, галса по колдунчикам было не отличить — а на воде первое,
// что по ним читают, это именно галс.
const TELL_ROWS = [2, 5, 8];      // строки сетки паруса, где висят ленточки
const TELL_COL = 5;               // столбец: примерно 15% хорды от шкаторины
const TELL_SEG = 4;               // звеньев в ленточке
const TELL_LEN = 0.34;            // длина, м
const TELL_OFF = 0.03;            // отступ от полотна, м
const TELL_W = 0.018;             // полуширина ленты, м
const SAIL_STALL = 13;            // градусов, как в physics.sailCoeffs

// Ленточка — не линия, а узкая полоса: линия толщиной в пиксель на воде не
// читается, а тут ещё и не утолщается (WebGL везде рисует её в один пиксель).
// Полосу разворачиваем в плоскости паруса — тогда с наветра, откуда на них и
// смотрят, она видна плашмя.
//
// Тест глубины включён. Раньше ленточки рисовались поверх всего, чтобы
// подветренный колдунчик было видно сквозь полотно, — но за это платили тем,
// что они светились и сквозь корпус, и сквозь дальний парус, и с любого ракурса
// путались между собой. Пусть лучше подветренный прячется за полотном, как и на
// воде: там его видно, только когда ткань тонкая и солнце сзади.
const TELL_VERT = TELL_SEG * 6;   // два треугольника на звено

const TELL_PORT = [0.98, 0.36, 0.30];    // левый борт — красный
const TELL_STBD = [0.35, 0.88, 0.58];    // правый — зелёный

// Перекрасить: `lee` — знак локальной Z подветренной стороны (Z вправо).
// Первая половина вершин наветренная, вторая подветренная.
function telltaleColours(mesh, lee) {
  const col = mesh.geometry.attributes.color.array;
  const n = col.length / 3;
  const leeC = lee > 0 ? TELL_STBD : TELL_PORT;
  const winC = lee > 0 ? TELL_PORT : TELL_STBD;
  for (let i = 0; i < n; i++) {
    const c = i >= n / 2 ? leeC : winC;
    col[i * 3] = c[0]; col[i * 3 + 1] = c[1]; col[i * 3 + 2] = c[2];
  }
  mesh.geometry.attributes.color.needsUpdate = true;
}

function telltaleMesh() {
  const n = TELL_ROWS.length * 2 * TELL_VERT;
  const g = new BufferGeometry();
  g.setAttribute('position', new Float32BufferAttribute(new Float32Array(n * 3), 3));
  const col = new Float32Array(n * 3);
  g.setAttribute('color', new Float32BufferAttribute(col, 3));
  // С тестом глубины: без него ленточки светились сквозь полотно и сквозь
  // корпус, и на любом ракурсе было не понять, какая из них с этой стороны, а
  // какая с той. Подветренный на просвет не виден — но и на воде он виден лишь
  // тогда, когда полотно тонкое и солнце сзади.
  const m = new Mesh(g, new MeshBasicMaterial({
    vertexColors: true, side: DoubleSide }));
  m.renderOrder = 3;
  m.frustumCulled = false;
  return m;
}
const telltales = [telltaleMesh(), telltaleMesh()];
boatGroup.add(telltales[0], telltales[1]);
// Борт, на котором стоят колдунчики сейчас. Перекрашиваются они не каждый кадр,
// а когда парус перешёл: буфер цвета мал, но и трогать его без нужды незачем.
let tellLee = [0, 0];

// Ленточка лёгкая, но не безынерционная: она отзывается за доли секунды, а не
// мгновенно. Без этого запаздывания колдунчик дёргается на каждом порыве и на
// каждой качке, чего на воде нет и в помине — там он ведёт себя заметно
// спокойнее самого потока.
const TELL_TAU = 0.28;            // с, постоянная времени отклика
const tellState = [];             // по паре чисел на каждую ленточку

// Колдунчики на ЗАДНЕЙ ШКАТОРИНЕ грота.
//
// Показывают другое, чем передние, и потому висят отдельно. Передние говорят,
// как поток ПРИХОДИТ на парус: наветренный поднялся — приведено, подветренный
// повис — увалено или перебрано. Задние говорят, как он с паруса СХОДИТ:
// пока кромка держит поток, ленточка вытянута в корму; оторвался — она
// заворачивается за парус и мечется.
//
// Ценность их в том, что кромка сдаёт РАНЬШЕ передней шкаторины. Перебрал
// шкот — задний завернулся, а передние ещё стелются, и парус вроде бы везёт;
// на этом и держат грот. В модели этот порядок не назначен, а получается: см.
// leechSeparation в aero.js и замер в комментарии там же.
//
// Их три, по числу лат, и цвет у них свой — они ни наветренные, ни
// подветренные.
const LEECH_ROWS = [3, 6, 9];
const LEECH_LEN = 0.30;           // ленты по 25–30 см, как их и режут
const LEECH_COLOUR = [0.96, 0.84, 0.42];

function leechMesh() {
  const n = LEECH_ROWS.length * TELL_VERT;
  const g = new BufferGeometry();
  g.setAttribute('position', new Float32BufferAttribute(new Float32Array(n * 3), 3));
  const col = new Float32Array(n * 3);
  for (let i = 0; i < n; i++) {
    col[i * 3] = LEECH_COLOUR[0];
    col[i * 3 + 1] = LEECH_COLOUR[1];
    col[i * 3 + 2] = LEECH_COLOUR[2];
  }
  g.setAttribute('color', new Float32BufferAttribute(col, 3));
  const m = new Mesh(g, new MeshBasicMaterial({
    vertexColors: true, side: DoubleSide }));
  m.renderOrder = 3;
  m.frustumCulled = false;
  return m;
}
const leechTells = leechMesh();
boatGroup.add(leechTells);

// Одна ленточка: от точки на полотне по потоку, с изломом и трепетом.
// `bend` — насколько её задирает или роняет, `wob` — насколько мечется.
function drawTelltale(arr, at, px, py, pz, ux, uz, bend, wob, phase, length) {
  let x = px, y = py, z = pz, i = at;
  const step = (length || TELL_LEN) / TELL_SEG;
  for (let s = 0; s < TELL_SEG; s++) {
    const f = (s + 1) / TELL_SEG;
    const a = bend * f + wob * Math.sin(phase + 3 * f);
    const c = Math.cos(a), sn = Math.sin(a);
    const nx = x + ux * c * step, ny = y + sn * step, nz = z + uz * c * step;
    // поперёк ленты, в плоскости паруса: единичное, потому что c² + sin² = 1
    const wx = sn * ux * TELL_W, wy = -c * TELL_W, wz = sn * uz * TELL_W;
    const v = [x - wx, y - wy, z - wz,  x + wx, y + wy, z + wz,
               nx + wx, ny + wy, nz + wz,
               x - wx, y - wy, z - wz,  nx + wx, ny + wy, nz + wz,
               nx - wx, ny - wy, nz - wz];
    for (let j = 0; j < 18; j++) arr[i + j] = v[j];
    x = nx; y = ny; z = nz; i += 18;
  }
  return i;
}

