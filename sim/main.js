// Старт: галфвинд, шкот под него, ход близкий к установившемуся и включённый
// авторулевой. Без этого лодка первым делом уваливается в фордевинд, где
// парус работает одним сопротивлением, — и посмотреть на её поведение
// не получается, пока не возьмёшь руль.
const boat = new Boat(PACK, terrain);
// Свободная пелена на телефоне остаётся в силах, но её работа РАЗМАЗАНА по
// шагам: за шаг считается треть узлов, остальные держат прошлую скорость сноса
// (`FreeWake.pickSlice`). Молодые ряды при этом считаются всегда — их и видит
// парус.
//
// Сначала она была здесь просто выключена: на телефоне стоила девять с
// половиной миллисекунд из семнадцати с половиной. Но выключение — это ДРУГАЯ
// МОДЕЛЬ: скос считают прямые лучи, запаздывание — подобранный фильтр, и
// установившийся ход уезжает от −3.9% на галфвинде до +2.5% в бейдевинд.
//
// Деление работы такой цены не имеет вовсе. Замер по пяти курсам: ход совпадает
// до четвёртого знака (5.0939 уз при любом делении), отклик на ступеньку ветра
// тот же (0.56 / 0.82 / 0.98 против 0.56 / 0.82 / 0.98), поворот через
// фордевинд держится так же (Γ 23.4 против 23.3). Цена шага при этом 1.68 мс
// против 2.70.
