// портит доверие ко всему остальному, что там написано.
function plural(n, one, few, many) {
  const a = Math.abs(n) % 100, b = a % 10;
  const w = (a > 10 && a < 20) || b === 0 || b > 4 ? many : b === 1 ? one : few;
  return n + ' ' + w;
}

