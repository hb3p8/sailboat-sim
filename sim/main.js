function frame() {
  const now = performance.now() / 1000;
  const dt = Math.min(0.25, now - last);
  last = now;
  acc += dt;

  // Волна — плавучести, до шага, а не после. Глубину корпуса физика меряет от
  // этой поверхности, и качка на волне получается у неё сама — тем же объёмом,
  // той же жёсткостью, тем же демпфированием, что и посадка под грузом.
  // Подрисованной посадки корпуса в сцене нет.
  //
  // Ответ приходит с прошлого кадра: читается он с видеокарты асинхронно. На
  // волне с периодом в пару секунд это сантиметры.
  readSeaPlane(boat.psi,
               windMapSample(toSceneX(boat.x), toSceneZ(boat.y)) ** 2);
  boat.setWater(seaPlane.z, seaPlane.se, seaPlane.sn);

  let steps = 0;
  while (acc >= DT && steps < 8) {
    prev.x = boat.x; prev.y = boat.y; prev.psi = boat.psi; prev.phi = boat.phi;
    prev.zc = boat.zc; prev.th = boat.th;
    readControls(DT);
    boat.step(DT);
    if (![boat.x, boat.y, boat.psi, boat.phi, boat.u, boat.v].every(Number.isFinite)) {
      boat.reset(); boat.u = 1;
      const box = document.getElementById('crash');
      box.hidden = false;
      box.textContent = 'Физика разошлась, состояние сброшено. Проверьте make test.';
      acc = 0;
      break;
    }
    recorder.push(boat);
    acc -= DT;
    steps++;
  }
  const a = Math.min(1, acc / DT);
  const ix = prev.x + (boat.x - prev.x) * a;
  const iy = prev.y + (boat.y - prev.y) * a;
  const ipsi = prev.psi + wrapPi(boat.psi - prev.psi) * a;
  const iphi = prev.phi + (boat.phi - prev.phi) * a;
  const izc = prev.zc + (boat.zc - prev.zc) * a;
  const ith = prev.th + (boat.th - prev.th) * a;
  const t = boat.telemetry || {};

  // Лодка ходит и по вертикали: садится под грузом, приседает под тягой и
  // стоит с дифферентом. С волной сюда же входит и то, как её поднимает
  // гребнем: zc считается от СПОКОЙНОЙ воды, а плавучесть меряет глубину от
  // местной поверхности, которую ей даёт проба из ocean.js. Поэтому подрисовывать
  // здесь нечего — всплытие и дифферент приходят из физики целиком.
  //
  // Порядок поворотов YXZ означает, что дифферент применяется первым, в осях
  // самой лодки, — то есть так, как он и получается.
  boatGroup.position.set(toSceneX(ix), heaveY(izc), toSceneZ(iy));
  boatGroup.rotation.order = 'YXZ';
  boatGroup.rotation.y = headingRotY(ipsi);
  boatGroup.rotation.x = heelRotX(iphi);
  boatGroup.rotation.z = pitchRotZ(ith);
  rudderPivot.rotation.y = rudderRotY(boat.o.rudder);

  // Борт паруса берём у физики: там он с запасом на перекидывание и меняется
  // за конечное время, так что гик переходит плавно, а не телепортируется.
  // До первого шага физики он ещё не поставлен.
  const side = rigSideZ(boat.rigSide != null ? boat.rigSide : 1);
  shapeSails(side);

  updateWindMap();
  sea.position.set(toSceneX(Math.round(ix / CELL) * CELL), 0,
                   toSceneZ(Math.round(iy / CELL) * CELL));

  // Море. Состояние берётся у физики, а не считается заново: высоту и период
  // уже посчитал waves.js — по ветру и по разгону, который на акватории свой в
  // каждой точке. Так волна на воде и волна в сопротивлении — одна и та же
  // волна, и по виду моря можно судить, за что лодка платит ходом.
  //
  // Волны бегут по ветру. Направление берётся у лодки вместе с поворотом к оси
  // долины — по тому же соображению, что и языки ряби ниже: там, где на волну
  // смотрят, она обязана совпадать со стрелками.
  {
    const st = seaState(boat.o.windSpeed, boat.fetchM || 0);
    ocean.setSea(boat.seaHs || 0, st.tp, boat.o.windDir + (boat.chanRot || 0));
    // Пробы под корпусом — ДО прогона: ядро проб идёт последним в том же
    // пакете, и точки обязаны быть свежими. Ответ придёт следующим кадром.
    placeSeaProbes(ix, iy, ipsi);
    // Время — модельное, а не настенное: при паузе и перемотке записи вода
    // обязана стоять и отматываться вместе с лодкой.
    ocean.step(boat.t);
  }
  seaGust.value = boat.wind.o.gust;
  seaShadeGust.value = boat.o.shadeGust;
  // Языки ряби кладутся по направлению ветра У ЛОДКИ, вместе с поворотом к оси
  // долины: там, где на них и смотрят, они обязаны совпадать со стрелками. На
  // дальней воде поворот будет уже другой, и этого рябь не показывает — поле
  // одно на всю поверхность, и разрешать его по месту стоило бы дороже, чем
  // стоит сама разница.
  seaWindDir.value = boat.wind.o.dir + (boat.chanRot || 0);
  seaWindSpeed.value = boat.wind.o.speed;
  seaTime.value = boat.t;
  if (debugOn) updateGrid(toSceneX(ix), toSceneZ(iy));
  seaProbeMarks.visible = debugOn && camMode !== HIGH_CAM;
  if (seaProbeMarks.visible) updateSeaProbes(ix, iy, ipsi);
  updateStreaks(toSceneX(ix), toSceneZ(iy), dt);
  curField.visible = debugMode === 1 && terrain.ready && boat.o.current > 0;
  if (debugMode === 2) updateBalance();
  if (debugMode === 1) {
    updateField(toSceneX(ix), toSceneZ(iy), now);
    updateBattens(side);
    // Линии тока считаются по всей решётке в каждой точке — это дорого, и
    // каждый кадр не нужно: поток меняется не быстрее самой лодки.
    flowGroup.position.set(toSceneX(ix), 0, toSceneZ(iy));
    flowGroup.rotation.y = headingRotY(ipsi);
    if ((tick % 12) === 0) updateFlow();
  }

  const spd = t.speed || 0;
  if ((tick % 2) === 0) {
    wakePts.unshift({
      x: toSceneX(ix - 2.9 * Math.cos(ipsi)),
      z: toSceneZ(iy - 2.9 * Math.sin(ipsi)),
      psi: ipsi, w: 0.30 + 0.07 * spd });
    if (wakePts.length > WAKE) wakePts.length = WAKE;
  }
  const wp = wakeGeo.attributes.position.array;
  const wc = wakeGeo.attributes.color.array;
  for (let i = 0; i < wakePts.length; i++) {
    const p = wakePts[i];
    const f = 1 - i / WAKE;
    const w = p.w * (0.8 + 0.9 * (1 - f));
    const nx = stbdSceneX(p.psi), nz = stbdSceneZ(p.psi);
    wp[i * 6] = p.x + nx * w; wp[i * 6 + 1] = 0.05; wp[i * 6 + 2] = p.z + nz * w;
    wp[i * 6 + 3] = p.x - nx * w; wp[i * 6 + 4] = 0.05; wp[i * 6 + 5] = p.z - nz * w;
    const b = f * f * Math.min(1, spd / 3);
    for (let k = 0; k < 6; k++) wc[i * 6 + k] = 0.75 + 0.25 * b;
  }
  // Рисуем только накопленные звенья: иначе хвост схлопывается в одну точку
  // и получается веер поперёк всей акватории.
  wakeGeo.setDrawRange(0, Math.max(0, (wakePts.length - 1) * 6));
  wakeGeo.attributes.position.needsUpdate = true;
  wakeGeo.attributes.color.needsUpdate = true;
  wake.material.opacity = 0.12 + 0.45 * Math.min(1, spd / 4);

  if ((tick % 6) === 0 && trackN < TRACK) {
    const tp = trackGeo.attributes.position.array;
    tp[trackN * 3] = toSceneX(ix); tp[trackN * 3 + 1] = 0.06;
    tp[trackN * 3 + 2] = toSceneZ(iy);
    trackN++;
    trackGeo.setDrawRange(0, trackN);
    trackGeo.attributes.position.needsUpdate = true;
  }

  // Стрелка — тоже прибор: рулевой читает ветер по колдунчикам, розе и воде, а
  // указатель, висящий над мачтой, отвечает на вопрос отладки «куда дует здесь».
  arrow.position.set(toSceneX(ix + 4 * Math.cos(boat.o.windDir)), 6.2,
                     toSceneZ(iy + 4 * Math.sin(boat.o.windDir)));
  // Стрелка показывает ветер У ЛОДКИ, а не положение ползунка: с канализацией
  // поток разворачивается к оси долины на десятки градусов, и стрелка,
  // оставленная на свободном ветре, спорила бы со стрелками поля вокруг —
  // те-то считают поворот в каждой точке. Два указателя ветра, показывающие
  // разное и не говорящие об этом, читаются как поломка.
  arrow.rotation.y = windRotY(boat.o.windDir + (boat.chanRot || 0));

  // Орты лодки в сцене: куда смотрит нос и где правый борт. Через них
  // камеры пишутся без тригонометрии в каждой строке и, главное, без шанса
  // случайно поставить камеру не с того борта.
  const bx = toSceneX(ix), bz = toSceneZ(iy);
  const fx = bowSceneX(ipsi), fz = bowSceneZ(ipsi);     // в нос
  const sx = stbdSceneX(ipsi), sz = stbdSceneZ(ipsi);   // на правый борт
  const at = (fwd, stb, h) =>
    new Vector3(bx + fwd * fx + stb * sx, h, bz + fwd * fz + stb * sz);
  let want;
  if (camMode === 0) want = at(-13, 2.5, 4.6);
  else if (camMode === 1) want = at(-2, 5, 3.0);
  else if (camMode === 2) want = at(-1.2, 1.0, 1.9);
  else if (camMode === 3) want = at(-2, 0, 28);
  else if (camMode === HIGH_CAM) want = at(-60, 0, HIGH_CAM_UP);
  else {
    // Свободная: сферические координаты вокруг лодки, в мировых осях.
    const c = Math.cos(freeCam.el), d = freeCam.dist;
    want = new Vector3(bx + d * c * Math.cos(freeCam.az),
                       rig.mast_height_m * 0.35 + d * Math.sin(freeCam.el),
                       bz + d * c * Math.sin(freeCam.az));
  }
  // Отметка на карте — только в виде с высоты, где лодка иначе не видна. Сетка
  // на воде, наоборот, гасится: она мерит скорость на глаз, а с двух километров
  // её стометровый лоскут читается заплаткой, а не масштабом.
  grid.visible = camMode !== HIGH_CAM;
  mark.visible = camMode === HIGH_CAM;
  if (mark.visible) {
    mark.position.set(bx, 1.0, bz);
    mark.rotation.y = headingRotY(ipsi);
    mark.scale.setScalar(Math.max(60, camPos.y) / MARK_AT);
  }
  // Туман зависит от вида: с воды он в километре, с высоты в четырёх.
  if (scene.fog) {
    const hi = camMode === HIGH_CAM;
    scene.fog.near = hi ? HIGH_FOG[0] : (FAR_WATER ? 900 : 110);
    scene.fog.far = hi ? HIGH_FOG[1] : (FAR_WATER ? 14000 : 420);
  }
  const aim = camMode === FREE_CAM
    ? new Vector3(bx + 1.5 * fx, rig.mast_height_m * 0.35, bz + 1.5 * fz)
    : at(2, 0, camMode === 3 || camMode === HIGH_CAM ? 0 : 1.4);
  // Свободную камеру не сглаживаем: под рукой она должна ходить сразу.
  if (camMode === FREE_CAM) { camPos.copy(want); camAim.copy(aim); }
  else {
    camPos.lerp(want, 1 - Math.pow(camMode === 2 ? 1e-7 : 0.004, dt));
    camAim.lerp(aim, 1 - Math.pow(0.004, dt));
  }
  camera.position.copy(camPos);
  camera.lookAt(camAim);

  updateCrew();
  if (orthoView) renderOrtho(bx, bz, fx, fz, sx, sz);
  else renderer.render(scene, camera);
  if ((tick % 3) === 0) { updateHud(t); updateRose(t); if (debugMode === 1) updateRig(t);
    if (debugMode === 2) updateBalCard();
    if (topShown) updateTop(); }
  tick++;
  requestAnimationFrame(frame);
}

