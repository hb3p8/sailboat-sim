// Парус как мембрана: форма сечения из равновесия ткани под давлением.
//
// До этого пузо было числом — 2.6% хорды, одно на весь риг, подобранное так,
// чтобы коэффициенты попали в коридор продувок. Число неправильное вдвойне:
// настоящие паруса шьют с пузом в 8–13%, а лодка в модели набирала свою
// подъёмную силу не пузом, а углом атаки, как плоская пластина. Отсюда врали
// и сопротивление, и отклик на настройку.
//
// Здесь пузо считается. Сечение паруса — нерастяжимая полоса ткани длиной G,
// натянутая между передней и задней шкаторинами на хорду c. Под нормальным
// давлением натяжение вдоль сечения постоянно, и равновесие даёт
//
//     T·y'' = −Δp(x),     y(0) = y(c) = 0.
//
// Форма отсюда известна с точностью до множителя 1/T, а сам T находится из
// нерастяжимости: длина дуги обязана равняться G. Отсюда сразу два следствия,
// которых у постоянного пуза быть не могло:
//
//   * пузо зависит от РАСПРЕДЕЛЕНИЯ давления по хорде, а не от его величины.
//     Ткань не знает, сильно ли дует; она знает, где давление больше. Отсюда
//     смещение пуза вперёд и назад по хорде — то, что на воде видно глазом;
//
//   * запас длины G−c — это то, что задаётся кроем и снастями. Фал, оттяжка
//     Каннингема и оттяжка гика убирают запас, и парус становится плоским.
//     Это и есть управление пузом, которого раньше не было вовсе.
//
// Проверяется всё это в tests/membrane.test.mjs: при равномерном давлении
// решение обязано совпасть с дугой окружности, у которой пузо считается
// вручную.

// Число подынтервалов на панель при численном интегрировании. Восемь хватает:
// на равномерной нагрузке ответ сходится с аналитическим до пятого знака.
const SUB = 8;

// Форма сечения при единичном натяжении.
//
// Возвращает то, что от неё нужно дальше: где горб, какой он высоты, и
// интеграл квадрата наклона — по нему находится натяжение.
export function sectionShape(q) {
  const n = q.length, M = SUB * n, h = 1 / M;
  // Q(ξ) = ∫q, потом I(ξ) = ∫Q. Постоянная интегрирования берётся из условия
  // на задней шкаторине: Y(1) = 0.
  let Q = 0, I = 0, sYp2 = 0;
  const Qn = new Float64Array(M + 1);
  for (let j = 0; j < M; j++) {
    const mid = (j + 0.5) * h;
    Q += h * q[Math.min(n - 1, Math.floor(mid * n))];
    Qn[j + 1] = Q;
    I += h * (Qn[j] + Qn[j + 1]) / 2;
  }
  const C = I;
  let maxAbs = 0, at = 0.5, sum = 0, a0 = 0;
  I = 0;
  for (let j = 0; j < M; j++) {
    const mid = (j + 0.5) * h;
    const Qm = (Qn[j] + Qn[j + 1]) / 2;
    const yp = C - Qm;
    sYp2 += h * yp * yp;
    I += h * (Qn[j] + Qn[j + 1]) / 2;
    const y = C * (j + 1) * h - I;
    sum += y;
    if (Math.abs(y) > Math.abs(maxAbs)) { maxAbs = y; at = (j + 1) * h; }
    // Средний наклон по углу θ (x = ½c(1−cosθ)) — тот самый интеграл из тонкой
    // теории, что даёт нагрузку на самой передней кромке: A₀ = α − ⟨dz/dx⟩θ.
    // У параболы он равен нулю, и «идеальный» угол атаки выходит нулевым; у
    // сечения с горбом впереди или сзади — уже нет.
    // dθ = dξ/√(ξ(1−ξ)) — замена x = ½c(1−cosθ).
    a0 += h * yp / (Math.PI * Math.sqrt(Math.max(1e-12, mid * (1 - mid))));
  }
  return { maxY: maxAbs, sYp2: sYp2, draft: at, meanY: sum / M, a0: a0 };
}

// Пузо сечения из распределения давления и запаса длины ткани.
//
// `slack` — относительный запас (G−c)/c. Величина давления сюда не входит: у
// нерастяжимой мембраны форма от неё не зависит, и это не упрощение, а
// свойство задачи.
export function membraneCamber(q, slack) {
  if (!(slack > 0)) return { camber: 0, draft: 0.5, ideal: 0, sign: 1 };
  const s = sectionShape(q);
  if (!(s.sYp2 > 1e-12) || !(Math.abs(s.maxY) > 1e-12)) {
    return { camber: 0, draft: 0.5, ideal: 0, sign: 1 };
  }
  const camber = Math.abs(s.maxY) * Math.sqrt(2 * slack / s.sYp2);
  return {
    camber: camber, draft: s.draft, sign: Math.sign(s.maxY || 1),
    // Идеальный («безударный») угол атаки: при нём поток входит на переднюю
    // кромку по касательной и нагрузка на ней нулевая. Ниже него мягкая ткань
    // передней шкаторины держать форму перестаёт.
    ideal: (camber / Math.abs(s.maxY)) * s.a0 * Math.sign(s.maxY || 1),
  };
}

// Насколько парус держит переднюю шкаторину: по запасу угла атаки над
// идеальным. Ниже идеального нагрузка на кромке меняет знак, и ткань там
// сминается — это и есть заполаскивание.
//
// Раньше порог стоял просто по модулю угла атаки, пять градусов, и был чистым
// назначением. Теперь назначен только разгон — сколько градусов уходит на
// переход, — а сама точка, от которой он считается, берётся из формы сечения.
const LUFF_RANGE = 4 * Math.PI / 180;

export function luffFactor(alphaWork, ideal) {
  const f = Math.min(1, Math.max(0, (alphaWork - ideal) / LUFF_RANGE));
  return f * f * (3 - 2 * f);
}

// Запас длины ткани по проектному пузу. Обратная задача к предыдущей: у дуги
// с пузом m длина больше хорды в (1 + 8m²/3) раз.
export function slackOf(camber) {
  return (8 / 3) * camber * camber;
}

// Подбой: насколько наполнена передняя треть сечения.
//
// Второй способ смять переднюю шкаторину — не углом атаки, а соседом. Грот
// стоит вплотную позади стакселя, и у самой мачты нагрузка на нём может
// перевернуться, хотя сечение в целом работает. Заполаскивание по идеальному
// углу этого не видит: у грота угол атаки там как раз большой.
//
// Нормируется на НАИБОЛЬШУЮ нагрузку по хорде, а не на среднюю. Со средней
// получался разрыв: при почти нулевой сумме отношение уходило в бесконечность,
// и стоило парусу пройти через ноль нагрузки — на рывке паруснóсти, на порыве —
// как модель дёргалась. Наибольшая по модулю нагрузка нулю равна только вместе
// со всем сечением, а там и подъёмной силы никакой.
export function fillFactor(q) {
  let sum = 0, peak = 0;
  for (let i = 0; i < q.length; i++) {
    sum += q[i];
    peak = Math.max(peak, Math.abs(q[i]));
  }
  if (peak < 1e-12) return 0;
  const r = q[0] * Math.sign(sum || 1) / peak;   // >0 — передняя кромка ещё несёт
  const f = Math.min(1, Math.max(0, r / 0.35));
  return f * f * (3 - 2 * f);
}

// Двумерное сечение мягкого паруса: подъёмная сила и сопротивление.
//
// Угол нулевой подъёмной силы у дуги равен −2m, отсюда линейная часть. Дальше
// начинается то, чего тонкая теория не знает: у паруса острая передняя кромка,
// поток на ней срывается, и подъёмная сила упирается в потолок. Потолок взят
// по замерам двумерных парусных сечений: у плоской пластины около 1.25, у
// дуги с пузом 10% около 1.7.
//
// Показатель 3 в стыковке — не подгонка под данные, а выбор гладкости: при
// нём переход от линейной части к потолку занимает примерно тот же диапазон
// углов, что и в замерах.
export function sectionLift(alpha, camber) {
  const lin = 2 * Math.PI * (alpha + 2 * camber);
  // Пузо со знаком: на другом галсе парус выгнут в другую сторону, а потолок
  // от этого не меняется.
  const max = 1.25 + 4.5 * Math.abs(camber);
  const r = Math.abs(lin) / max;
  return lin / Math.pow(1 + r * r * r, 1 / 3);
}

// Доля хорды от передней шкаторины, потерявшая нагрузку.
//
// Наполнение (fillFactor) говорит, сколько формы осталось, но не говорит, где
// проходит граница. Для картинки нужна именно граница: пузырь заполаскивания
// живёт от шкаторины до того места, где давление меняет знак, а дальше парус
// стоит и работает. Место это находится линейной прошивкой между центрами
// панелей — грубо, зато непрерывно и без скачков при переходе через ноль.
export function luffFraction(q) {
  const n = q.length;
  let sum = 0;
  for (let i = 0; i < n; i++) sum += q[i];
  const s = Math.sign(sum || 1);
  if (q[0] * s > 0) return 0;                 // передняя кромка ещё несёт
  const centre = i => (i + 0.5) / n;
  for (let i = 1; i < n; i++) {
    if (q[i] * s > 0) {
      const a = q[i - 1] * s, b = q[i] * s;
      return centre(i - 1) + (centre(i) - centre(i - 1)) * (-a) / (b - a);
    }
  }
  return 1;                                    // нагрузка перевёрнута везде
}
