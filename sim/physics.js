  // ПОДЪЁМ ГЕНАКЕРА УБИРАЕТ СТАКСЕЛЬ — так лодку и водят (со слов владельца).
  //
  // Это не обход трудности, а порядок работы с парусами, и он же избавляет от
  // трудности. Замер показал её до того, как выяснилось, что вопроса нет: с
  // поднятым стакселем полотно генакера проходит СКВОЗЬ него — галс вынесен на
  // бушприт вперёд по ДП, хорда четыре с половиной метра уходит вбок под шкот,
