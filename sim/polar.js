// Поляра сечения паруса: чтение измеренной таблицы вместо назначенных формул.
//
// Таблица собирается в `src/sv20/polar.py` из опытов Уоллиса (ARL Aero Note 74,
// 1946) на изогнутых пластинах постоянной кривизны и приезжает в пакете физики
// полем `sail_polar`. Что там измерено, а что достроено, написано в том модуле;
// провенанс и цитаты — в `data/section/wallis_arl74.json`.
//
// Здесь только чтение: двойная линейная интерполяция по углу атаки и по пузу.
//
// Про знак угла. Прежние формулы считали сечение симметричным по углу — брали
// модуль и возвращали знак. Опыт говорит, что оно НЕ симметрично: у пластины с
// пузом 8% подъёмная сила обращается в ноль на −3.6°, а не на −9.2°, как велит
// теория тонкого профиля, и ниже нуля кривая идёт втрое круче, чем выше. Поэтому
// таблица спрашивается знаковым углом, приведённым к системе самого сечения:
// сторона, в которую парус выгнут, задаётся знаком пуза.

let TABLE = null;

// Пакет ставится один раз при сборке рига. Держать таблицу в модуле, а не
// таскать сквозь все вызовы, — сознательный размен: она одна на всю программу и
// меняться в ходе счёта не может.
export function setSailPolar(table) {
  TABLE = table && table.cl ? table : null;
}

export function hasSailPolar() {
  return TABLE !== null;
}

// Место в сетке: индекс левого узла и доля до правого.
function slot(xs, x) {
  if (x <= xs[0]) return [0, 0];
  const n = xs.length;
  if (x >= xs[n - 1]) return [n - 2, 1];
  let lo = 0, hi = n - 1;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (xs[mid] <= x) lo = mid; else hi = mid;
  }
  return [lo, (x - xs[lo]) / (xs[lo + 1] - xs[lo])];
}

function bilinear(grid, ia, ta, ic, tc) {
  const a = grid[ic][ia] + (grid[ic][ia + 1] - grid[ic][ia]) * ta;
  const b = grid[ic + 1][ia] + (grid[ic + 1][ia + 1] - grid[ic + 1][ia]) * ta;
  return a + (b - a) * tc;
}

// Подъёмная сила и сопротивление сечения по углу атаки (рад) и пузу со знаком.
//
// Угол переводится в систему сечения умножением на знак пуза, ответ переводится
// обратно тем же знаком. При нулевом пузе знак берётся у самого угла — там
// сечение и правда симметрично.
export function polarCoeffs(alphaRad, camber) {
  const s = camber === 0 ? Math.sign(alphaRad || 1) : Math.sign(camber);
  const aDeg = alphaRad * (180 / Math.PI) * s;
  const [ia, ta] = slot(TABLE.alpha_deg, aDeg);
  const [ic, tc] = slot(TABLE.camber, Math.abs(camber));
  return {
    cl: bilinear(TABLE.cl, ia, ta, ic, tc) * s,
    cd: bilinear(TABLE.cd, ia, ta, ic, tc),
  };
}

// Потолок подъёмной силы сечения по пузу — та же таблица, взятая по максимуму в
// измеренном диапазоне углов.
//
// Нужен отдельно, и не для красоты: этим же потолком ограничивается циркуляция
// в вихревой решётке. Если сечение будет упираться в одно число, а решётка
// считать другое, поле взаимного влияния парусов пойдёт от перегруженного рига —
// на это в `aero.js` стоит отдельное предупреждение. Раньше потолок был формулой
// (1.25 + 4.5·пузо), теперь берётся из тех же измерений: 0.83 у плоской
// пластины, 1.60 при восьми процентах, 1.75 при десяти.
let CEIL = null;

// Окно, в котором у ряда ищется вершина. Оно РАЗНОЕ у рядов с острым срывом и у
// рядов без него, и это та же категориальная ошибка, что уже поймана у угла
// срыва, только с другой стороны.
//
// Четырнадцать градусов поставлены были затем, чтобы не читать вершину за
// срывом: таблица идёт на весь круг, и там все сечения переходят к плоской
// пластине, у которой на −135° своя вершина в единицу — она перебивала вершину
// плоского паруса (0.83). Для рядов Уоллиса окно верное: их срыв лежит на
// 9…13°, и вершина внутри.
//
// А у рядов МИЛГРЭМА срыва нет вовсе («a sharp stall is not observed»), и
// вершина стоит на 18…22°. Четырнадцатиградусное окно отрезало у них ровно то,
// ради чего потолок и заведён: ряд 18% ИЗМЕРЕН до 2.48, а потолок отдавал
// 2.075. Ровно то, от чего предостерегает комментарий выше: одна половина
// модуля отдавала 2.38 на рабочей полоске генакера, другая уверяла, что выше
// 2.075 ничего измеренного нет.
//
// Двадцать четыре — последний угол, на котором Милгрэм эти ряды МЕРИЛ (фиг.
// 6a/8a). Дальше в таблице идёт продолжение, а не измерение, и потолку там
// делать нечего.
const CEIL_TO_HARD = 14;
const CEIL_TO_SOFT = 24;

export function polarCeiling(camber) {
  if (!CEIL) {
    const soft = new Set(TABLE['мягкий_срыв'] || []);
    CEIL = TABLE.camber.map((c, k) => {
      const to = soft.has(c) ? CEIL_TO_SOFT : CEIL_TO_HARD;
      let m = 0;
      for (let i = 0; i < TABLE.alpha_deg.length; i++) {
        const a = TABLE.alpha_deg[i];
        if (a < 0) continue;
        if (a > to) break;
        m = Math.max(m, TABLE.cl[k][i]);
      }
      return m;
    });
  }
  const [ic, tc] = slot(TABLE.camber, Math.abs(camber));
  return CEIL[ic] + (CEIL[ic + 1] - CEIL[ic]) * tc;
}

// Угол срыва по пузу, градусы: там, где таблица берёт наибольшую подъёмную силу.
// Раньше он был назначен — тринадцать градусов при любом пузе. Измерено: 9.5° у
// плоской пластины, 13° при восьми процентах, 12.5° при десяти. То есть плоский
// парус сдаёт заметно раньше пузатого, чего назначенное число не знало вовсе.
//
// Ряды с МЯГКИМ срывом (Милгрэм, пузо 12…18%) в угол срыва не входят: у этих
// сечений его нет — «a sharp stall is not observed», пик Cl лежит на 18…24° и
// срывом не является. Прочитать его как срыв значило бы отодвинуть порог
// отрыва задней шкаторины за половину этого пика — и колдунчик у перебранного
// грота перестал бы предупреждать. Пузо выше последнего ряда с острым срывом
// держит угол этого последнего ряда.
let STALL = null;

export function polarStallDeg(camber) {
  if (!STALL) {
    const soft = new Set(TABLE['мягкий_срыв'] || []);
    const hard = TABLE.camber.filter(c => !soft.has(c));
    STALL = {
      camber: hard,
      deg: hard.map(c => {
        const k = TABLE.camber.indexOf(c);
        let m = 0, at = 0;
        for (let i = 0; i < TABLE.alpha_deg.length; i++) {
          const a = TABLE.alpha_deg[i];
          if (a < 0) continue;               // см. оговорку у потолка
          if (a > 20) break;
          if (TABLE.cl[k][i] > m) { m = TABLE.cl[k][i]; at = a; }
        }
        return at;
      }),
    };
  }
  const [ic, tc] = slot(STALL.camber, Math.abs(camber));
  return STALL.deg[ic] + (STALL.deg[ic + 1] - STALL.deg[ic]) * tc;
}

// Сброс памяти о потолке — нужен только тем, кто подменяет таблицу на ходу
// (батареи).
export function resetSailPolar() {
  CEIL = null;
  STALL = null;
}
