// Отдельным файлом не по величине, а по владению. Обе функции нужны и физике, и
// гидродинамике, и сцене; оставь их в одной из них — и остальные начнут тянуть
// друг друга кольцом, а вклейка в общую область видимости такое кольцо прячет:
// на странице оно соберётся, а в node сломается.

// Градус в радианах. Живёт здесь по той же причине: им пользуются все.
export const DEG = Math.PI / 180;

// Нормировка угла без цикла: при расходимости `while` по бесконечности вешает
// вкладку намертво, и это не гипотеза — так и было.
export function wrapPi(a) {
  if (!isFinite(a)) return 0;
  a = a % (2 * Math.PI);
  if (a > Math.PI) a -= 2 * Math.PI;
  if (a < -Math.PI) a += 2 * Math.PI;
  return a;
}

export function clamp(v, lim) {
  if (!isFinite(v)) return 0;
  return v < -lim ? -lim : (v > lim ? lim : v);
}

// Телефон это или настольная машина, и решается это ОДИН раз на всю страницу.
//
// Признак — НЕ ширина окна и не строка агента. Ширина врёт на разделённом
// экране планшета и на узком окне ноутбука; строка агента врёт всегда.
// Спрашивается то, что действительно решает: есть ли у указателя точность мыши
// и есть ли наведение. Грубый указатель без наведения — это палец.
//
// Поверх этого `?ui=game` и `?ui=debug`: без них ни игровой интерфейс не
// посмотреть с ноутбука, ни телефонные упрощения не проверить.
//
// Живёт здесь, а не в mobile.js, по одной причине: от него зависит не только
// интерфейс. Плотность пикселей и карта теней ставятся в main.js, пелена в
// силах — там же, а вклеивается mobile.js ПОСЛЕ, и обращение к нему сверху
// давало бы временную мёртвую зону. Один признак на всех — и он объявлен
// раньше всех.
export const MOBILE_UI = (() => {
  if (typeof location === 'undefined' || typeof matchMedia === 'undefined') return false;
  const want = new URLSearchParams(location.search).get('ui');
  if (want === 'game') return true;
  if (want === 'debug') return false;
  return matchMedia('(pointer: coarse)').matches
    && matchMedia('(hover: none)').matches;
})();
