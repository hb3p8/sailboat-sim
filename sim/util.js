// друг друга кольцом, а вклейка в общую область видимости такое кольцо прячет:
// на странице оно соберётся, а в node сломается.

// Градус в радианах. Живёт здесь по той же причине: им пользуются все.
export const DEG = Math.PI / 180;

// Нормировка угла без цикла: при расходимости `while` по бесконечности вешает
// вкладку намертво, и это не гипотеза — так и было.
export function wrapPi(a) {
  if (!isFinite(a)) return 0;
  a = a % (2 * Math.PI);
  if (a > Math.PI) a -= 2 * Math.PI;
  if (a < -Math.PI) a += 2 * Math.PI;
  return a;
}

export function clamp(v, lim) {
  if (!isFinite(v)) return 0;
  return v < -lim ? -lim : (v > lim ? lim : v);
}
