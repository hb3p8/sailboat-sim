// Вихревая решётка: индуктивная задача рига.
//
// Что она решает. Полоска паруса сама по себе не знает ни о соседних полосках,
// ни о втором парусе. Между тем несущая поверхность конечного размаха сама себе
// меняет набегающий поток: за ней сходит вихревая пелена, и та наводит на самой
// поверхности скос потока — вниз у одиночного крыла, вверх или вниз у соседа,
// смотря где он стоит. Отсюда берутся сразу три вещи, которых в модели по
// независимым полоскам нет вовсе:
//
//   индуктивное сопротивление — не по паспортному удлинению, а по настоящей
//   форме паруса и его закрутке;
//
//   щелевой эффект — грот и стаксель узнают друг о друге. Стаксель наводит на
//   гроте восходящий скос, грот на стакселе нисходящий; ради этого стаксель и
//   ставят, и без этого он в модели просто складывался с гротом;
//
//   распределение нагрузки по высоте, а с ним и настоящий центр парусности.
//
// Как она это делает. Каждая полоска несёт присоединённый вихрь на четверти
// хорды и два свободных, уходящих по потоку, — подкова. Циркуляция подковы
// связана с подъёмной силой сечения: Γ = ½·V·b·cl. Скос считается по закону
// Био — Савара от всех подков сразу, включая чужой парус.
//
// Контрольная точка лежит НА линии присоединённых вихрей, и собственный
// присоединённый вихрь полоски из расчёта исключён. Это не мелочь, а выбор
// метода. Есть два разных способа: у Вайссингера контрольная точка на трёх
// четвертях хорды, собственный вихрь учитывается, а подъёмная сила берётся
// прямо из циркуляции — но тогда двумерная модель сечения не нужна и срыва
// не будет вовсе. У Прандтля контрольная точка на несущей линии, скос
// наводится только пеленой, а подъёмная сила берётся из двумерных данных
// сечения — они собственный вихрь уже содержат. Смешать их нельзя: получится
// двойной учёт, и итерации просто разойдутся. Здесь второй способ, ради срыва
// и заполаскивания.
//
// Задача нелинейная: скос меняет угол атаки, угол атаки меняет циркуляцию.
// Решается простой итерацией с недорелаксацией — сходится за несколько
// проходов, а матрица влияния при этом одна и та же.
//
// Нелинейность живёт в модели сечения, а не здесь. Это принципиально: сама
// вихревая решётка — потенциальное течение, она не умеет ни срыва, ни
// заполаскивания, ни обтекания задом наперёд, а на полных курсах парус живёт
// именно там. Решётка даёт только скос — величину линейную и хорошо себя
// ведущую, — а всё остальное остаётся за sailCoeffs, как и было.

const EPS = 1e-10;

// Ядро вихря: на каком расстоянии нить перестаёт быть нитью.
//
// Био — Савар растёт как 1/r, и у бесконечно тонкой нити скорость рядом с ней
// не ограничена ничем. В решётке это не отвлечённая беда: сходящие вихри уходят
// по потоку через весь риг, и стоит пелене стакселя пройти вплотную к
// контрольной точке грота, как влияние уходит в бесконечность, матрица теряет
// обусловленность, а решение — смысл. Ловилось это так: при совершенно гладкой
// правой части суммарная циркуляция рига скакала между соседними шагами со 161
// на −127 и обратно. В силы это почти не выходило — скос упирался в
// ограничитель, а наполнение и без того лежало на нуле, — но модель в такие
// моменты решала не ту задачу, какую думала.
//
// Лечится тем же, чем во всех решётках: у нити появляется ядро радиуса rc,
// внутри которого скорость не растёт. Физически это и есть правда — настоящая
// пелена не нить, а слой конечной толщины, и разрешать её ближе, чем на
// расстояние между соседними нитями, дискретизация всё равно не может.
// Радиус приходит последним доводом, `rc2` — его квадрат; ноль — прежнее
// поведение. Задаётся он полем `core` решётки, в метрах.
//
// В обеих формулах ниже c2 — квадрат «плеча»: у отрезка это (|r0|·d)², у
// полубесконечной нити просто d². Поэтому ограничитель у них выглядит
// по-разному, а означает одно и то же: ближе rc не подходить.
// Скорость от отрезка вихревой нити P1→P2 единичной циркуляции в точке P.
// Классический Био — Савар в форме, не требующей делить на длину отрезка.
function segment(px, py, pz, ax, ay, az, bx, by, bz, out, rc2) {
  const r1x = px - ax, r1y = py - ay, r1z = pz - az;
  const r2x = px - bx, r2y = py - by, r2z = pz - bz;
  const cx = r1y * r2z - r1z * r2y;
  const cy = r1z * r2x - r1x * r2z;
  const cz = r1x * r2y - r1y * r2x;
  const c2 = cx * cx + cy * cy + cz * cz;
  const l1 = Math.sqrt(r1x * r1x + r1y * r1y + r1z * r1z);
  const l2 = Math.sqrt(r2x * r2x + r2y * r2y + r2z * r2z);
  if (c2 < EPS || l1 < EPS || l2 < EPS) { out[0] = out[1] = out[2] = 0; return; }
  const r0x = bx - ax, r0y = by - ay, r0z = bz - az;
  const f = (r0x * r1x + r0y * r1y + r0z * r1z) / l1 -
            (r0x * r2x + r0y * r2y + r0z * r2z) / l2;
  const l0 = r0x * r0x + r0y * r0y + r0z * r0z;
  const k = f / (4 * Math.PI * Math.max(c2, rc2 * l0));
  out[0] = cx * k; out[1] = cy * k; out[2] = cz * k;
}

// Скорость от полубесконечной нити, начинающейся в P1 и уходящей по единичному
// вектору u. Предел отрезка, у которого второй конец ушёл на бесконечность.
function tail(px, py, pz, ax, ay, az, ux, uy, uz, out, rc2) {
  const rx = px - ax, ry = py - ay, rz = pz - az;
  const cx = uy * rz - uz * ry;
  const cy = uz * rx - ux * rz;
  const cz = ux * ry - uy * rx;
  const c2 = cx * cx + cy * cy + cz * cz;
  const l = Math.sqrt(rx * rx + ry * ry + rz * rz);
  if (c2 < EPS || l < EPS) { out[0] = out[1] = out[2] = 0; return; }
  const k = (1 + (ux * rx + uy * ry + uz * rz) / l) /
            (4 * Math.PI * Math.max(c2, rc2));
  out[0] = cx * k; out[1] = cy * k; out[2] = cz * k;
}

export class Lattice {
  constructor(n) {
    this.n = n;
    this.k = new Float64Array(n * n);       // матрица влияния
    this.kw = new Float64Array(n * n);      // то же, но только от пелены
    this.gamma = new Float64Array(n);
    this.aInd = new Float64Array(n);        // скос потока, рад
    this.aWake = new Float64Array(n);       // скос от одной пелены, рад
    this.core = 0;                          // радиус ядра вихревой нити, м
    this.panels = [];
    for (let i = 0; i < n; i++) {
      this.panels.push({
        a: [0, 0, 0],      // конец присоединённого вихря, начало размаха
        b: [0, 0, 0],      // другой конец
        ta: [0, 0, 0],     // задняя шкаторина под A — оттуда сходит пелена
        tb: [0, 0, 0],     // задняя шкаторина под B
        c: [0, 0, 0],      // контрольная точка, на несущей линии
        nrm: [0, 0, 0],    // нормаль к поверхности в контрольной точке
        chord: 1, speed: 1,
      });
    }
    this._v = [0, 0, 0];
    this._t = [0, 0, 0];
  }

  // Матрица влияния: нормальная скорость в контрольной точке i от подковы j
  // единичной циркуляции. Зависит только от геометрии и направления пелены,
  // поэтому считается один раз на кадр, а итерации по ней уже дешёвые.
  // `self` — учитывать ли собственный присоединённый вихрь полоски. Это и есть
  // выбор между двумя постановками (см. заголовок): без него — Прандтль, с ним
  // — Вайссингер.
  //
  // `ground` — отражать ли систему вихрей в плоскости z = 0. Для паруса это
  // обязательно: он работает не в свободном потоке, а у самой воды, и нижняя
  // шкаторина не сбрасывает свободный вихрь, как конец крыла, — вода ей не
  // даёт. Отражение с обратной циркуляцией это и выражает. Без него скос
  // получается примерно вдвое больше настоящего, и грот в расчёте умирает.
  build(ux, uy, uz, self, ground) {
    const n = this.n, P = this.panels, v = this._v, t = this._t;
    const rc2 = this.core * this.core;
    const mir = this._mir || (this._mir = {
      a: [0, 0, 0], b: [0, 0, 0], ta: [0, 0, 0], tb: [0, 0, 0] });
    const reflect = (src, dst) => { dst[0] = src[0]; dst[1] = src[1]; dst[2] = -src[2]; };
    // У решётки с панелями по хорде свободные вихри уходят прямо от
    // присоединённого: ta совпадает с a, tb с b. Отрезки вдоль хорды тогда
    // нулевой длины и наводят ровно ноль — Био — Савар отдаёт его точно, через
    // нулевое векторное произведение. Считать их незачем, а стоят они восьми
    // вызовов из восемнадцати на каждую пару панелей: сборка матрицы — это
    // четыре пятых шага физики, и пропуск срезает с неё сорок процентов.
    //
    // Проверка поточечная, потому что решётка умеет и вторую постановку —
    // Прандтля, с пеленой от задней шкаторины (tests/vlm.test.mjs), — и там
    // отрезки настоящие.
    const same = (p, q) => p[0] === q[0] && p[1] === q[1] && p[2] === q[2];
    const lead = new Array(n), trail = new Array(n);
    for (let j = 0; j < n; j++) {
      lead[j] = !same(P[j].ta, P[j].a);
      trail[j] = !same(P[j].b, P[j].tb);
    }
    for (let i = 0; i < n; i++) {
      const ci = P[i].c, ni = P[i].nrm;
      for (let j = 0; j < n; j++) {
        const A = P[j].a, B = P[j].b, TA = P[j].ta, TB = P[j].tb;
        // Замкнутый контур: из бесконечности в TA, вдоль хорды в A, связанный
        // отрезок A→B, обратно по хорде в TB, и оттуда пелена на бесконечность.
        //
        // Пелена сходит с ЗАДНЕЙ ШКАТОРИНЫ, а не с четверти хорды, и это здесь
        // принципиально. Стаксель стоит вплотную впереди грота: если пустить
        // его пелену с четверти хорды, грот окажется внутри неё и получит скос
        // втрое больше настоящего — в расчёте он просто умирал. На деле грот
        // стоит ВПЕРЕДИ того места, где сходит пелена стакселя, и попадает не в
        // скос, а в подпор от его присоединённого вихря. В этом и весь смысл
        // щели: стаксель не отбирает у грота поток, а подкручивает его.
        //
        // Собственный присоединённый вихрь пропускается — его вклад уже сидит
        // в двумерной модели сечения. Отрезки вдоль хорды и пелена остаются:
        // они и дают скос от собственной сходящей вихревой пелены.
        v[0] = v[1] = v[2] = 0;
        if (self || i !== j) {
          segment(ci[0], ci[1], ci[2], A[0], A[1], A[2], B[0], B[1], B[2], v, rc2);
        }
        if (lead[j]) {
          segment(ci[0], ci[1], ci[2], TA[0], TA[1], TA[2], A[0], A[1], A[2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        }
        if (trail[j]) {
          segment(ci[0], ci[1], ci[2], B[0], B[1], B[2], TB[0], TB[1], TB[2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        }
        tail(ci[0], ci[1], ci[2], TB[0], TB[1], TB[2], ux, uy, uz, t, rc2);
        v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        tail(ci[0], ci[1], ci[2], TA[0], TA[1], TA[2], ux, uy, uz, t, rc2);
        v[0] -= t[0]; v[1] -= t[1]; v[2] -= t[2];
        let kij = v[0] * ni[0] + v[1] * ni[1] + v[2] * ni[2];
        if (ground) {
          // Зеркальный контур: та же геометрия, отражённая в z = 0, и обратная
          // циркуляция — тогда на самой плоскости нормальная скорость нулевая.
          reflect(A, mir.a); reflect(B, mir.b);
          reflect(TA, mir.ta); reflect(TB, mir.tb);
          v[0] = v[1] = v[2] = 0;
          segment(ci[0], ci[1], ci[2], mir.a[0], mir.a[1], mir.a[2],
                  mir.b[0], mir.b[1], mir.b[2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          if (lead[j]) {
            segment(ci[0], ci[1], ci[2], mir.ta[0], mir.ta[1], mir.ta[2],
                    mir.a[0], mir.a[1], mir.a[2], t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          }
          if (trail[j]) {
            segment(ci[0], ci[1], ci[2], mir.b[0], mir.b[1], mir.b[2],
                    mir.tb[0], mir.tb[1], mir.tb[2], t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          }
          tail(ci[0], ci[1], ci[2], mir.tb[0], mir.tb[1], mir.tb[2], ux, uy, uz, t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          tail(ci[0], ci[1], ci[2], mir.ta[0], mir.ta[1], mir.ta[2], ux, uy, uz, t, rc2);
          v[0] -= t[0]; v[1] -= t[1]; v[2] -= t[2];
          kij -= v[0] * ni[0] + v[1] * ni[1] + v[2] * ni[2];
        }
        this.k[i * n + j] = kij;

        // Вторая матрица — для индуктивного сопротивления, и она другая.
        //
        // Скос в контрольной точке годится, чтобы найти эффективный угол атаки,
        // но не годится, чтобы наклонить подъёмную силу назад: в нём сидит
        // вклад ПРИСОЕДИНЁННЫХ вихрей соседей. У двух парусов, стоящих один за
        // другим, стаксель наводит на грот подпор, скос выходит отрицательным,
        // и «индуктивное сопротивление» получается тягой. Явление настоящее
        // (это и есть щелевой эффект), а вот вывод неверный: подпор от
        // присоединённого вихря сопротивления не создаёт, он перекладывает
        // подъёмную силу между парусами.
        //
        // Сопротивление даёт только сходящая пелена. Поэтому здесь берутся
        // одни продольные отрезки — вдоль хорды и хвосты, — а связанный отрезок
        // A→B пропускается у обоих контуров, и настоящего, и зеркального.
        // Считается скос в середине присоединённого вихря, где и приложена
        // сила по Жуковскому.
        const mx = (P[i].a[0] + P[i].b[0]) / 2;
        const my = (P[i].a[1] + P[i].b[1]) / 2;
        const mz = (P[i].a[2] + P[i].b[2]) / 2;
        v[0] = v[1] = v[2] = 0;
        if (lead[j]) {
          segment(mx, my, mz, TA[0], TA[1], TA[2], A[0], A[1], A[2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        }
        if (trail[j]) {
          segment(mx, my, mz, B[0], B[1], B[2], TB[0], TB[1], TB[2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        }
        tail(mx, my, mz, TB[0], TB[1], TB[2], ux, uy, uz, t, rc2);
        v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        tail(mx, my, mz, TA[0], TA[1], TA[2], ux, uy, uz, t, rc2);
        v[0] -= t[0]; v[1] -= t[1]; v[2] -= t[2];
        let kwij = v[0] * ni[0] + v[1] * ni[1] + v[2] * ni[2];
        if (ground) {
          v[0] = v[1] = v[2] = 0;
          if (lead[j]) {
            segment(mx, my, mz, mir.ta[0], mir.ta[1], mir.ta[2],
                    mir.a[0], mir.a[1], mir.a[2], t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          }
          if (trail[j]) {
            segment(mx, my, mz, mir.b[0], mir.b[1], mir.b[2],
                    mir.tb[0], mir.tb[1], mir.tb[2], t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          }
          tail(mx, my, mz, mir.tb[0], mir.tb[1], mir.tb[2], ux, uy, uz, t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          tail(mx, my, mz, mir.ta[0], mir.ta[1], mir.ta[2], ux, uy, uz, t, rc2);
          v[0] -= t[0]; v[1] -= t[1]; v[2] -= t[2];
          kwij -= v[0] * ni[0] + v[1] * ni[1] + v[2] * ni[2];
        }
        this.kw[i * n + j] = kwij;
      }
    }
  }

  // Скос от одной пелены — тот, по которому наклоняется подъёмная сила.
  // Знак тот же, что у aInd: положительный скос уменьшает угол атаки.
  wakeAngles() {
    const n = this.n, P = this.panels, g = this.gamma, out = this.aWake;
    for (let i = 0; i < n; i++) {
      let w = 0;
      for (let j = 0; j < n; j++) w += this.kw[i * n + j] * g[j];
      const V = P[i].speed;
      out[i] = V > 1e-3 ? Math.atan2(-w, V) : 0;
    }
    return out;
  }

  // Решение задачи: скос меняет угол атаки, угол атаки меняет циркуляцию.
  //
  // Простой итерацией «посчитал скос — пересчитал циркуляцию» это решать нельзя,
  // хотя и заманчиво. Матрица влияния плохо обусловлена по построению: у своей
  // же полоски свободные вихри стоят на её краях и дают вклад порядка 1/ширины,
  // а у соседей вихри в тех же точках с обратным знаком почти его гасят.
  // Большие взаимно сокращающиеся члены — и простая итерация либо расходится,
  // либо даёт ответ, зависящий от числа полосок. Это и вылезло: CL прыгал вдвое
  // при удвоении разбивки.
  //
  // Поэтому система решается напрямую. Кривая сечения линеаризуется в текущей
  // точке (cl ≈ a·α + b), подстановка Γ = ½·V·b·cl даёт линейную систему по Γ,
  // и она решается методом Гаусса. Внешних проходов нужно два-три: они
  // догоняют нелинейность сечения, а не саму индуктивную задачу.
  //
  // `cl` — двумерная модель сечения: подъёмная сила БЕЗ поправки на удлинение
  // и без индуктивного сопротивления. И то и другое теперь получается здесь.
  solve(alphaGeom, cl, iters) {
    const n = this.n, P = this.panels, g = this.gamma, ai = this.aInd;
    const it = iters || 3;
    const M = this._m || (this._m = new Float64Array(n * (n + 1)));
    const H = 0.5 * Math.PI / 180;              // шаг численной производной

    for (let pass = 0; pass < it; pass++) {
      for (let i = 0; i < n; i++) {
        const V = P[i].speed;
        const aEff = alphaGeom[i] - ai[i];
        // Наклон кривой сечения в текущей точке. За срывом он отрицателен, и
        // система от этого теряет устойчивость, поэтому снизу он подрезан:
        // нелинейность доберут внешние проходы.
        let slope = (cl(aEff + H, i) - cl(aEff - H, i)) / (2 * H);
        if (!(slope > 0.2)) slope = 0.2;
        const free = cl(aEff, i) - slope * aEff;
        const w = 0.5 * V * P[i].chord;
        for (let j = 0; j < n; j++) {
          // Скос входит в угол атаки со знаком минус, а сам он равен −w/V,
          // поэтому в системе получается МИНУС. Со знаком плюс диагональ
          // вырождается и решение идёт вразнос — проверено.
          //   Γi − ½·b·a·Σ Kij·Γj = ½·V·b·(a·αгеом + свободный член)
          M[i * (n + 1) + j] = (i === j ? 1 : 0) -
            0.5 * P[i].chord * slope * this.k[i * n + j];
        }
        M[i * (n + 1) + n] = w * (slope * alphaGeom[i] + free);
      }
      solveGauss(M, g, n);
      for (let i = 0; i < n; i++) {
        let w = 0;
        for (let j = 0; j < n; j++) w += this.k[i * n + j] * g[j];
        const V = P[i].speed;
        // Скос отрицателен по нормали — пелена «поджимает» поверхность, и
        // эффективный угол атаки уменьшается. Знак берётся отсюда, а не из
        // соглашения: нормаль задаёт вызывающий код.
        ai[i] = V > 1e-3 ? Math.atan2(-w, V) : 0;
      }
    }
    return ai;
  }

  // Скорость, наведённая всей системой вихрей, в произвольной точке. Нужна не
  // для сил, а для картинки: по ней рисуются линии тока вокруг парусов —
  // ровно то, что показывают в трубе дымом. Считать это каждый кадр незачем,
  // отрисовка обновляет линии в несколько раз реже.
  induced(px, py, pz, ux, uy, uz, ground, out) {
    const n = this.n, P = this.panels, t = this._t;
    const rc2 = this.core * this.core;
    out[0] = out[1] = out[2] = 0;
    const add = (A, B, TA, TB, sign) => {
      segment(px, py, pz, A[0], A[1], A[2], B[0], B[1], B[2], t, rc2);
      out[0] += sign * t[0]; out[1] += sign * t[1]; out[2] += sign * t[2];
      tail(px, py, pz, TB[0], TB[1], TB[2], ux, uy, uz, t, rc2);
      out[0] += sign * t[0]; out[1] += sign * t[1]; out[2] += sign * t[2];
      tail(px, py, pz, TA[0], TA[1], TA[2], ux, uy, uz, t, rc2);
      out[0] -= sign * t[0]; out[1] -= sign * t[1]; out[2] -= sign * t[2];
    };
    const m = this._mirTmp || (this._mirTmp = {
      a: [0, 0, 0], b: [0, 0, 0], ta: [0, 0, 0], tb: [0, 0, 0] });
    for (let j = 0; j < n; j++) {
      const g = this.gamma[j];
      if (!g) continue;
      const p = P[j];
      const before = [out[0], out[1], out[2]];
      out[0] = out[1] = out[2] = 0;
      add(p.a, p.b, p.ta, p.tb, 1);
      if (ground) {
        for (const k of ['a', 'b', 'ta', 'tb']) {
          m[k][0] = p[k][0]; m[k][1] = p[k][1]; m[k][2] = -p[k][2];
        }
        add(m.a, m.b, m.ta, m.tb, -1);
      }
      out[0] = before[0] + g * out[0];
      out[1] = before[1] + g * out[1];
      out[2] = before[2] + g * out[2];
    }
    return out;
  }

  // Постановка Вайссингера: условие непротекания в контрольной точке на трёх
  // четвертях хорды. Система линейная, решается один раз, срыва не знает — его
  // навешивают потом, по полученному эффективному углу атаки.
  //
  // Ради неё всё и затевалось. Несущая линия Прандтля даёт верный ответ для
  // одиночной поверхности, но грот со стакселем стоят вплотную, и там она
  // завышает взаимное влияние втрое: у неё вся поверхность стянута в одну
  // линию, а на расстоянии в одну хорду это уже неправда. Условие
  // непротекания ставится на самой поверхности и с таким расположением
  // справляется — это стандартный способ считать многоэлементные крылья.
  solveLinear(rhs) {
    const n = this.n, g = this.gamma;
    const M = this._m || (this._m = new Float64Array(n * (n + 1)));
    for (let i = 0; i < n; i++) {
      for (let j = 0; j < n; j++) M[i * (n + 1) + j] = this.k[i * n + j];
      M[i * (n + 1) + n] = rhs[i];
    }
    solveGauss(M, g, n);
    return g;
  }
}

// Гаусс с выбором главного элемента. Матрица маленькая — двенадцать полосок на
// весь риг, — поэтому ни разложений впрок, ни разреженности здесь не нужно.
function solveGauss(M, out, n) {
  const w = n + 1;
  for (let c = 0; c < n; c++) {
    let best = c, bv = Math.abs(M[c * w + c]);
    for (let r = c + 1; r < n; r++) {
      const v = Math.abs(M[r * w + c]);
      if (v > bv) { bv = v; best = r; }
    }
    if (bv < 1e-12) { out[c] = 0; continue; }
    if (best !== c) {
      for (let k = c; k <= n; k++) {
        const t = M[c * w + k]; M[c * w + k] = M[best * w + k]; M[best * w + k] = t;
      }
    }
    const d = M[c * w + c];
    for (let r = c + 1; r < n; r++) {
      const f = M[r * w + c] / d;
      if (!f) continue;
      for (let k = c; k <= n; k++) M[r * w + k] -= f * M[c * w + k];
    }
  }
  for (let r = n - 1; r >= 0; r--) {
    let s = M[r * w + n];
    for (let k = r + 1; k < n; k++) s -= M[r * w + k] * out[k];
    const d = M[r * w + r];
    out[r] = Math.abs(d) > 1e-12 ? s / d : 0;
  }
}
