// Вихревая решётка: индуктивная задача рига.
//
// Что она решает. Полоска паруса сама по себе не знает ни о соседних полосках,
// ни о втором парусе. Между тем несущая поверхность конечного размаха сама себе
// меняет набегающий поток: за ней сходит вихревая пелена, и та наводит на самой
// поверхности скос потока — вниз у одиночного крыла, вверх или вниз у соседа,
// смотря где он стоит. Отсюда берутся сразу три вещи, которых в модели по
// независимым полоскам нет вовсе:
//
//   индуктивное сопротивление — не по паспортному удлинению, а по настоящей
//   форме паруса и его закрутке;
//
//   щелевой эффект — грот и стаксель узнают друг о друге. Стаксель наводит на
//   гроте восходящий скос, грот на стакселе нисходящий; ради этого стаксель и
//   ставят, и без этого он в модели просто складывался с гротом;
//
//   распределение нагрузки по высоте, а с ним и настоящий центр парусности.
//
// Как она это делает. Каждая полоска несёт присоединённый вихрь на четверти
// хорды и два свободных, уходящих по потоку, — подкова. Циркуляция подковы
// связана с подъёмной силой сечения: Γ = ½·V·b·cl. Скос считается по закону
// Био — Савара от всех подков сразу, включая чужой парус.
//
// Контрольная точка лежит НА линии присоединённых вихрей, и собственный
// присоединённый вихрь полоски из расчёта исключён. Это не мелочь, а выбор
// метода. Есть два разных способа: у Вайссингера контрольная точка на трёх
// четвертях хорды, собственный вихрь учитывается, а подъёмная сила берётся
// прямо из циркуляции — но тогда двумерная модель сечения не нужна и срыва
// не будет вовсе. У Прандтля контрольная точка на несущей линии, скос
// наводится только пеленой, а подъёмная сила берётся из двумерных данных
// сечения — они собственный вихрь уже содержат. Смешать их нельзя: получится
// двойной учёт, и итерации просто разойдутся. Здесь второй способ, ради срыва
// и заполаскивания.
//
// Задача нелинейная: скос меняет угол атаки, угол атаки меняет циркуляцию.
// Решается простой итерацией с недорелаксацией — сходится за несколько
// проходов, а матрица влияния при этом одна и та же.
//
// Нелинейность живёт в модели сечения, а не здесь. Это принципиально: сама
// вихревая решётка — потенциальное течение, она не умеет ни срыва, ни
// заполаскивания, ни обтекания задом наперёд, а на полных курсах парус живёт
// именно там. Решётка даёт только скос — величину линейную и хорошо себя
// ведущую, — а всё остальное остаётся за sailCoeffs, как и было.

const EPS = 1e-10;

// Ядро вихря: на каком расстоянии нить перестаёт быть нитью.
//
// Био — Савар растёт как 1/r, и у бесконечно тонкой нити скорость рядом с ней
// не ограничена ничем. В решётке это не отвлечённая беда: сходящие вихри уходят
// по потоку через весь риг, и стоит пелене стакселя пройти вплотную к
// контрольной точке грота, как влияние уходит в бесконечность, матрица теряет
// обусловленность, а решение — смысл. Ловилось это так: при совершенно гладкой
// правой части суммарная циркуляция рига скакала между соседними шагами со 161
// на −127 и обратно. В силы это почти не выходило — скос упирался в
// ограничитель, а наполнение и без того лежало на нуле, — но модель в такие
// моменты решала не ту задачу, какую думала.
//
// Лечится тем же, чем во всех решётках: у нити появляется ядро радиуса rc,
// внутри которого скорость не растёт. Физически это и есть правда — настоящая
// пелена не нить, а слой конечной толщины, и разрешать её ближе, чем на
// расстояние между соседними нитями, дискретизация всё равно не может.
// Радиус приходит последним доводом, `rc2` — его квадрат; ноль — прежнее
// поведение. Задаётся он полем `core` решётки, в метрах.
//
// В обеих формулах ниже c2 — квадрат «плеча»: у отрезка это (|r0|·d)², у
// полубесконечной нити просто d². Поэтому ограничитель у них выглядит
// по-разному, а означает одно и то же: ближе rc не подходить.
// Скорость от отрезка вихревой нити P1→P2 единичной циркуляции в точке P.
// Классический Био — Савар в форме, не требующей делить на длину отрезка.
function segment(px, py, pz, ax, ay, az, bx, by, bz, out, rc2) {
  const r1x = px - ax, r1y = py - ay, r1z = pz - az;
  const r2x = px - bx, r2y = py - by, r2z = pz - bz;
  const cx = r1y * r2z - r1z * r2y;
  const cy = r1z * r2x - r1x * r2z;
  const cz = r1x * r2y - r1y * r2x;
  const c2 = cx * cx + cy * cy + cz * cz;
  const l1 = Math.sqrt(r1x * r1x + r1y * r1y + r1z * r1z);
  const l2 = Math.sqrt(r2x * r2x + r2y * r2y + r2z * r2z);
  if (c2 < EPS || l1 < EPS || l2 < EPS) { out[0] = out[1] = out[2] = 0; return; }
  const r0x = bx - ax, r0y = by - ay, r0z = bz - az;
  const f = (r0x * r1x + r0y * r1y + r0z * r1z) / l1 -
            (r0x * r2x + r0y * r2y + r0z * r2z) / l2;
  const l0 = r0x * r0x + r0y * r0y + r0z * r0z;
  const k = f / (4 * Math.PI * Math.max(c2, rc2 * l0));
  out[0] = cx * k; out[1] = cy * k; out[2] = cz * k;
}

// Скорость от полубесконечной нити, начинающейся в P1 и уходящей по единичному
// вектору u. Предел отрезка, у которого второй конец ушёл на бесконечность.
function tail(px, py, pz, ax, ay, az, ux, uy, uz, out, rc2) {
  const rx = px - ax, ry = py - ay, rz = pz - az;
  const cx = uy * rz - uz * ry;
  const cy = uz * rx - ux * rz;
  const cz = ux * ry - uy * rx;
  const c2 = cx * cx + cy * cy + cz * cz;
  const l = Math.sqrt(rx * rx + ry * ry + rz * rz);
  if (c2 < EPS || l < EPS) { out[0] = out[1] = out[2] = 0; return; }
  const k = (1 + (ux * rx + uy * ry + uz * rz) / l) /
            (4 * Math.PI * Math.max(c2, rc2));
  out[0] = cx * k; out[1] = cy * k; out[2] = cz * k;
}

export class Lattice {
  constructor(n) {
    this.n = n;
    this.k = new Float64Array(n * n);       // матрица влияния
    this.kw = new Float64Array(n * n);      // то же, но только от пелены
    this.gamma = new Float64Array(n);
    this.aInd = new Float64Array(n);        // скос потока, рад
    this.aWake = new Float64Array(n);       // скос от одной пелены, рад
    // Скос от СВОБОДНОЙ пелены в середине присоединённого вихря. Матрицей его
    // не выразить — циркуляции сошедших колец уже не зависят от решаемых, — и
    // он кладётся сюда снаружи. Нули, пока пелена в силы не входит.
    this.wExtra = new Float64Array(n);
    this.core = 0;                          // радиус ядра вихревой нити, м
    this.panels = [];
    for (let i = 0; i < n; i++) {
      this.panels.push({
        a: [0, 0, 0],      // конец присоединённого вихря, начало размаха
        b: [0, 0, 0],      // другой конец
        ta: [0, 0, 0],     // задняя шкаторина под A — оттуда сходит пелена
        tb: [0, 0, 0],     // задняя шкаторина под B
        c: [0, 0, 0],      // контрольная точка, на несущей линии
        nrm: [0, 0, 0],    // нормаль к поверхности в контрольной точке
        chord: 1, speed: 1,
      });
    }
    this._v = [0, 0, 0];
    this._t = [0, 0, 0];
  }

  // Матрица влияния: нормальная скорость в контрольной точке i от подковы j
  // единичной циркуляции. Зависит только от геометрии и направления пелены,
  // поэтому считается один раз на кадр, а итерации по ней уже дешёвые.
  // `self` — учитывать ли собственный присоединённый вихрь полоски. Это и есть
  // выбор между двумя постановками (см. заголовок): без него — Прандтль, с ним
  // — Вайссингер.
  //
  // `ground` — отражать ли систему вихрей в плоскости z = 0. Для паруса это
  // обязательно: он работает не в свободном потоке, а у самой воды, и нижняя
  // шкаторина не сбрасывает свободный вихрь, как конец крыла, — вода ей не
  // даёт. Отражение с обратной циркуляцией это и выражает. Без него скос
  // получается примерно вдвое больше настоящего, и грот в расчёте умирает.
  // `noTail` — собрать матрицу БЕЗ прямых сходящих лучей. Нужно, когда пелену
  // считает не решётка, а свободный лист: лучи и есть его прямая замена, и
  // держать оба значит посчитать пелену дважды. Скос от листа тогда приходит
  // правой частью (он известен: циркуляции сошедших колец уже не меняются), а
  // не матрицей.
  build(ux, uy, uz, self, ground, noTail) {
    const n = this.n, P = this.panels, v = this._v, t = this._t;
    const rc2 = this.core * this.core;
    // Отражённая геометрия зависит только от панели, а не от контрольной точки,
    // и считается один раз на сборку, а не n раз для каждой из n.
    let M = this._mir;
    if (!M || M.a.length !== n * 3) {
      M = this._mir = { a: new Float64Array(n * 3), b: new Float64Array(n * 3),
                        ta: new Float64Array(n * 3), tb: new Float64Array(n * 3) };
    }
    if (ground) {
      for (let j = 0; j < n; j++) {
        const p = P[j], o = j * 3;
        for (const [src, dst] of [[p.a, M.a], [p.b, M.b], [p.ta, M.ta], [p.tb, M.tb]]) {
          dst[o] = src[0]; dst[o + 1] = src[1]; dst[o + 2] = -src[2];
        }
      }
    }
    // У решётки с панелями по хорде свободные вихри уходят прямо от
    // присоединённого: ta совпадает с a, tb с b. Отрезки вдоль хорды тогда
    // нулевой длины и наводят ровно ноль — Био — Савар отдаёт его точно, через
    // нулевое векторное произведение. Считать их незачем, а стоят они восьми
    // вызовов из восемнадцати на каждую пару панелей: сборка матрицы — это
    // четыре пятых шага физики, и пропуск срезает с неё сорок процентов.
    //
    // Проверка поточечная, потому что решётка умеет и вторую постановку —
    // Прандтля, с пеленой от задней шкаторины (tests/vlm.test.mjs), — и там
    // отрезки настоящие.
    const same = (p, q) => p[0] === q[0] && p[1] === q[1] && p[2] === q[2];
    const lead = new Array(n), trail = new Array(n);
    for (let j = 0; j < n; j++) {
      lead[j] = !same(P[j].ta, P[j].a);
      trail[j] = !same(P[j].b, P[j].tb);
    }
    for (let i = 0; i < n; i++) {
      const ci = P[i].c, ni = P[i].nrm;
      for (let j = 0; j < n; j++) {
        const A = P[j].a, B = P[j].b, TA = P[j].ta, TB = P[j].tb, o = j * 3;
        // Замкнутый контур: из бесконечности в TA, вдоль хорды в A, связанный
        // отрезок A→B, обратно по хорде в TB, и оттуда пелена на бесконечность.
        //
        // Пелена сходит с ЗАДНЕЙ ШКАТОРИНЫ, а не с четверти хорды, и это здесь
        // принципиально. Стаксель стоит вплотную впереди грота: если пустить
        // его пелену с четверти хорды, грот окажется внутри неё и получит скос
        // втрое больше настоящего — в расчёте он просто умирал. На деле грот
        // стоит ВПЕРЕДИ того места, где сходит пелена стакселя, и попадает не в
        // скос, а в подпор от его присоединённого вихря. В этом и весь смысл
        // щели: стаксель не отбирает у грота поток, а подкручивает его.
        //
        // Собственный присоединённый вихрь пропускается — его вклад уже сидит
        // в двумерной модели сечения. Отрезки вдоль хорды и пелена остаются:
        // они и дают скос от собственной сходящей вихревой пелены.
        v[0] = v[1] = v[2] = 0;
        if (self || i !== j) {
          segment(ci[0], ci[1], ci[2], A[0], A[1], A[2], B[0], B[1], B[2], v, rc2);
        }
        if (lead[j]) {
          segment(ci[0], ci[1], ci[2], TA[0], TA[1], TA[2], A[0], A[1], A[2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        }
        if (trail[j]) {
          segment(ci[0], ci[1], ci[2], B[0], B[1], B[2], TB[0], TB[1], TB[2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        }
        if (!noTail) {
          tail(ci[0], ci[1], ci[2], TB[0], TB[1], TB[2], ux, uy, uz, t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          tail(ci[0], ci[1], ci[2], TA[0], TA[1], TA[2], ux, uy, uz, t, rc2);
          v[0] -= t[0]; v[1] -= t[1]; v[2] -= t[2];
        }
        let kij = v[0] * ni[0] + v[1] * ni[1] + v[2] * ni[2];
        if (ground) {
          // Зеркальный контур: та же геометрия, отражённая в z = 0, и обратная
          // циркуляция — тогда на самой плоскости нормальная скорость нулевая.
          v[0] = v[1] = v[2] = 0;
          segment(ci[0], ci[1], ci[2], M.a[o], M.a[o + 1], M.a[o + 2],
                  M.b[o], M.b[o + 1], M.b[o + 2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          if (lead[j]) {
            segment(ci[0], ci[1], ci[2], M.ta[o], M.ta[o + 1], M.ta[o + 2],
                    M.a[o], M.a[o + 1], M.a[o + 2], t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          }
          if (trail[j]) {
            segment(ci[0], ci[1], ci[2], M.b[o], M.b[o + 1], M.b[o + 2],
                    M.tb[o], M.tb[o + 1], M.tb[o + 2], t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          }
          if (!noTail) {
            tail(ci[0], ci[1], ci[2], M.tb[o], M.tb[o + 1], M.tb[o + 2], ux, uy, uz, t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
            tail(ci[0], ci[1], ci[2], M.ta[o], M.ta[o + 1], M.ta[o + 2], ux, uy, uz, t, rc2);
            v[0] -= t[0]; v[1] -= t[1]; v[2] -= t[2];
          }
          kij -= v[0] * ni[0] + v[1] * ni[1] + v[2] * ni[2];
        }
        this.k[i * n + j] = kij;

        // Вторая матрица — для индуктивного сопротивления, и она другая.
        //
        // Скос в контрольной точке годится, чтобы найти эффективный угол атаки,
        // но не годится, чтобы наклонить подъёмную силу назад: в нём сидит
        // вклад ПРИСОЕДИНЁННЫХ вихрей соседей. У двух парусов, стоящих один за
        // другим, стаксель наводит на грот подпор, скос выходит отрицательным,
        // и «индуктивное сопротивление» получается тягой. Явление настоящее
        // (это и есть щелевой эффект), а вот вывод неверный: подпор от
        // присоединённого вихря сопротивления не создаёт, он перекладывает
        // подъёмную силу между парусами.
        //
        // Сопротивление даёт только сходящая пелена. Поэтому здесь берутся
        // одни продольные отрезки — вдоль хорды и хвосты, — а связанный отрезок
        // A→B пропускается у обоих контуров, и настоящего, и зеркального.
        // Считается скос в середине присоединённого вихря, где и приложена
        // сила по Жуковскому.
        const mx = (P[i].a[0] + P[i].b[0]) / 2;
        const my = (P[i].a[1] + P[i].b[1]) / 2;
        const mz = (P[i].a[2] + P[i].b[2]) / 2;
        v[0] = v[1] = v[2] = 0;
        if (lead[j]) {
          segment(mx, my, mz, TA[0], TA[1], TA[2], A[0], A[1], A[2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        }
        if (trail[j]) {
          segment(mx, my, mz, B[0], B[1], B[2], TB[0], TB[1], TB[2], t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
        }
        if (!noTail) {
          tail(mx, my, mz, TB[0], TB[1], TB[2], ux, uy, uz, t, rc2);
          v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          tail(mx, my, mz, TA[0], TA[1], TA[2], ux, uy, uz, t, rc2);
          v[0] -= t[0]; v[1] -= t[1]; v[2] -= t[2];
        }
        let kwij = v[0] * ni[0] + v[1] * ni[1] + v[2] * ni[2];
        if (ground) {
          v[0] = v[1] = v[2] = 0;
          if (lead[j]) {
            segment(mx, my, mz, M.ta[o], M.ta[o + 1], M.ta[o + 2],
                    M.a[o], M.a[o + 1], M.a[o + 2], t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          }
          if (trail[j]) {
            segment(mx, my, mz, M.b[o], M.b[o + 1], M.b[o + 2],
                    M.tb[o], M.tb[o + 1], M.tb[o + 2], t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
          }
          if (!noTail) {
            tail(mx, my, mz, M.tb[o], M.tb[o + 1], M.tb[o + 2], ux, uy, uz, t, rc2);
            v[0] += t[0]; v[1] += t[1]; v[2] += t[2];
            tail(mx, my, mz, M.ta[o], M.ta[o + 1], M.ta[o + 2], ux, uy, uz, t, rc2);
            v[0] -= t[0]; v[1] -= t[1]; v[2] -= t[2];
          }
          kwij -= v[0] * ni[0] + v[1] * ni[1] + v[2] * ni[2];
        }
        this.kw[i * n + j] = kwij;
      }
    }
  }

  // Скос от одной пелены — тот, по которому наклоняется подъёмная сила.
  // Знак тот же, что у aInd: положительный скос уменьшает угол атаки.
  wakeAngles() {
    const n = this.n, P = this.panels, g = this.gamma, out = this.aWake;
    for (let i = 0; i < n; i++) {
      let w = 0;
      for (let j = 0; j < n; j++) w += this.kw[i * n + j] * g[j];
      w += this.wExtra[i];
      const V = P[i].speed;
      out[i] = V > 1e-3 ? Math.atan2(-w, V) : 0;
    }
    return out;
  }

  // Решение задачи: скос меняет угол атаки, угол атаки меняет циркуляцию.
  //
  // Простой итерацией «посчитал скос — пересчитал циркуляцию» это решать нельзя,
  // хотя и заманчиво. Матрица влияния плохо обусловлена по построению: у своей
  // же полоски свободные вихри стоят на её краях и дают вклад порядка 1/ширины,
  // а у соседей вихри в тех же точках с обратным знаком почти его гасят.
  // Большие взаимно сокращающиеся члены — и простая итерация либо расходится,
  // либо даёт ответ, зависящий от числа полосок. Это и вылезло: CL прыгал вдвое
  // при удвоении разбивки.
  //
  // Поэтому система решается напрямую. Кривая сечения линеаризуется в текущей
  // точке (cl ≈ a·α + b), подстановка Γ = ½·V·b·cl даёт линейную систему по Γ,
  // и она решается методом Гаусса. Внешних проходов нужно два-три: они
  // догоняют нелинейность сечения, а не саму индуктивную задачу.
  //
  // `cl` — двумерная модель сечения: подъёмная сила БЕЗ поправки на удлинение
  // и без индуктивного сопротивления. И то и другое теперь получается здесь.
  solve(alphaGeom, cl, iters) {
    const n = this.n, P = this.panels, g = this.gamma, ai = this.aInd;
    const it = iters || 3;
    const M = this._m || (this._m = new Float64Array(n * (n + 1)));
    const H = 0.5 * Math.PI / 180;              // шаг численной производной

    for (let pass = 0; pass < it; pass++) {
      for (let i = 0; i < n; i++) {
        const V = P[i].speed;
        const aEff = alphaGeom[i] - ai[i];
        // Наклон кривой сечения в текущей точке. За срывом он отрицателен, и
        // система от этого теряет устойчивость, поэтому снизу он подрезан:
        // нелинейность доберут внешние проходы.
        let slope = (cl(aEff + H, i) - cl(aEff - H, i)) / (2 * H);
        if (!(slope > 0.2)) slope = 0.2;
        const free = cl(aEff, i) - slope * aEff;
        const w = 0.5 * V * P[i].chord;
        for (let j = 0; j < n; j++) {
          // Скос входит в угол атаки со знаком минус, а сам он равен −w/V,
          // поэтому в системе получается МИНУС. Со знаком плюс диагональ
          // вырождается и решение идёт вразнос — проверено.
          //   Γi − ½·b·a·Σ Kij·Γj = ½·V·b·(a·αгеом + свободный член)
          M[i * (n + 1) + j] = (i === j ? 1 : 0) -
            0.5 * P[i].chord * slope * this.k[i * n + j];
        }
        M[i * (n + 1) + n] = w * (slope * alphaGeom[i] + free);
      }
      solveGauss(M, g, n);
      for (let i = 0; i < n; i++) {
        let w = 0;
        for (let j = 0; j < n; j++) w += this.k[i * n + j] * g[j];
        const V = P[i].speed;
        // Скос отрицателен по нормали — пелена «поджимает» поверхность, и
        // эффективный угол атаки уменьшается. Знак берётся отсюда, а не из
        // соглашения: нормаль задаёт вызывающий код.
        ai[i] = V > 1e-3 ? Math.atan2(-w, V) : 0;
      }
    }
    return ai;
  }

  // Скорость, наведённая всей системой вихрей, в произвольной точке. Нужна не
  // для сил, а для картинки: по ней рисуются линии тока вокруг парусов —
  // ровно то, что показывают в трубе дымом. Считать это каждый кадр незачем,
  // отрисовка обновляет линии в несколько раз реже.
  // Скорость, наведённая всей решёткой в точке. КАНОНИЧЕСКИЙ КОНТУР панели,
  // один и тот же здесь и в матрице влияния:
  //
  //     из бесконечности в TA → вдоль хорды в A → связанный отрезок A→B →
  //     обратно по хорде в TB → и оттуда пелена в бесконечность
  //
  // У нынешнего рига TA совпадает с A, а TB с B: свободные вихри уходят прямо
  // от присоединённого, а роль отрезков вдоль хорды играют присоединённые вихри
  // следующих панелей (см. aero.js, где панели и ставятся). Тогда контур
  // вырождается в обычную подкову, и отрезки вдоль хорды считать не нужно.
  //
  // Но вырождение это — свойство ГЕОМЕТРИИ, а не метода, и держаться на нём
  // нельзя: стоит пелене стать свободной, и TA разойдётся с A. Поэтому отрезки
  // считаются, когда они не нулевые, и обе половины кода — эта и матрица —
  // описывают один контур при любой геометрии. Проверка на совпадение точек
  // стоит три сравнения на панель и в нынешнем риге отсекает всю добавку.
  //
  // Зеркало от воды: тот же контур, отражённый по Z, с обратным знаком.
  induced(px, py, pz, ux, uy, uz, ground, out, noTail) {
    const n = this.n, P = this.panels, t = this._t;
    const rc2 = this.core * this.core;
    let ox = 0, oy = 0, oz = 0;
    for (let j = 0; j < n; j++) {
      const g = this.gamma[j];
      if (!g) continue;
      const p = P[j], a = p.a, b = p.b, ta = p.ta, tb = p.tb;
      const lead = ta[0] !== a[0] || ta[1] !== a[1] || ta[2] !== a[2];
      const trail = tb[0] !== b[0] || tb[1] !== b[1] || tb[2] !== b[2];
      let vx = 0, vy = 0, vz = 0;
      segment(px, py, pz, a[0], a[1], a[2], b[0], b[1], b[2], t, rc2);
      vx += t[0]; vy += t[1]; vz += t[2];
      if (lead) {
        segment(px, py, pz, ta[0], ta[1], ta[2], a[0], a[1], a[2], t, rc2);
        vx += t[0]; vy += t[1]; vz += t[2];
      }
      if (trail) {
        segment(px, py, pz, b[0], b[1], b[2], tb[0], tb[1], tb[2], t, rc2);
        vx += t[0]; vy += t[1]; vz += t[2];
      }
      // `noTail` — считать без сходящих лучей, одни связанные вихри. Нужно
      // свободной пелене: она сама и есть эти лучи, только не прямые, и
      // складывать её с их прямой заменой значит посчитать пелену дважды.
      if (!noTail) {
        tail(px, py, pz, tb[0], tb[1], tb[2], ux, uy, uz, t, rc2);
        vx += t[0]; vy += t[1]; vz += t[2];
        tail(px, py, pz, ta[0], ta[1], ta[2], ux, uy, uz, t, rc2);
        vx -= t[0]; vy -= t[1]; vz -= t[2];
      }
      if (ground) {
        segment(px, py, pz, a[0], a[1], -a[2], b[0], b[1], -b[2], t, rc2);
        vx -= t[0]; vy -= t[1]; vz -= t[2];
        if (lead) {
          segment(px, py, pz, ta[0], ta[1], -ta[2], a[0], a[1], -a[2], t, rc2);
          vx -= t[0]; vy -= t[1]; vz -= t[2];
        }
        if (trail) {
          segment(px, py, pz, b[0], b[1], -b[2], tb[0], tb[1], -tb[2], t, rc2);
          vx -= t[0]; vy -= t[1]; vz -= t[2];
        }
        if (!noTail) {
          tail(px, py, pz, tb[0], tb[1], -tb[2], ux, uy, uz, t, rc2);
          vx -= t[0]; vy -= t[1]; vz -= t[2];
          tail(px, py, pz, ta[0], ta[1], -ta[2], ux, uy, uz, t, rc2);
          vx += t[0]; vy += t[1]; vz += t[2];
        }
      }
      ox += g * vx; oy += g * vy; oz += g * vz;
    }
    out[0] = ox; out[1] = oy; out[2] = oz;
    return out;
  }

  // Плотная запись связанного контура — то же, что `FreeWake.pack`, и по той же
  // причине.
  //
  // Пелена спрашивает поле решётки в каждом своём узле: триста с лишним точек на
  // двести с лишним отрезков за шаг. В `induced` при этом на КАЖДУЮ точку заново
  // читались концы панели, проверялись вырожденные отрезки вдоль хорды и
  // считалась длина — всё то, что от точки не зависит. Здесь это считается раз
  // за шаг, а поле берётся `fieldBound`.
  //
  // Сходящие лучи сюда не входят: со свободной пеленой их нет, а её саму она
  // добавляет себе сама.
  packBound(ground) {
    const n = this.n, P = this.panels;
    const cap = n * 3 * 2 * 8;
    if (!this.bg || this.bg.length < cap) this.bg = new Float64Array(cap);
    const e = this.bg, rc2 = this.core * this.core;
    let m = 0;
    const put = (ax, ay, az, bx, by, bz, g) => {
      const r0x = bx - ax, r0y = by - ay, r0z = bz - az;
      const l0 = r0x * r0x + r0y * r0y + r0z * r0z;
      if (l0 < EPS) return;
      e[m] = ax; e[m + 1] = ay; e[m + 2] = az;
      e[m + 3] = r0x; e[m + 4] = r0y; e[m + 5] = r0z;
      e[m + 6] = g; e[m + 7] = rc2 * l0;
      m += 8;
    };
    for (let mir = 0; mir < (ground ? 2 : 1); mir++) {
      const sz = mir ? -1 : 1, sg = mir ? -1 : 1;
      for (let j = 0; j < n; j++) {
        const g = this.gamma[j];
        if (!g) continue;
        const p = P[j], a = p.a, b = p.b, ta = p.ta, tb = p.tb;
        put(a[0], a[1], sz * a[2], b[0], b[1], sz * b[2], sg * g);
        put(ta[0], ta[1], sz * ta[2], a[0], a[1], sz * a[2], sg * g);
        put(b[0], b[1], sz * b[2], tb[0], tb[1], sz * tb[2], sg * g);
      }
    }
    this.nb = m / 8;
  }

  // Поле связанного контура сразу в наборе точек. Кернел тот же, что у пелены.
  fieldBound(qx, qy, qz, np, ox, oy, oz) {
    for (let j = 0; j < np; j++) { ox[j] = 0; oy[j] = 0; oz[j] = 0; }
    const e = this.bg, ne = this.nb || 0;
    for (let m = 0, k8 = 0; m < ne; m++, k8 += 8) {
      const ax = e[k8], ay = e[k8 + 1], az = e[k8 + 2];
      const r0x = e[k8 + 3], r0y = e[k8 + 4], r0z = e[k8 + 5];
      const g = e[k8 + 6], den = e[k8 + 7];
      for (let j = 0; j < np; j++) {
        const r1x = qx[j] - ax, r1y = qy[j] - ay, r1z = qz[j] - az;
        const r2x = r1x - r0x, r2y = r1y - r0y, r2z = r1z - r0z;
        const cx = r1y * r2z - r1z * r2y;
        const cy = r1z * r2x - r1x * r2z;
        const cz = r1x * r2y - r1y * r2x;
        const c2 = cx * cx + cy * cy + cz * cz;
        if (c2 < EPS) continue;
        const l1 = Math.sqrt(r1x * r1x + r1y * r1y + r1z * r1z);
        const l2 = Math.sqrt(r2x * r2x + r2y * r2y + r2z * r2z);
        if (l1 < EPS || l2 < EPS) continue;
        const fq = (r0x * r1x + r0y * r1y + r0z * r1z) / l1 -
                   (r0x * r2x + r0y * r2y + r0z * r2z) / l2;
        const kk = fq / (FOURPI * Math.max(c2, den));
        ox[j] += g * (cx * kk); oy[j] += g * (cy * kk); oz[j] += g * (cz * kk);
      }
    }
  }

  // Постановка Вайссингера: условие непротекания в контрольной точке на трёх
  // четвертях хорды. Система линейная, решается один раз, срыва не знает — его
  // навешивают потом, по полученному эффективному углу атаки.
  //
  // Ради неё всё и затевалось. Несущая линия Прандтля даёт верный ответ для
  // одиночной поверхности, но грот со стакселем стоят вплотную, и там она
  // завышает взаимное влияние втрое: у неё вся поверхность стянута в одну
  // линию, а на расстоянии в одну хорду это уже неправда. Условие
  // непротекания ставится на самой поверхности и с таким расположением
  // справляется — это стандартный способ считать многоэлементные крылья.
  solveLinear(rhs) {
    const n = this.n, g = this.gamma;
    const M = this._m || (this._m = new Float64Array(n * (n + 1)));
    for (let i = 0; i < n; i++) {
      for (let j = 0; j < n; j++) M[i * (n + 1) + j] = this.k[i * n + j];
      M[i * (n + 1) + n] = rhs[i];
    }
    solveGauss(M, g, n);
    return g;
  }
}

// Гаусс с выбором главного элемента. Матрица маленькая — двенадцать полосок на
// весь риг, — поэтому ни разложений впрок, ни разреженности здесь не нужно.
function solveGauss(M, out, n) {
  const w = n + 1;
  for (let c = 0; c < n; c++) {
    let best = c, bv = Math.abs(M[c * w + c]);
    for (let r = c + 1; r < n; r++) {
      const v = Math.abs(M[r * w + c]);
      if (v > bv) { bv = v; best = r; }
    }
    if (bv < 1e-12) { out[c] = 0; continue; }
    if (best !== c) {
      for (let k = c; k <= n; k++) {
        const t = M[c * w + k]; M[c * w + k] = M[best * w + k]; M[best * w + k] = t;
      }
    }
    const d = M[c * w + c];
    for (let r = c + 1; r < n; r++) {
      const f = M[r * w + c] / d;
      if (!f) continue;
      for (let k = c; k <= n; k++) M[r * w + k] -= f * M[c * w + k];
    }
  }
  for (let r = n - 1; r >= 0; r--) {
    let s = M[r * w + n];
    for (let k = r + 1; k < n; k++) s -= M[r * w + k] * out[k];
    const d = M[r * w + r];
    out[r] = Math.abs(d) > 1e-12 ? s / d : 0;
  }
}

// --- свободная пелена ----------------------------------------------------------
//
// Сегодня решётка отпускает от каждой панели два ПРЯМЫХ луча в бесконечность
// вдоль набегающего потока. Настоящая пелена так себя не ведёт: она сходит с
// задней кромки и дальше плывёт вместе с потоком, сворачиваясь у топа в жгут, а
// после поворота оставаясь за кормой чужим следом.
//
// Здесь она построена цепочками узлов. Схема маршевая по времени: каждый шаг с
// кромки сходит новый узел, а все прежние сносятся местной скоростью. Так она
// становится историей, а не мгновенной картинкой, и это честнее для симулятора:
// след после поворота получается сам, из той же арифметики.
//
// Узлы хранятся в МИРОВЫХ осях, а не в связанных с лодкой. Это не мелочь
// выбора: в связанных осях старая пелена поворачивается вместе с лодкой, то
// есть висящий в воздухе след послушно едет за кормой при каждом повороте — и
// ровно то, ради чего маршевая схема и берётся (лодка идёт по своему старому
// следу), не получается вовсе. Расплата — переводы туда-обратно: точка схода
// переводится из корпуса в мир, точка запроса к решётке из мира в корпус,
// наведённая ею скорость обратно в мир.
//
// ВАЖНО, что она пока НЕ ВХОДИТ В СИЛЫ. Матрица влияния по-прежнему считает
// прямые лучи, и отпечаток модели обязан совпадать побайтово с тем, что был до
// пелены. Это первый шаг из трёх (docs/flow-plan.md, III.2.a): сначала показать,
// потом уже считать. Разделение здесь важнее, чем в прочих частях, потому что
// отделяет проверяемое от рискованного.
// Расплывание ядра вихря со временем, м²/с.
//
// Вихрь не остаётся тонким: вязкость размазывает его, и по Лэмбу — Озеену
// радиус растёт как r² = r0² + 4·α·δν·t, где α = 1.2564. Настоящая
// (молекулярная) вязкость воздуха тут ни при чём — она дала бы миллиметры за
// час; в свободных пеленах берут турбулентную, в δ = 10²…10³ раз больше
// (Скуайр; Бхагват и Лейшман по замерам следа винта). Взято δ = 800:
// 4 · 1.2564 · 800 · 1.5e-5 ≈ 0.06. За полторы секунды жизни узла ядро
// вырастает с пяти сантиметров до тридцати — примерно в толщину той вихревой
// пелены, что видно за парусом в дыму.
const CORE_GROW = 0.06;
const FOURPI = 4 * Math.PI;

export class FreeWake {
  // `fil` — сколько нитей (по числу границ полосок), `len` — сколько узлов в
  // каждой. Сорок узлов при тридцати герцах это тридцать девять промежутков, то
  // есть 1.3 секунды истории, а не три: узел сходит каждый шаг. Больше стоит
  // дорого — самоиндукция растёт как квадрат длины цепочки.
  //
  // Дальний конец сейчас просто обрывается в воздухе. Для картинки это сойдёт, а
  // перед тем как пелена войдёт в силы, его придётся продолжать полубесконечным
  // хвостом: оборванная нить наводит не то, что тянущаяся до бесконечности.
  constructor(fil, len) {
    this.fil = fil;
    this.len = len;
    this.x = new Float64Array(fil * len);
    this.y = new Float64Array(fil * len);
    this.z = new Float64Array(fil * len);
    // Состояние пелены — циркуляции КОЛЕЦ, а не нитей.
    //
    // Кольцо `f`, ряд `i` — это четырёхугольник между нитями f и f+1 и рядами
    // узлов i и i+1, то есть кусок вихревого листа, сошедший с одной полоски за
    // один шаг. Его циркуляция равна связанной циркуляции той полоски в момент
    // схода и БОЛЬШЕ НЕ МЕНЯЕТСЯ: сошедший вихрь живёт своей жизнью, что бы
    // дальше ни делал парус. В этом вся разница между следом и мгновенным
    // снимком, и ради этого маршевая схема и берётся.
    //
    // Раньше у нити была одна сила на всю длину, и она переписывалась каждый
    // шаг. Такая пелена не помнила ничего: потрави шкот — и весь след, включая
    // сошедший секунду назад, мгновенно менял силу. Для картинки сходило, для
    // сил не годится вовсе.
    this.gr = new Float64Array(fil * len);  // циркуляция кольца [нить, ряд]
    // Есть ли за парой нитей (f, f+1) парус, то есть натянуто ли между ними
    // полотно. Это ТОПОЛОГИЯ листа, и берётся она из раскладки полосок, а не из
    // циркуляции: у полоски она то и дело проходит через ноль — у топа, на
    // порыве, у стакселя в тени грота, — а полотно от этого никуда не девается.
    this.ring = new Int8Array(fil);
    // Силы РЁБЕР — то, чем induced и пользуется. Собираются из колец раз в шаг:
    // ребро общее у двух соседних колец и несёт их разность, поэтому считать его
    // на каждой точке заново вчетверо дороже.
    this.et = new Float64Array(fil * len);  // вдоль нити: узел (f,i) -> (f,i+1)
    this.es = new Float64Array(fil * len);  // поперёк:    узел (f,i) -> (f+1,i)
    // Куда уходит полубесконечный хвост — единичный вектор, ОДИН на всю пелену.
    //
    // Направление берётся по набегающему потоку, а не по последнему звену нити.
    // Разница видна только на полном курсе, зато там она решает всё: пелена там
    // сворачивается в клубок, направление последнего звена случайно, и луч в
    // бесконечность бьёт сквозь собственную пелену. Излом нити от этого 29° на
    // узел вместо 3.7 — то есть по картинке не отличить от прежнего разноса, а
    // причина совсем другая. Далеко за кормой пелена всё равно вытягивается
    // вдоль потока, так что честнее сразу туда её и продолжать.
    // А вот ПО КАКОМУ потоку — по тому, что был, когда этот ряд сходил, и это не
    // придирка. Направление было одно на всю пелену и переписывалось каждый шаг
    // текущим ветром: после поворота весь дальний след разом менял направление,
    // хотя ближние узлы стояли на месте. Памяти о том, куда шла лодка, не было
    // ровно никакой. Теперь направление стареет вместе с рядом.
    this.tdx = new Float64Array(len);
    this.tdy = new Float64Array(len);
    this.tdz = new Float64Array(len);
    this.tdx[0] = 1;
    this.dirx = 1; this.diry = 0; this.dirz = 0;   // поток для СВЕЖЕГО ряда
    this.g = new Float64Array(fil);         // сила нити у кромки — только для цвета
    this.rc = new Float64Array(fil * len);  // радиус ядра В КАЖДОМ узле
    // Доля расстояния до ближайшей соседней нити, ниже которой ядро не
    // опускается. Половина — то есть ядра соседей хотя бы касаются.
    //
    // Число ЧИСЛЕННОЕ, а не выведенное, и это честно проверено сходимостью.
    // Главное, что она показала: пол не украшение, а условие сходимости ПО
    // ШАГУ. С нулём ответ от шага зависит катастрофически — вдвое мельче шаг, и
    // галфвинд рушится, тяга 230 Н вместо 421. Причина понятна: узлы становятся
    // вдвое ближе друг к другу, а ядро от этого не растёт.
    //
    // Выше 0.1 ответ выходит на полку. Между 0.25 и 1.0 тяга гуляет на 2–3.5%,
    // то есть это параметр сетки, а не физика, — и об этом надо помнить. Взято
    // 0.5 как лучшее по согласию между 30 и 60 Гц: 1% на обоих курсах против
    // 3% у 0.25. Таблицы — в docs/wake.md.
    this.spaceK = 0.5;
    this.hold = false;                      // свежий ряд вынут в неизвестные
    this.n = 0;                             // сколько узлов уже сошло
    this.core = 0.05;                       // ядро свежесошедшего узла
  }

  clear() { this.n = 0; }

  // Скорость, наведённая пеленой. Тот же закон Био — Савара, что у решётки:
  // пелена — продолжение её вихрей, а не отдельная сущность.
  //
  // А вот ядро своё у каждого звена, и это не тонкость счёта. У решётки вихрь
  // приколочен к парусу и сойтись с соседом ближе, чем стоят панели, не может.
  // Пелена свободна: на полном курсе нити сходились до семи сантиметров при
  // ядре в пять, а внутри ядра Био — Савар даёт скорость тем больше, чем ближе
  // подошли. Явный шаг швырял узел дальше, тот подходил к соседу ещё ближе —
  // и узел ехал со скоростью 2000 м/с при кажущемся ветре 4.5. Ядро на звено
  // берётся как средний квадрат по его концам.
  induced(px, py, pz, ground, out) {
    const L = this.len, N = this.n;
    let ox = 0, oy = 0, oz = 0;
    if (N < 2) { out[0] = out[1] = out[2] = 0; return out; }
    const e = this.eg, ne = ground ? this.ne : this.neReal;
    for (let m = 0, k8 = 0; m < ne; m++, k8 += 8) {
      const ax = e[k8], ay = e[k8 + 1], az = e[k8 + 2];
      const r0x = e[k8 + 3], r0y = e[k8 + 4], r0z = e[k8 + 5];
      const r1x = px - ax, r1y = py - ay, r1z = pz - az;
      const r2x = r1x - r0x, r2y = r1y - r0y, r2z = r1z - r0z;
      const cx = r1y * r2z - r1z * r2y;
      const cy = r1z * r2x - r1x * r2z;
      const cz = r1x * r2y - r1y * r2x;
      const c2 = cx * cx + cy * cy + cz * cz;
      if (c2 < EPS) continue;
      const l1 = Math.sqrt(r1x * r1x + r1y * r1y + r1z * r1z);
      const l2 = Math.sqrt(r2x * r2x + r2y * r2y + r2z * r2z);
      if (l1 < EPS || l2 < EPS) continue;
      const fq = (r0x * r1x + r0y * r1y + r0z * r1z) / l1 -
                 (r0x * r2x + r0y * r2y + r0z * r2z) / l2;
      const kk = fq / (FOURPI * Math.max(c2, e[k8 + 7]));
      const g = e[k8 + 6];
      ox += g * (cx * kk); oy += g * (cy * kk); oz += g * (cz * kk);
    }
    // Хвосты — своим ядром и своей формулой; их четырнадцать, в общий список
    // класть не за чем.
    const t = [0, 0, 0];
    for (let f = 0; f < this.fil; f++) {
      const p = f * L + N - 1, g = this.et[p];
      if (!g) continue;
      const rc2 = this.rc[p] * this.rc[p];
      const dx = this.tdx[N - 1], dy = this.tdy[N - 1], dz = this.tdz[N - 1];
      tail(px, py, pz, this.x[p], this.y[p], this.z[p], dx, dy, dz, t, rc2);
      ox += g * t[0]; oy += g * t[1]; oz += g * t[2];
      if (ground) {
        tail(px, py, pz, this.x[p], this.y[p], -this.z[p], dx, dy, -dz, t, rc2);
        ox -= g * t[0]; oy -= g * t[1]; oz -= g * t[2];
      }
    }
    out[0] = ox; out[1] = oy; out[2] = oz;
    return out;
  }

  // Плотная запись всех рёбер: то, чем считается поле, и то, что не зависит от
  // точки запроса.
  //
  // На каждое ребро восемь чисел: начало (3), вектор до конца (3), сила и
  // знаменатель ограничителя. Всё это раньше пересчитывалось ЗАНОВО в каждой из
  // пятисот шестидесяти точек — вычитание концов, длина ребра, квадрат ядра.
  // Здесь считается один раз за шаг.
  //
  // Отражение от воды лежит в том же списке отдельными рёбрами: зеркальное
  // ребро — это то же ребро с перевёрнутым z и обратным знаком силы. Отдельной
  // ветки на воду от этого не нужно вовсе, а стоила она 45% всего счёта.
  // Настоящие рёбра идут первыми, зеркальные следом, — значит запрос без воды
  // это просто обход первой половины списка.
  pack() {
    const L = this.len, F = this.fil, N = this.n;
    const cap = 2 * F * (2 * L) * 8;
    if (!this.eg || this.eg.length < cap) this.eg = new Float64Array(cap);
    const e = this.eg;
    let m = 0;
    for (let mir = 0; mir < 2; mir++) {
      const sz = mir ? -1 : 1, sg = mir ? -1 : 1;
      for (let f = 0; f < F; f++) {
        const b = f * L;
        for (let i = 0; i + 1 < N; i++) {
          const g = this.et[b + i];
          if (g) m = this.put(e, m, b + i, b + i + 1, mir ? -g : g, sz);
        }
        if (f + 1 < F) {
          for (let i = 1; i < N; i++) {
            const g = this.es[b + i];
            if (g) m = this.put(e, m, b + i, b + i + L, mir ? -g : g, sz);
          }
        }
        sg;
      }
      if (!mir) this.neReal = m / 8;
    }
    this.ne = m / 8;
  }

  // Одно ребро в плотную запись. `sz` = -1 для зеркального.
  put(e, m, p, q, g, sz) {
    const ax = this.x[p], ay = this.y[p], az = sz * this.z[p];
    const r0x = this.x[q] - ax, r0y = this.y[q] - ay, r0z = sz * this.z[q] - az;
    const rc2 = 0.5 * (this.rc[p] * this.rc[p] + this.rc[q] * this.rc[q]);
    e[m] = ax; e[m + 1] = ay; e[m + 2] = az;
    e[m + 3] = r0x; e[m + 4] = r0y; e[m + 5] = r0z;
    e[m + 6] = g;
    e[m + 7] = rc2 * (r0x * r0x + r0y * r0y + r0z * r0z);
    return m + 8;
  }

  // Силы рёбер из циркуляций колец. Раз в шаг, а не на каждой точке запроса.
  //
  // Ребро вдоль нити общее у колец f-1 и f и несёт их разность; ребро поперёк
  // общее у соседних по возрасту рядов одного кольца и несёт разность по
  // времени. Собранная так пелена замкнута по Гельмгольцу сама собой: в каждом
  // узле сколько завихренности втекло, столько и вытекло, и проверять это можно
  // числом (tests/wake.test.mjs).
  //
  // Знак разностей — не свободный выбор, и стоил он отдельного разбирательства.
  // У решётки конец `a` присоединённого вихря ВЕРХНИЙ (проверено по z), значит
  // на нижний сходящий луч она вешает +Г, а на верхний -Г. Пелена обязана
  // вешать то же самое, иначе она наводит скос ровно наоборот: подъёмная сила
  // не уменьшается от собственного следа, а растёт. Ошибка на картинке
  // невидима (жёлтое с синим меняются местами, и только), а в силах она
  // переворачивает всю индуктивную часть. Поймано сверкой скоса в контрольных
  // точках с прямыми лучами: отношение выходило -0.92…-1.00, то есть та же
  // величина с обратным знаком.
  edges() {
    const L = this.len, F = this.fil, N = this.n;
    for (let f = 0; f < F; f++) {
      const b = f * L;
      for (let i = 0; i < N; i++) {
        // `hold` — считать свежий ряд колец ПУСТЫМ.
        //
        // Он несёт циркуляцию, которую как раз и решают, а не известную. Пока
        // он лежал в правой части с прошлого шага, в матрице не оставалось
        // скоса вовсе: решётка выдавала циркуляцию бесконечного размаха, ответ
        // приходил на шаг позже и перебарщивал, и лодка на эталоне вставала и
        // шла назад. Здесь он вынимается, а обратно кладётся уже как
        // неизвестная — тремя отрезками в матрицу (aero.js, nearRing).
        const cur = (i === 0 && this.hold) ? 0 : this.gr[b + i];
        const lo = f > 0 ? ((i === 0 && this.hold) ? 0 : this.gr[b - L + i]) : 0;
        const pr = i > 0 ? ((i === 1 && this.hold) ? 0 : this.gr[b + i - 1]) : 0;
        this.et[b + i] = cur - lo;
        this.es[b + i] = i > 0 ? pr - cur : 0;
      }
      this.g[f] = this.et[b];
    }
  }

  // Поле пелены сразу в НАБОРЕ точек: снаружи рёбра, внутри точки.
  //
  // Тот же счёт, что в `induced`, и тот же порядок сложения по рёбрам, но
  // данные ребра остаются в регистрах на весь набор вместо того, чтобы
  // читаться заново под каждую точку. Этим считается и снос самой пелены
  // (пятьсот шестьдесят узлов), и её скос на парусе (семьдесят две точки).
  field(qx, qy, qz, np, ox, oy, oz) {
    const L = this.len, F = this.fil, N = this.n;
    for (let j = 0; j < np; j++) { ox[j] = 0; oy[j] = 0; oz[j] = 0; }
    if (N < 2) return;
    const e = this.eg, ne = this.ne;
    for (let m = 0, k8 = 0; m < ne; m++, k8 += 8) {
      const ax = e[k8], ay = e[k8 + 1], az = e[k8 + 2];
      const r0x = e[k8 + 3], r0y = e[k8 + 4], r0z = e[k8 + 5];
      const g = e[k8 + 6], den = e[k8 + 7];
      for (let j = 0; j < np; j++) {
        const r1x = qx[j] - ax, r1y = qy[j] - ay, r1z = qz[j] - az;
        const r2x = r1x - r0x, r2y = r1y - r0y, r2z = r1z - r0z;
        const cx = r1y * r2z - r1z * r2y;
        const cy = r1z * r2x - r1x * r2z;
        const cz = r1x * r2y - r1y * r2x;
        const c2 = cx * cx + cy * cy + cz * cz;
        if (c2 < EPS) continue;
        const l1 = Math.sqrt(r1x * r1x + r1y * r1y + r1z * r1z);
        const l2 = Math.sqrt(r2x * r2x + r2y * r2y + r2z * r2z);
        if (l1 < EPS || l2 < EPS) continue;
        const fq = (r0x * r1x + r0y * r1y + r0z * r1z) / l1 -
                   (r0x * r2x + r0y * r2y + r0z * r2z) / l2;
        const kk = fq / (FOURPI * Math.max(c2, den));
        ox[j] += g * (cx * kk); oy[j] += g * (cy * kk); oz[j] += g * (cz * kk);
      }
    }
    const t = [0, 0, 0];
    for (let f = 0; f < F; f++) {
      const p = f * L + N - 1, g = this.et[p];
      if (!g) continue;
      const rc2 = this.rc[p] * this.rc[p];
      const hx = this.x[p], hy = this.y[p], hz = this.z[p];
      const dx = this.tdx[N - 1], dy = this.tdy[N - 1], dz = this.tdz[N - 1];
      for (let j = 0; j < np; j++) {
        tail(qx[j], qy[j], qz[j], hx, hy, hz, dx, dy, dz, t, rc2);
        ox[j] += g * t[0]; oy[j] += g * t[1]; oz[j] += g * t[2];
        tail(qx[j], qy[j], qz[j], hx, hy, -hz, dx, dy, -dz, t, rc2);
        ox[j] -= g * t[0]; oy[j] -= g * t[1]; oz[j] -= g * t[2];
      }
    }
  }

  // Скорость, наведённая пеленой на саму себя, — сразу ВО ВСЕХ узлах.
  //
  // Тот же счёт, что и в `induced`, но цикл вывернут наизнанку: снаружи рёбра,
  // внутри точки. Ответ до последнего разряда тот же (порядок сложения по
  // рёбрам не меняется), а стоит втрое дешевле: данные ребра остаются в
  // регистрах на все пятьсот шестьдесят точек, вместо того чтобы читаться
  // заново для каждой.
  //
  // Это и есть та самая петля, в которой живёт 95% цены пелены: пятьсот
  // шестьдесят точек на две тысячи рёбер — миллион с лишним отрезков за шаг.
  selfInduce() {
    const L = this.len, F = this.fil, N = this.n;
    if (!this.sx || this.sx.length < F * L) {
      this.sx = new Float64Array(F * L);
      this.sy = new Float64Array(F * L);
      this.sz = new Float64Array(F * L);
      this.qx = new Float64Array(F * L);
      this.qy = new Float64Array(F * L);
      this.qz = new Float64Array(F * L);
    }
    for (let f = 0; f < F; f++) {
      for (let i = 0; i < N; i++) {
        const j = f * N + i, k = f * L + i;
        this.qx[j] = this.x[k]; this.qy[j] = this.y[k]; this.qz[j] = this.z[k];
      }
    }
    this.field(this.qx, this.qy, this.qz, F * N, this.sx, this.sy, this.sz);
  }

  // `seed(f, out)` даёт точку схода нити, `vel(x, y, z, out, j)` — местную
  // скорость БЕЗ собственного поля пелены (его она добавляет сама, и сразу всем
  // узлам); `j` — номер узла в той же плотной раскладке, что у `selfInduce`,
  // чтобы вызывающий мог держать посчитанное заранее,
  // `gring` — связанные циркуляции полосок (нулевые там, где между соседними
  // нитями паруса нет).
  step(dt, seed, vel, gring) {
    const L = this.len, N = this.fil * L, v = [0, 0, 0], p = [0, 0, 0];
    if (!this.vx || this.vx.length !== N) {
      this.vx = new Float64Array(N);
      this.vy = new Float64Array(N);
      this.vz = new Float64Array(N);
    }
    // Проход первый: скорости по СТАРОМУ полю, ничего не двигаем. Своё поле
    // пелена считает одним заходом на весь список узлов, чужое — по точкам.
    if (this.n > 1) this.selfInduce();
    for (let f = 0; f < this.fil; f++) {
      const b = f * L;
      for (let i = 0; i < this.n; i++) {
        const k = b + i, j = f * this.n + i;
        vel(this.x[k], this.y[k], this.z[k], v, f * this.n + i);
        if (this.n > 1) {
          this.vx[k] = v[0] + this.sx[j];
          this.vy[k] = v[1] + this.sy[j];
          this.vz[k] = v[2] + this.sz[j];
        } else {
          this.vx[k] = v[0]; this.vy[k] = v[1]; this.vz[k] = v[2];
        }
      }
    }
    // Проход второй: все переезжают и стареют на одну позицию. Вместе с узлом
    // стареет и его ядро — по Лэмбу — Озеену (см. CORE_GROW).
    for (let f = 0; f < this.fil; f++) {
      const b = f * L;
      for (let i = this.n - 1; i >= 0; i--) {
        const k = b + i;
        if (i + 1 < L) {
          // Первое звено — полный шаг сноса, как и все прочие.
          //
          // Укорачивать его (Кац и Плоткин советуют четверть шага, чтобы
          // разгонный вихрь сидел ближе к кромке) пробовали и померили: первый
          // отсчёт после ступеньки ветра от этого не улучшается, а ПОРТИТСЯ —
          // 1.32 при полном звене, 1.66 при половине, 1.96 при десятой. Тренд
          // объясняет сам себя: в этой постановке главный стабилизатор системы —
          // не разгонный вихрь, а сходящие ножки ближнего кольца, и укоротить их
          // значит его ослабить. Совет верен для схем, где ближняя пелена
          // задана, а не решается вместе с циркуляцией.
          this.x[k + 1] = this.x[k] + this.vx[k] * dt;
          this.y[k + 1] = this.y[k] + this.vy[k] * dt;
          this.z[k + 1] = this.z[k] + this.vz[k] * dt;
          this.rc[k + 1] = Math.sqrt(this.rc[k] * this.rc[k] + CORE_GROW * dt);
        }
      }
      // Кольца стареют вместе с узлами. Сдвиг идёт с конца, чтобы не затереть
      // ещё не переехавшее.
      for (let i = Math.min(this.n, L - 2); i >= 0; i--) {
        this.gr[b + i + 1] = this.gr[b + i];
      }
      seed(f, p);
      this.x[b] = p[0]; this.y[b] = p[1]; this.z[b] = p[2];
      this.rc[b] = this.core;
      this.gr[b] = gring[f];

    }
    // Направление хвоста стареет вместе с рядами: сдвиг с конца, свежему ряду —
    // сегодняшний поток.
    for (let i = Math.min(this.n, L - 2); i >= 0; i--) {
      this.tdx[i + 1] = this.tdx[i];
      this.tdy[i + 1] = this.tdy[i];
      this.tdz[i + 1] = this.tdz[i];
    }
    this.tdx[0] = this.dirx; this.tdy[0] = this.diry; this.tdz[0] = this.dirz;
    if (this.n < L) this.n++;
    this.spaceCore();
    this.edges();
    this.pack();
  }

  // Свежее кольцо нити f — то, что несёт решаемую циркуляцию. Отдаётся тремя
  // отрезками: две сходящие ножки (по нитям f и f+1, от кромки к первому
  // снесённому узлу) и замыкающий поперечный между ними. Четвёртый, у самой
  // кромки, замыкается связанным вихрем решётки и потому не нужен.
  //
  // Знаки — те же, что даёт `edges` для кольца ряда 0: +Г на ножку нити f, -Г
  // на ножку нити f+1, +Г на поперечный по ряду 1.
  // Зовётся семьсот раз за шаг (кольца на панели, и по две точки на панель),
  // поэтому ни замыканий, ни временных массивов внутри: и то и другое здесь
  // стоило дороже самого Био — Савара.
  nearInfluence(f, px, py, pz, ground, out) {
    const L = this.len, b = f * L, c = (f + 1) * L;
    const t = this._nt || (this._nt = [0, 0, 0]);
    const rc2 = 0.5 * (this.rc[b] * this.rc[b] + this.rc[b + 1] * this.rc[b + 1]);
    let vx = 0, vy = 0, vz = 0;
    const x = this.x, y = this.y, z = this.z;
    const P = this._np || (this._np = [0, 0, 0, 0, 0, 0]);
    P[0] = b; P[1] = b + 1; P[2] = c; P[3] = c + 1; P[4] = b + 1; P[5] = c + 1;
    for (let mir = 0; mir < (ground ? 2 : 1); mir++) {
      const sz = mir ? -1 : 1, k = mir ? -1 : 1;
      for (let e = 0; e < 3; e++) {
        const p = P[e * 2], q = P[e * 2 + 1];
        segment(px, py, pz, x[p], y[p], sz * z[p], x[q], y[q], sz * z[q], t, rc2);
        const sg = e === 1 ? -k : k;    // средняя ножка (по нити f+1) с минусом
        vx += sg * t[0]; vy += sg * t[1]; vz += sg * t[2];
      }
    }
    out[0] = vx; out[1] = vy; out[2] = vz;
    return out;
  }

  // Ядро не может быть меньше половины расстояния до соседней нити.
  //
  // Возраст сам по себе не спасает: сворачиваясь в жгут, нити сходятся быстрее,
  // чем ядро расплывается, и в тесноте всё повторяется. Поэтому вторым условием
  // ставится геометрия — ядра соседних нитей всегда хотя бы касаются, и подойти
  // теснее ядра нити просто не могут. Это и есть то, чем настоящая пелена
  // отличается от набора нулевых нитей: сворачивается ЛИСТ конечной толщины, а
  // не математические линии, и толщина у него — расстояние между нитями.
  //
  // Мерится по узлам ОДНОГО возраста: они и есть один поперечный разрез листа.
  //
  // Из двух средств против разноса это оказалось главным, и не тем, на которое
  // я ставил. На полном курсе излом нити (угол между соседними звеньями, чем
  // больше — тем рванее пелена) без всего 65° на узел; один возраст даёт 37°,
  // один пол по соседу — 2.4°, вместе 1.7°. То есть расплывание со временем
  // само по себе почти не спасает: сворачиваясь в жгут, нити сходятся быстрее,
  // чем ядро успевает вырасти. Обе оставлены — вместе всё же лучше, — но знать,
  // которая из них держит, стоит: цифры в tests/wake.test.mjs.
  spaceCore() {
    const L = this.len;
    for (let f = 0; f < this.fil; f++) {
      // Сосед есть там, где между нитями натянуто ПОЛОТНО, и определяется это
      // топологией, а не сегодняшней силой нити.
      //
      // Было наоборот, и оба раза неверно. Нить целиком выпадала из
      // ограничителя, если её свежая разность циркуляций обнулилась, — а старые
      // её рёбра при этом несли вихрь как ни в чём не бывало. И сосед брался
      // просто как f±1: на стыке грота со стакселем это нить ЧУЖОГО паруса, а
      // полотна между ними нет вовсе, и мерить по ней толщину листа — всё равно
      // что мерить расстояние до соседней комнаты.
      const b = f * L;
      const left = f > 0 && this.ring[f - 1], right = this.ring[f];
      if (!left && !right) continue;
      for (let i = 0; i < this.n; i++) {
        const k = b + i;
        // Квадратами: корень нужен один раз, а не на каждого соседа.
        let d2 = Infinity;
        for (let s = -1; s <= 1; s += 2) {
          const nf = f + s;
          if (s < 0 ? !left : !right) continue;
          const m = nf * L + i;
          const ax = this.x[m] - this.x[k], ay = this.y[m] - this.y[k],
                az = this.z[m] - this.z[k];
          const q = ax * ax + ay * ay + az * az;
          if (q < d2) d2 = q;
        }
        if (d2 < Infinity) {
          const half = this.spaceK * Math.sqrt(d2);
          if (half > this.rc[k]) this.rc[k] = half;
        }
      }
    }
  }
}
