// След за лодкой: мировое поле, которое читает сама вода.
//
// До этого след был лентой — сто пятьдесят точек, склеенных в полосу белых
// четырёхугольников на высоте пять сантиметров. Пока вода была почти плоской,
// это сходило. С БПФ перестало: поверхность ходит на десятки сантиметров, а при
// разгоне в тридцать километров — на метр, и лента про это ничего не знает. На
// гребне она уходит под воду, в подошве висит в воздухе. Подобрать высоту нельзя
// никакую: след обязан быть СВОЙСТВОМ ПОВЕРХНОСТИ, а не геометрией над ней.
//
// Поэтому здесь не рисуется ничего. Здесь живёт поле, привязанное к миру, а
// рисует его вода — тем же выражением, которым рисует пену на гребне.
//
// Два канала, и они про разное:
//
//   ПЕНА — взбитая белая вода. Гаснет медленно, десятками секунд, и это
//     единственное, что в старой ленте было;
//
//   ВОЛНА — знаковая высота корабельных волн, тех самых кельвиновых усов.
//     Единственный канал, который входит в ГЕОМЕТРИЮ, а не в цвет: усы читаются
//     только рельефом, крашеной галочкой на воде их не изобразить;
//
//   ГЛАДКОСТЬ — то, чего в ленте не было вовсе, а видно её дальше всего.
//     Прошедший корпус сбивает капиллярную рябь, и дорожка за кормой ещё долго
//     остаётся ЗЕРКАЛЬНЕЕ воды вокруг — даже там, где пены давно нет. Именно по
//     этой гладкой полосе чужой след и читается с расстояния, на котором никакой
//     белизны уже не различить. Живёт она ДОЛЬШЕ пены, а не меньше: пузыри
//     всплывают и лопаются за десяток секунд, а рябь в слабый ветер отрастает
//     минуту. Сначала было наоборот, и след выходил ровно наизнанку — белая
//     полоса во весь участок и никакой дорожки за ней.
//
// Поле идёт за лодкой, но НЕ едет вместе с ней: начало щёлкает по целым
// текселям. Это не мелочь и не оптимизация. Поле, которое каждый кадр
// пересэмплируется билинейно на дробный сдвиг, размазывается само об себя: за
// пару секунд от следа остаётся ровное пятно. Целый тексель — значит чтение
// попадает точно в тексель, и накопления размытия нет вовсе.

const WAKE_N = 512;
const WAKE_SPAN = 128;                        // м на всё поле
const WAKE_CELL = WAKE_SPAN / WAKE_N;         // 0.25 м на тексель
// Времена жизни, секунды.
//
// Белизна уходит быстро — за корпус с небольшим, и это тоже правка по натуре.
// Пена за транцем на воде живёт недолго, а длинной белой полосы за швертботом не
// бывает вовсе: то, что тянется далеко, это не пена, а ПРИГЛАЖЕННАЯ вода.
// Пена на кромочной волне держится не временем жизни, а тем, что её кладут
// заново вдоль всей кромки каждый кадр.
//
// Гладкая дорожка держится на порядок дольше: при здешнем ходе это дальше, чем
// всё поле, и значит по краю участка она и обрывается, гашением у кромки.
const WAKE_TAU_FOAM = 3.5;
const WAKE_TAU_SLICK = 45;
// Ход, на котором след начинается и на котором он выходит в полную силу. Ниже
// первого числа за лодкой не остаётся ничего — и это правда: яхта, ползущая в
// полузла, идёт по воде, а не пашет её.
const WAKE_V0 = 0.8;                          // м/с
const WAKE_V1 = 3.2;                          // м/с
// Полуширина полосы: полуширина по ватерлинии плюс прибавка на ход. Корма
// разгоняет воду шире корпуса, и чем быстрее, тем шире.
const WAKE_WIDE_V = 0.10;                     // м на каждый м/с
// Во сколько раз нос уже кормы и во сколько раз бледнее. За транцем — сорванный
// поток и воздух, затянутый под корпус; у форштевня вода раздвигается, а не
// взбивается, и белого там немного.
const WAKE_BOW_WIDE = 0.55;
const WAKE_BOW_FOAM = 0.40;
// Дрейф. Идущая боком лодка подставляет потоку не ширину, а проекцию корпуса, и
// полоса за ней заметно шире. Полный корпус поперёк — это полудлина вместо
// полуширины, отсюда и мера: доля от полудлины на радиан дрейфа.
const WAKE_DRIFT_WIDE = 0.55;
// Крен: подветренная скула зарывается и гребёт. На двадцати градусах белого
// заметно больше, чем на ровном киле.
const WAKE_HEEL_FOAM = 0.5;                   // прибавка на радиан

// --- кельвиновы усы ------------------------------------------------------------
//
// Расходящийся ус за судном — не украшение и не выдумка: это стационарная фаза
// волновой системы, и угол у неё один и тот же для лодки и для сухогруза.
// arcsin(1/3) = 19.47°, полуугол клина, и он НЕ ЗАВИСИТ ОТ СКОРОСТИ. Зависит от
// неё только шаг: длина основной волны λ = 2πU²/g. На четырёх метрах в секунду
// это десять метров, на двух — два с половиной.
//
// Внутри клина живут две системы. ПОПЕРЕЧНАЯ — гребни поперёк курса, шаг λ,
// сильнее у диаметрали. РАСХОДЯЩАЯСЯ — гребни под 35.26° к курсу, сильнее у
// самой кромки клина; их огибающая кромку и образует. Обе взяты приближением
// стационарной фазы, то есть дальним полем: у самой кормы, в двух метрах от
// транца, формула не про что. Там всё равно всё закрыто пеной.
//
// Впрыск идёт КАЖДЫЙ КАДР целиком, от нынешнего транца, — и это не портит
// картину, хотя выглядит так, будто должно. Рисунок привязан по фазе к
// источнику, а источник за кадр уезжает на шесть сантиметров при длине волны в
// восемь метров; сместившись же на целую λ, гребни встают ровно на место
// соседних. Так и должно быть: в системе отсчёта лодки кельвинов рисунок
// НЕПОДВИЖЕН, потому его и можно класть заново.
//
// Чего это стоит: на повороте рисунок поедет за лодкой, вместо того чтобы
// остаться там, где его наделали. Гасится это подмешиванием — новый рисунок
// входит долей за кадр, а не целиком, — и на руле в полборта разница не читается.
const WAKE_KELVIN_TAN = 0.35355;              // tg 19.47°
const WAKE_KELVIN_AMP = 0.26;                 // м на полном ходу
// Полуширина кромочной волны в долях λ. Гребень занимает примерно четверть
// длины волны, ложбины — по бокам от него.
const WAKE_RIDGE_L = 0.16;
// Пена на гребне кромочной волны. Она там обрушивается, и это главное белое,
// что видно на воде: внутри конуса пены практически нет.
const WAKE_RIDGE_FOAM = 0.85;
// Насколько конус гасит ветровую рябь. Почти нацело: приглаженный клин за кормой
// и есть то, по чему след читается издали.
const WAKE_WEDGE_SLICK = 0.9;
// Поперечная система — та, что гребнями поперёк курса. Оставлена еле заметной
// нарочно: в теории она есть, но на здешних числах Фруда на воде видно другое —
// две волны по кромкам конуса, а внутри гладко.
const WAKE_KELVIN_TRANS = 0.18;
const WAKE_KELVIN_MIX = 0.30;                 // с, за сколько новый рисунок входит
const WAKE_TAU_WAVE = 7;                      // с, время жизни вне впрыска
// Дальше скольких длин волны усы не кладутся. Не ради экономии: за этой чертой
// рисунок держится только тем, что его кладут заново, а значит именно там
// поворот и размазал бы его сильнее всего.
const WAKE_KELVIN_LEN = 5;
// Дальше какого расстояния за кадр отрезок считается не ходом, а прыжком.
// Сброс лодки (`X`, расхождение физики) не должен прочерчивать полосу через всю
// акваторию — ровно та беда, ради которой в чужих реализациях заведены флаги
// «стоит» и «телепорт».
const WAKE_JUMP = 6;                          // м

// Обводы ставятся снаружи: они живут в пакете физики, а не здесь. По
// ватерлинии, а не по палубе — след оставляет то, что в воде.
let HALF_BEAM = 0.9, HALF_LEN = 2.7, AFT_X = 0.55, FWD_X = 6.0;
function wakeSetHull(halfBeam, aftX, fwdX) {
  HALF_BEAM = halfBeam;
  AFT_X = aftX;
  FWD_X = fwdX;
  HALF_LEN = (fwdX - aftX) / 2;
}

class Wake {
  constructor(renderer) {
    this.renderer = renderer;

    const make = () => {
      const t = new StorageTexture(WAKE_N, WAKE_N);
      // Половинная точность: тут доли единицы, точности хватает с запасом.
      t.type = HalfFloatType;
      // Поле не кроется — за его краем нет следа, а не «след из-за угла».
      t.wrapS = ClampToEdgeWrapping;
      t.wrapT = ClampToEdgeWrapping;
      t.minFilter = LinearFilter;
      t.magFilter = LinearFilter;
      return t;
    };
    this.tex = [make(), make()];
    this.flip = 0;

    this.uOrigin = uniform(new Vector2(0, 0));   // мировой угол поля
    this.uShift = uniform(new Vector2(0, 0));    // на сколько текселей уехало
    this.uDecay = uniform(new Vector3(1, 1, 1));  // гашение за кадр: пена, гладь, волна
    this.uSegA = uniform(new Vector2(0, 0));     // кормовой конец впрыска, мир
    this.uSegB = uniform(new Vector2(0, 0));     // носовой конец
    this.uWide = uniform(new Vector2(1, 1));     // полуширина у кормы и у носа
    this.uInj = uniform(new Vector4(0, 0, 1, 0));  // пена, гладкость, доля у носа, вкл
    this.uTrack = uniform(new Vector2(1, 0));    // орт хода, мир
    this.uKel = uniform(new Vector4(1, 0, 1, 0)); // k, амплитуда, полуширина кромки, доля
    this.uWedge = uniform(new Vector2(0, 0));    // гладкость в конусе, пена на кромке

    // Узел для выборки водой. Значение подменяется каждый кадр — производные
    // узлы (`sample`) держат ссылку на этот же, базовый, и едут за ним. Так же
    // устроено зеркало отражения в three.
    this.node = texture(this.tex[0]);

    this.kStep = [this._kernel(this.tex[0], this.tex[1]),
                  this._kernel(this.tex[1], this.tex[0])];

    this.have = false;      // была ли прошлая точка, от которой вести отрезок
    this.px = 0; this.py = 0;
    this.ox = 0; this.oy = 0;
    this.cleared = false;
  }

  // Один проход: сдвинуть, погасить, впрыснуть.
  _kernel(src, dst) {
    const N = WAKE_N;
    return Fn(() => {
      const i = instanceIndex;
      const ix = i.mod(uint(N)), iy = i.div(uint(N));

      // Тот же кусок мира в прошлом кадре лежал на uShift текселей в сторону.
      const fx = float(ix).add(this.uShift.x).toVar();
      const fy = float(iy).add(this.uShift.y).toVar();
      // «Попали ли в прошлое поле» — арифметикой, без логических узлов.
      // Координаты здесь целые, поэтому clamp(fx + 1, 0, 1) даёт ровно ноль при
      // fx = −1 и ровно единицу при fx ≥ 0; то же с другого конца. Приведение
      // bool к числу в этой цепочке однажды уже стоило чёрной воды.
      const ok = fx.add(1).clamp(0, 1).mul(float(N).sub(fx).clamp(0, 1))
        .mul(fy.add(1).clamp(0, 1)).mul(float(N).sub(fy).clamp(0, 1)).toVar();
      const prev = textureLoad(src, ivec2(int(fx.clamp(0, N - 1)),
                                          int(fy.clamp(0, N - 1)))).toVar();
      const foam = prev.x.mul(this.uDecay.x).mul(ok).toVar();
      const slick = prev.y.mul(this.uDecay.y).mul(ok).toVar();
      const wave = prev.z.mul(this.uDecay.z).mul(ok).toVar();

      // Впрыск — по ОТРЕЗКУ, а не точкой. Точкой след выходит пунктиром: на
      // четырёх метрах в секунду и просевших кадрах лодка успевает уехать на
      // треть корпуса между впрысками.
      //
      // Отрезок идёт от ПРОШЛОГО ТРАНЦА к НЫНЕШНЕМУ ФОРШТЕВНЮ и потому делает
      // сразу две вещи: накрывает след за кормой и накрывает сам корпус. Второе
      // важно не меньше: лодка обязана стоять в собственной взбитой воде, а не
      // на гладкой глади, из-под которой след начинается позади транца.
      const p = this.uOrigin
        .add(vec2(float(ix).add(0.5), float(iy).add(0.5)).mul(WAKE_CELL)).toVar();
      const ab = this.uSegB.sub(this.uSegA).toVar();
      const t = p.sub(this.uSegA).dot(ab).div(ab.dot(ab).max(1e-6))
        .clamp(0, 1).toVar();
      const d = p.sub(this.uSegA.add(ab.mul(t))).length().toVar();
      // Полоса СУЖАЕТСЯ к носу и там же бледнеет: за транцем сорванный поток и
      // затянутый воздух, у форштевня вода раздвигается, а не взбивается.
      const half = mix(this.uWide.x, this.uWide.y, t).toVar();
      const prof = mix(float(1.0), this.uInj.z, t).toVar();
      // Мягкий край: сердцевина полосы полная, к кромке сходит на нет. Концы у
      // smoothstep по возрастанию, разворот через oneMinus — у WGSL при
      // low ≥ high результат не определён.
      const w = d.smoothstep(half.mul(0.45), half)
        .oneMinus().mul(prof).mul(this.uInj.w).toVar();
      // Не сложение, а максимум: сложение зависело бы от числа кадров, и на
      // просевшей частоте след выходил бы бледнее при том же ходе.
      foam.assign(foam.max(w.mul(this.uInj.x)));
      slick.assign(slick.max(w.mul(this.uInj.y)));

      // --- конус и его кромки ---
      //
      // Координаты в осях хода: ξ — сколько метров ПОЗАДИ транца, η — вбок.
      const rel = p.sub(this.uSegA).toVar();
      const xi = rel.dot(this.uTrack).negate().toVar();
      const eta = rel.dot(vec2(this.uTrack.y.negate(), this.uTrack.x)).abs().toVar();
      const k = this.uKel.x.toVar();
      // Расстояние ДО КРОМКИ клина, в метрах: внутри отрицательное, снаружи
      // положительное, ноль ровно на кромке. Дальше всё меряется от неё, а не от
      // диаметрали, — потому что на кромке всё и происходит.
      const dc = eta.sub(xi.max(0.0).mul(WAKE_KELVIN_TAN)).toVar();
      const q = dc.div(this.uKel.z).toVar();
      // Гаснет с дальностью как корень — так убывает дальнее поле, — и обрезано
      // спереди (только позади транца) и сзади (см. WAKE_KELVIN_LEN).
      //
      // Дальность ОБРЕЗАНА СНИЗУ до нуля, и это не про красоту огибающей.
      // Впереди транца ξ отрицательна, и корень из отрицательного — NaN; на
      // множитель ноль он не умножается, а расползается. Первый заход именно так
      // и кончился: NaN попал в высоту вершины, и вода исчезла из сцены целиком,
      // без единой ошибки в консоли. Видно было только киль под несуществующей
      // водой.
      const far = xi.mul(k).div(2 * Math.PI).max(0.0).toVar();
      const env = far.smoothstep(0.0, 0.25)
        .mul(far.smoothstep(WAKE_KELVIN_LEN * 0.5, WAKE_KELVIN_LEN).oneMinus())
        .div(far.add(0.5).sqrt()).toVar();

      // ВНУТРИ КОНУСА вода ПРИГЛАЖЕНА. Это главное, что видно на воде, и это
      // ровно то, что было сделано неправильно: конус — не полоса пены по
      // диаметрали, а широкий гладкий клин, в котором ветровая рябь сбита и
      // новой почти не прибавляется.
      const inside = q.smoothstep(-0.35, 0.75).oneMinus().toVar();
      slick.assign(slick.max(inside.mul(env.min(1.0)).mul(this.uWedge.x)));

      // НА КРОМКАХ — по волне с каждой стороны, и пена только на них. Профиль:
      // один гребень ровно на кромке и по ложбине с боков; за пределами полутора
      // полуширин сходит на нет.
      const ridge = q.mul(2.2).cos()
        .mul(q.abs().smoothstep(1.2, 2.2).oneMinus()).toVar();
      // Поперечная система оставлена еле заметной. Она есть в теории, но на
      // здешних числах Фруда её не видно: на воде читаются две кромочные волны, а
      // внутри клина гладко.
      const kel = ridge.add(xi.mul(k).cos().mul(inside).mul(WAKE_KELVIN_TRANS))
        .mul(env).mul(this.uKel.y).toVar();
      // Подмешивается долей, а не кладётся целиком: на повороте это и есть та
      // задержка, которая не даёт рисунку прыгать за лодкой.
      wave.assign(mix(wave, kel, this.uKel.w.mul(inside.max(ridge.abs()))));
      // Пена — на гребне кромочной волны, и только на нём: она там обрушивается.
      // Ложбина не пенится, поэтому берётся положительная часть, да ещё в
      // квадрате — белое собирается на самой макушке.
      foam.assign(foam.max(ridge.max(0.0).mul(ridge.max(0.0))
        .mul(env.min(1.0)).mul(this.uWedge.y)));

      textureStore(dst, ivec2(int(ix), int(iy)), vec4(foam, slick, wave, 1));
    })().compute(N * N);
  }

  // Кадр. Мировые XY — оси физики: восток и север.
  //
  // `x`, `y` — начало координат лодки, `psi` — курс, `speed` — ход ПО ВОДЕ,
  // `drift` — угол дрейфа в радианах, `heel` — крен в радианах, `dt` — секунды.
  step(dt, x, y, psi, speed, drift, heel) {
    // Начало поля щёлкает по целым текселям — см. заголовок.
    const ox = Math.round((x - WAKE_SPAN / 2) / WAKE_CELL) * WAKE_CELL;
    const oy = Math.round((y - WAKE_SPAN / 2) / WAKE_CELL) * WAKE_CELL;
    // Первый кадр: поле пустое, а гасить нечего. Сдвиг тогда заведомо огромный,
    // и всё поле честно обнулится признаком «мимо прошлого поля».
    const shiftX = this.cleared ? Math.round((ox - this.ox) / WAKE_CELL) : WAKE_N;
    const shiftY = this.cleared ? Math.round((oy - this.oy) / WAKE_CELL) : WAKE_N;
    this.uShift.value.set(shiftX, shiftY);
    this.uOrigin.value.set(ox, oy);
    this.ox = ox; this.oy = oy;

    const s = Math.max(0, Math.min(1, (speed - WAKE_V0) / (WAKE_V1 - WAKE_V0)));
    // Пена набирается с хода круто: до трети первого узла её нет вовсе, а на
    // полном ходу она сплошная. Гладкость появляется раньше и держится дольше —
    // рябь сбивает и медленный корпус.
    //
    // Крен добавляет белого: подветренная скула зарывается и гребёт.
    const foam = Math.min(1, s * s * (1 + WAKE_HEEL_FOAM * Math.abs(heel)));
    const slick = Math.sqrt(s);
    // Ширина: полуширина по ватерлинии, плюс ход, плюс ДРЕЙФ. Идущая боком
    // лодка подставляет потоку проекцию корпуса, а не свою ширину, — и полоса за
    // ней шире ровно на эту разницу.
    const wide = HALF_BEAM + WAKE_WIDE_V * speed
      + WAKE_DRIFT_WIDE * HALF_LEN * Math.abs(drift);

    // Концы отрезка: кормовой — ПРОШЛЫЙ транец, носовой — НЫНЕШНИЙ форштевень.
    // Так одним примитивом накрывается и след, и сам корпус.
    const c = Math.cos(psi), sn = Math.sin(psi);
    const tx = x + AFT_X * c, ty = y + AFT_X * sn;     // транец
    const bx = x + FWD_X * c, by = y + FWD_X * sn;     // форштевень
    // Полосу сносит под ветер вместе с самой лодкой: на дрейфе взбитая вода
    // остаётся с подветренной скулы, а не строго по диаметрали. Знак дрейфа и
    // задаёт, с какой.
    const off = HALF_BEAM * Math.sin(drift) * 1.5;
    const ox2 = -sn * off, oy2 = c * off;

    const moved = this.have ? Math.hypot(tx - this.px, ty - this.py) : 0;
    const on = this.have && moved < WAKE_JUMP && s > 0 ? 1 : 0;
    this.uSegA.value.set((on ? this.px : tx) + ox2, (on ? this.py : ty) + oy2);
    this.uSegB.value.set(bx + ox2, by + oy2);
    this.uWide.value.set(wide, wide * WAKE_BOW_WIDE);
    this.uInj.value.set(foam, slick, WAKE_BOW_FOAM, on);
    this.px = tx; this.py = ty; this.have = true;

    // Кельвинов рисунок. Волновое число k = g/U² — это ровно 2π/λ при
    // λ = 2πU²/g. Снизу оно ограничено длиной волны в метр: короче — рисунок не
    // помещается в тексель, и вместо усов выходит шум.
    const kel = Math.min(2 * Math.PI / 1.0, 9.81 / Math.max(0.6, speed * speed));
    // Полуширина кромочной волны — доля от длины волны, но не уже пары текселей:
    // гребень в один тексель это не гребень, а строка шума.
    const ridge = Math.max(WAKE_CELL * 2.5, WAKE_RIDGE_L * (2 * Math.PI / kel));
    this.uTrack.value.set(Math.cos(psi + drift), Math.sin(psi + drift));
    this.uKel.value.set(kel, WAKE_KELVIN_AMP * s, ridge,
                        1 - Math.exp(-dt / WAKE_KELVIN_MIX));
    this.uWedge.value.set(WAKE_WEDGE_SLICK * Math.sqrt(s), WAKE_RIDGE_FOAM * s * s);

    // Гашение экспоненциальное и считается от dt, а не от кадра: на просевшей
    // частоте след обязан жить те же секунды, а не то же число кадров.
    this.uDecay.value.set(Math.exp(-dt / WAKE_TAU_FOAM),
                          Math.exp(-dt / WAKE_TAU_SLICK),
                          Math.exp(-dt / WAKE_TAU_WAVE));

    this.renderer.compute(this.kStep[this.flip]);
    this.flip = 1 - this.flip;
    this.node.value = this.tex[this.flip];
    this.cleared = true;
  }

  // Забыть след целиком: сброс лодки, перемотка записи. Одного кадра с
  // заведомо промахивающимся сдвигом хватает, чтобы поле обнулилось.
  clear() {
    this.cleared = false;
    this.have = false;
  }

  // Выборка поля водой: (пена, гладкость, волна), уже погашенная к краю
  // участка. У поля есть кромка, и без гашения след обрывался бы по ней ровной
  // чертой поперёк воды.
  sample(worldXY) {
    const uv = worldXY.sub(this.uOrigin).div(WAKE_SPAN);
    const edge = uv.sub(0.5).abs().mul(2.0);
    const fade = edge.x.max(edge.y).smoothstep(0.86, 1.0).oneMinus();
    return this.node.sample(uv).xyz.mul(fade);
  }

  // Уклон волнового канала: разности вперёд от уже взятой выборки. Отдельным
  // методом, а не каналом поля, потому что нужен он только в пиксельной стадии —
  // геометрии довольно высоты.
  //
  // Разности ВПЕРЁД, а не центральные, и это не небрежность, а счёт выборок:
  // центральные стоили бы четырёх на пиксель, эти — двух, потому что середина
  // уже взята. Смещение на полшага при длине волны в метры не читается ничем.
  //
  // Шаг в два текселя: на одном половинная точность поля начинает шуметь.
  slope(worldXY, here) {
    const h = WAKE_CELL * 2;
    return vec2(this.sample(worldXY.add(vec2(h, 0))).z.sub(here),
                this.sample(worldXY.add(vec2(0, h))).z.sub(here)).div(h);
  }
}

export { Wake, wakeSetHull, WAKE_N, WAKE_SPAN, WAKE_CELL,
         WAKE_TAU_FOAM, WAKE_TAU_SLICK, WAKE_V0, WAKE_V1, WAKE_JUMP };
