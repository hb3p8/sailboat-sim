// Волнение: состояние моря по ветру и добавочное сопротивление на волне.
//
// До этого лодка ходила по идеально гладкой воде. Волны в сцене были нарисованы
// и ни на что не влияли, а всё, что волна отнимает у хода, сидело внутри
// подобранной кривой остаточного сопротивления — слитое с волновым
// сопротивлением тихой воды и потому неразделимое.
//
// Разделение важно не ради чистоты. Волна штрафует НЕ ВСЕ курсы одинаково:
// сильнее всего она бьёт по приведению, где своего хода мало и проталкиваться
// сквозь неё нечем. Именно этот перекос и держит настоящий лавировочный угол в
// восьмидесяти с лишним градусах, тогда как на гладкой воде лодка с таким килем
// и таким ригом идёт заметно круче — и это не ошибка модели, а свойство
// гладкой воды.
//
// Что здесь есть:
//
//   * состояние моря по ветру и разгону — JONSWAP в форме, ограниченной
//     разгоном. Разгон вынесен в орган управления: на пруду волны нет вовсе,
//     на заливе с парой километров она уже заметна;
//
//   * спектр Брецшнейдера и добавочное сопротивление по нему. Считается не по
//     одной «значительной» волне, а по нескольким полосам спектра: у одной
//     волны резонанс выходит игольчатым, у спектра — таким, каким он на воде и
//     бывает;
//
//   * резонанс — на собственной частоте вертикальной качки лодки, посчитанной
//     в пакете из площади ватерлинии и водоизмещения. Не подгонянное число, а
//     геометрия: у шестиметровой лодки период выходит около 0.84 с, а частота
//     встречи с волной в лавировку по такой воде — как раз около того же.
//     Отсюда и провал хода: лодка идёт в резонансе.
//
// Подгоняется здесь ровно одно число — величина пика. Форма кривой по частоте
// и зависимость от курса берутся из встречной частоты, то есть из кинематики.

const G = 9.80665;
const RHO = 1025.0;

// Полос спектра. Семи хватает: на четырнадцати ответ меняется меньше чем на
// процент, а считать это каждый шаг.
const BANDS = 7;

// Ширина резонансного колокола в логарифме частоты. Замеренные кривые
// добавочного сопротивления имеют довольно острый пик; октава, взятая сначала,
// размазывала его так, что лодка оказывалась «в резонансе» на любом ветре и
// теряла ход даже там, где по частоте встречи уже далеко ушла.
const PEAK_W = 0.45;

// Скорость, на которой добавочное сопротивление набирает силу.
//
// Добавочное сопротивление — это сопротивление ДВИЖЕНИЮ, и у неподвижной лодки
// его нет: остаётся сила дрейфа, а она не тормозит, а толкает по волне, и в
// этой модели её нет вовсе. Поэтому множитель квадратичный: на малом ходу он
// гасит почти всё, на рабочем почти ничего не меняет (на 2.6 м/с — три
// четверти).
//
// Без него лодка, выброшенная в левентик в свежий ветер, упиралась на ходу в
// полтора узла в семьдесят пять ньютонов при шести ньютонах сопротивления
// тихой воды и не могла увалиться — то есть оставалась в левентике навсегда.
// Тест это и поймал.
const V_RAMP = 1.5;

// Величина пика — добавочное сопротивление в безразмерном виде
// R·L/(ρ·g·ζ²·B²) на резонансе — единственное подгоняемое число здесь, и
// живёт оно не тут, а в пакете: подбирается в scripts/build_physics.py по
// лавировочному углу. Здесь только значение по умолчанию, если пакет старый.
const PEAK_DEFAULT = 3.4;

// Состояние моря по ветру и разгону.
//
// JONSWAP, ограниченный разгоном: высота и период растут с разгоном, но не
// выше полностью развитого волнения. `fetch` в метрах; ноль — гладкая вода.
export function seaState(windSpeed, fetch) {
  const u = Math.max(0.1, windSpeed);
  if (!(fetch > 0)) return { hs: 0, tp: 1, omega: 2 * Math.PI };
  const xhat = G * fetch / (u * u);
  const hs = Math.min(0.0016 * Math.sqrt(xhat), 0.243) * u * u / G;
  const tp = Math.min(0.286 * Math.pow(xhat, 1 / 3), 8.13) * u / G;
  return { hs: hs, tp: tp, omega: 2 * Math.PI / tp };
}

// Спектр Брецшнейдера: плотность энергии по частоте.
function spectrum(hs, wp, w) {
  const r = wp / w;
  return (5 / 16) * hs * hs * Math.pow(r, 4) / w * Math.exp(-1.25 * Math.pow(r, 4));
}

// Множитель по курсу к волне. Частота встречи одна отвечает не за всё: волна с
// борта лодку почти не тормозит, хотя частота встречи у неё как у стоячей.
// Дело в том, что вертикальную качку раскачивает волна, бегущая вдоль корпуса,
// а не поперёк — отсюда квадрат косинуса. Пятнадцать процентов снизу оставлены
// на отражение от борта, которое от курса зависит слабо.
function heading(cosRel) {
  return 0.15 + 0.85 * cosRel * cosRel;
}

// Добавочное сопротивление на волнении, Н.
//
// `speed` — скорость лодки, `cosRel` — косинус угла между её курсом и
// направлением бега волн. Встречная волна (cosRel < 0) повышает частоту
// встречи и загоняет лодку в резонанс; попутная понижает, и на полном курсе
// резонанса не бывает — оттого там почти ничего и не теряется.
//
// `omegaN` — собственная частота вертикальной качки, `bwl`, `lwl` — размерения.
export function addedResistance(sea, omegaN, bwl, lwl, speed, cosRel, peak) {
  if (!(sea.hs > 0) || !(omegaN > 0)) return 0;
  const wp = sea.omega;
  const vAlong = speed * cosRel;
  const dir = heading(cosRel) * speed * speed /
              (speed * speed + V_RAMP * V_RAMP);
  let sum = 0;
  for (let i = 0; i < BANDS; i++) {
    // полосы от 0.5 до 2.6 пиковой частоты, равномерно по логарифму
    const f = 0.5 * Math.pow(2.6 / 0.5, (i + 0.5) / BANDS);
    const w = wp * f;
    const dw = w * Math.log(2.6 / 0.5) / BANDS;
    const s = spectrum(sea.hs, wp, w);
    if (!(s > 0)) continue;
    // встречная частота: ω − k·v, k = ω²/g
    const we = Math.abs(w - (w * w / G) * vAlong);
    if (!(we > 1e-3)) continue;
    const l = Math.log(we / omegaN);
    sum += (peak || PEAK_DEFAULT) * dir *
           Math.exp(-l * l / (2 * PEAK_W * PEAK_W)) * s * dw;
  }
  return 2 * RHO * G * bwl * bwl / lwl * sum;
}
