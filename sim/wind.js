// Поле ветра: профиль по высоте и порывы.
//
// До этого ветер был одним числом на всю лодку. Это не мелочь и не украшение:
// парус внизу и наверху работает по-разному, и вся настройка твиста существует
// ровно из-за этого. Здесь два независимых явления.
//
// Профиль по высоте — пограничный слой над водой, логарифмический закон.
// Скорость, которую задаёт ползунок, это ветер на стандартной
// метеорологической высоте десять метров: так его и меряют, и так его называют
// в прогнозе. Топ мачты видит около 0.98 от неё, гик — около 0.75. Разница
// между низом и верхом паруса выходит примерно в треть, и она настоящая.
//
// Поле порывов существует ровно в одном экземпляре — здесь. Вода в симуляторе
// не пересчитывает его в шейдере, а берёт готовым из текстуры, которую строит
// gustTexture(); подробности ниже, у GUST_ALONG.
//
// Порывы и заходы — поле, вмороженное в поток и несомое по ветру (гипотеза
// Тейлора). Полосы вытянуты вдоль ветра втрое: на воде порывы так и выглядят,
// длинными языками, а не пятнами. Усиление и заход связаны, потому что порыв —
// это опустившийся сверху воздух, который и быстрее, и приходит под другим
// углом; разыгрывать их порознь было бы враньём, заметным на воде.

const WIND_Z0 = 0.001;      // м, шероховатость открытой воды
const WIND_ZREF = 10.0;     // м, стандартная высота замера ветра

// Поле порывов периодично: оно повторяется через GUST_ALONG метров вдоль ветра
// и GUST_ACROSS поперёк. Это сделано нарочно, и вот зачем.
//
// Воде положено показывать ровно то поле, по которому считаются силы. Пока
// шейдер считал его сам, второй реализацией, две формулы жили каждая своей
// жизнью — и разошлись: множитель сглаживания в шейдере оказался переписан с
// ошибкой, поле рвалось на границах ячеек, вода шла полосами, а физика при этом
// считала правильное поле. Ни тестом, ни консолью такое не ловится.
//
// У периодического поля есть период, а значит его можно посчитать здесь один
// раз на весь период и отдать в текстуру. Шейдеру остаётся перевести мировые
// координаты в «вдоль ветра / поперёк» и взять выборку. Реализация одна.
//
// Размеры ячеек подобраны так, чтобы период делился на каждую нацело: иначе
// решётка не сойдётся сама с собой на стыке и появится шов.
const GUST_ALONG = 1040;    // м, период вдоль ветра
const GUST_ACROSS = 336;    // м, поперёк

// Ячейка вдоль, ячейка поперёк, вес. Веса спадают к мелким масштабам, как в
// спектре турбулентности: крупные языки несут основную часть.
const GUST_SCALES = [
  [130, 42, 0.55],          // 8 и 8 ячеек на период
  [52, 21, 0.30],           // 20 и 16
  [26, 7, 0.15],            // 40 и 48
];

function hash2(i, j, salt) {
  let h = (Math.imul(i | 0, 374761393) + Math.imul(j | 0, 668265263) +
           Math.imul(salt | 0, 2654435761)) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 2147483647.5 - 1;
}

const wrap = (i, n) => ((i % n) + n) % n;

// Гладкий шум на решётке, замкнутой в кольцо: индексы берутся по модулю числа
// ячеек в периоде, поэтому решётка сходится сама с собой на стыке без шва.
// Гладкость тут не украшение: на рваном поле лодку будет дёргать, а порыв
// должен приходить постепенно, как на воде.
//
// Множитель f²·(3 − 2f) обязан доходить до единицы на границе ячейки, иначе
// значение соседнего узла не достигается никогда и поле рвётся. Это ровно та
// ошибка, из-за которой вода однажды пошла полосами.
function noise2(x, y, nx, ny, salt) {
  const i = Math.floor(x), j = Math.floor(y);
  const fx = x - i, fy = y - j;
  const u = fx * fx * (3 - 2 * fx), v = fy * fy * (3 - 2 * fy);
  const i0 = wrap(i, nx), i1 = wrap(i + 1, nx);
  const j0 = wrap(j, ny), j1 = wrap(j + 1, ny);
  const a = hash2(i0, j0, salt), b = hash2(i1, j0, salt);
  const c = hash2(i0, j1, salt), d = hash2(i1, j1, salt);
  return (a + (b - a) * u) * (1 - v) + (c + (d - c) * u) * v;
}

// Значение поля в системе, связанной с ветром. Всё, что зависит от лодки и
// времени, остаётся снаружи: здесь только сама картина порывов.
export function gustAt(along, across) {
  let v = 0;
  for (let i = 0; i < GUST_SCALES.length; i++) {
    const g = GUST_SCALES[i];
    v += g[2] * noise2(along / g[0], across / g[1],
                       GUST_ALONG / g[0], GUST_ACROSS / g[1], i + 1);
  }
  return v;
}

// Поле, посчитанное на один период, для показа на воде. Возвращает байты:
// значение от −1 до 1, разложенное в 0…255. Байта хватает: на яркость воды
// один шаг приходится меньше процента, а вывод и так восьмибитный.
//
// Значение кладётся в ЦЕНТР тексела — так выборка с линейной фильтрацией по
// координате along/период попадает ровно туда, куда надо.
export function gustTexture(width, height) {
  const data = new Uint8Array(width * height);
  for (let j = 0; j < height; j++) {
    const across = (j + 0.5) / height * GUST_ACROSS;
    for (let i = 0; i < width; i++) {
      const along = (i + 0.5) / width * GUST_ALONG;
      const v = gustAt(along, across);
      data[j * width + i] = Math.max(0, Math.min(255, Math.round((v + 1) * 127.5)));
    }
  }
  return data;
}

export const GUST_PERIOD = { along: GUST_ALONG, across: GUST_ACROSS };

export class WindField {
  constructor(opts) {
    this.o = Object.assign({
      speed: 6.0,           // м/с на высоте zRef
      dir: 0,               // откуда дует, рад, от оси X мира
      gust: 0.0,            // размах порывов, доля от средней скорости
      shift: 0.0,           // размах захода, рад
      gradient: true,       // профиль по высоте
      z0: WIND_Z0, zRef: WIND_ZREF,
    }, opts || {});
  }

  // Доля от опорной скорости на высоте z. Ниже четверти метра логарифм теряет
  // смысл и уходит в минус, поэтому там просто обрезается.
  profile(z) {
    if (!this.o.gradient) return 1;
    return Math.log(Math.max(0.25, z) / this.o.z0) /
           Math.log(this.o.zRef / this.o.z0);
  }

  // Координаты точки в системе, связанной с ветром: вдоль потока и поперёк.
  // Поле вморожено в поток и едет по ветру со скоростью потока, отсюда
  // вычитание speed·t.
  frame(x, y, t) {
    const o = this.o;
    const c = Math.cos(o.dir), s = Math.sin(o.dir);
    return { along: -(x * c + y * s) - o.speed * t, across: -x * s + y * c };
  }

  // Значение поля порывов в точке: от −1 (заход, дыра) до +1 (порыв).
  gust(x, y, t) {
    const f = this.frame(x, y, t);
    return gustAt(f.along, f.across);
  }

  // Медленное колебание направления, не связанное с порывами: ветер заходит
  // и отходит сам по себе, с периодом в минуты. Замыкать его в кольцо незачем —
  // на воде оно не показывается, — поэтому решётка берётся заведомо длинной.
  swing(t) {
    return noise2(t / 55, 17.3, 1 << 20, 1 << 20, 7);
  }

  // Ветер в точке. Возвращает вектор, КУДА дует, в мировых осях — та же
  // условность, что у кажущегося ветра в physics.js.
  sample(x, y, z, t) {
    const o = this.o;
    let speed = o.speed * this.profile(z);
    let dir = o.dir;
    if (o.gust || o.shift) {
      const g = this.gust(x, y, t);
      speed *= 1 + o.gust * g;
      dir += o.shift * (0.65 * g + 0.35 * this.swing(t));
    }
    return { x: -speed * Math.cos(dir), y: -speed * Math.sin(dir),
             speed: speed, dir: dir };
  }
}
