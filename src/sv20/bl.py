"""Интегральный пограничный слой на сечении: Твейтс, переход, Хед.

Что это и зачем. Невязкий расчёт (`section.py`) даёт скорость на краю слоя
`U_e(s)` — и на этом кончается: в потенциальном течении отрыва не существует, а
парус в нём везёт на любом угле. Отрыв живёт в тонком слое у самого полотна, и
считается он отдельно, вдоль поверхности, тремя величинами:

    θ   толщина потери импульса — сколько импульса недосчитался поток
    δ*  толщина вытеснения — на сколько слой «утолщает» тело
    H   формпараметр δ*/θ — по нему и объявляется отрыв

Гонит их сама `U_e(s)`, точнее её падение: слой отрывается там, где поток идёт
против растущего давления и у пристеночных частиц кончается запас импульса.
Обратной связи здесь нет — слой читает поле, но не меняет его. Это осознанно:
совместная постановка у самого отрыва расходится (особенность Гольдштейна), и
бороться с ней нечем, кроме приёмов Дрелы, которым в этом проекте не место. То,
ради чего слой и считается — точка отрыва, — прямым маршем берётся честно.

Ламинарный участок — Твейтс, турбулентный — Хед с трением по Людвигу—Тильману.
Оба метода старые и оба поверены в батарее не «похоже», а числами, которые
известны точно: Блазиус на пластине и отрыв Хоуарта на линейно тормозящемся
потоке.

Всё безразмерное: хорда единичная, набегающая скорость единичная, вязкость
входит как 1/Re.
"""

import numpy as np

__all__ = ["thwaites", "head", "march", "squire_young", "SEP_H"]

# Турбулентный отрыв по Хеду объявляется, когда формпараметр переходит порог.
# 2.4 — обычное для метода число; величина не строгая (у Хеда порог размыт от
# 2.2 до 2.6), и от неё зависит только положение точки отрыва, а не сам факт.
SEP_H = 2.4
# Ламинарный отрыв по Твейтсу — там порог как раз строгий: λ = −0.09.
SEP_LAMBDA = -0.09


def _thwaites_closure(lam):
    """Корреляции Твейтса: формпараметр и трение по λ (Cebeci & Bradshaw)."""
    lam = np.asarray(lam, dtype=float)
    lo = lam < 0
    ell = np.where(lo,
                   0.22 + 1.402 * lam + 0.018 * lam / np.clip(lam + 0.107, 1e-9, None),
                   0.22 + 1.57 * lam - 1.8 * lam**2)
    h = np.where(lo,
                 2.088 + 0.0731 / np.clip(lam + 0.14, 1e-9, None),
                 2.61 - 3.75 * lam + 5.24 * lam**2)
    return ell, h


def thwaites(s, ue, nu):
    """Ламинарный слой в один проход, без итераций.

        θ²(s) = 0.45·ν/U_e⁶ · ∫₀ˢ U_e⁵ ds

    Формула замкнутая — в этом и прелесть метода: ни начального условия, ни
    марша. Возвращает (θ, H, cf, λ, i_sep), где i_sep — первый узел, в котором
    λ упал ниже −0.09, или None.
    """
    s = np.asarray(s, float)
    ue = np.asarray(ue, float)
    integ = np.concatenate(([0.0], np.cumsum(np.diff(s) * (ue[1:] ** 5 + ue[:-1] ** 5) / 2)))
    th2 = 0.45 * nu / np.clip(ue, 1e-9, None) ** 6 * integ
    th = np.sqrt(np.clip(th2, 0.0, None))
    duds = np.gradient(ue, s)
    lam = th2 / nu * duds
    ell, h = _thwaites_closure(lam)
    cf = 2 * ell * nu / np.clip(ue * th, 1e-12, None)
    bad = np.nonzero(lam < SEP_LAMBDA)[0]
    return th, h, cf, lam, (int(bad[0]) if bad.size else None)


def _h1_of_h(h):
    """Корреляция Хеда: H₁ по H."""
    return (3.3 + 0.8234 * (h - 1.1) ** -1.287 if h <= 1.6
            else 3.3 + 1.5501 * (h - 0.6778) ** -3.064)


def _h_of_h1(h1):
    """Она же наоборот. Ниже 3.3 обратной ветви нет — там слой уже оторвался."""
    if h1 <= 3.3:
        return 3.0
    return (0.6778 + 1.1538 * (h1 - 3.3) ** -0.326 if h1 < 5.3
            else 1.1 + 0.86 * (h1 - 3.3) ** -0.777)


def _cf_turb(h, re_th):
    """Трение по Людвигу—Тильману."""
    return 0.246 * 10 ** (-0.678 * h) * np.clip(re_th, 1.0, None) ** -0.268


def head(s, ue, nu, theta0, h0=1.4):
    """Турбулентный слой маршем по Хеду.

    Два уравнения вдоль поверхности: импульса и вовлечения.

        dθ/ds  = cf/2 − (H + 2)·(θ/U)·dU/ds
        d(U·θ·H₁)/ds = U·E(H₁),   E = 0.0306·(H₁ − 3)^(−0.6169)

    Интегрируются явно по той же сетке, что пришла из невязкого расчёта:
    у неё сгущение к передней кромке, а там как раз всё и происходит.
    Марш останавливается на отрыве — дальше прямая постановка не имеет решения,
    и продолжать её значит получать числа, за которыми ничего нет.
    """
    s = np.asarray(s, float)
    ue = np.asarray(ue, float)
    duds = np.gradient(ue, s)
    n = s.size
    th = np.full(n, np.nan)
    hh = np.full(n, np.nan)
    cf = np.full(n, np.nan)
    th[0], hh[0] = theta0, h0
    h1 = _h1_of_h(h0)
    i_sep = None
    for i in range(n - 1):
        ds = s[i + 1] - s[i]
        u = max(ue[i], 1e-9)
        cf[i] = _cf_turb(hh[i], u * th[i] / nu)
        dth = cf[i] / 2 - (hh[i] + 2) * th[i] / u * duds[i]
        # d(U θ H₁)/ds = U·E  →  H₁ вперёд через произведение, чтобы не делить
        # на маленькие величины в разгоне.
        prod = u * th[i] * h1
        prod_next = prod + ds * u * 0.0306 * max(h1 - 3.0, 1e-6) ** -0.6169
        th[i + 1] = max(th[i] + ds * dth, 1e-12)
        u_next = max(ue[i + 1], 1e-9)
        h1 = max(prod_next / (u_next * th[i + 1]), 3.0 + 1e-9)
        hh[i + 1] = _h_of_h1(h1)
        if hh[i + 1] >= SEP_H:
            i_sep = i + 1
            break
    cf[n - 1] = _cf_turb(hh[n - 1], max(ue[n - 1], 1e-9) * th[n - 1] / nu) \
        if np.isfinite(th[n - 1]) else np.nan
    return th, hh, cf, i_sep


def march(s, ue, nu, s_tr=0.05, s_start=0.0):
    """Слой по всей стороне: Твейтс до перехода, дальше Хед.

    `s_tr` — положение перехода, `s_start` — откуда вообще начинать. Оба не
    вычисляются, а задаются, и это главное допущение здесь.

    Почему переход задан. На гладком крыле его считают по числу Рейнольдса и
    росту возмущений; на парусе считать нечего — ткань шершавая, по ней идут
    шов и карман латы, и слой сбивается в турбулентный сразу за передней
    шкаториной. Задать его ранним честнее, чем считать по критерию, выведенному
    для полированного профиля.

    Почему марш начинают не от кромки. У тонкого сечения на передней кромке
    особенность: U_e растёт как 1/√x, и интеграл Твейтса от нуля расходится. У
    настоящего паруса в этом же месте сидит короткий пузырь отрыва — кромка
    острая, поток заворачивает за неё и садится обратно. Так что начинать надо
    за пузырём, и `s_start` — это его длина (`Section.le_invalid_x` даёт
    оценку сверху).

    Возвращает словарь: точка отрыва (доля дуги, None если не оторвался),
    θ и H на задней кромке, и сами распределения.
    """
    s = np.asarray(s, float)
    ue = np.asarray(ue, float)
    i0 = int(np.searchsorted(s, s_start))
    i0 = min(i0, s.size - 3)
    itr = max(int(np.searchsorted(s, s_tr)), i0 + 2)
    itr = min(itr, s.size - 2)

    th_l, h_l, cf_l, lam, sep_l = thwaites(s[i0:itr + 1] - s[i0], ue[i0:itr + 1], nu)
    if sep_l is not None:
        # Ламинарный отрыв до заданного перехода — это и есть пузырь: слой
        # отрывается, но на шершавой ткани тут же садится обратно уже
        # турбулентным. Переход переносится в точку отрыва, дальше идёт Хед.
        itr = i0 + sep_l
        th_l, h_l, cf_l, lam, _ = thwaites(s[i0:itr + 1] - s[i0], ue[i0:itr + 1], nu)

    th_t, h_t, cf_t, sep_t = head(s[itr:], ue[itr:], nu, theta0=th_l[-1], h0=1.4)

    th = np.concatenate((np.full(i0, np.nan), th_l, th_t[1:]))
    hh = np.concatenate((np.full(i0, np.nan), h_l, h_t[1:]))
    cf = np.concatenate((np.full(i0, np.nan), cf_l, cf_t[1:]))
    i_sep = None if sep_t is None else itr + sep_t
    tail = i_sep if i_sep is not None else s.size - 1
    return {
        "s_sep": None if i_sep is None else float(s[i_sep]),
        "i_sep": i_sep,
        "i_tr": itr,
        "theta_te": float(th[tail]),
        "h_te": float(hh[tail]),
        "ue_te": float(ue[tail]),
        "theta": th, "h": hh, "cf": cf,
    }


def squire_young(theta_te, ue_te, h_te):
    """Сопротивление стороны по формуле Сквайра—Янга.

        Cd = 2·θ_кромки·(U_кромки/U∞)^((H + 5)/2)

    Смысл в том, что толщина потери импульса далеко в следе связана с толщиной
    на кромке через то, как там восстанавливается давление, а сопротивление —
    это она и есть. Считать след при этом не нужно.
    """
    return 2.0 * theta_te * max(ue_te, 1e-9) ** ((h_te + 5.0) / 2.0)
