# -*- coding: utf-8 -*-
"""Панельный метод по замкнутому обводу: источники плюс вихрь (Хесс—Смит).

Зачем понадобился, если тонкая пелена уже есть. Пелена (`section.py`) считает
подъёмную силу точно и дёшево, но на передней кромке у неё особенность: скорость
растёт как 1/√x, и полоса, в которой ею нельзя пользоваться, расширяется с углом
атаки — два процента хорды на восьми градусах, десять на шестнадцати. Марш
пограничного слоя приходится начинать за этой полосой, то есть выбрасывать ровно
ту область, где на большом угле и решается срыв, и выбрасывать тем больше, чем
больше угол. Замерено: на пузе 10% при Re = 10⁶ задняя кромка ведёт себя
правильно, а срыва нет и на двадцати градусах.

Здесь особенности нет вовсе. Сечению даётся носик: поверх средней линии кладётся
тонкая симметричная толщина с закруглённой передней кромкой, обвод замыкается, и
скорость на нём всюду конечна. Тогда пограничный слой маршируется от самой точки
торможения по обеим сторонам, и срыв получается сам — когда пик разрежения у
кромки перестаёт восстанавливаться.

Носик у паруса и физически есть: у стакселя это ликтрос в фаловом кармане, у
грота — мачта, которая на хорде в полтора метра даёт куда больше процента. Так
что толщина здесь не математическая уловка, а недостающая часть формы. Величина
её — параметр, и в таблице поляр она будет осью наравне с пузом.

Метод классический (Hess & Smith, изложение Морана): на каждой панели свой
источник постоянной силы, и один общий вихрь на весь обвод. Неизвестных N+1,
уравнений столько же: непротекание в серединах панелей и условие Кутты на
задней кромке. Метод старый, хорошо обусловленный и, главное, поверяемый точно —
на цилиндре, где ответ выписывается рукой.
"""

import numpy as np

__all__ = ["naca_thickness", "luff_thickness", "milgram_thickness", "sail_contour",
           "cylinder_contour", "Panels"]


def naca_thickness(x, t):
    """Толщина по NACA-4 с сомкнутой задней кромкой.

    Носик здесь и берётся: член с √x даёт закруглённую кромку с радиусом
    1.1019·t² в долях хорды. Последний коэффициент взят −0.1036, а не −0.1015,
    чтобы толщина на задней кромке была ровно нулевой: обвод обязан замкнуться,
    иначе условие Кутты ставить не на что.
    """
    x = np.clip(np.asarray(x, float), 0.0, 1.0)
    return 5 * t * (0.2969 * np.sqrt(x) - 0.1260 * x - 0.3516 * x**2
                    + 0.2843 * x**3 - 0.1036 * x**4)


def luff_thickness(x, t, nose=None):
    """Толщина паруса: круглый носок и сходящее на нет полотно.

    Форму NACA сюда брать нельзя, и это выяснилось замером. У неё радиус носка
    равен 1.1019·t², то есть при толщине в два процента хорды — четыре десятых
    ТЫСЯЧНОЙ. Такой носок остаётся, по сути, лезвием: пик разрежения на восьми
    градусах выходит 9.5 набегающей, на двадцати — 23, слой рвёт сразу за
    носком, и парус выходит сорванным с двух градусов.

    У настоящего паруса передняя кромка тупая по сравнению со своей толщиной. У
    грота это мачта: семьдесят восемь миллиметров на хорде в полтора-три метра,
    то есть радиус в два-три процента хорды. У стакселя — ликтрос в кармане или
    профиль штага. Поэтому носок здесь эллиптический с полуосями (nose, t/2), и
    по умолчанию круглый: радиус t/2 против t²·1.1 у NACA — при t = 3% это
    шестьдесят раз разницы.

    Дальше полотно сходит к задней кромке параболой, состыкованной с носком без
    излома: у обоих кусков в точке стыка касательная горизонтальна.
    """
    x = np.clip(np.asarray(x, float), 0.0, 1.0)
    h = t / 2.0
    a = h if nose is None else float(nose)
    fore = x <= a
    y = np.empty_like(x)
    y[fore] = h * np.sqrt(np.clip(1 - ((a - x[fore]) / a) ** 2, 0.0, None))
    y[~fore] = h * (1 - ((x[~fore] - a) / (1 - a)) ** 2)
    return y


def milgram_thickness(x, t=0.034, edge=0.0022):
    """Толщина опытных сечений Милгрэма (NASA CR-1767), слово в слово по отчёту.

    «Симметрична и по хорде, и по толщине, параболическое распределение с
    относительной толщиной 0.034 и отношением толщины кромки к хорде 0.0022.»
    Кромки СХОСТРЕНЫ: на носке остаётся сливер в одну десятую процента хорды.

    Нужна ровно для сверки с опубликованными данными — своей формой паруса это
    не является. У настоящего паруса носок тупой (мачта, ликтрос), у Милгрэма
    острый, и разница между ними видна во всём: у него поток оторван при любом
    угле, минимальное сопротивление 0.06 и срыва как события нет вовсе.

    Задняя кромка у Милгрэма тоже тупая, на те же 0.22% хорды, и обвод из-за
    этого не замыкается — а условие Кутты ставить некуда. Поэтому толщина
    сводится к нулю линейной поправкой по хорде: на носке она ничего не меняет
    (там всё и решается), в середине снимает одну десятую процента, на кромке
    замыкает обвод.
    """
    x = np.clip(np.asarray(x, float), 0.0, 1.0)
    return edge / 2 * (1 - x) + (t - edge) / 2 * 4 * x * (1 - x)


def sail_contour(f=0.10, p=0.5, t=0.03, n=200, nose=None, naca=False, thick=None):
    """Замкнутый обвод сечения паруса: средняя линия плюс толщина по нормали.

    Точки идут от задней кромки вперёд по наветренной стороне, огибают носок и
    возвращаются к задней кромке по подветренной. Сгущение косинусом — к обеим
    кромкам, потому что на носке всё решается, а на задней кромке ставится Кутта.
    """
    from .section import mean_line

    beta = np.linspace(0.0, np.pi, n // 2 + 1)
    xs = (1 - np.cos(beta)) / 2                     # от 0 до 1, гуще по краям
    z, dz = mean_line(xs, f, p)
    if thick is not None:
        yt = thick(xs)
    else:
        yt = naca_thickness(xs, t) if naca else luff_thickness(xs, t, nose)
    th = np.arctan(dz)
    # По нормали к средней линии, а не по вертикали: на пузе в 15% разница видна.
    xl, yl = xs + yt * np.sin(th), z - yt * np.cos(th)      # наветренная
    xu, yu = xs - yt * np.sin(th), z + yt * np.cos(th)      # подветренная
    x = np.concatenate((xl[::-1], xu[1:]))
    y = np.concatenate((yl[::-1], yu[1:]))
    return x, y


def cylinder_contour(n=200, r=0.5, cx=0.5, cy=0.0):
    """Окружность тем же обходом — эталон для батареи, а не часть расчёта."""
    a = np.linspace(0.0, 2 * np.pi, n + 1)
    return cx + r * np.cos(a), cy - r * np.sin(a)


class Panels:
    """Обвод, разбитый на панели: на каждой источник, на всех один вихрь.

    Хорда и набегающая скорость единичные; наружу идут безразмерные величины.
    """

    def __init__(self, x, y):
        self.x = np.asarray(x, float)
        self.y = np.asarray(y, float)
        if abs(self.x[0] - self.x[-1]) > 1e-12 or abs(self.y[0] - self.y[-1]) > 1e-12:
            raise ValueError("обвод не замкнут")
        dx = np.diff(self.x)
        dy = np.diff(self.y)
        self.n = dx.size
        self.ds = np.hypot(dx, dy)
        self.theta = np.arctan2(dy, dx)                  # наклон панели
        self.tx, self.ty = dx / self.ds, dy / self.ds    # касательная
        self.nx, self.ny = -self.ty, self.tx             # внешняя нормаль
        self.mx = self.x[:-1] + dx / 2                   # середины панелей
        self.my = self.y[:-1] + dy / 2
        self._solved = False

    def _influence(self, px, py, own=False):
        """Скорости от единичных источника и вихря каждой панели в точках (px, py).

        Возвращает (us, vs, uv, vv), каждая — матрица «точка × панель».
        Формулы стандартные: в своей системе координат панели источник даёт
        (ln(r_j/r_{j+1}), β)/2π, а вихрь — то же самое, повёрнутое на прямой угол.
        β — угол, под которым панель видна из точки; на самой панели он равен π,
        и это тот самый скачок, который и даёт непротекание.

        Собственная панель считается не формулой, а прямо: точка лежит НА
        отрезке, числитель под atan2 обращается в ноль, и знак этого нуля решает,
        выйдет π или −π. На цилиндре, где ответ известен, это давало ошибку в
        полторы скорости при любой разбивке — то есть половина панелей выходила
        с вывернутым источником. Поэтому при `own=True` диагональ ставится
        руками: β = π, логарифм ноль.
        """
        px = np.asarray(px, float)[:, None]
        py = np.asarray(py, float)[:, None]
        x1, y1 = self.x[:-1][None, :], self.y[:-1][None, :]
        x2, y2 = self.x[1:][None, :], self.y[1:][None, :]
        r1 = np.hypot(px - x1, py - y1)
        r2 = np.hypot(px - x2, py - y2)
        beta = np.arctan2((px - x1) * (py - y2) - (px - x2) * (py - y1),
                          (px - x1) * (px - x2) + (py - y1) * (py - y2))
        lg = np.log(np.clip(r1, 1e-300, None) / np.clip(r2, 1e-300, None))
        ct, st = np.cos(self.theta)[None, :], np.sin(self.theta)[None, :]
        k = 1.0 / (2 * np.pi)
        if own:
            d = np.arange(self.n)
            beta[d, d] = np.pi
            lg[d, d] = 0.0
        us = k * (lg * ct - beta * st)
        vs = k * (lg * st + beta * ct)
        uv = k * (beta * ct + lg * st)
        vv = k * (beta * st - lg * ct)
        return us, vs, uv, vv

    def solve(self, alpha):
        """Решить на угле атаки в радианах."""
        us, vs, uv, vv = self._influence(self.mx, self.my, own=True)
        n = self.n
        a = np.zeros((n + 1, n + 1))
        a[:n, :n] = us * self.nx[:, None] + vs * self.ny[:, None]
        a[:n, n] = np.sum(uv * self.nx[:, None] + vv * self.ny[:, None], axis=1)
        ux, uy = np.cos(alpha), np.sin(alpha)
        rhs = np.zeros(n + 1)
        rhs[:n] = -(ux * self.nx + uy * self.ny)
        # Кутта: касательная скорость на первой и последней панели равна по
        # величине и противоположна по направлению обхода. Обе панели лежат у
        # задней кромки по разные стороны от неё.
        f, l = 0, n - 1
        a[n, :n] = (us[f] * self.tx[f] + vs[f] * self.ty[f]
                    + us[l] * self.tx[l] + vs[l] * self.ty[l])
        a[n, n] = (np.sum(uv[f] * self.tx[f] + vv[f] * self.ty[f])
                   + np.sum(uv[l] * self.tx[l] + vv[l] * self.ty[l]))
        rhs[n] = -(ux * (self.tx[f] + self.tx[l]) + uy * (self.ty[f] + self.ty[l]))
        sol = np.linalg.solve(a, rhs)
        self.q, self.gamma = sol[:n], float(sol[n])
        # Свёртка по панелям берётся суммой, а не матричным произведением. На
        # Accelerate матричное произведение поднимает флаг деления на ноль при
        # полностью конечных входах и правильном ответе — проверено, все четыре
        # матрицы влияния конечны, а предупреждение всё равно есть. Гасить его
        # errstate значит гасить и настоящие; сумма по сотням панелей стоит
        # столько же, и молчит.
        qs = (us * self.q[None, :]).sum(axis=1)
        qv = (vs * self.q[None, :]).sum(axis=1)
        vt = (ux * self.tx + uy * self.ty
              + self.tx * qs + self.ty * qv
              + self.gamma * (self.tx * uv.sum(axis=1) + self.ty * vv.sum(axis=1)))
        self.vt = vt                     # касательная скорость в серединах
        self.cp = 1.0 - vt**2
        self.alpha = float(alpha)
        self._solved = True
        return self

    @property
    def cl(self):
        """Подъёмная сила по Жуковскому: Γ = γ·обвод, Cl = 2Γ (хорда единичная)."""
        self._need()
        return 2.0 * self.gamma * float(np.sum(self.ds))

    @property
    def cl_from_cp(self):
        """Она же интегрированием давления — независимая проверка самой себя."""
        self._need()
        cx = -float(np.sum(self.cp * self.nx * self.ds))
        cy = -float(np.sum(self.cp * self.ny * self.ds))
        return cy * np.cos(self.alpha) - cx * np.sin(self.alpha)

    def stagnation(self):
        """Номер панели, на которой касательная скорость меняет знак.

        Это и есть точка торможения — оттуда в обе стороны и пойдёт марш
        пограничного слоя. У тонкой пелены такой точки не было вовсе, и в этом
        всё дело.
        """
        self._need()
        sgn = np.sign(self.vt)
        turn = np.nonzero(np.diff(sgn) != 0)[0]
        if turn.size == 0:
            return self.n // 2
        # Ближайшая к носку смена знака: у задней кромки бывает своя, от
        # численного шума на сомкнутых панелях.
        nose = int(np.argmin(self.mx))
        return int(turn[np.argmin(np.abs(turn - nose))])

    def sides(self):
        """Разложить обвод на две стороны от точки торможения.

        Возвращает две пары (s, U) — длина дуги от точки торможения и модуль
        скорости вдоль неё, — готовые для марша слоя. Первая идёт по обходу
        назад (наветренная), вторая вперёд (подветренная).
        """
        self._need()
        i = self.stagnation()
        back = slice(i, None, -1)
        s_b = np.concatenate(([0.0], np.cumsum(self.ds[back][:-1])))
        s_f = np.concatenate(([0.0], np.cumsum(self.ds[i + 1:][:-1])))
        return (s_b, np.abs(self.vt[back])), (s_f, np.abs(self.vt[i + 1:]))

    def _need(self):
        if not self._solved:
            raise RuntimeError("обвод не решён: сначала solve(alpha)")
