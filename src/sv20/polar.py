# -*- coding: utf-8 -*-
"""Поляра сечения паруса: таблица, собранная из опытных данных.

Что это. Сетка (угол атаки × пузо) с коэффициентами подъёмной силы и
сопротивления, которую симулятор читает интерполяцией вместо назначенных формул
`sailCoeffs`. План — `docs/flow-plan.md`, Часть II.

Откуда числа. Опыт Уоллиса (ARL Aero Note 74, 1946; воспроизведён в «Axial Flow
Fans and Ducts», 1983, фиг. 6.22, 6.23, 6.28) на изогнутых пластинах постоянной
кривизны с пузом от нуля до десяти процентов. Это ровно рабочая область наших
полосок: замер даёт пузо 3.3…11.9% при медиане 7.5%.

Почему по опыту, а не расчётом. Расчёт пробовали, и он этот класс сечений не
берёт: у пластины поток частично оторван при любом угле, а прямой марш слоя за
отрывом решения не имеет. Совместный вязко-невязкий расчёт (`coupled.py`) снимает
около восьми процентов недобора подъёмной силы, а опыт теряет от шестнадцати до
тридцати трёх, и разница растёт с пузом. Подробности — в `tests/coupled.test.py`.

Что где измерено, а что достроено, — здесь важнее самих чисел:

  * пузо 4, 6, 8% при α от −4 до 12°   ИЗМЕРЕНО целиком (фиг. 6.23, Re = 6·10⁵);
  * пузо 0, 2, 3, 10%                  измерены только ВЕРШИНЫ (фиг. 6.22): сама
                                       кривая на той фигуре тонет в соседних, и
                                       снять её на глаз нельзя. Линейный участок
                                       достроен по измеренному наклону и
                                       измеренной вершине;
  * сопротивление                      минимум и его положение измерены,
                                       кривизна снята с фиг. 6.28 по одной
                                       кривой (4%), остальное — та же кривизна;
  * за срывом и ниже нулевой подъёмной силы — НЕ измерено вовсе, там переход к
    плоской пластине, как и раньше.

Достроенное проверяется тем же опытом: там, где кривая измерена целиком, правило
обязано её воспроизвести. Расхождение печатает батарея.
"""

import json
import math
import os

# numpy здесь НЕТ намеренно. Пакет физики собирается голым python3 (см. Makefile),
# и ни один модуль, который в эту сборку входит, numpy не требует — а этот входит.
# Считать тут нечего: две интерполяции и парабола.

__all__ = ["CL_SLOPE", "build_table", "REF_PATH", "MREF_PATH"]

REF_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "..", "..", "data", "section", "wallis_arl74.json")

# Второй опыт: Милгрэм, NASA CR-1767 (1971) — острые тонкие сечения с пузом 12 и
# 18%, измеренные до ±24°. Уоллис кончается на десяти процентах пуза и
# пятнадцати градусах; всё, что выше и дальше, раньше было экстраполяцией и
# пластиной, а теперь измерено.
MREF_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "..", "..", "data", "section", "milgram_cr1767.json")

# Ряды таблицы, которые берутся из Милгрэма, и их ключи в файле данных.
MILGRAM_ROWS = {0.12: "65-12", 0.18: "65-18"}

# Наклон кривой подъёмной силы ВЫШЕ нуля градусов, 1/градус. Снят с измеренных
# кривых 4, 6 и 8%: у всех трёх он один и тот же с точностью до сотой доли —
# 0.0925, 0.0925, 0.096. Это 5.4 на радиан против 2π у теории тонкого профиля:
# пластина теряет пятнадцать процентов наклона на вязкость, и теряет одинаково
# при любом пузе.
CL_SLOPE = 0.094

# Подъёмная сила НА НУЛЕ градусов, по пузу. Тоже измерена, и без неё ничего не
# сходится: кривая между углом нулевой подъёмной силы и нулём идёт втрое круче,
# чем выше нуля. Прямая от α₀ с обычным наклоном давала бы на восьми градусах 1.08
# вместо измеренных 1.45. Это не изъян данных, а то самое, о чём пишут оба отчёта:
# ниже идеального угла отрывается наветренная сторона, и там наклон превышает 2π,
# а выше — не дотягивает.
CL0_CAMBER = (0.0, 0.04, 0.06, 0.08)
CL0 = (0.0, 0.42, 0.55, 0.68)

# Сопротивление. Минимум измерен и от пуза почти не зависит (текст книги: «около
# 0.017 для всех пуз до 8%»), лежит около двух градусов. Кривизна снята с кривой
# 4% на фиг. 6.28: от минимума 0.018 при 2° до 0.038 при 8°, то есть 5.6e-4 на
# квадрат градуса; для ровного счёта взято 6e-4.
CD_MIN = 0.018
CD_ALPHA_MIN = 2.0
CD_CURV = 6.0e-4

# За срывом сечение работает как плоская пластина, и это не измерено, а принято —
# ровно как было в `sailCoeffs` до всякой таблицы. Ширина перехода в градусах.
BLEND_DEG = 12.0


def _flat_plate(a_deg):
    """Плоская пластина за срывом: Cl = 2·sinα·cosα, Cd = 1.2·sin²α + 0.08."""
    a = math.radians(a_deg)
    return 2 * math.sin(a) * math.cos(a), 1.2 * math.sin(a) ** 2 + 0.08


def _measured(ref, cam):
    """Измеренная кривая для этого пуза, если она есть целиком."""
    key = "%.2f" % cam
    row = ref["Re6e5"]["пузо"].get(key)
    if row is None:
        return None
    pairs = [(float(a), float(c)) for a, c in zip(ref["Re6e5"]["alpha_deg"], row)
             if c is not None]
    return [p[0] for p in pairs], [p[1] for p in pairs]


def _lin(x, xs, ys):
    """Линейная интерполяция с ЛИНЕЙНЫМ же продолжением за краем.

    Обычный np.interp за краем держит константу, и таблица на пузе 12% выходила
    точной копией десятипроцентной. Наши полоски доходят до 11.9%, так что край
    надо продолжать, а не упирать в него.
    """
    x = float(x)
    if x <= xs[0]:
        k = (ys[1] - ys[0]) / (xs[1] - xs[0])
        return float(ys[0] + k * (x - xs[0]))
    if x >= xs[-1]:
        k = (ys[-1] - ys[-2]) / (xs[-1] - xs[-2])
        return float(ys[-1] + k * (x - xs[-1]))
    for i in range(1, len(xs)):
        if x <= xs[i]:
            t = (x - xs[i - 1]) / (xs[i] - xs[i - 1])
            return float(ys[i - 1] + t * (ys[i] - ys[i - 1]))
    return float(ys[-1])


def _hold(x, xs, ys):
    """Интерполяция, ДЕРЖАЩАЯ крайнее значение за краем — как np.interp.

    Именно так и должны вести себя измеренные кривые ниже своего края: у
    пластины там полка, а не продолжение прямой вниз. Оба опыта показывают одно
    и то же — на отрицательных углах сечение держит остаточную подъёмную силу от
    пуза, потому что наветренная сторона оторвана.
    """
    if x <= xs[0]:
        return float(ys[0])
    if x >= xs[-1]:
        return float(ys[-1])
    for i in range(1, len(xs)):
        if x <= xs[i]:
            t = (x - xs[i - 1]) / (xs[i] - xs[i - 1])
            return float(ys[i - 1] + t * (ys[i] - ys[i - 1]))
    return float(ys[-1])


def _peak(ref, cam):
    """Измеренная вершина: (Cl_max, угол) с интерполяцией по пузу между опытными."""
    cams = ref["Re3e5_максимумы"]["пузо"]
    return (_lin(cam, cams, ref["Re3e5_максимумы"]["cl_max"]),
            _lin(cam, cams, ref["Re3e5_максимумы"]["alpha_max"]))


# Угол нулевой подъёмной силы, градусы. Снят с измеренных кривых по пересечению
# нуля, а при нулевом пузе взят точным нулём — там он следует из симметрии, и
# мерить его незачем. Числа сами по себе примечательны: от четырёх до восьми
# процентов пуза угол почти не меняется, хотя теория тонкого профиля требовала бы
# −4.6, −6.9 и −9.2 градуса. Причина та же, что и во всём остальном: на
# отрицательном угле наветренная сторона отрывается, и подъёмная сила падает к
# нулю раньше, чем велит теория.
A0_CAMBER = (0.0, 0.04, 0.06, 0.08)
A0_DEG = (0.0, -3.12, -3.35, -3.60)


def _alpha0(cam):
    """Угол нулевой подъёмной силы для этого пуза."""
    return _lin(cam, A0_CAMBER, A0_DEG)


def cl_curve(ref, cam, a_deg):
    """Подъёмная сила по углу для одного пуза.

    Там, где кривая измерена, берётся она. Где измерена только вершина —
    достраивается: прямая с измеренным наклоном, проведённая через вершину назад,
    и скругление у самой вершины. За вершиной и ниже нулевой подъёмной силы —
    переход к плоской пластине.
    """
    cl_max, a_max = _peak(ref, cam)
    m = _measured(ref, cam)
    if m is not None:
        am, cm = m
        out = [_hold(v, am, cm) for v in a_deg]        # внутри измеренного
        lo, hi = am[0], am[-1]
    else:
        # Кривая складывается из четырёх ИЗМЕРЕННЫХ величин и ни одной
        # подобранной: угол нулевой подъёмной силы, подъёмная сила на нуле
        # градусов, наклон выше нуля и вершина. Ниже нуля — прямая от α₀ к этой
        # точке, выше — обычный наклон до вершины. Проверка правила там, где
        # кривая измерена целиком: оно обязано её воспроизвести, и батарея это
        # проверяет.
        a0 = _alpha0(cam)
        cl0 = _lin(cam, CL0_CAMBER, CL0)
        steep = cl0 / max(-a0, 1e-6)
        # Ниже угла нулевой подъёмной силы крутой участок обрывается и дальше
        # идёт полка — так ведут себя ИЗМЕРЕННЫЕ кривые, и достроенные обязаны
        # вести себя так же, иначе таблица теряет монотонность по пузу: при
        # −8 градусах достроенная двухпроцентная уходила ниже измеренной
        # четырёхпроцентной.
        lo, hi = a0 - 1.0, a_max
        out = []
        for v in a_deg:
            aa = max(v, lo)
            out.append(min(cl0 + (CL_SLOPE if aa >= 0.0 else steep) * aa, cl_max))
    # Вершиной обрезается ТОЛЬКО достроенная кривая. Измеренную обрезать нечем:
    # вершины сняты с фиг. 6.22 при Re = 3·10⁵, а кривые — с фиг. 6.23 при
    # 6·10⁵, и на большем числе Рейнольдса сечение вывозит чуть больше. У пуза
    # 4% измеренная кривая доходит до 1.25, а вершина с другой фигуры — 1.23;
    # обрезать первое вторым значило бы испортить измеренное ради согласования
    # двух разных опытов.
    # Ниже измеренного кривая НЕ продолжается прямой вниз: у пластины там полка.
    # Оба опыта показывают одно — на отрицательных углах сечение держит остаточную
    # подъёмную силу от пуза вместо теоретического минуса, потому что наветренная
    # сторона оторвана. np.interp за краем как раз держит крайнее значение, и это
    # ровно то, что нужно; дальше идёт переход к пластине.
    # За измеренным — переход к пластине. Ширина перехода принята, не измерена.
    res = []
    for v, o in zip(a_deg, out):
        fl_cl, _ = _flat_plate(v)
        w = min(1.0, max(0.0, (v - hi) / BLEND_DEG))
        o = o * (1 - w) + fl_cl * w
        w = min(1.0, max(0.0, (lo - v) / BLEND_DEG))
        res.append(o * (1 - w) + fl_cl * w)
    return res


def _smooth(t):
    """Гладкая ступень 0…1 без изломов на краях."""
    t = min(1.0, max(0.0, t))
    return t * t * (3.0 - 2.0 * t)


def _deep_cl(a_e, cl_e, a):
    """Подъёмная сила за измеренным краем: продолжение нормальной силой.

    За срывом сила перпендикулярна хорде. Её величина N берётся с измеренного
    края (N = Cl/cos α там) и плавно уступает пластине к девяноста градусам.
    Конструкция проверена CFD-зондом собственного сечения генакера
    (docs/cfd-validation.md, §13.12–13.13): N(24°) = 2.42/cos 24° = 2.65 даёт
    Cl(35°) = 2.07 против расчётных 2.17 ± 0.25. Точка 45° зонда (2.88)
    свидетелем не взята: за касательной носка (4·пузо ≈ 42°) сечение —
    плохообтекаемое тело, и 2D URANS с когерентным сходом там завышает, ровно
    как завысил плоскую пластину (1.54 при 35° против классических ~1.0).
    """
    n = cl_e / math.cos(math.radians(a_e))
    s = _smooth((a - a_e) / (90.0 - a_e))
    fl_cl, _ = _flat_plate(a)
    return n * math.cos(math.radians(a)) * (1.0 - s) + fl_cl * s


def _deep_cd(a_e, cl_e, cd_e, a):
    """Сопротивление за измеренным краем — той же нормальной силой.

    На краю у сечения ещё есть подсос на носке: измеренное Cd меньше, чем
    N·sin α. Этот недостаток вычитается и затухает вместе с весом N, поэтому на
    самом краю продолжение сшито с измеренным точно, а к пластине уходит без
    ступеньки. Даёт Cd(35°, пузо 18%) ≈ 1.16 — внутри честной вилки между
    продолжением Милгрэма и CFD-зондом (1.54), который по присоединённому
    свидетелю NACA сопротивление завышает.
    """
    n = cl_e / math.cos(math.radians(a_e))
    deficit = n * math.sin(math.radians(a_e)) - cd_e
    s = _smooth((a - a_e) / (90.0 - a_e))
    _, fl_cd = _flat_plate(a)
    return (n * math.sin(math.radians(a)) - deficit) * (1.0 - s) + fl_cd * s


def milgram_cl_curve(mref, cam, a_deg):
    """Подъёмная сила ряда, измеренного Милгрэмом, с продолжением за краем.

    Внутри ±24° — измеренная кривая. Ниже края — полка и переход к пластине,
    как у рядов Уоллиса. Выше края — продолжение нормальной силой `_deep_cl`.
    """
    sec = mref[MILGRAM_ROWS[cam]]
    am = [float(v) for v in sec["alpha_deg"]]
    cm = [float(v) for v in sec["cl"]]
    lo, hi = am[0], am[-1]
    res = []
    for v in a_deg:
        if v > hi:
            res.append(_deep_cl(hi, cm[-1], v))
            continue
        o = _hold(v, am, cm)
        fl_cl, _ = _flat_plate(v)
        w = min(1.0, max(0.0, (lo - v) / BLEND_DEG))
        res.append(o * (1 - w) + fl_cl * w)
    return res


# Минимальное сопротивление острых тонких сечений по Милгрэму — заявлено текстом
# отчёта («The ever present flow separation…»). У Уоллиса на гладкой пластине
# 0.017: разница — не пузо, а острые кромки и вечно оторванный носок.
MILGRAM_CD_MIN = 0.06


def milgram_cd_curve(mref, cam, a_deg):
    """Сопротивление ряда Милгрэма.

    Измерено оно только у пуза 12% (фиг. 6b). Для 18% берётся та же кривая,
    поднятая к заявленному минимуму 0.06, — ближайшее измеренное соседство, а
    не расчёт; продолжение за краем при этом идёт от СОБСТВЕННОЙ подъёмной
    силы ряда, так что за срывом ряды расходятся как им положено.
    """
    base = mref[MILGRAM_ROWS[0.12]]
    am = [float(v) for v in base["alpha_deg"]]
    dm = [float(v) for v in base["cd"]]
    shift = MILGRAM_CD_MIN - min(dm) if cam != 0.12 else 0.0
    sec = mref[MILGRAM_ROWS[cam]]
    cl_am = [float(v) for v in sec["alpha_deg"]]
    cl_cm = [float(v) for v in sec["cl"]]
    lo, hi = am[0], am[-1]
    cd_e = _hold(hi, am, dm) + shift
    res = []
    for v in a_deg:
        if v > hi:
            res.append(_deep_cd(hi, cl_cm[-1], cd_e, v))
            continue
        o = _hold(v, am, dm) + shift
        _, fl_cd = _flat_plate(v)
        w = min(1.0, max(0.0, (lo - v) / BLEND_DEG))
        res.append(o * (1 - w) + fl_cd * w)
    return res


def cd_curve(ref, cam, a_deg):
    """Сопротивление по углу: измеренная парабола, за срывом — пластина."""
    _, a_max = _peak(ref, cam)
    res = []
    for v in a_deg:
        cd = CD_MIN + CD_CURV * (v - CD_ALPHA_MIN) ** 2
        _, fl_cd = _flat_plate(v)
        w = min(1.0, max(0.0, (abs(v - CD_ALPHA_MIN) - (a_max - CD_ALPHA_MIN)) / BLEND_DEG))
        # За переходом остаётся ТОЛЬКО пластина. Прежде здесь стоял максимум из
        # двух, и парабола, годная на рабочих углах, выигрывала у пластины на
        # больших: на девяноста градусах выходило 4.66 вместо 1.28, то есть парус
        # поперёк потока тормозил вчетверо сильнее, чем может. Парабола описывает
        # прилипший поток и за своим диапазоном не значит ничего.
        res.append(cd * (1 - w) + fl_cd * w)
    return res


def alpha_axis():
    """Сетка по углу: густо там, где работает парус, редко на остальном круге.

    Круг нужен ЦЕЛИКОМ, и это выяснилось не сразу. Сперва таблица кончалась на
    сорока градусах — с запасом против замеренных 37° у полосок на ходу. Но в
    чистый фордевинд полоска видит и девяносто, и больше, а таблица за краем
    держит крайнее значение: сопротивление замирало на 0.58 вместо 1.28, и парус
    переставал работать парашютом. Ошибка вылезла на батарее, которая проверяет,
    что в фордевинд быстрее идёт сорванный парус.

    От тридцати градусов и дальше это уже не поляра сечения, а плоская пластина,
    и мельчить там незачем: шаг пять градусов.
    """
    fine = [v for v in range(-30, 31)]
    coarse_lo = [v for v in range(-180, -30, 5)]
    coarse_hi = [v for v in range(35, 181, 5)]
    return [float(v) for v in coarse_lo + fine + coarse_hi]


def build_table(ref=None, mref=None,
                cambers=(0.0, 0.02, 0.04, 0.06, 0.08, 0.10, 0.12, 0.18),
                a_from=None, a_to=None, step=None):
    """Собрать таблицу. Возвращает словарь, готовый для пакета.

    Ряды до десяти процентов пуза — Уоллис (как и было). Ряды 12 и 18% раньше
    экстраполировались из Уоллиса, а теперь берутся из измеренного Милгрэма
    вместе с продолжением за срывом: это верхняя половина таблицы, которой
    живёт генакер (пузо 18.5%) и глубоко выбранные полоски грота.
    """
    if ref is None:
        with open(REF_PATH, encoding="utf-8") as fh:
            ref = json.load(fh)
    if mref is None:
        with open(MREF_PATH, encoding="utf-8") as fh:
            mref = json.load(fh)
    a = alpha_axis()
    cl = [milgram_cl_curve(mref, c, a) if c in MILGRAM_ROWS
          else cl_curve(ref, c, a) for c in cambers]
    cd = [milgram_cd_curve(mref, c, a) if c in MILGRAM_ROWS
          else cd_curve(ref, c, a) for c in cambers]
    # Монотонность по пузу навязывается ТОЛЬКО достроенным рядам, и это урок,
    # купленный измерением. Прежняя версия поднимала любой ряд до соседнего
    # снизу — и подняла измеренный ноль градусов у пуза 18% с 0.8 до 1.0,
    # потому что 12% там везёт больше. Инверсия настоящая: глубокое пузо на
    # малом угле далеко ниже своего идеального угла, наветренная сторона
    # оторвана, и сечение везёт МЕНЬШЕ умеренного — Милгрэм это измерил, а
    # «пузатее — значит больше» оказалось верным только выше пары градусов.
    # Измеренное вообще не трогается — ни кривые, ни ряды с измеренной
    # вершиной: у стыка опытов (вершина Уоллиса 1.75 на пузе 10% при Re 3·10⁵
    # против кривой Милгрэма 1.68 на 12% при 9·10⁵) таблица честно несёт
    # небольшую инверсию, и подавлять её значило бы молча выбрать, который из
    # двух опытов врёт. Зажимаются снизу только достроенные ряды — швы, ради
    # которых навязывание и появилось, это и были места, где достройка
    # вылезала за измеренное.
    fully = set(MILGRAM_ROWS) | {0.04, 0.06, 0.08}
    for k in range(1, len(cl)):
        if cambers[k] not in fully:
            cl[k] = [max(v, w) for v, w in zip(cl[k], cl[k - 1])]
    return {
        "источник": "Wallis, ARL Aero Note 74 (1946), фиг. 6.22/6.23/6.28 книги 1983 г.; "
                    "Milgram, NASA CR-1767 (1971), фиг. 6a/6b/8a — пузо 12 и 18%",
        "измерено_целиком": [0.04, 0.06, 0.08, 0.12, 0.18],
        "измерены_вершины": [0.0, 0.02, 0.03, 0.04, 0.06, 0.08, 0.10],
        # У рядов Милгрэма угла срыва НЕТ: «a sharp stall is not observed» —
        # цитата из самого отчёта. Пик Cl у них лежит на 18…24°, но это не
        # срыв, а пологий максимум вечно подорванного сечения, и читать его
        # как угол срыва (например, для порога отрыва задней шкаторины)
        # — категориальная ошибка. Потребители угла срыва обязаны считать
        # его только по рядам с острым срывом.
        "мягкий_срыв": sorted(MILGRAM_ROWS),
        "наклон_на_градус": CL_SLOPE,
        "cd_min": CD_MIN,
        "camber": list(cambers),
        "alpha_deg": [round(v, 3) for v in a],
        "cl": [[round(v, 5) for v in row] for row in cl],
        "cd": [[round(v, 5) for v in row] for row in cd],
    }
