# -*- coding: utf-8 -*-
"""Двумерное сечение паруса: невязкий расчёт по тонкой вихревой пелене.

Зачем это здесь. В симуляторе коэффициенты сечения назначены: `sailCoeffs` в
`sim/aero.js` держит подъёмную силу линейной до тринадцати градусов, а дальше
переводит её к плоской пластине. Тринадцать градусов — это выбранное число, и
всё, что от него зависит (угол срыва, полоса отрыва, порог колдунчика на задней
шкаторине), назначено вместе с ним. Здесь готовится замена: поляра сечения,
посчитанная заранее и уложенная в пакет, откуда симулятор берёт её
интерполяцией. План — `docs/flow-plan.md`, Часть II.

Почему тонкая пелена, а не замкнутый контур. Парус — мембрана: толщины у него
нет вовсе, и панельный метод по замкнутому обводу для него не определён.
Классический ответ для таких сечений — теория тонкого профиля: вихревая пелена
кладётся на саму среднюю линию, а скорости на двух сторонах получаются из
скачка поперёк неё. Это не упрощение ради удобства, а то, что парус и есть.

Дискретизация — элемент с сосредоточенным вихрем (Katz & Plotkin, гл. 11):
вихрь в четверти панели, контрольная точка в трёх четвертях. Выбор не
произволен: именно при таком размещении одна-единственная панель даёт для
плоской пластины ТОЧНЫЙ ответ, а не приближение к нему. Условие Кутты при этом
выполняется само — за задней кромкой вихрей нет.

Линеаризации по углу и по пузу здесь НЕТ, и это не мелочь. Вихри садятся на
саму искривлённую среднюю линию, нормали берутся настоящие, набегающий поток
входит своими косинусами. Поэтому плоская пластина даёт 2π·sin α, а не 2π·α, а
угол нулевой подъёмной силы у пуза в 10% расходится с глауэртовым −2f/c на
восьмую долю градуса — и расходится правильно: при таком пузе передняя кромка
наклонена к хорде на тридцать градусов, а вся линейная теория выведена в
предположении, что наклоны малы.

Расчёт невязкий. Вязкая поправка (пограничный слой, точка отрыва, потеря
подъёмной силы за отрывом) — следующим заходом; сюда она придёт через
распределение скорости `surface_speed`, ради которого половина этого модуля и
написана.
"""

import numpy as np

__all__ = ["mean_line", "Section", "zero_lift_angle_exact", "ideal_angle",
           "cl_converged"]


def mean_line(x, f, p):
    """Средняя линия и её наклон в долях хорды: две параболы, сшитые в максимуме.

    Форма взята у NACA-4 не из почтения к традиции, а потому, что она задаётся
    ровно теми двумя числами, которые есть у полоски паруса: величиной пуза `f`
    и его положением по хорде `p`. При p = 0.5 это обычная парабола, то есть
    круговая дуга в пределе малого пуза.
    """
    x = np.asarray(x, dtype=float)
    if not 0.0 < p < 1.0:
        raise ValueError("положение пуза должно лежать строго внутри хорды")
    fore = x <= p
    z = np.empty_like(x)
    dz = np.empty_like(x)
    if f == 0.0:
        return np.zeros_like(x), np.zeros_like(x)
    z[fore] = f / p**2 * (2 * p * x[fore] - x[fore] ** 2)
    z[~fore] = f / (1 - p) ** 2 * ((1 - 2 * p) + 2 * p * x[~fore] - x[~fore] ** 2)
    dz[fore] = 2 * f / p**2 * (p - x[fore])
    dz[~fore] = 2 * f / (1 - p) ** 2 * (p - x[~fore])
    return z, dz


def zero_lift_angle_exact(f, p, n=4001):
    """Угол нулевой подъёмной силы по Глауэрту — эталон, а не расчёт.

    α₀ = −(1/π)·∫₀^π (dz/dx)·(cos θ − 1) dθ,  x = (1 − cos θ)/2

    Интеграл берётся численно по той же средней линии, но никакого отношения к
    решателю не имеет: это независимый ответ теории тонкого профиля, с которым
    решатель и сверяется в батарее. Проверять решатель им же самим смысла нет.
    """
    th = np.linspace(0.0, np.pi, n)
    x = (1 - np.cos(th)) / 2
    _, dz = mean_line(x, f, p)
    return -np.trapezoid(dz * (np.cos(th) - 1), th) / np.pi


def ideal_angle(f, p, n=4001):
    """Угол атаки, на котором особенность передней кромки пропадает.

        α_ид = (1/π)·∫₀^π (dz/dx) dθ,   x = (1 − cos θ)/2

    По Глауэрту это условие A₀ = 0: поток входит на кромку по касательной к
    средней линии, и вместо бесконечности в γ получается конечная величина. У
    параболической средней линии (пузо посередине) интеграл равен нулю при любом
    пузе, то есть идеальный угол ровно нулевой; стоит сдвинуть пузо — и он
    сдвигается тоже.

    Для паруса это не отвлечённость, а то самое положение, при котором передняя
    шкаторина не заполаскивает и не «пережата»: угол входа совпал с наклоном
    полотна у кромки.

    Условие ЛИНЕАРИЗОВАННОЕ, и решателю оно родным не приходится. Замерено: при
    пузе посередине (p = 0.5) особенность на этом угле пропадает начисто — γ на
    первой панели перестаёт зависеть от числа панелей (−0.366 при ста, −0.375
    при восьмистах). Стоит сдвинуть пузо к носу или к корме — и особенность
    остаётся, только слабеет раз в двадцать пять против угла в пяти градусах от
    идеального. Причина в том, что у сшитой из двух парабол линии кривизна в
    точке сшивки терпит разрыв, а глауэртово условие про это ничего не знает.

    Поэтому пользоваться этим числом можно как ориентиром («парус поставлен») и
    нельзя как гарантией, что пузыря у кромки нет.
    """
    th = np.linspace(0.0, np.pi, n)
    x = (1 - np.cos(th)) / 2
    _, dz = mean_line(x, f, p)
    return np.trapezoid(dz, th) / np.pi


class Section:
    """Сечение с заданной средней линией, решённое на заданном угле атаки.

    Хорда единичная, набегающая скорость единичная: всё, что отсюда выходит, —
    безразмерные коэффициенты и скорости в долях набегающей. Размерности
    появляются позже, когда к этому добавится число Рейнольдса.
    """

    def __init__(self, f=0.0, p=0.5, n=80):
        self.f, self.p, self.n = float(f), float(p), int(n)
        # Разбивка косинусом: у передней кромки пелена особенная (γ растёт как
        # 1/√x), и равномерная сетка там врёт больше всего. Косинус сгущает
        # панели именно туда, где особенность.
        th = np.linspace(0.0, np.pi, self.n + 1)
        self.xe = (1 - np.cos(th)) / 2                 # края панелей
        self.ze, _ = mean_line(self.xe, self.f, self.p)
        dx = np.diff(self.xe)
        dz = np.diff(self.ze)
        self.ds = np.hypot(dx, dz)                     # длина панели
        self.slope = np.arctan2(dz, dx)                # наклон панели
        # Вихрь в четверти панели, контрольная точка в трёх четвертях.
        self.xv = self.xe[:-1] + 0.25 * dx
        self.zv = self.ze[:-1] + 0.25 * dz
        self.xc = self.xe[:-1] + 0.75 * dx
        self.zc = self.ze[:-1] + 0.75 * dz
        self.nx = -np.sin(self.slope)                  # нормаль к панели
        self.nz = np.cos(self.slope)
        self._solved_at = None

    # -- поле точечного вихря --------------------------------------------------
    #
    # Вихрь силы Γ в точке (x0, z0) наводит
    #
    #     u = Γ/(2π)·(z − z0)/r² ,   w = −Γ/(2π)·(x − x0)/r²
    #
    # Знак выбран так, чтобы положительная Γ давала подъёмную силу вверх и
    # L = ρ·U·Γ без лишнего минуса: над вихрем поток ускоряется, под ним
    # тормозится.
    @staticmethod
    def _vortex(x, z, x0, z0):
        dx = x[:, None] - x0[None, :]
        dz = z[:, None] - z0[None, :]
        r2 = dx * dx + dz * dz
        k = 1.0 / (2 * np.pi * r2)
        return k * dz, -k * dx

    def solve(self, alpha):
        """Решить на угле атаки в радианах. Возвращает себя, чтобы читалось."""
        u, w = self._vortex(self.xc, self.zc, self.xv, self.zv)
        a = u * self.nx[:, None] + w * self.nz[:, None]
        ux, uz = np.cos(alpha), np.sin(alpha)
        rhs = -(ux * self.nx + uz * self.nz)
        self.gamma = np.linalg.solve(a, rhs)            # Γ на панель
        self.alpha = float(alpha)
        self._solved_at = float(alpha)
        return self

    @property
    def cl(self):
        """Подъёмная сила по Жуковскому: Cl = 2·ΣΓ/(U·c), а U и c единичные."""
        self._check()
        return 2.0 * float(np.sum(self.gamma))

    @property
    def cm_le(self):
        """Момент относительно передней кромки, положительный на кабрирование."""
        self._check()
        return -2.0 * float(np.sum(self.gamma * self.xv))

    @property
    def sheet(self):
        """Плотность пелены γ(s) — циркуляция на единицу длины панели."""
        self._check()
        return self.gamma / self.ds

    def surface_speed(self):
        """Скорости на двух сторонах полотна в долях набегающей.

        Поперёк вихревой пелены касательная скорость терпит скачок в γ: с одной
        стороны она на γ/2 больше средней, с другой на столько же меньше. Средняя
        для тонкого сечения — сама набегающая с точностью до второго порядка по
        пузу, и здесь она такой и берётся.

        Возвращается (подветренная, наветренная), то есть (быстрая, медленная)
        при положительном угле атаки. Именно эти две величины и есть `U_e(s)`,
        по которой дальше пойдёт марш пограничного слоя, — и брать их из
        трёхмерной решётки было бы нечем: она даёт скачок давления поперёк
        полотна, а не скорость по каждой из сторон.

        ВНИМАНИЕ на передней кромке. У тонкого сечения там особенность: γ растёт
        как 1/√x и на сетке ничем не ограничен — при вдвое мельче панелях
        скорость на первой панели ровно вдвое больше. Формула 1 ± γ/2 в этой
        полосе не просто неточна, а бессмысленна: наветренная скорость уходит в
        минус. Ширину полосы возвращает `le_invalid_x`; она сходится примерно к
        двум процентам хорды и от числа панелей почти не зависит.

        Это не изъян расчёта, а место, где у настоящего паруса сидит пузырь
        отрыва: острая кромка, поток заворачивает за неё и садится обратно.
        Марш пограничного слоя начинать надо ЗА этой полосой, а не в ней.
        """
        self._check()
        g = self.sheet
        return 1.0 + g / 2.0, 1.0 - g / 2.0

    def le_invalid_x(self):
        """Докуда от передней кромки формула скоростей неприменима, в долях хорды.

        Признак прямой: там, где наветренная скорость по ней выходит
        отрицательной, применять её нельзя. Ноль означает, что таких панелей
        нет — так бывает на малых углах и малом пузе.
        """
        self._check()
        bad = self.sheet / 2.0 > 1.0
        return float(self.xv[bad].max()) if bool(np.any(bad)) else 0.0

    def arc(self):
        """Длина дуги от передней кромки до середины каждой панели."""
        return np.cumsum(self.ds) - self.ds / 2

    def _check(self):
        if self._solved_at is None:
            raise RuntimeError("сечение не решено: сначала solve(alpha)")


def cl_converged(f, p, alpha, n=200):
    """Cl с исключённой ошибкой разбивки: Ричардсон по n и 2n.

    Элемент с сосредоточенным вихрем сходится первым порядком по числу панелей
    — разность между n и 2n делится ровно пополам на каждом удвоении, это
    видно в батарее. Раз порядок известен, предел выписывается: C∞ ≈ 2·C₂ₙ − Cₙ.
    Двести панелей с экстраполяцией дают точнее восьмисот без неё и считаются
    в шесть раз быстрее — а таблицу поляр гонять по всем углам, пузам и
    положениям пуза.
    """
    c1 = Section(f=f, p=p, n=n).solve(alpha).cl
    c2 = Section(f=f, p=p, n=2 * n).solve(alpha).cl
    return 2 * c2 - c1
