"""Ф7: волновое сопротивление по интегралу Мичелла.

До этого остаточное сопротивление задавалось таблицей из одиннадцати чисел,
нарисованной от руки: единственная величина во всём пакете, не выведенная из
геометрии. Здесь она выводится.

Мичелл (1898) решил задачу для **тонкого судна**: обводы заменяются
распределением источников по диаметральной плоскости с плотностью, равной
производной полушироты по длине. Ответ — интеграл по углу распространения
волн:

    R = (4ρg²/πU²) ∫₀^{π/2} (P² + Q²) sec³θ dθ,

    P + iQ = ∬ (∂f/∂x) · exp(k₀ sec²θ · z) · exp(i k₀ secθ · x) dx dz,

где f(x, z) — полуширота, k₀ = g/U², а двойной интеграл берётся по проекции
смоченной части на ДП. Начало отсчёта по X роли не играет: сдвиг умножает
P + iQ на постоянную фазу, а в ответ входит только модуль.

Чего эта теория не знает — и почему множитель всё-таки остаётся:

  * **тонкое судно.** Отношение ширины к длине у 610 около трети, а теория
    строится по малости этого отношения. Для полных обводов Мичелл завышает,
    для стройных ошибается на проценты; наша лодка посередине;

  * **транец.** Тело у Мичелла обязано замыкаться, а у 610 в корме широкий
    погружённый транец. Здесь он честно оформлен обрывом — полуширота падает
    до нуля за один шаг сетки, — и это даёт лишнюю волну. На ходу транец
    осушается и волны почти не делает, чего теория не видит;

  * **посадка.** Интеграл берётся по неподвижной ватерлинии, а лодка на ходу
    садится и дифферентует;

  * **глиссирование.** Динамической подъёмной силы в теории нет вовсе. У нас
    её место занимает всё тот же транцевый обрыв: на глиссировании транец
    осушается и волны не делает, зато даёт разрежение за кормой, а величина
    выходит того же порядка. Разделить эти два механизма честно можно только
    расчётом свободной поверхности.

Ещё одно, уже численное: сетка по длине разрешает волну примерно с полутора
метров в секунду (число Фруда около 0.2). Медленнее ответ вырождается в
численный пол порядка ньютона — при том что трение там уже полтора десятка.
Проверяется это в `selftest` и на поведение не влияет: на таком ходу лодка не
идёт, а дрейфует.

Первые три уходят в один множитель, четвёртое приходится добавлять отдельно;
и то и другое живёт в scripts/build_physics.py, где видно, что подгоняется.

Зависимости: hydro (граница смоченной части).
"""

import math

from . import hydro

G = 9.80665
RHO_SEA = 1025.0


def _grid(hull, z_wl, nx, nz):
    """Сетка полуширот по ДП: (x в метрах, z в метрах, f в метрах).

    По высоте сетка сгущается к ватерлинии: под экспонентой exp(k₀sec²θ·z)
    почти весь вклад сидит в верхнем слое, тем более тонком, чем медленнее ход.
    Равномерная сетка на малых числах Фруда просто не видит источников.
    """
    span = hydro.immersed_span(hull, z_wl)
    if span is None:
        raise ValueError("корпус не касается воды на этом уровне")
    xa, xf = span
    xs = [xa + (xf - xa) * i / float(nx) for i in range(nx + 1)]
    secs = [hull.section(x) for x in xs]

    z_min = min(hull.z_keel(x) for x in xs)
    # (j/nz)² — шаг у поверхности вдвое-втрое мельче, чем у киля
    zs = [z_wl + (z_min - z_wl) * (j / float(nz)) ** 2 for j in range(nz + 1)]

    f = [[s.half_beam_at(z) / 1000.0 for z in zs] for s in secs]
    return ([x / 1000.0 for x in xs], [z / 1000.0 for z in zs], f)


def _slopes(xs, f):
    """∂f/∂x на той же сетке.

    На кормовом конце — односторонняя разность к нулю: транец обрывается, и
    полуширота там падает со своего значения до нуля. Это и есть источник,
    которым Мичелл описывает обрыв тела; выбросить его нельзя, иначе корма
    перестанет делать волны вовсе.
    """
    n = len(xs)
    out = []
    for i in range(n):
        row = []
        for j in range(len(f[0])):
            if i == 0:
                dx = xs[1] - xs[0]
                row.append(f[0][j] / dx if dx > 0 else 0.0)
            elif i == n - 1:
                dx = xs[-1] - xs[-2]
                row.append((f[-1][j] - f[-2][j]) / dx if dx > 0 else 0.0)
            else:
                dx = xs[i + 1] - xs[i - 1]
                row.append((f[i + 1][j] - f[i - 1][j]) / dx if dx > 0 else 0.0)
        out.append(row)
    return out


def _weights(v):
    """Веса трапеций для неравномерной сетки."""
    n = len(v)
    w = [0.0] * n
    for i in range(n):
        lo = v[i] - v[i - 1] if i > 0 else 0.0
        hi = v[i + 1] - v[i] if i < n - 1 else 0.0
        w[i] = 0.5 * (abs(lo) + abs(hi))
    return w


def resistance(hull, speeds, z_wl=0.0, nx=96, nz=48, n_theta=320,
               t_max=40.0, rho=RHO_SEA):
    """Волновое сопротивление, Н, для списка скоростей в м/с.

    Интегрирование по углу идёт в подстановке t = tgθ: тогда

        sec³θ dθ = √(1 + t²) dt,   secθ = √(1 + t²),   sec²θ = 1 + t²,

    и особенность у π/2 исчезает — вместо неё бесконечный, но быстро
    затухающий хвост. Прямо по θ считать нельзя: sec³θ у верхнего предела
    растёт, и ответ на быстрых ходах зависел от того, где обрезать. Проверено:
    на 1.45 радиана ошибка доходила до четырнадцати процентов.

    `t_max` — где обрывается хвост, `n_theta` — сколько узлов на него, со
    сгущением к нулю.
    """
    xs, zs, f = _grid(hull, z_wl, nx, nz)
    return from_grid(xs, zs, f, speeds, n_theta=n_theta, t_max=t_max, rho=rho)


def from_grid(xs, zs, f, speeds, n_theta=320, t_max=40.0, rho=RHO_SEA):
    """То же, но по готовой сетке полуширот. Здесь и живёт сам интеграл.

    Отдельной функцией — чтобы её можно было проверить на теле, у которого
    ответ известен, не собирая ради этого корпус целиком (см. `selftest`).
    """
    fx = _slopes(xs, f)
    wx, wz = _weights(xs), _weights(zs)

    # предвычисленные произведения весов и наклонов — внутренний цикл горячий
    cells = []
    for i, x in enumerate(xs):
        for j, z in enumerate(zs):
            a = fx[i][j] * wx[i] * wz[j]
            if a != 0.0:
                cells.append((x, z, a))

    out = []
    for u in speeds:
        if u <= 0.05:
            out.append(0.0)
            continue
        k0 = G / (u * u)
        # узлы по t со сгущением к нулю: там сидит основной вклад
        nodes = [t_max * (i / float(n_theta)) ** 2 for i in range(n_theta + 1)]
        total = 0.0
        for i, t in enumerate(nodes):
            sec2 = 1.0 + t * t
            sec = math.sqrt(sec2)
            k, m = k0 * sec, k0 * sec2
            p = q = 0.0
            for x, z, a in cells:
                e = a * math.exp(m * z)          # z ≤ 0, экспонента убывает
                if e == 0.0:
                    continue
                p += e * math.cos(k * x)
                q += e * math.sin(k * x)
            lo = t - nodes[i - 1] if i > 0 else 0.0
            hi = nodes[i + 1] - t if i < n_theta else 0.0
            total += 0.5 * (lo + hi) * (p * p + q * q) * sec
        out.append(4.0 * rho * G * G / (math.pi * u * u) * total)
    return out


def curve(hull, mass_kg, froudes, lwl_m, **kw):
    """Таблица (число Фруда -> волновое сопротивление в долях веса)."""
    speeds = [fn * math.sqrt(G * lwl_m) for fn in froudes]
    r = resistance(hull, speeds, **kw)
    w = mass_kg * G
    return [(fn, rw / w) for fn, rw in zip(froudes, r)]


# ------------------------------------------------------------------- проверка

def wigley(length, beam, draft, nx=96, nz=48, x0=0.0):
    """Сетка полуширот корпуса Вигли — стандартного тела для таких проверок.

        f(x, z) = (B/2)·(1 − (2x/L)²)·(1 − (z/T)²)

    Он тонкий, гладкий и замкнутый с обоих концов, то есть ровно то, для чего
    теория Мичелла и выведена. На нём должна быть видна главная её черта —
    гребни и впадины от того, что носовая и кормовая волны то складываются, то
    гасят друг друга.
    """
    xs = [x0 - length / 2.0 + length * i / float(nx) for i in range(nx + 1)]
    zs = [-draft * (j / float(nz)) ** 2 for j in range(nz + 1)]
    f = [[(beam / 2.0) * (1.0 - (2.0 * (x - x0) / length) ** 2)
          * (1.0 - (z / draft) ** 2) for z in zs] for x in xs]
    return xs, zs, f


def selftest(hull=None):
    """Сверки интеграла: свойства, которые обязаны выполняться точно.

    Возвращает список (название, значение, допуск, прошло) — так же, как это
    делает calibrate для привязки чертежа.
    """
    L, B, T = 6.0, 0.6, 0.4
    speeds = [3.0, 4.5, 6.0]
    base = from_grid(*wigley(L, B, T), speeds=speeds)

    out = []

    # 1. Начало отсчёта по X. Сдвиг тела вдоль оси меняет фазу, но не модуль:
    #    если ответ поехал, значит потерян знак или перепутаны синус с косинусом.
    moved = from_grid(*wigley(L, B, T, x0=17.0), speeds=speeds)
    err = max(abs(a - b) / b for a, b in zip(moved, base))
    out.append(("не зависит от начала отсчёта по X", err, 1e-9, err < 1e-9))

    # 2. Ширина. Плотность источников пропорциональна полушироте, ответ — её
    #    квадрату: удвоение ширины обязано дать ровно вчетверо.
    wide = from_grid(*wigley(L, 2 * B, T), speeds=speeds)
    err = max(abs(a / b - 4.0) for a, b in zip(wide, base))
    out.append(("вдвое шире — вчетверо больше", err, 1e-6, err < 1e-6))

    # 3. Сходимость по сетке и по хвосту интегрирования.
    fine = from_grid(*wigley(L, B, T, nx=192, nz=96), speeds=speeds)
    err = max(abs(a - b) / b for a, b in zip(fine, base))
    out.append(("сетка сошлась", err, 0.02, err < 0.02))

    tail = from_grid(*wigley(L, B, T), speeds=speeds, t_max=80.0)
    err = max(abs(a - b) / b for a, b in zip(tail, base))
    out.append(("хвост по углу сошёлся", err, 0.02, err < 0.02))

    # 4. Гребни и впадины. У замкнутого тонкого тела кривая волнового
    #    сопротивления обязана быть немонотонной: носовая и кормовая системы
    #    волн интерферируют. Если её нет — интеграл считает не то.
    fns = [0.15 + 0.01 * i for i in range(36)]
    vs = [fn * math.sqrt(G * L) for fn in fns]
    r = from_grid(*wigley(L, B, T), speeds=vs)
    cw = [rr / (v * v) if v > 0 else 0.0 for rr, v in zip(r, vs)]
    turns = sum(1 for i in range(1, len(cw) - 1)
                if (cw[i] - cw[i - 1]) * (cw[i + 1] - cw[i]) < 0)
    out.append(("на корпусе Вигли видны гребни и впадины", turns, 2, turns >= 2))

    if hull is not None:
        # Сходимость на настоящих обводах — с полутора метров в секунду.
        # Медленнее сетка по длине волну уже не разрешает, и ответ там —
        # численный мусор порядка ньютона. На поведение это не влияет:
        # на таком ходу лодка почти стоит, а трение там впятеро больше.
        work = [1.5, 3.0, 4.5, 6.0, 7.5]
        used = resistance(hull, work)                       # рабочая сетка
        fine_h = resistance(hull, work, nx=192, nz=96)
        err = max(abs(a - b) / b for a, b in zip(used, fine_h))
        out.append(("сетка сошлась на обводах 610 от 1.5 м/с", err, 0.07, err < 0.07))

    return out
