# -*- coding: utf-8 -*-
"""Пограничный слой против известных решений: .venv/bin/python tests/bl.test.py

Проверять слой на парусе бессмысленно: он всегда выдаст какую-нибудь точку
отрыва, и она всегда будет выглядеть правдоподобно. Поэтому здесь три задачи, у
которых ответ известен с точностью до третьего знака и получен не этим методом:

    Блазиус, пластина без градиента     θ = 0.664·x/√Re_x
    Хоуарт, U = U₀(1 − x/L)             ламинарный отрыв на x/L = 0.120
    турбулентная пластина, Re = 10⁶     Cd ≈ 0.0091 по эмпирике 0.074/Re^0.2

Первая проверяет ламинарную часть, вторая — то, ради чего слой вообще считают
(отрыв), третья — турбулентную часть вместе со Сквайром—Янгом.
"""

import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from sv20.bl import head, march, squire_young, thwaites  # noqa: E402

failures = 0


def check(name, ok, detail=""):
    global failures
    if not ok:
        failures += 1
    print(("  ok   " if ok else "  ПЛОХО") + "  " + name + ("   " + detail if detail else ""))


# --- Блазиус ------------------------------------------------------------------
#
# Твейтс на пластине даёт 0.671 против точных 0.664 — известное отклонение
# метода в один процент, и оно обязано быть именно таким. Если станет меньше,
# значит где-то подгонка; если больше — ошибка.
print("\nПластина без градиента давления (Блазиус):\n")
print("       Re      θ·√Re/x расчёт   Блазиус 0.664   откл.")
worst = 0.0
for re in (1e4, 1e5, 1e6):
    s = np.linspace(0.0, 1.0, 4001)
    ue = np.ones_like(s)
    th, h, cf, lam, sep = thwaites(s, ue, 1.0 / re)
    val = th[-1] * np.sqrt(re)
    worst = max(worst, abs(val / 0.664 - 1))
    print("  %9.0e %16.5f %15.3f %8.2f%%" % (re, val, 0.664, (val / 0.664 - 1) * 100))
print("")
check("Твейтс на пластине даёт свои канонические 0.671",
      abs(th[-1] * np.sqrt(1e6) - 0.671) < 0.002, "%.5f" % (th[-1] * np.sqrt(1e6)))
check("отклонение от Блазиуса — тот самый один процент", 0.005 < worst < 0.015,
      "%.2f%%" % (worst * 100))
check("толщина растёт как √x",
      abs(th[-1] / th[1000] / np.sqrt(s[-1] / s[1000]) - 1) < 1e-3)
check("формпараметр на пластине равен 2.59 (Блазиус 2.59)",
      abs(h[-1] - 2.59) < 0.03, "%.3f" % h[-1])
check("без градиента отрыва нет", sep is None)
# Трение по Твейтсу против точного cf = 0.664/√Re_x.
cf_exact = 0.664 / np.sqrt(1e6 * s[-1])
check("трение на пластине сходится с точным", abs(cf[-1] / cf_exact - 1) < 0.02,
      "%.6f против %.6f" % (cf[-1], cf_exact))

# --- Хоуарт -------------------------------------------------------------------
#
# Линейно тормозящийся поток — эталонная задача на отрыв. Точное решение
# Хоуарта даёт x/L = 0.1198, Твейтс — 0.120; совпадение здесь известное и
# случайным не является.
print("Линейно тормозящийся поток (Хоуарт), U = U₀·(1 − x/L):\n")
s = np.linspace(0.0, 0.2, 20001)
ue = 1.0 - s
th, h, cf, lam, sep = thwaites(s, ue, 1e-5)
x_sep = s[sep] if sep is not None else float("nan")
print("  отрыв на x/L = %.4f, точное решение Хоуарта 0.1198\n" % x_sep)
check("ламинарный отрыв находится там же, где у Хоуарта",
      abs(x_sep - 0.1198) < 0.004, "%.4f против 0.1198" % x_sep)
check("до отрыва λ падает монотонно",
      bool(np.all(np.diff(lam[: sep + 1]) < 1e-12)))
check("положение отрыва не зависит от вязкости",
      abs(s[thwaites(s, ue, 1e-7)[4]] - x_sep) < 1e-4,
      "при вязкости в сто раз меньше %.4f" % s[thwaites(s, ue, 1e-7)[4]])

# --- турбулентная пластина ----------------------------------------------------
#
# Здесь проверяется связка «Хед + Людвиг—Тильман + Сквайр—Янг» целиком, и
# эталон эмпирический: Cf = 0.074/Re^0.2 на сторону, θ/x = 0.036/Re^0.2.
print("Турбулентная пластина, Re = 10⁶:\n")
re = 1e6
s = np.linspace(0.0, 1.0, 4001)
ue = np.ones_like(s)
x0 = s[10]
th0 = 0.036 * x0**0.8 * (1.0 / re) ** 0.2   # запуск с той же эмпирики в точке x0
th, h, cf, sep = head(s[10:], ue[10:], 1.0 / re, theta0=th0, h0=1.4)
th_ref = 0.036 / re**0.2
cd = 2 * squire_young(th[-1], 1.0, h[-1])
cd_ref = 2 * 0.074 / re**0.2
print("  θ на кромке: %.5f, эмпирика %.5f" % (th[-1], th_ref))
print("  H на кромке: %.3f (у турбулентного слоя 1.3…1.4)" % h[-1])
print("  Cd двух сторон: %.5f, эмпирика %.5f\n" % (cd, cd_ref))

# Восемь процентов ниже эмпирики — это не промах, а расхождение самих
# корреляций: Людвиг—Тильман и степень одной седьмой описывают одно и то же
# трение и между собой расходятся примерно на столько же. Проверено, что дело
# не в запуске марша: сдвиг θ₀ на порядок меняет ответ в третьем знаке.
check("толщина потери импульса сходится с эмпирикой пластины",
      abs(th[-1] / th_ref - 1) < 0.12, "%.1f%%" % ((th[-1] / th_ref - 1) * 100))
check("формпараметр турбулентного слоя в своих пределах", 1.25 < h[-1] < 1.45,
      "%.3f" % h[-1])
check("сопротивление по Сквайру—Янгу сходится с эмпирикой",
      abs(cd / cd_ref - 1) < 0.12, "%.5f против %.5f" % (cd, cd_ref))
check("без градиента турбулентный слой не отрывается", sep is None)
check("трение падает вниз по потоку", bool(cf[-1] < cf[100]))

# --- турбулентный отрыв -------------------------------------------------------
#
# Точного эталона для отрыва по Хеду нет, поэтому проверяются свойства: чем
# круче торможение, тем раньше отрыв, и слабое торможение слой держит.
print("Турбулентный отрыв на тормозящемся потоке:\n")
print("   спад U на хорде    точка отрыва")
prev = 2.0
mono = True
for drop in (0.1, 0.2, 0.3, 0.45, 0.6):
    s = np.linspace(0.0, 1.0, 4001)
    ue = 1.0 - drop * s
    r = march(s, ue, 1.0 / 1e6, s_tr=0.02, s_start=0.005)
    x = r["s_sep"]
    print("   %10.2f %18s" % (drop, "%.3f" % x if x else "не оторвался"))
    if x is not None:
        mono = mono and x < prev
        prev = x
print("")
check("чем круче торможение, тем раньше отрыв", mono)
s = np.linspace(0.0, 1.0, 4001)
check("слабое торможение слой держит",
      march(s, 1.0 - 0.1 * s, 1e-6, s_tr=0.02, s_start=0.005)["s_sep"] is None)
check("сильное торможение слой не держит",
      march(s, 1.0 - 0.6 * s, 1e-6, s_tr=0.02, s_start=0.005)["s_sep"] is not None)
# Зависимость от числа Рейнольдса — не мелочь: по ней в таблице поляр и пойдёт
# одна из осей. Слой на большем Re полнее и держится дольше, значит отрыв обязан
# отползать к задней кромке, и монотонно.
xs = [march(s, 1.0 - 0.6 * s, 1.0 / q, s_tr=0.02, s_start=0.005)["s_sep"]
      for q in (1e5, 3e5, 1e6, 3e6)]
print("  отрыв при Re = 10⁵, 3·10⁵, 10⁶, 3·10⁶: "
      + ", ".join("%.3f" % v for v in xs) + "\n")
check("с ростом числа Рейнольдса отрыв отползает назад, и монотонно",
      all(xs[i] > xs[i - 1] for i in range(1, len(xs))),
      ", ".join("%.3f" % v for v in xs))

print(("%d проверок провалено" % failures) if failures else "все проверки прошли")
print("")
sys.exit(1 if failures else 0)
