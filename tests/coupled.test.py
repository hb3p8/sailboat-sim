# -*- coding: utf-8 -*-
"""Совместный расчёт против опыта: .venv/bin/python tests/coupled.test.py

Батарея медленная (десятки секунд) и потому лежит в `make slow`, а не в
`make test`. Считается совместная вязко-невязкая задача: поле → пограничный слой
→ выдув → поле, до сходимости.

Ради чего она написана. Данным Уоллиса сорок шестого года разумно не верить на
слово. Первая проверка — согласие с независимым опытом Милгрэма семьдесят
первого — уже пройдена (`tests/sailcoeffs.test.mjs`). Здесь вторая: посчитать то
же самое современным способом и посмотреть, воспроизводится ли главное
расхождение с невязкой теорией — вязкое раскамберивание.

Ответ, коротко: воспроизводится по знаку и по механизму, но не по величине.
Совместный расчёт даёт около восьми процентов потери подъёмной силы на всех
пузах, а опыт показывает от шестнадцати до тридцати трёх, и разница растёт с
пузом. Остаток — отрыв с задней кромки, которого прямой марш не берёт; на него
же указывают и оба опыта, независимо друг от друга.
"""

import json
import os
import sys

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "src"))

from sv20.coupled import couple  # noqa: E402

D = np.pi / 180
failures = 0
W = json.load(open(os.path.join(ROOT, "data/section/wallis_arl74.json"), encoding="utf-8"))


def check(name, ok, detail=""):
    global failures
    if not ok:
        failures += 1
    print(("  ok   " if ok else "  ПЛОХО") + "  " + name + ("   " + detail if detail else ""))


# --- сам метод ----------------------------------------------------------------
#
# Прежде чем сравнивать с опытом, надо убедиться, что связь вообще работает как
# задумано: вязкость обязана ОТНИМАТЬ подъёмную силу, тем больше, чем меньше
# число Рейнольдса, и обращаться в ноль в невязком пределе.
print("\nПотеря подъёмной силы по числу Рейнольдса (пузо 6%, α = 2°):\n")
print("        Re    Cl невязкий   Cl совместный   потеря   итераций")
loss = []
for re in (2e5, 6e5, 2e6, 2e7):
    r = couple(f=0.06, alpha=2 * D, re=re, n=200, iters=400, relax=0.08)
    loss.append(1 - r.cl / r.cl_inviscid)
    print("  %9.0e %13.4f %15.4f %8.1f%% %10d"
          % (re, r.cl_inviscid, r.cl, 100 * loss[-1], r.iters))
print("")

check("вязкость отнимает подъёмную силу, а не добавляет", all(v > 0 for v in loss),
      ", ".join("%.1f%%" % (v * 100) for v in loss))
check("потеря растёт с падением числа Рейнольдса, и монотонно",
      all(loss[i] < loss[i - 1] for i in range(1, len(loss))),
      ", ".join("%.1f%%" % (v * 100) for v in loss))
check("в невязком пределе потеря стремится к нулю", loss[-1] < 0.04,
      "%.1f%% при Re = 2·10⁷" % (loss[-1] * 100))
# Нулевой выдув — точный предел, и проверяется он точно: условие транспирации с
# нулём обязано дать в точности прежнее непротекание, до последнего разряда.
# Иначе связь подмешивает что-то своё и все числа выше ничего не стоят.
from sv20.panel import Panels, sail_contour  # noqa: E402

pz = Panels(*sail_contour(f=0.06, p=0.5, t=0.02, n=200))
a_ = pz.solve(2 * D).cl
b_ = pz.solve(2 * D, blow=np.zeros(pz.n)).cl
check("нулевой выдув в точности возвращает непротекание", abs(a_ - b_) < 1e-12,
      "%.2e" % abs(a_ - b_))

# --- против Уоллиса -----------------------------------------------------------
print("Против опыта Уоллиса (t/c = 0.02, Re = 6·10⁵):\n")
print("   пузо    α    опыт   невязкий   совместный    опыт/невязк.   совм./невязк.")
rows = []
A = W["Re6e5"]["alpha_deg"]
for key in ("0.04", "0.06", "0.08"):
    cam, row = float(key), W["Re6e5"]["пузо"][key]
    for a in (0, 2):
        exp = row[A.index(a)]
        r = couple(f=cam, alpha=a * D, re=6e5, n=200, iters=400, relax=0.08)
        rows.append((cam, a, exp, r.cl_inviscid, r.cl))
        print("  %5.0f%% %4d° %7.2f %10.3f %12.3f %14.0f%% %15.0f%%"
              % (cam * 100, a, exp, r.cl_inviscid, r.cl,
                 100 * exp / r.cl_inviscid, 100 * r.cl / r.cl_inviscid))
print("")

check("совместный расчёт ближе к опыту, чем невязкий, везде",
      all(abs(cl - e) < abs(inv - e) for _, _, e, inv, cl in rows),
      "невязкий врал в среднем на %.0f%%, совместный на %.0f%%"
      % (100 * np.mean([abs(inv / e - 1) for _, _, e, inv, _ in rows]),
         100 * np.mean([abs(cl / e - 1) for _, _, e, _, cl in rows])))
# Но не настолько ближе, чтобы вопрос был закрыт, и это тоже надо держать числом.
# Прилипший расчёт снимает около восьми процентов, опыт теряет от шестнадцати до
# тридцати трёх, и разница РАСТЁТ с пузом — то есть остаток не шум, а физика,
# которой в методе нет: отрыв с задней кромки.
gap = [(e / inv) / (cl / inv) for _, _, e, inv, cl in rows]
print("  необъяснённый остаток (опыт в долях совместного расчёта):")
for (cam, a, e, inv, cl), g in zip(rows, gap):
    print("    пузо %.0f%%, %d°: %.2f" % (cam * 100, a, g))
print("")
check("совместный расчёт снимает часть недобора, но далеко не весь",
      all(g < 0.95 for g in gap), "остаток от %.2f до %.2f" % (min(gap), max(gap)))
check("остаток растёт с пузом — значит это не шум, а отрыв",
      np.mean([g for (c, *_), g in zip(rows, gap) if c >= 0.08])
      < np.mean([g for (c, *_), g in zip(rows, gap) if c <= 0.04]) - 0.05,
      "%.2f при пузе 8%% против %.2f при 4%%"
      % (np.mean([g for (c, *_), g in zip(rows, gap) if c >= 0.08]),
         np.mean([g for (c, *_), g in zip(rows, gap) if c <= 0.04])))

print(("%d проверок провалено" % failures) if failures else "все проверки прошли")
print("")
sys.exit(1 if failures else 0)
