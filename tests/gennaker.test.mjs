// Генакер: node tests/gennaker.test.mjs
//
// Батарея заведена по ревью (docs/gennaker-planing-plan.md, §4.9): ни одна из
// прежних не считала третий парус, и потому ни полуметровые щели между
// полосками, ни разнос циркуляции на обычном положении шкота они поймать не
// могли. Здесь проверяется то, что относится к самому парусу и к постановке, а
// не к ходовым качествам: их мерить нечем, пока модель не устойчива.
//
// Порядок проверок — от геометрии пакета к устойчивости решения: если врёт
// геометрия, устойчивость мерить бессмысленно.
//
// БАТАРЕЯ ВАЛИТСЯ НА ОДНОЙ КЛЕТКЕ, и потому в `make test` НЕ входит: набор
// обязан оставаться зелёным, иначе он перестаёт что-либо значить для всего
// остального. Открытая клетка — 135°/4.5.
//
// Что уже закрыто. Клетка 120°/7.5 разносилась (Γ = 797 при фоновом 21.6,
// скачок тяги 17.5 %); причина оказалась не в пелене, а в знаке пуза, который
// переключался по `Math.sign(alpha)`, и у сваленной по потоку полоски, где угол
// атаки равен нулю ТОЖДЕСТВЕННО, пузо прыгало с +m на −m за шаг. Чинится
// непрерывным знаком (`camberSign` в membrane.js). Клетка держит 0.0 %.
//
// Что открыто. Клетка 135°/4.5 была ХАОТИЧНА: от тысячной доли узла в начальном
// ходе скачок ходил через порог в обе стороны (замер на HEAD `d0929fd`: 3.4, 6.6,
// 2.9, 5.2, 4.5 % при начальных ходах 3.000…3.100). Остальные двадцать четыре
// при том же возмущении стояли побитово. Поэтому карта и меряется теперь с ДВУХ
// начальных ходов с худшим из двух — и показывает то, что было и раньше, но
// пряталось за одним прогоном. Сейчас эта клетка держит 0 %.
//
// ОТКРЫТА И ВТОРАЯ ПРОВЕРКА — размах тяги на установившемся режиме, двенадцать
// клеток из тридцати шести, худшая 54 %. Она заведена этим же заходом и меряет
// то, чего прежняя не видела: скачок за шаг ловит РАЗРЫВ, а плавная раскачка
// даёт нулевой скачок и проходит насквозь. Раскачка при этом была и ДО ткани в
// решётке — 29 % на 110°/5.5 при шести метрах, 49 и 86 % при десяти, — просто
// мерить её было нечем. Разбор и то, чем она НЕ является, — в docs/wake.md,
// «Петля: один узел развязан».
//
// ОТКРЫТЫ ДВЕ КЛЕТКИ первой проверки: 120°/4.5 (6 %) и 120°/6.5 (5 %), обе от Б3 —
// панелями генакера по ткани. Причина разобрана и НЕ в ткани: с замороженным
// полотном числа те же до разряда. Это петля пелена ↔ решётка на НИЖНЕЙ ПОЛОСКЕ
// ГРОТА, и вот её замер на клетке 120°/4.5:
//
//   до Б3:  Γ нижней полоски −5.73…−3.25, наполнение 0.00 ровно, тяга 699 Н ровно
//   с Б3:   Γ −2.09…1.76, наполнение 0.00…0.51, тяга 445…501 Н, период около 1 с
//
// То есть честная геометрия генакера переносит его пелену так, что подошва грота
// из «уверенно подбитой» становится краевой, и её циркуляция начинает ходить
// через ноль. Выключить пелену из сил — 0.0 %; убрать грот — 0.0 %; заморозить
// ткань — без изменений. Это та самая петля из docs/wake.md §9, которую веер
// просто не возбуждал.
//
// Цена клеток названа: за них модель отдаёт промах по тяге против продувок с
// 69 % до 39 % и впервые проходит проверку боковой силы
// (docs/gennaker-sota-plan.md, «Б3 сделан»). Крен при этом дышит на 0.05°, то
// есть лодка этих шести процентов не чувствует — а порог ставился именно по
// тому, что чувствует лодка.
//
// Полоса шкота 5.4…6.6 м при TWA 140° при шаге 1/30 стоит; мельчение шага её
// больше не разносит — с тех пор как запрет лететь в парус стал скоростью, а не
// перестановкой (docs/wake.md, «Мельчение шага»).

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { Boat } from '../sim/physics.js';
import { gennakerSetOf, gennakerClew } from '../sim/aero.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PACK = JSON.parse(readFileSync(join(ROOT, 'out/export/physics.json'), 'utf8'));
const D = Math.PI / 180;

let failures = 0;
const check = (name, ok, detail) => {
  if (!ok) failures++;
  console.log((ok ? '  ok   ' : '  ПЛОХО') + '  ' + name + (detail ? '   ' + detail : ''));
};

const G = PACK.rig.gennaker;

// --- геометрия пакета ---------------------------------------------------------
{
  console.log('\nГеометрия пакета:\n');
  // Площадь — единственное, что пришло от конструктора, и обмерная формула
  // обязана её воспроизвести. Всё остальное в парусе выведено из неё.
  const area = (G.luff_m + G.leech_m) / 2 * (G.foot_m + 4 * G.girth_mid_m) / 6;
  check('обмерная площадь сходится с конструкторской 27 м²',
        Math.abs(area - 27) < 0.05, area.toFixed(3) + ' м²');
  check('средняя ширина не ниже порога спинакера (0.75 нижней)',
        G.girth_mid_m >= 0.75 * G.foot_m,
        (G.girth_mid_m / G.foot_m).toFixed(3));
  // Галс на бушприте, впереди форштевня; фал выше хаундов.
  check('галс вынесен вперёд форштевня', G.tack[0] > PACK.rig.forestay.stem[0],
        G.tack[0].toFixed(3) + ' против ' + PACK.rig.forestay.stem[0].toFixed(3));
  check('фаловый угол имеет ширину, а не сходится в точку',
        G.head[0] - G.head_aft[0] > 0.05,
        (G.head[0] - G.head_aft[0]).toFixed(3) + ' м');
  // Длина шкота -> вынос: обязана расти монотонно, иначе ползунок не орган
  // управления, а лотерея.
  let mono = true, prev = -1;
  for (let L = G.sheet_min_m; L <= G.sheet_max_m; L += 0.1) {
    const a = gennakerSetOf({ genSheetLen: L }, G);
    if (a < prev - 1e-9) mono = false;
    prev = a;
  }
  check('вынос растёт с длиной шкота монотонно', mono);
  // ЗАМКНУТОСТЬ ТРЁХ ШКАТОРИН. Шкотовый угол держат две снасти-не-снасти —
  // нижняя и задняя шкаторины, — и обе концами закреплены. Значит при любой
  // длине шкота расстояния до галса и до фала обязаны быть ОДНИ И ТЕ ЖЕ. Пока
  // угол водился по горизонтальной окружности вокруг галса, |фал—шкот| рос с
  // 8.66 до 10.68 м: задняя шкаторина растягивалась на четверть, и летящей
  // формы у паруса не было вовсе (поймано тканью, docs/gennaker-sota-plan.md,
  // §Б2). Это §4.8 плана, и здесь он закрывается.
  let foot0 = null, leech0 = null, footMax = 0, leechMax = 0;
  const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);
  const tack3 = [G.tack[0], 0, G.tack[1]], head3 = [G.head[0], 0, G.head[1]];
  for (let L = G.sheet_min_m; L <= G.sheet_max_m; L += 0.05) {
    const c = gennakerClew({ genSheetLen: L }, G);
    const f = dist(tack3, c), e = dist(head3, c);
    if (foot0 == null) { foot0 = f; leech0 = e; }
    footMax = Math.max(footMax, Math.abs(f - foot0));
    leechMax = Math.max(leechMax, Math.abs(e - leech0));
  }
  check('нижняя шкаторина не тянется ни при каком шкоте', footMax < 1e-3,
        (footMax * 1000).toFixed(3) + ' мм');
  check('задняя шкаторина не тянется ни при каком шкоте', leechMax < 1e-3,
        (leechMax * 1000).toFixed(3) + ' мм');
  check('нижняя шкаторина построена той длины, что заявлена',
        Math.abs(foot0 - G.foot_m) < 1e-3, foot0.toFixed(4) + ' против ' + G.foot_m);
  // Задняя ПО ДУГЕ длиннее прямой фал—шкот ровно на свой серп: дуга, по которой
  // ходит шкотовый угол, держит ПРЯМУЮ. Разница — то, чем шкаторина выгнута, и
  // она обязана быть небольшой.
  check('серп задней шкаторины не больше половины нижней',
        G.leech_m - leech0 < 0.5 * G.foot_m,
        (G.leech_m - leech0).toFixed(3) + ' м = ' +
        ((G.leech_m - leech0) / G.foot_m).toFixed(2) + ' нижней');
  // Шкотовый угол ПОДНИМАЕТСЯ над галсом, а не ползает по палубе (§Б0.4).
  const rise = gennakerClew({ genSheetLen: G.sheet_max_m }, G)[2] - G.tack[1];
  check('на отданном шкоте шкотовый угол поднят над галсом больше чем на метр',
        rise > 1.0, rise.toFixed(2) + ' м');
}

// --- топология рига -----------------------------------------------------------
{
  console.log('\nТопология рига:\n');
  const mk = up => {
    const b = new Boat(PACK);
    b.o.freeWake = true; b.o.wakeForces = true;
    if (up) b.setGennaker(true);
    b.o.windSpeed = 6; b.o.windDir = 100 * D; b.u = 3;
    b.step(1 / 30);
    return b;
  };
  const a = mk(false), c = mk(true);
  check('без генакера двенадцать полосок', a.rig.strips.length === 12,
        String(a.rig.strips.length));
  check('с генакером восемнадцать', c.rig.strips.length === 18,
        String(c.rig.strips.length));
  // Нитей на стык парусов приходится по лишней: NS + 1 + стыков.
  check('нитей пелены без генакера четырнадцать', a.rig.wake.fil === 14,
        String(a.rig.wake.fil));
  check('с генакером двадцать одна', c.rig.wake.fil === 21, String(c.rig.wake.fil));
  check('подъём убирает стаксель', c.o.jibUp === false);
  // Уборка возвращает риг ровно к прежнему.
  c.setGennaker(false);
  check('уборка возвращает двенадцать полосок и стаксель',
        c.rig.strips.length === 12 && c.o.jibUp === true);
}

// --- непрерывность несущей поверхности ----------------------------------------
//
// ГЛАВНАЯ проверка этой батареи. Боковой вынос передней шкаторины считался один
// раз в середине полоски и подавался на обе её границы — общая граница двух
// соседей получала две разные координаты, и поверхность размахом 8.6 м
// оказывалась разрезана щелями до полуметра. Точки схода пелены рвались на
// столько же. Решётка предполагает общее ребро; на щелях она даёт лишние
// краевые вихри и теряет обусловленность.
//
// Мерка — не ноль, а грот: у него полоски тоже стоят под разным твистом, и
// стык на этом расходится. Генакер обязан быть не хуже своего же рига.
{
  console.log('\nНепрерывность поверхности:\n');
  const b = new Boat(PACK);
  b.o.freeWake = true; b.o.wakeForces = true;
  b.o.crewHike = -1; b.o.crewMass = 219.9;
  b.wind.o.gust = 0; b.wind.o.shift = 0;
  b.setGennaker(true);
  b.o.sheet = 70 * D; b.o.twist = 8 * D; b.o.genSheetLen = 6.0;
  b.reset();
  b.o.windSpeed = 6; b.o.windDir = 100 * D; b.u = 3; b.psi = -40 * D;
  for (let i = 0; i < 60; i++) b.step(1 / 30);

  const S = b.rig.strips, lat = b.rig.lattice, NC = lat.n / S.length;
  const dist = (p, q) => Math.hypot(p[0] - q[0], p[1] - q[1], p[2] - q[2]);
  const seam = (from, to) => {
    let panel = 0, shed = 0;
    for (let i = from; i < to; i++) {
      for (let k = 0; k < NC; k++) {
        panel = Math.max(panel, dist(lat.panels[i * NC + k].a,
                                     lat.panels[(i + 1) * NC + k].b));
      }
      shed = Math.max(shed, dist(b.rig.shedHi[i], b.rig.shedLo[i + 1]));
    }
    return { panel, shed };
  };
  const main = seam(0, 5), gen = seam(12, 17);
  console.log('    грот:    панели %s м, точки схода %s м',
              main.panel.toFixed(3), main.shed.toFixed(3));
  console.log('    генакер: панели %s м, точки схода %s м\n',
              gen.panel.toFixed(3), gen.shed.toFixed(3));
  // Втрое — с запасом на то, что у генакера хорды вчетверо длиннее гротовых, и
  // тот же угол твиста разводит концы дальше.
  check('щели между полосками генакера того же порядка, что у грота',
        gen.panel < 3 * main.panel && gen.shed < 3 * main.shed,
        'панели ' + (gen.panel / main.panel).toFixed(2) + '×, схода ' +
        (gen.shed / main.shed).toFixed(2) + '×');
}

// --- устойчивость решения по всей полосе шкота ---------------------------------
//
// Ползунок шкота — орган управления, и на любом его положении решение обязано
// оставаться решением. Мерка — связанная циркуляция: ход тут не свидетель, он
// ограничен полярой сечения и остаётся правдоподобным даже при Γ порядка 10⁷
// (docs/wake.md, §5.12).
{
  console.log('\nУстойчивость по длине шкота (TWA 140°, ветер 6 м/с):\n');
  const wrap = a => ((a + Math.PI) % (2 * Math.PI) + 2 * Math.PI) % (2 * Math.PI) - Math.PI;
  const once = (len, twa, u0) => {
    const b = new Boat(PACK);
    b.o.freeWake = true; b.o.wakeForces = true;
    b.o.crewHike = -1; b.o.crewMass = 219.9;
    b.wind.o.gust = 0; b.wind.o.shift = 0;
    b.setGennaker(true);
    b.o.sheet = 70 * D; b.o.twist = 8 * D; b.o.genSheetLen = len;
    b.reset();
    b.o.windSpeed = 6; b.o.windDir = 100 * D; b.u = u0;
    b.psi = (100 - twa) * D;
    // Две мерки за один прогон.
    //
    // Γmax ловит РАЗНОС: связанная циркуляция уходит на порядки, ход тут не
    // свидетель — он ограничен полярой и правдоподобен даже при Γ порядка 10⁷.
    //
    // jump ловит РАЗРЫВ СИЛЫ на переходе постановки. Это и есть настоящая мера
    // гибридного режима, а не число срабатываний предохранителя: срабатывание
    // — не поломка, а передача управления поляре, и считать его провалом
    // значит мерить не то. Лодка чувствует не то, сколько раз переключилась
    // модель, а насколько дёрнулась тяга. Меряется наибольший ОТНОСИТЕЛЬНЫЙ
    // скачок тяги за шаг на установившемся окне; в здоровом обтекании он равен
    // нулю (замер: 0.0…0.7 Н из шестисот), при разрыве — десятки ньютонов.
    // Обе мерки берутся на УСТАНОВИВШЕМСЯ окне (после десяти секунд), и это не
    // удобство. Разнос — вещь стойкая: настоящая неустойчивость растёт и
    // держится, а одиночный выброс Γ на стартовом переходнике (замер: Γ 744 на
    // одном шаге при t = 9.7 с, следующий шаг уже здоров) — это не разнос, и
    // красить им клетку значит ловить переходник, а не решение. Скачок тяги —
    // тем более про установившийся режим.
    let gmax = 0, jump = 0, prevDrive = null, refDrive = 1;
    for (let i = 0; i < 25 * 30; i++) {
      b.o.rudderTarget = Math.max(-25 * D, Math.min(25 * D,
        -(2.2 * wrap((100 - twa) * D - b.psi) - 0.9 * b.r)));
      b.step(1 / 30);
      if (i <= 10 * 30) { prevDrive = b.telemetry.driveN; continue; }
      const Gs = b.rig.stripGamma;
      if (Gs) for (let k = 0; k < Gs.length; k++) gmax = Math.max(gmax, Math.abs(Gs[k]));
      const drive = b.telemetry.driveN;
      if (Number.isFinite(drive)) {
        refDrive = Math.max(refDrive, Math.abs(drive));
        if (prevDrive !== null) jump = Math.max(jump, Math.abs(drive - prevDrive));
      }
      prevDrive = drive;
    }
    return { gmax, v: b.telemetry.speedKn, fuse: b.rig.fuseTrips || 0,
             jump: jump / refDrive };
  };
  // КАЖДАЯ КЛЕТКА МЕРЯЕТСЯ ДВАЖДЫ, с двух начальных ходов, и берётся ХУДШЕЕ.
  //
  // Не запас прочности, а исправление свидетеля. Правило проекта прямо говорит:
  // один прогон при одном значении параметра свидетелем не считается, — и карта
  // это правило нарушала. Замер: клетка 135°/4.5 при начальных ходах 3.000,
  // 3.001, 3.010, 3.050, 3.100 узла даёт скачок 3.4, 6.6, 2.9, 5.2, 4.5 % (это
  // на HEAD `d0929fd`, до правки выталкивания), то есть от ТЫСЯЧНОЙ УЗЛА ходит
  // через порог в обе стороны. Зелёной она была не по замеру, а по тому, какое
  // число стояло начальным ходом.
  //
  // Остальные клетки при том же возмущении стоят побитово: 135°/5.5, 120°/5.5 и
  // 150°/6.5 дают размах 0.0 процентных пункта. То есть хаотична не карта, а
  // одна её клетка, и знать про это надо явно, а не узнавать случайно.
  //
  // Двух точек хватает: они ловят именно то, что клетка неустойчива к начальным
  // данным. Цена — вдвое дольше прогон карты, и это дешевле, чем принимать
  // решения по монетке.
  const run = (len, twa = 140) => {
    const a = once(len, twa, 3), b2 = once(len, twa, 3.05);
    return {
      gmax: Math.max(a.gmax, b2.gmax),
      jump: Math.max(a.jump, b2.jump),
      fuse: Math.max(a.fuse, b2.fuse),
      v: a.v,
    };
  };
  // Предел: рабочая циркуляция полоски здесь порядка тридцати, сотня — уже с
  // запасом вдвое, а разнос всегда уходит на порядки, а не на проценты.
  const LIMIT = 300;
  let worst = 0, worstAt = 0;
  for (let L = 4.0; L <= 7.01; L += 0.2) {
    const r = run(L);
    if (r.gmax > worst) { worst = r.gmax; worstAt = L; }
    console.log('    шкот %s м:  Γ до %s   ход %s уз   предохранитель %s%s',
      L.toFixed(1), r.gmax.toExponential(1).padStart(9), r.v.toFixed(2),
      String(r.fuse).padStart(3),
      r.gmax > LIMIT ? '   РАЗНОС' : '');
  }
  console.log('');
  check('решение не разносится ни на одном положении шкота', worst < LIMIT,
        'худшее Γ = ' + worst.toExponential(1) + ' при шкоте ' + worstAt.toFixed(1) + ' м');

  // И ТО ЖЕ САМОЕ ПО КУРСУ, потому что одной развёртки мало.
  //
  // Развёртка выше идёт при TWA 140° и однажды уже обманула: по ней объявили,
  // что генакер сделан, а он держался на одном курсе. Двумерная карта показала,
  // что здоровая область — диагональная полоса в (курс, шкот), и середина
  // заявленного диапазона в неё не попадает.
  //
  // Мерка клетки — НЕПРЕРЫВНОСТЬ СИЛЫ, а не число срабатываний предохранителя.
  // Прежде клетку красило `fuse > 2`, и это меряло не то: с гибридным режимом
  // срабатывание предохранителя — штатная передача управления поляре, а не
  // поломка. Больная клетка — та, где тяга ДЁРГАЕТСЯ на переходе, потому что
  // именно рывок тяги лодка и чувствует: скачок в J долей тяги на высоте
  // паруса даёт скачок кренящего момента в ту же долю от парусного, а он у
  // борту соизмерим с восстанавливающим. Порог — пять процентов тяги за шаг:
  // в здоровом обтекании скачок нулевой (0.0…0.7 Н), так что пять процентов
  // (около тридцати ньютонов из шестисот) заведомо выше шума и заведомо ниже
  // рывка, который видно на крене. Разнос (Γ за пределом) остаётся отдельным,
  // более грубым отказом.
  //
  // Заявленный диапазон назван владельцем лодки: «в основном бакштаг, но бывает
  // близко к фордевинду», то есть TWA 120…180°. Проверка стоит на нём целиком, и
  // пока она красная — генакер не сделан, как бы ни выглядела одна развёртка.
  const JUMP = 0.05;
  console.log('\nНепрерывность силы по курсу и шкоту (ветер 6 м/с),',
              'скачок тяги за шаг:\n');
  const TWAS = [120, 135, 150, 165, 180];
  const LENS = [3.5, 4.5, 5.5, 6.5, 7.5];
  let head = '      шкот \\ курс';
  for (const t of TWAS) head += (t + '°').padStart(12);
  console.log(head);
  let bad = 0, badAt = '';
  for (const L of LENS) {
    let line = ('    ' + L.toFixed(1) + ' м').padStart(17);
    for (const t of TWAS) {
      const r = run(L, t);
      const ill = r.gmax > LIMIT || r.jump > JUMP;
      if (ill) { bad++; if (!badAt) badAt = 'TWA ' + t + '°, шкот ' + L.toFixed(1) + ' м'; }
      const tag = r.gmax > LIMIT ? 'разнос' : (100 * r.jump).toFixed(0) + '%';
      line += ((ill ? '!' : ' ') + tag).padStart(12);
    }
    console.log(line);
  }
  console.log('');
  check('на всех заявленных курсах сила непрерывна на переходе', bad === 0,
        bad ? bad + ' клеток из 25, первая — ' + badAt : '');
}

// --- УСТАНОВИВШИЙСЯ РЕЖИМ ОБЯЗАН БЫТЬ УСТАНОВИВШИМСЯ ----------------------------
//
// Карта выше меряет СКАЧОК тяги за шаг, и это ловит разрыв. Но она слепа к
// КОЛЕБАНИЮ: медленная раскачка с плавными краями даёт нулевой скачок за шаг и
// проходит насквозь. А раскачка есть, и немалая — до восьмидесяти шести
// процентов размаха тяги при неизменных ветре, курсе и шкоте.
//
// Нашлось это при разборе петли пелена ↔ решётка (docs/wake.md). Карта гоняется
// на шести метрах в секунду; на десяти те же настройки ведут себя иначе, и
// клетки, чистые на шести, там раскачиваются. Поэтому здесь ветер в развёртке, а
// мерка — размах тяги на установившемся окне, а не скачок за шаг.
//
// Порог взят той же логикой, что и пять процентов у скачка: в здоровой клетке
// размах 0…4 %, в больной 10…86 %, разрыв между ними чистый. Десять процентов
// лежат в этом разрыве и заведомо выше шума.
{
  console.log('\nРазмах тяги на установившемся режиме, % (курс × шкот × ветер):\n');
  const wrap2 = a => ((a + Math.PI) % (2 * Math.PI) + 2 * Math.PI) % (2 * Math.PI) - Math.PI;
  const TWAS2 = [110, 120, 135, 150, 165, 180];
  const LENS2 = [4.5, 5.5, 6.5];
  const SWING = 0.10;
  const swing = (twa, len, wind) => {
    const b = new Boat(PACK);
    b.o.freeWake = true; b.o.wakeForces = true;
    b.o.crewHike = -1; b.o.crewMass = 219.9;
    b.wind.o.gust = 0; b.wind.o.shift = 0;
    b.setGennaker(true);
    b.o.sheet = 70 * D; b.o.twist = 8 * D; b.o.genSheetLen = len;
    b.reset();
    b.o.windSpeed = wind; b.o.windDir = 100 * D; b.u = 3;
    b.psi = (100 - twa) * D;
    let lo = Infinity, hi = -Infinity, sum = 0, n = 0;
    for (let i = 0; i < 28 * 30; i++) {
      b.o.rudderTarget = Math.max(-25 * D, Math.min(25 * D,
        -(2.2 * wrap2((100 - twa) * D - b.psi) - 0.9 * b.r)));
      b.step(1 / 30);
      if (i < 18 * 30) continue;
      const d = b.telemetry.driveN;
      lo = Math.min(lo, d); hi = Math.max(hi, d); sum += d; n++;
    }
    const m = Math.abs(sum / n);
    return m > 1 ? (hi - lo) / m : 0;
  };
  let bad2 = 0, at2 = '', worst2 = 0;
  for (const wind of [6, 10]) {
    console.log(`  ветер ${wind} м/с`);
    let head = '     шкот \\ курс';
    for (const t of TWAS2) head += (t + '°').padStart(9);
    console.log(head);
    for (const L of LENS2) {
      let line = ('    ' + L.toFixed(1) + ' м').padStart(17);
      for (const t of TWAS2) {
        const v = swing(t, L, wind);
        worst2 = Math.max(worst2, v);
        const ill = v > SWING;
        if (ill) { bad2++; if (!at2) at2 = `TWA ${t}°, шкот ${L.toFixed(1)} м, ветер ${wind}`; }
        line += ((ill ? '!' : ' ') + (100 * v).toFixed(0) + '%').padStart(9);
      }
      console.log(line);
    }
  }
  console.log('');
  check('тяга на установившемся режиме не раскачивается', bad2 === 0,
        bad2 ? `${bad2} клеток из ${2 * TWAS2.length * LENS2.length}, худшая ` +
               `${(100 * worst2).toFixed(0)} %, первая — ${at2}`
             : `худший размах ${(100 * worst2).toFixed(0)} %`);
}

