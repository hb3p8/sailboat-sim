// Полный прогон или регрессионный.
//
// Две батареи — лавировочная и физическая — устроены так, что их не сократить
// без потери: одна перебирает настройки паруса (двадцать три установившихся хода
// на каждую точку поляры, и грубее нельзя — оптимум начинает скакать), другая
// держит лодку десять минут, чтобы показать, что она не разгоняется без конца.
// Обе честно нужны, и обе стоят своего времени.
//
// Поэтому у них два режима, и разница между ними — НЕ в проверках, а в том, как
// густо взята сетка и как долго идёт прогон. Проверки одни и те же, все до
// единой, в обоих режимах.
//
//   регрессионный (по умолчанию) — «что-то сломалось?». Гоняется и на итерациях,
//       и перед коммитом, потому и должен быть быстрым.
//   полный (`--full` или SV20_FULL=1) — «что именно сломалось?». Зовётся, когда
//       есть ОСНОВАНИЯ думать, что сломалось: регрессионный покраснел, отпечаток
//       поехал, или правка достаёт туда, что меряется в другом месте.
//
// Цену разделения стоит назвать прямо: редкая сетка может пройти там, где густая
// уже красная. Это не гипотетическая опасность — ровно так одна развёртка по
// шкоту при TWA 140° объявила генакер сделанным, тогда как соседние курсы
// разносились (docs/wake.md). Поэтому «нет оснований» значит «посмотрел, и
// правка сюда не достаёт», а не «не смотрел». Подробнее — в CLAUDE.md.
export const FULL = process.argv.includes('--full') || process.env.SV20_FULL === '1';

// Выбор между полным и регрессионным значением одной строкой.
export const pick = (full, quick) => (FULL ? full : quick);

// Заголовок режима — чтобы по отчёту всегда было видно, что именно гонялось.
export function modeLine() {
  return FULL ? 'режим ПОЛНЫЙ' : 'режим регрессионный (полный: --full)';
}
