// Мембрана: node tests/membrane.test.mjs
//
// Проверяется не «похоже на парус», а совпадение с тем, что можно посчитать
// отдельно. Главная проверка — предельный случай: при равномерном давлении
// мембрана обязана лечь по дуге окружности, а у дуги пузо считается вручную
// из длины хорды и длины дуги. Если это сходится, значит и интегрирование, и
// условие нерастяжимости написаны правильно.
//
// Дальше — свойства, которых от мембраны ждут: пузо не зависит от величины
// давления, горб едет за нагрузкой, передняя кромка сминается первой.

import { sectionShape, membraneCamber, slackOf, luffFraction, sectionLift }
  from '../sim/membrane.js';

let failures = 0;
function check(name, ok, detail) {
  if (!ok) failures++;
  console.log((ok ? '  ok   ' : '  ПЛОХО') + '  ' + name + (detail ? '   ' + detail : ''));
}

const rep = (n, v) => Array.from({ length: n }, () => v);

// --- предельный случай: равномерное давление -> дуга ---------------------------
//
// У пологой дуги длина больше хорды в (1 + 8m²/3) раз, значит по запасу σ пузо
// восстанавливается как m = sqrt(3σ/8). Мембрана обязана дать то же самое.

console.log('\nРавномерное давление: мембрана против дуги окружности\n');
console.log('  проектное пузо   запас длины   пузо мембраны   расхождение');
let worst = 0;
for (const m of [0.02, 0.05, 0.08, 0.10, 0.13, 0.18]) {
  const s = slackOf(m);
  const got = membraneCamber(rep(3, 1), s).camber;
  worst = Math.max(worst, Math.abs(got - m) / m);
  console.log('        ' + (100 * m).toFixed(1).padStart(5) + '%      ' +
    s.toFixed(5).padStart(8) + '        ' + (100 * got).toFixed(2).padStart(6) +
    '%      ' + (100 * (got - m) / m).toFixed(3).padStart(7) + '%');
}
check('на равномерном давлении мембрана даёт дугу', worst < 3e-3,
  'наибольшее расхождение ' + (100 * worst).toFixed(2) + '%');

// Горб дуги стоит ровно посередине.
check('у дуги горб посередине хорды',
  Math.abs(membraneCamber(rep(3, 1), slackOf(0.1)).draft - 0.5) < 0.03,
  membraneCamber(rep(3, 1), slackOf(0.1)).draft.toFixed(3));

// --- пузо не зависит от величины давления --------------------------------------
//
// Это не приближение, а свойство нерастяжимой мембраны: масштаб нагрузки
// уходит в натяжение. Если проверка провалится — значит где-то потерялась
// нормировка и ткань «растянулась».

{
  const s = slackOf(0.11);
  const a = membraneCamber([1, 1.4, 0.8], s).camber;
  const b = membraneCamber([50, 70, 40], s).camber;
  console.log('\nОдно распределение, нагрузка в пятьдесят раз больше: пузо ' +
    (100 * a).toFixed(3) + '% против ' + (100 * b).toFixed(3) + '%\n');
  check('пузо не зависит от величины давления', Math.abs(a - b) < 1e-9);
}

// --- горб едет за нагрузкой -----------------------------------------------------

console.log('Куда едет горб при разном распределении по хорде:\n');
console.log('  нагрузка (нос→корма)      пузо      горб');
const rows = [
  [[2.0, 1.0, 0.4], 'загружен нос'],
  [[1.0, 1.0, 1.0], 'равномерно'],
  [[0.4, 1.0, 2.0], 'загружена корма'],
];
const drafts = [];
for (const [q, label] of rows) {
  const r = membraneCamber(q, slackOf(0.11));
  drafts.push(r.draft);
  console.log('  ' + label.padEnd(22) + (100 * r.camber).toFixed(2).padStart(6) +
    '%   ' + (100 * r.draft).toFixed(0).padStart(4) + '% хорды');
}
console.log('');
check('нагрузка на нос двигает горб вперёд', drafts[0] < drafts[1] - 0.03,
  (100 * drafts[0]).toFixed(0) + '% против ' + (100 * drafts[1]).toFixed(0) + '%');
check('нагрузка на корму двигает горб назад', drafts[2] > drafts[1] + 0.03,
  (100 * drafts[2]).toFixed(0) + '% против ' + (100 * drafts[1]).toFixed(0) + '%');

// Запас длины один и тот же, значит и пузо должно остаться примерно тем же:
// ткани не прибавилось. Меняется форма, а не глубина.
{
  const c = rows.map(([q]) => membraneCamber(q, slackOf(0.11)).camber);
  check('от перекладки нагрузки пузо меняется мало',
    Math.max(...c) / Math.min(...c) < 1.15,
    (100 * Math.min(...c)).toFixed(1) + '…' + (100 * Math.max(...c)).toFixed(1) + '%');
}

// --- смятая доля хорды ----------------------------------------------------------
//
// Передняя кромка сминается первой: как только давление на первой панели
// уходит, держать форму там нечем. Дальше пузырь растёт назад, но панель,
// потерявшая нагрузку посреди хорды, пузырём у шкаторины не считается.
//
// Знак рабочей нагрузки приходит снаружи — это сторона, на которую парус
// поставлен. Из самой нагрузки его брать нельзя: она проходит через ноль на
// каждом перекладывании, и ответ переворачивался бы целиком.

console.log('\nСмятая доля хорды по нагрузке:\n');
console.log('  нагрузка (нос→корма)      доля');
const dead = [];
for (const q of [[1, 1, 1], [0.5, 1, 1], [0.2, 1, 1], [0.05, 1, 1],
                 [-0.3, 1, 1], [-0.3, -0.3, 1], [1, 0.05, 1]]) {
  const f = luffFraction(q, 1);
  dead.push(f);
  console.log('  ' + JSON.stringify(q).padEnd(22) + f.toFixed(3).padStart(8));
}
console.log('');
check('полная нагрузка — мять нечего', dead[0] < 1e-9);
check('нагрузка уходит с носа — смятая доля растёт',
  dead.every((f, i) => i > 3 || i === 0 || f >= dead[i - 1] - 1e-9));
check('обратный знак на носу — смялась передняя панель',
  Math.abs(dead[4] - 1 / 3) < 0.02, dead[4].toFixed(3));
check('обратный знак на двух панелях — смялись обе',
  Math.abs(dead[5] - 2 / 3) < 0.02, dead[5].toFixed(3));
check('провал посреди хорды пузырём у шкаторины не считается',
  dead[6] < 0.02, dead[6].toFixed(3));

// --- двумерное сечение ----------------------------------------------------------
//
// Сверяется с замерами двумерных парусных сечений: дуга с пузом 10% на нулевом
// угле к хорде даёт около 1.1–1.2, потолок около 1.7; плоская пластина — около
// 1.25 на своём наибольшем.

console.log('Двумерное сечение: CL по углу атаки и пузу\n');
console.log('   пузо    α=-4°    α=0°    α=4°    α=8°   α=12°');
for (const m of [0, 0.05, 0.10, 0.15]) {
  let line = '  ' + (100 * m).toFixed(0).padStart(4) + '% ';
  for (const a of [-4, 0, 4, 8, 12]) {
    line += sectionLift(a * Math.PI / 180, m).toFixed(2).padStart(8);
  }
  console.log(line);
}
console.log('');
check('дуга 10% на нулевом угле даёт около 1.15',
  Math.abs(sectionLift(0, 0.10) - 1.15) < 0.15,
  sectionLift(0, 0.10).toFixed(2));
check('пузо поднимает подъёмную силу',
  sectionLift(0, 0.13) > sectionLift(0, 0.08));
check('наклон у малых углов близок к теоретическому 2π',
  Math.abs((sectionLift(0.02, 0) - sectionLift(-0.02, 0)) / 0.04 - 2 * Math.PI)
    / (2 * Math.PI) < 0.06,
  ((sectionLift(0.02, 0) - sectionLift(-0.02, 0)) / 0.04).toFixed(2) +
  ' против ' + (2 * Math.PI).toFixed(2));
check('подъёмная сила упирается в потолок, а не растёт без предела',
  sectionLift(0.5, 0.10) < 1.9, sectionLift(0.5, 0.10).toFixed(2));
check('сечение нечётно по (α, пузо)',
  Math.abs(sectionLift(-0.1, -0.1) + sectionLift(0.1, 0.1)) < 1e-9);

console.log((failures ? failures + ' проверок провалено' : 'все проверки прошли') + '\n');
process.exit(failures ? 1 : 0);
