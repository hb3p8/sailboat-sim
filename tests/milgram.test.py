# -*- coding: utf-8 -*-
"""Сверка с опытом: .venv/bin/python tests/milgram.test.py

Батарея не похожа на остальные, и это нарочно. Остальные проверяют, что код
считает то, что задумано. Эта проверяет, ЧЕГО ОН НЕ УМЕЕТ, — и держит это
числом, чтобы не забылось и чтобы нельзя было тихо объявить задачу решённой.

Данные — NASA CR-1767 (Милгрэм, 1971), опыты на тонких сильно изогнутых
сечениях: средняя линия постоянной кривизны, пузо 12 и 18 процентов, толщина
3.4% с ОСТРЫМИ кромками, числа Рейнольдса 6…12·10⁵. Это ровно тот класс, ради
которого пишется Часть II. Оцифровано с фигур на глаз, точность ±0.03 по Cl;
провенанс и цитаты — в data/section/milgram_cr1767.json.

Итог сверки, если коротко: в области прилипшего потока решатель верен и
бесполезен, потому что у такого сечения прилипшего потока почти не бывает.
Опытная кривая всюду ниже теории тонкого профиля, резкого срыва нет, а
минимальное сопротивление вдесятеро больше, чем у толстого профиля, — потому что
отрыв присутствует ВСЕГДА, с наветренной стороны ниже идеального угла и с
подветренной выше.
"""

import json
import os
import sys

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "src"))

from sv20.bl import march, squire_young  # noqa: E402
from sv20.panel import Panels, milgram_thickness, sail_contour  # noqa: E402
from sv20.section import ideal_angle, zero_lift_angle_exact  # noqa: E402

D = np.pi / 180
failures = 0
REF = json.load(open(os.path.join(ROOT, "data/section/milgram_cr1767.json"), encoding="utf-8"))


def check(name, ok, detail=""):
    global failures
    if not ok:
        failures += 1
    print(("  ok   " if ok else "  ПЛОХО") + "  " + name + ("   " + detail if detail else ""))


def solve(f, alpha, re, n=400):
    """Наш ответ на секции Милгрэма: невязкий Cl, доля прилипшей хорды, Cl и Cd."""
    x, y = sail_contour(f=f, p=0.5, n=n, thick=milgram_thickness)
    pn = Panels(x, y).solve(alpha)
    (sb, ub), (sf, uf) = pn.sides()
    lee = march(sf, uf, 1.0 / re, s_tr=0.03)
    wind = march(sb, ub, 1.0 / re, s_tr=0.03)
    frac = (lee["s_sep"] / sf[-1]) if lee["s_sep"] else 1.0
    cl = pn.cl * ((1 + np.sqrt(frac)) / 2) ** 2          # замыкание Кирхгофа
    cd = (squire_young(lee["theta_te"], lee["ue_te"], lee["h_te"])
          + squire_young(wind["theta_te"], wind["ue_te"], wind["h_te"]))
    return pn.cl, frac, cl, cd


# --- сами данные: не переврана ли оцифровка -----------------------------------
#
# Проверяется то, что отчёт УТВЕРЖДАЕТ ТЕКСТОМ, против того, что снято с фигур.
# Если при переносе чисел сползла строка, здесь это и вылезет.
print("\nЧто говорит отчёт и что снято с фигур:\n")
for key in ("65-12", "65-18"):
    d = REF[key]
    a = np.array(d["alpha_deg"], float)
    cl = np.array(d["cl"], float)
    i = int(np.argmax(cl))
    print("  %s: Cl_max = %.2f на %.0f°;  теория тонкого профиля там же %.2f"
          % (key, cl[i], a[i], 2 * np.pi * np.sin((a[i] - zero_lift_angle_exact(d["пузо"], 0.5) / D) * D)))
print("")

for key in ("65-12", "65-18"):
    d = REF[key]
    a = np.array(d["alpha_deg"], float)
    cl = np.array(d["cl"], float)
    th = 2 * np.pi * np.sin(a * D - zero_lift_angle_exact(d["пузо"], 0.5))
    # Утверждение отчёта («опыт всегда ниже теории») проверяется в рабочей
    # области — выше теоретического угла нулевой подъёмной силы. Ниже него
    # сравнивать не с чем: у 65-18 опытная кривая вообще НЕ ПЕРЕСЕКАЕТ ноль на
    # всём диапазоне до −24°, а теория там давно в минусе. Это не противоречие, а
    # та же самая причина — сечение оторвано всегда, и на отрицательных углах оно
    # держит остаточную подъёмную силу от пуза вместо теоретического минуса.
    work = a * D > zero_lift_angle_exact(d["пузо"], 0.5) + 5 * D
    check("%s: в рабочей области опыт всюду ниже теории тонкого профиля" % key,
          bool(np.all(cl[work] < th[work] + 0.05)),
          "худший запас %.2f" % float(np.min(th[work] - cl[work])))
    i = int(np.argmax(cl))
    check("%s: наибольшая подъёмная сила достигается за пятнадцатью градусами" % key,
          a[i] >= 15, "Cl_max = %.2f на %.0f°" % (cl[i], a[i]))
    after = cl[i + 1:]
    check("%s: резкого срыва нет — за пиком теряется меньше десятой" % key,
          after.size and float((cl[i] - after.min()) / cl[i]) < 0.10,
          "падение %.1f%%" % (float((cl[i] - after.min()) / cl[i]) * 100))

# Отдельно — та самая остаточная подъёмная сила ниже теоретического нуля. У
# 65-18 при пузе 18% опыт не уходит в минус ВОВСЕ на всём диапазоне до −24°,
# хотя теория там даёт −0.37. Это и есть подпись «оторвано всегда».
c18 = np.array(REF["65-18"]["cl"], float)
check("65-18: опыт не уходит в минус даже на −24°, где теория уже в минусе",
      bool(np.all(c18 > 0)) and 2 * np.pi * np.sin(-24 * D - zero_lift_angle_exact(0.18, 0.5)) < -0.2,
      "наименьшее опытное %.2f при теоретическом %.2f"
      % (float(c18.min()), 2 * np.pi * np.sin(-24 * D - zero_lift_angle_exact(0.18, 0.5))))

cd = np.array(REF["65-12"]["cd"], float)
check("минимальное сопротивление совпадает с заявленным в тексте 0.06",
      abs(float(cd.min()) - 0.06) < 0.015, "%.3f по фигуре" % float(cd.min()))
check("сопротивление вдесятеро больше, чем у толстого профиля (0.006)",
      float(cd.min()) / 0.006 > 5, "в %.0f раз" % (float(cd.min()) / 0.006))
# Идеальный угол у дуги постоянной кривизны нулевой — и это единственное число,
# в котором наша теория и опыт Милгрэма сходятся без оговорок: минимум
# сопротивления на фигуре 6b лежит на 1…3°, а не где попало.
i_cd = int(np.argmin(cd))
check("минимум сопротивления лежит у идеального угла, а тот нулевой",
      abs(REF["65-12"]["alpha_deg"][i_cd] - ideal_angle(0.12, 0.5) / D) < 4,
      "минимум на %.0f°, идеальный угол %.1f°"
      % (REF["65-12"]["alpha_deg"][i_cd], ideal_angle(0.12, 0.5) / D))

# --- наш расчёт против опыта --------------------------------------------------
print("\n65-12 (пузо 12%, острые кромки), Re = 9·10⁵:\n")
print("     α    опыт   теория тонк.   наш невязкий   прилипло   наш вязкий      Cd опыт   Cd наш")
d = REF["65-12"]
worst_lo, worst_hi = 0.0, 0.0
for a, cl_e, cd_e in zip(d["alpha_deg"], d["cl"], d["cd"]):
    if not -8 <= a <= 20:
        continue
    cli, frac, clv, cdv = solve(0.12, a * D, 9e5)
    th = 2 * np.pi * np.sin(a * D - zero_lift_angle_exact(0.12, 0.5))
    print("  %5d° %7.2f %13.2f %14.2f %10.3f %12.2f %12.3f %8.3f"
          % (a, cl_e, th, cli, frac, clv, cd_e, cdv))
    if cl_e > 0.3:
        worst_lo = max(worst_lo, (cl_e - clv) / cl_e)      # мы ниже опыта
    if a < 0:
        worst_hi = max(worst_hi, (clv - cl_e) / max(cl_e, 0.1))   # мы выше опыта
print("")

# Вот это и есть итог сверки, и он записан числом нарочно. Ниже идеального угла
# решатель считает поток прилипшим и завышает подъёмную силу в разы — потому что
# замыкание Кирхгофа смотрит только на подветренную сторону, а у Милгрэма ниже
# идеального угла отрывается НАВЕТРЕННАЯ. Выше идеального угла решатель, наоборот,
# объявляет полный отрыв и занижает — потому что у настоящего сечения носовой
# пузырь присоединяется обратно, а прямой марш такого не умеет.
#
# ЕСЛИ ЭТА ПРОВЕРКА УПАЛА — скорее всего, модель починили. Тогда сюда надо
# вписать новое, меньшее число, а не убрать проверку.
check("известный промах ВЫШЕ идеального угла: занижаем вдвое и больше",
      worst_lo > 0.4, "наибольшее занижение %.0f%%" % (worst_lo * 100))
check("известный промах НИЖЕ идеального угла: завышаем в разы",
      worst_hi > 1.0, "наибольшее завышение %.0f%%" % (worst_hi * 100))

# И третий промах, самый неприятный: у порога отрыва ответ не сходится по сетке.
# Прямая (несовместная) постановка даёт около нужного угла раздвоение — либо
# поток прилипший до задней кромки, либо оторванный с носка, — и на какую ветвь
# он сядет, решает разбивка, а не физика. У 65-12 на нуле градусов при четырёхстах
# панелях прилипло 96% хорды, при пятистах — ноль.
print("Доля прилипшей хорды на нуле градусов по числу панелей:\n")
grid = []
for n_ in (200, 400, 500, 800):
    _, fr, _, _ = solve(0.12, 0.0, 9e5, n=n_)
    grid.append(fr)
    print("  %4d панелей: %.3f" % (n_, fr))
print("")
check("у порога отрыва ответ не сходится по сетке — это известно и это не мелочь",
      max(grid) - min(grid) > 0.5,
      "от %.3f до %.3f" % (min(grid), max(grid)))

# А это то, что сходится: невязкая часть. Ради неё панельный метод и писался, и
# она остаётся верной — просто её одной мало.
bad = 0.0
for a in (-8, -4, 0, 4, 8):
    cli, _, _, _ = solve(0.12, a * D, 9e5)
    th = 2 * np.pi * np.sin(a * D - zero_lift_angle_exact(0.12, 0.5))
    bad = max(bad, abs(cli / th - 1))
check("невязкая часть сходится с теорией тонкого профиля",
      bad < 0.06, "худшее расхождение %.1f%%" % (bad * 100))

print(("%d проверок провалено" % failures) if failures else "все проверки прошли")
print("")
sys.exit(1 if failures else 0)
