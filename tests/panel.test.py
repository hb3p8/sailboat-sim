# -*- coding: utf-8 -*-
"""Панельный метод против точных решений: .venv/bin/python tests/panel.test.py

Главная проверка здесь одна и она точная: обтекание цилиндра. На окружности
скорость известна с точностью до буквы, U = 2·U∞·sin θ, и никакая ошибка в
знаке, в нормали или в собственном влиянии панели этого не переживёт. Так и
вышло: первая редакция считала собственную панель общей формулой, где знак нуля
под atan2 решал, выйдет π или −π, — и на цилиндре давала ошибку в полторы
скорости при любой разбивке.

Вторая проверка — против тонкой пелены (`section.py`). Это два независимых
решателя одной задачи, и на малой толщине они обязаны сойтись; расходиться им
позволено ровно на толщинную поправку, которая известна по знаку и по порядку.
"""

import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from sv20.panel import (Panels, cylinder_contour,  # noqa: E402
                        luff_thickness, naca_thickness, sail_contour)
from sv20.section import Section  # noqa: E402

D = np.pi / 180
failures = 0


def check(name, ok, detail=""):
    global failures
    if not ok:
        failures += 1
    print(("  ok   " if ok else "  ПЛОХО") + "  " + name + ("   " + detail if detail else ""))


# --- цилиндр ------------------------------------------------------------------
print("\nОбтекание цилиндра, точное решение U = 2·sin θ:\n")
print("   панелей   худшая ошибка скорости    Cl")
worst = 0.0
for n in (60, 120, 240, 480):
    x, y = cylinder_contour(n=n)
    p = Panels(x, y).solve(0.0)
    ang = np.arctan2(-p.my, p.mx - 0.5)
    err = float(np.max(np.abs(np.abs(p.vt) - 2 * np.abs(np.sin(ang)))))
    worst = max(worst, err)
    print("  %8d %22.2e %9.2e" % (n, err, p.cl))
print("")

check("на цилиндре скорость точная при любой разбивке", worst < 1e-12,
      "худшая ошибка %.2e" % worst)
check("на цилиндре подъёмной силы нет", abs(p.cl) < 1e-12, "%.2e" % p.cl)
check("на цилиндре нет и сопротивления по давлению (парадокс Даламбера)",
      abs(float(np.sum(p.cp * p.nx * p.ds))) < 1e-12)
# Цилиндр под углом сюда не годится, и это стоит записать, чтобы не вернуться:
# условие Кутты ставится на две панели у задней кромки, а у окружности задней
# кромки нет — на угле оно просто навязывает ей циркуляцию. Вместо этого
# проверяется независимость от системы координат: обвод и поток поворачиваются
# вместе, ответ обязан не измениться ни в одном разряде.
bx, by = sail_contour(f=0.10, p=0.5, t=0.03, n=400)
base = Panels(bx, by).solve(5 * D)
b = 37 * D
rot = Panels(bx * np.cos(b) - by * np.sin(b), bx * np.sin(b) + by * np.cos(b)).solve(5 * D + b)
check("ответ не зависит от того, как повёрнуты оси",
      float(np.max(np.abs(rot.vt - base.vt))) < 1e-9 and abs(rot.cl - base.cl) < 1e-9,
      "скорость расходится на %.1e, Cl на %.1e"
      % (float(np.max(np.abs(rot.vt - base.vt))), abs(rot.cl - base.cl)))

try:
    Panels(np.array([0.0, 1.0, 0.5]), np.array([0.0, 0.0, 0.5]))
    check("незамкнутый обвод отвергается", False)
except ValueError:
    check("незамкнутый обвод отвергается", True)

# --- носок --------------------------------------------------------------------
#
# Это не мелочь оформления, а то, из-за чего первая редакция объявляла парус
# сорванным с двух градусов. Радиус носка у NACA равен 1.1019·t², у круглого
# носка — t/2: при трёх процентах толщины это пятнадцать раз, при двух — двадцать
# два. Пик разрежения падает как корень из радиуса, и на NACA он выходил вдвое
# с лишним выше, чем слой способен пережить.
print("Радиус носка при толщине 3%:\n")
xs = np.array([1e-6, 1e-5, 1e-4])
r_naca = float(np.mean(naca_thickness(xs, 0.03) ** 2 / (2 * xs)))
r_luff = float(np.mean(luff_thickness(xs, 0.03) ** 2 / (2 * xs)))
print("   NACA:    %.6f хорды (теория 1.1019·t² = %.6f)" % (r_naca, 1.1019 * 0.03**2))
print("   круглый: %.6f хорды (теория t/2 = %.4f)\n" % (r_luff, 0.015))
check("у NACA радиус носка равен 1.1019·t²", abs(r_naca / (1.1019 * 0.03**2) - 1) < 0.02,
      "%.6f" % r_naca)
check("у круглого носка радиус равен половине толщины", abs(r_luff / 0.015 - 1) < 0.02,
      "%.6f" % r_luff)
check("круглый носок тупее NACA на порядок с лишним", r_luff / r_naca > 10,
      "в %.0f раз при толщине 3%%" % (r_luff / r_naca))
check("толщина смыкается на задней кромке",
      abs(float(luff_thickness(np.array([1.0]), 0.03)[0])) < 1e-12
      and abs(float(naca_thickness(np.array([1.0]), 0.03)[0])) < 1e-12)

# --- против тонкой пелены -----------------------------------------------------
#
# Толщина поднимает наклон кривой подъёмной силы — известно и по знаку, и по
# порядку (для тонких профилей примерно 1 + 0.8·t/c). Проверяется, что при
# стремлении толщины к нулю два решателя сходятся, а с ростом — расходятся
# именно в эту сторону и примерно на столько.
print("Панели против тонкой пелены (пузо 0.10, 5°):\n")
print("   толщина     Cl панели   Cl по Cp    Cl пелены    разница   1 + 0.8·t/c")
rows = []
for t in (0.005, 0.01, 0.02, 0.05):
    pp = Panels(*sail_contour(f=0.10, p=0.5, t=t, n=600)).solve(5 * D)
    sec = Section(f=0.10, p=0.5, n=600).solve(5 * D)
    rows.append((t, pp.cl / sec.cl - 1))
    print("  %9.3f %11.4f %11.4f %12.4f %10.2f%% %12.2f%%"
          % (t, pp.cl, pp.cl_from_cp, sec.cl, (pp.cl / sec.cl - 1) * 100, 0.8 * t * 100))
print("")

check("при стремлении толщины к нулю решатели сходятся", abs(rows[0][1]) < 0.01,
      "%.2f%% при толщине полпроцента" % (rows[0][1] * 100))
check("толщина поднимает подъёмную силу, и монотонно",
      all(rows[i][1] > rows[i - 1][1] for i in range(1, len(rows))),
      ", ".join("%.2f%%" % (r * 100) for _, r in rows))
check("поправка на толщину того же порядка, что известная",
      all(0.3 * 0.8 * t < r < 2.5 * 0.8 * t for t, r in rows[1:]),
      ", ".join("%.2f%% против %.2f%%" % (r * 100, 0.8 * t * 100) for t, r in rows[1:]))
# Два способа посчитать подъёмную силу по одному решению: через циркуляцию и
# интегрированием давления. Расходятся они на ошибку разбивки, и это удобный
# внутренний признак — если разойдутся сильно, дело не в физике.
pp = Panels(*sail_contour(f=0.10, p=0.5, t=0.03, n=600)).solve(6 * D)
check("циркуляция и интеграл давления дают одно и то же",
      abs(pp.cl / pp.cl_from_cp - 1) < 0.02,
      "%.4f против %.4f" % (pp.cl, pp.cl_from_cp))

# --- симметрия и точка торможения ---------------------------------------------
print("Точка торможения (пузо 0.10, толщина 3%):\n")
print("     α      x точки торможения    пик скорости на подветренной")
xs_stag = []
for a in (-4, 0, 4, 8, 12):
    pp = Panels(*sail_contour(f=0.10, p=0.5, t=0.03, n=600)).solve(a * D)
    i = pp.stagnation()
    (sb, ub), (sf, uf) = pp.sides()
    xs_stag.append(pp.mx[i])
    print("  %5d° %18.5f %28.2f" % (a, pp.mx[i], uf.max()))
print("")

sym = Panels(*sail_contour(f=0.0, p=0.5, t=0.03, n=600)).solve(0.0)
check("у симметричного сечения на нулевом угле подъёмной силы нет",
      abs(sym.cl) < 1e-9, "%.2e" % sym.cl)
check("и точка торможения у него ровно на носке", sym.mx[sym.stagnation()] < 1e-3,
      "x = %.2e" % sym.mx[sym.stagnation()])
check("с ростом угла точка торможения уходит назад по наветренной, и монотонно",
      all(xs_stag[i] > xs_stag[i - 1] for i in range(1, len(xs_stag))),
      ", ".join("%.4f" % v for v in xs_stag))
check("скорость в точке торможения близка к нулю",
      abs(pp.vt[pp.stagnation()]) < 0.2, "%.4f" % abs(pp.vt[pp.stagnation()]))
# Условие Кутты: давление на двух панелях у задней кромки обязано совпасть.
check("условие Кутты выполняется: давления у задней кромки равны",
      abs(pp.cp[0] - pp.cp[-1]) < 0.02,
      "Cp %.4f и %.4f" % (pp.cp[0], pp.cp[-1]))

print(("%d проверок провалено" % failures) if failures else "все проверки прошли")
print("")
sys.exit(1 if failures else 0)
