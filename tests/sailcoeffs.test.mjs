// Коэффициенты паруса против опыта: node tests/sailcoeffs.test.mjs
//
// Это первая батарея, которая проверяет модель паруса не на самосогласованность,
// а на СОВПАДЕНИЕ С ИЗМЕРЕННЫМ. До неё `sailCoeffs` держался на том, что кривая
// выглядит правдоподобно и лодка едет.
//
// Данные — два опыта на сечениях постоянной кривизны:
//
//   Уоллис, ARL Aero Note 74 (1946)   пластины t/c = 0.02, пузо 0…10%, Re 3…6·10⁵
//   Милгрэм, NASA CR-1767 (1971)      острые кромки, пузо 12…18%, Re 6…12·10⁵
//
// Первый накрывает нашу рабочую область целиком (пузо 3.3…11.9%, медиана 7.5%
// по `node scripts/sail_envelope.mjs`), второй лежит выше неё и служит верхней
// опорой. Провенанс и оговорки — в самих файлах данных.
//
// Углы у обоих опытов отсчитываются от хорды, как и у `sailCoeffs`.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { sailCoeffs } from '../sim/aero.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const W = JSON.parse(readFileSync(join(ROOT, 'data/section/wallis_arl74.json'), 'utf8'));
const M = JSON.parse(readFileSync(join(ROOT, 'data/section/milgram_cr1767.json'), 'utf8'));
const D = Math.PI / 180;

let failures = 0;
const check = (name, ok, detail) => {
  if (!ok) failures++;
  console.log((ok ? '  ok   ' : '  ПЛОХО') + '  ' + name + (detail ? '   ' + detail : ''));
};

// --- подъёмная сила против Уоллиса --------------------------------------------
console.log('\nУоллис, дуга t/c = 0.02, Re = 6·10⁵ — против sailCoeffs:\n');
const A = W.Re6e5.alpha_deg;
let worstMid = 0, worstLow = 0;
for (const key of ['0.04', '0.06', '0.08']) {
  const cam = Number(key), row = W.Re6e5['пузо'][key];
  console.log('  пузо ' + (cam * 100).toFixed(0) + '%:');
  console.log('       α    опыт   sailCoeffs   отношение');
  for (let i = 0; i < A.length; i++) {
    if (row[i] === null || A[i] % 2 !== 0 || A[i] < 0) continue;
    const cl = sailCoeffs(A[i] * D, cam, 1).cl;
    const r = cl / row[i];
    if (A[i] >= 4) worstMid = Math.max(worstMid, Math.abs(r - 1));
    else worstLow = Math.max(worstLow, r - 1);
    console.log('    %s° %s %s %s', String(A[i]).padStart(4),
      row[i].toFixed(2).padStart(7), cl.toFixed(2).padStart(12), r.toFixed(2).padStart(11));
  }
  console.log('');
}

// Главный вывод: на рабочих углах назначенная кривая совпадает с опытом с
// точностью, которой от неё никто не требовал. Это стоит закрепить, чтобы не
// сломать при следующей правке.
check('на углах 4…12° подъёмная сила сходится с опытом в пределах десятой',
  worstMid < 0.12, 'худшее отклонение ' + (worstMid * 100).toFixed(0) + '%');
// А это известный промах, и он записан числом: у самого малого угла назначенная
// кривая идёт выше опыта. Причина видна из данных: у пластины подъёмная сила при
// нулевом угле составляет 0.67…0.84 от теории тонкого профиля (вязкое
// раскамберивание), а `sectionLift` берёт её почти по теории.
//
// ЕСЛИ ЭТА ПРОВЕРКА УПАЛА — вероятно, модель починили. Впишите новое, меньшее
// число, а не убирайте проверку.
check('известный промах: у нуля градусов завышаем, и заметно',
  worstLow > 0.25, 'наибольшее завышение ' + (worstLow * 100).toFixed(0) + '%');

// --- наибольшая подъёмная сила -------------------------------------------------
console.log('Наибольшая подъёмная сила по пузу (Уоллис, Re = 3·10⁵):\n');
console.log('    пузо    опыт   sailCoeffs   угол опыта');
let worstMax = 0;
const cams = W.Re3e5_максимумы['пузо'], cls = W.Re3e5_максимумы.cl_max;
for (let i = 0; i < cams.length; i++) {
  let best = 0;
  for (let a = 0; a <= 30; a += 0.25) best = Math.max(best, sailCoeffs(a * D, cams[i], 1).cl);
  worstMax = Math.max(worstMax, Math.abs(best / cls[i] - 1));
  console.log('  %s%% %s %s %s°', (cams[i] * 100).toFixed(0).padStart(5),
    cls[i].toFixed(2).padStart(8), best.toFixed(2).padStart(11),
    W.Re3e5_максимумы.alpha_max[i].toFixed(1).padStart(11));
}
console.log('');
// Отклонение не одно на всём диапазоне, а с наклоном: при малом пузе назначенная
// кривая завышает вершину, при большом занижает. То есть Cl_max у неё растёт с
// пузом слишком полого. В нашей рабочей области (пузо 4…10%, медиана 7.5%) это
// укладывается в десятую, у плоской пластины — четверть, но туда лодка почти не
// заходит: пятый процентиль по пузу 3.3%.
const rel = cams.map((c, i) => {
  let best = 0;
  for (let a = 0; a <= 30; a += 0.25) best = Math.max(best, sailCoeffs(a * D, c, 1).cl);
  return best / cls[i];
});
const work = cams.map((c, i) => i).filter(i => cams[i] >= 0.04);
check('в рабочей области пуза вершина сходится с опытом в пределах десятой',
  work.every(i => Math.abs(rel[i] - 1) < 0.12),
  'от ' + Math.min(...work.map(i => rel[i])).toFixed(2) +
  ' до ' + Math.max(...work.map(i => rel[i])).toFixed(2));
check('известный промах: у плоской пластины вершина завышена на четверть',
  rel[0] > 1.2, 'в ' + rel[0].toFixed(2) + ' раза');
check('и наклон промаха тот самый: с пузом отношение падает, а не скачет',
  rel.every((v, i) => i === 0 || v < rel[i - 1] + 0.01),
  rel.map(v => v.toFixed(2)).join(', '));
check('вершина растёт с пузом, как в опыте',
  cams.every((c, i) => i === 0 || cls[i] > cls[i - 1]));

// --- сопротивление -------------------------------------------------------------
//
// Здесь расхождение настоящее, и его надо назвать. Уоллис на гладкой пластине
// мерит минимум 0.017 и рекомендует расчётные 0.02; Милгрэм на острых кромках и
// большом пузе — 0.06. Наша модель назначает 0.02 + 0.25·пузо, то есть 0.03…0.04
// в рабочей области: вдвое выше гладкой пластины и вдвое ниже острого сечения.
//
// Это не обязательно ошибка: у паруса ткань шершавая, есть швы и карманы лат, а
// у грота на передней кромке мачта. Но выбрано это было без данных, и теперь
// известно, между чем оно лежит.
console.log('Сопротивление:\n');
console.log('    пузо   sailCoeffs   Уоллис (гладкая пластина)   Милгрэм (острые кромки)');
for (const cam of [0.04, 0.08, 0.12]) {
  console.log('  %s%% %s %s %s', (cam * 100).toFixed(0).padStart(5),
    sailCoeffs(4 * D, cam, 1).cd.toFixed(4).padStart(12),
    (cam <= 0.08 ? W['заявлено_текстом']['минимальное_профильное_сопротивление'].toFixed(3) : '   —').padStart(26),
    (cam >= 0.12 ? M['заявлено_текстом']['минимальное_сопротивление'].toFixed(3) : '   —').padStart(23));
}
console.log('');
const cd8 = sailCoeffs(4 * D, 0.08, 1).cd;
check('сопротивление лежит между гладкой пластиной и острым сечением',
  cd8 > W['заявлено_текстом']['минимальное_профильное_сопротивление']
  && cd8 < M['заявлено_текстом']['минимальное_сопротивление'],
  cd8.toFixed(4) + ' против 0.017 и 0.060');
check('известный промах: вдвое выше гладкой пластины',
  cd8 / W['заявлено_текстом']['минимальное_профильное_сопротивление'] > 1.8,
  'в ' + (cd8 / W['заявлено_текстом']['минимальное_профильное_сопротивление']).toFixed(1) + ' раза');

// --- два опыта против друг друга ------------------------------------------------
//
// Данным Уоллиса сорок шестого года разумно не верить на слово, и проверить их
// есть чем: у нас есть второй опыт, независимый — другая лаборатория, другая
// страна, двадцать пять лет спустя, другие сечения. Общего у них ничего, кроме
// физики.
//
// Сравнивать напрямую нечего (у Уоллиса пузо 4…10%, у Милгрэма 12…18%), но есть
// величина, которая осмысленна у обоих: во сколько раз измеренная подъёмная сила
// на идеальном угле НИЖЕ теории тонкого профиля. Это и есть вязкое
// раскамберивание, и оно обязано меняться с пузом плавно, без ступеньки на стыке
// между опытами.
console.log('Уоллис против Милгрэма: измеренное Cl на нулевом угле в долях теории 4π·f\n');
console.log('     пузо   опыт     4π·f   доля      источник');
const ratio = [];
for (const [cam, cl, who] of [
  [0.04, W.Re6e5['пузо']['0.04'][A.indexOf(0)], 'Уоллис 1946'],
  [0.06, W.Re6e5['пузо']['0.06'][A.indexOf(0)], 'Уоллис 1946'],
  [0.08, W.Re6e5['пузо']['0.08'][A.indexOf(0)], 'Уоллис 1946'],
  [0.12, M['65-12'].cl[M['65-12'].alpha_deg.indexOf(0)], 'Милгрэм 1971'],
  [0.18, M['65-18'].cl[M['65-18'].alpha_deg.indexOf(0)], 'Милгрэм 1971'],
]) {
  const th = 4 * Math.PI * cam;
  ratio.push([cam, cl / th, who]);
  console.log('  %s%% %s %s %s   %s', (cam * 100).toFixed(0).padStart(6),
    cl.toFixed(2).padStart(6), th.toFixed(2).padStart(8),
    (cl / th).toFixed(3).padStart(7), who);
}
console.log('');
check('раскамберивание падает с пузом монотонно, без ступеньки между опытами',
  ratio.every((r, i) => i === 0 || r[1] < ratio[i - 1][1]),
  ratio.map(r => r[1].toFixed(2)).join(' → '));
// Стык: 8% у Уоллиса и 12% у Милгрэма — соседние точки из РАЗНЫХ опытов. Если бы
// кто-то из двоих врал, здесь была бы ступенька.
check('на стыке двух опытов доли совпадают в пределах пяти сотых',
  Math.abs(ratio[2][1] - ratio[3][1]) < 0.05,
  ratio[2][1].toFixed(3) + ' (Уоллис, 8%) против ' + ratio[3][1].toFixed(3) + ' (Милгрэм, 12%)');

// --- верхняя опора: Милгрэм ----------------------------------------------------
console.log('Милгрэм, пузо 12%, Re = 9·10⁵ (выше нашей рабочей области):\n');
console.log('       α    опыт   sailCoeffs   отношение');
let worst12 = 0;
const ma = M['65-12'].alpha_deg, mc = M['65-12'].cl;
for (let i = 0; i < ma.length; i++) {
  if (ma[i] < 4 || ma[i] > 18) continue;
  const cl = sailCoeffs(ma[i] * D, 0.12, 1).cl;
  worst12 = Math.max(worst12, Math.abs(cl / mc[i] - 1));
  console.log('    %s° %s %s %s', String(ma[i]).padStart(4), mc[i].toFixed(2).padStart(7),
    cl.toFixed(2).padStart(12), (cl / mc[i]).toFixed(2).padStart(11));
}
console.log('');
check('на большом пузе расходимся сильнее, но в пределах трети',
  worst12 < 0.35, 'худшее отклонение ' + (worst12 * 100).toFixed(0) + '%');

console.log(failures ? failures + ' проверок провалено' : 'все проверки прошли');
console.log('');
process.exit(failures ? 1 : 0);
