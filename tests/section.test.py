# -*- coding: utf-8 -*-
"""Сечение против теории тонкого профиля: .venv/bin/python tests/section.test.py

Решатель поверяется не на парусе, а там, где ответ известен точно:

    плоская пластина        Cl = 2π·sin α,  момент по кромке = −Cl/4
    малое пузо              α₀ = −2f/c и интеграл Глауэрта

Это единственный способ поверить такую вещь. На парусе «похоже на правду» не
значит ничего: подъёмная сила выйдет гладкой кривой при любой ошибке в
множителе, а угол нулевой подъёмной силы на глаз не виден вовсе.

Про sin α стоит сказать отдельно, потому что первая редакция этой батареи
сверяла с 2π·α и падала. Расхождение было 0.127% на пяти градусах и не менялось
от числа панелей вовсе — по чему и стало понятно, что это не разбивка, а
sin 5° / 5°. Линейная теория пишет 2π·α, потому что линеаризует; решатель не
линеаризует, и прав он, а не она.
"""

import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from sv20.section import (Section, cl_converged, ideal_angle,  # noqa: E402
                          zero_lift_angle_exact)

D = np.pi / 180
failures = 0


def check(name, ok, detail=""):
    global failures
    if not ok:
        failures += 1
    print(("  ok   " if ok else "  ПЛОХО") + "  " + name + ("   " + detail if detail else ""))


# --- плоская пластина ---------------------------------------------------------
print("\nПлоская пластина, угол атаки 5°:\n")
print("   панелей    Cl расчёт    2π·sin α       откл.")
exact = 2 * np.pi * np.sin(5 * D)
worst = 0.0
for n in (1, 4, 20, 80, 200):
    cl = Section(f=0.0, n=n).solve(5 * D).cl
    worst = max(worst, abs(cl / exact - 1))
    print("  %6d %13.7f %12.7f %11.2e" % (n, cl, exact, abs(cl / exact - 1)))
print("")

# Одна панель обязана дать точный ответ — ради этого вихрь и стоит в четверти, а
# контрольная точка в трёх четвертях. Если это сломается, значит размещение
# уехало, и все остальные числа станут просто похожими на правду.
check("плоская пластина даёт 2π·sin α при любом числе панелей", worst < 1e-12,
      "худшее отклонение %.2e" % worst)
check("на нулевом угле подъёмной силы нет", abs(Section(f=0.0).solve(0.0).cl) < 1e-14)
check("подъёмная сила нечётна по углу",
      abs(Section(f=0.0).solve(-7 * D).cl + Section(f=0.0).solve(7 * D).cl) < 1e-14)
s = Section(f=0.0, n=200).solve(6 * D)
check("центр давления плоской пластины — на четверти хорды",
      abs(s.cm_le / (-s.cl / 4) - 1) < 2e-3,
      "%.6f против %.6f" % (s.cm_le, -s.cl / 4))

# --- средняя линия с пузом ----------------------------------------------------
#
# Глауэртов α₀ выведен в предположении малых наклонов средней линии. У паруса с
# пузом в 10% передняя кромка наклонена к хорде на 4f = 0.4 рад, то есть на 23°,
# и «малый наклон» кончается. Поэтому допуск здесь не один на всё, а по пузу:
# на малом решатель обязан лечь на линейную теорию точно, на большом — отойти,
# и отойти в сторону МЕНЬШЕЙ подъёмной силы.
print("Угол нулевой подъёмной силы (400 панелей):\n")
print("   пузо  положение    α₀ расчёт   α₀ Глауэрт    разница   наклон кромки")
rows = []
for f, p in ((0.02, 0.5), (0.05, 0.5), (0.10, 0.5), (0.15, 0.5), (0.10, 0.35), (0.10, 0.65)):
    sec = Section(f=f, p=p, n=400)
    a1, a2 = 0.0, 5 * D                       # кривая строго линейна по углу
    c1, c2 = sec.solve(a1).cl, sec.solve(a2).cl
    a0 = a1 - c1 * (a2 - a1) / (c2 - c1)
    ex = zero_lift_angle_exact(f, p)
    rows.append((f, p, a0, ex))
    print("  %5.2f %9.2f %11.3f° %11.3f° %10.3f° %12.1f°"
          % (f, p, a0 / D, ex / D, (a0 - ex) / D, np.arctan(2 * f / p) / D))
print("")

small = [r for r in rows if r[0] <= 0.05]
big = [r for r in rows if r[0] >= 0.10]
check("на малом пузе решатель ложится на линейную теорию",
      all(abs(a0 - ex) < 0.015 * D for _, _, a0, ex in small),
      "худшее %.4f°" % (max(abs(a0 - ex) for _, _, a0, ex in small) / D))
mid = [abs(a0 - ex) for f, p_, a0, ex in rows if p_ == 0.5]
check("расхождение с линейной теорией растёт с пузом, а не скачет",
      all(mid[i] > mid[i - 1] for i in range(1, len(mid))),
      ", ".join("%.4f°" % (v / D) for v in mid))
check("на парусном пузе отходит от неё, и в сторону меньшей подъёмной силы",
      all(a0 - ex > 0.05 * D for _, _, a0, ex in big),
      "от %.3f° до %.3f°" % (min(a0 - ex for _, _, a0, ex in big) / D,
                             max(a0 - ex for _, _, a0, ex in big) / D))
check("пузо, сдвинутое к корме, даёт больший по модулю α₀",
      [r for r in rows if r[1] == 0.65][0][2] < [r for r in rows if r[1] == 0.35][0][2])

# Круговая дуга — тот случай, где эталон выписывается вручную: α₀ = −2·f/c.
check("у параболической дуги глауэртов α₀ равен −2·f/c",
      abs(zero_lift_angle_exact(0.08, 0.5) - (-2 * 0.08)) < 1e-6)

# --- сходимость и её порядок --------------------------------------------------
#
# Порядок сходимости проверяется отдельно от самого ответа, и не из
# любопытства: на нём стоит `cl_converged`. Если разность перестанет делиться
# пополам, экстраполяция начнёт врать молча.
print("Сходимость по числу панелей (пузо 0.10 на 0.4 хорды, 7°):\n")
ns = (50, 100, 200, 400, 800)
cs = [Section(f=0.10, p=0.4, n=n).solve(7 * D).cl for n in ns]
for i, (n, c) in enumerate(zip(ns, cs)):
    d = "" if i == 0 else "%12.6f %10.2f" % (cs[i] - cs[i - 1],
                                             (cs[i - 1] - cs[i - 2]) / (cs[i] - cs[i - 1])
                                             if i > 1 else float("nan"))
    print("  n=%4d  Cl=%.6f %s" % (n, c, d))
lim = cl_converged(0.10, 0.4, 7 * D, n=200)
print("\n  Ричардсон по 200 и 400: %.6f;  восемьсот панелей без него: %.6f\n"
      % (lim, cs[-1]))

ratios = [(cs[i - 1] - cs[i - 2]) / (cs[i] - cs[i - 1]) for i in range(2, len(cs))]
check("сходимость первого порядка: разность делится пополам",
      all(abs(r - 2) < 0.05 for r in ratios),
      "отношения " + ", ".join("%.3f" % r for r in ratios))
check("экстраполяция точнее восьмисот панелей без неё",
      abs(lim - (2 * cs[-1] - cs[-2])) < abs(cs[-1] - (2 * cs[-1] - cs[-2])),
      "%.6f против %.6f" % (lim, cs[-1]))

# --- пелена и скорости на сторонах --------------------------------------------
print("Пелена и скорости на сторонах (пузо 0.08, 8°):\n")
print("   панелей   у кромки   γ·√x у кромки   на задней кромке   негодная полоса")
prev = None
for n in (100, 200, 400, 800):
    sec = Section(f=0.08, p=0.5, n=n).solve(8 * D)
    lee, wind = sec.surface_speed()
    print("  %7d %10.2f %14.4f %17.3f %17.4f"
          % (n, lee[0], sec.sheet[0] * np.sqrt(sec.xv[0]), lee[-1], sec.le_invalid_x()))
    prev = sec
sec, (lee, wind) = prev, prev.surface_speed()
print("")

check("подветренная сторона быстрее набегающей везде", bool(np.all(lee > 1.0)))
check("скачок скорости равен плотности пелены",
      float(np.max(np.abs((lee - wind) - sec.sheet))) < 1e-12)
check("скорость наибольшая у передней кромки", int(np.argmax(lee)) == 0)
# Особенность 1/√x: при вдвое мельче панелях первая точка вдвое ближе к кромке
# по x² косинусной сетки, и скорость на ней ровно вдвое больше. Проверяется не
# сама величина (она бесконечна), а показатель степени: γ·√x обязан сходиться.
g0 = [Section(f=0.08, p=0.5, n=n).solve(8 * D) for n in (200, 800)]
g0 = [s_.sheet[0] * np.sqrt(s_.xv[0]) for s_ in g0]
check("у кромки пелена растёт как 1/√x", abs(g0[1] / g0[0] - 1) < 0.02,
      "γ·√x: %.4f и %.4f при 200 и 800 панелях" % (g0[0], g0[1]))
# А то, что формула скоростей в этой полосе неприменима, — не изъян, а место
# пузыря отрыва. Проверяется, что полоса узкая и не расползается с сеткой.
check("негодная полоса у кромки — около двух процентов хорды и не растёт",
      0.005 < sec.le_invalid_x() < 0.04,
      "%.4f хорды" % sec.le_invalid_x())
check("к задней кромке скорость восстанавливается к набегающей",
      abs(lee[-1] - 1.0) < 0.25 and lee[-1] < lee[0],
      "%.3f на кромке" % lee[-1])
# --- идеальный угол входа -----------------------------------------------------
#
# Особенность у кромки не всегда: есть угол, на котором поток входит по
# касательной к полотну и γ у кромки конечно. У параболической средней линии он
# ровно нулевой при любом пузе — это и проверяется, причём не по величине γ (она
# на сетке какая угодно), а по тому, ЗАВИСИТ ли она от числа панелей.
print("Идеальный угол входа:\n")
print("   пузо  положение   α_ид      γ у кромки при 100…800 панелях")
for f, p_ in ((0.10, 0.5), (0.15, 0.5), (0.10, 0.35)):
    ai = ideal_angle(f, p_)
    g = [Section(f=f, p=p_, n=n).solve(ai).sheet[0] for n in (100, 200, 400, 800)]
    print("  %5.2f %9.2f %8.3f°  %s" % (f, p_, ai / D, " ".join("%8.4f" % v for v in g)))
print("")

for f in (0.10, 0.15):
    g = [Section(f=f, p=0.5, n=n).solve(ideal_angle(f, 0.5)).sheet[0] for n in (100, 800)]
    check("у параболической линии на идеальном угле особенности нет (пузо %.2f)" % f,
          abs(g[1] / g[0] - 1) < 0.05, "γ у кромки %.4f и %.4f" % (g[0], g[1]))
off = [Section(f=0.10, p=0.5, n=n).solve(5 * D).sheet[0] for n in (100, 800)]
check("а в пяти градусах от него — есть, и растёт с сеткой",
      off[1] / off[0] > 4, "γ у кромки %.2f и %.2f" % (off[0], off[1]))
check("у параболической линии идеальный угол нулевой при любом пузе",
      all(abs(ideal_angle(f, 0.5)) < 1e-9 for f in (0.02, 0.10, 0.15)))
check("сдвиг пуза к носу поднимает идеальный угол, к корме — опускает",
      ideal_angle(0.10, 0.35) > 0 > ideal_angle(0.10, 0.65))
# Сдвинутое пузо особенность не убирает, а только ослабляет — знать это надо
# заранее, иначе марш пограничного слоя начнётся не там.
weak = [Section(f=0.10, p=0.35, n=n).solve(ideal_angle(0.10, 0.35)).sheet[0]
        for n in (100, 800)]
check("сдвинутое пузо особенность ослабляет, но не убирает",
      weak[1] / weak[0] > 4 and abs(weak[1]) < abs(off[1]) / 10,
      "γ у кромки %.2f против %.2f на пяти градусах" % (weak[1], off[1]))

print(("%d проверок провалено" % failures) if failures else "все проверки прошли")
print("")
sys.exit(1 if failures else 0)
