// Стенд возмущения: node tests/stability.test.mjs [--full]
//
// Отвечает на один вопрос, от которого зависят сразу три других: НАСКОЛЬКО
// БЫСТРО модель забывает последний разряд.
//
// Зачем он понадобился. Первый повод — перенос счёта: нативная сборка и wasm
// побитово совпасть не могут в принципе (в wasm нет FMA, а нативный clang его
// сливает; у sin/cos своя libm с последними разрядами), и вопрос «эквивалентен
// ли порт» без этого числа не решается вовсе. Второй повод крупнее: если 1 ULP
// за полминуты вырастает до процента хода, то модели нельзя верить и БЕЗ
// всякого порта — а именно это и подозревалось по немонотонной карте генакера,
// где 3.5 м здорово, 4.5 звенит, 6.5 здорово, 7.5 звенит опять.
//
// Что меряется. Две лодки заводятся одинаково, греются до установившегося хода,
// потом у ОДНОЙ состояние толкается на один разряд младшего бита — величина, за
// которой не стоит никакой физики, — и дальше обе идут своим ходом. Пишется
// расхождение по времени.
//
// Число, ради которого всё: ВРЕМЯ УДВОЕНИЯ расхождения. Оно же показатель
// Ляпунова, только в удобных единицах. По нему читается всё остальное:
//
//   удвоение много больше горизонта батареи — расхождение не успевает вырасти,
//   порт можно принимать по допуску, а батареи воспроизводимы;
//
//   удвоение того же порядка, что горизонт, — сравнивать траектории нельзя, и
//   любая батарея, которая это делает, меряет шум;
//
//   удвоение сильно меньше — модель неустойчива по существу, и это уже не про
//   счёт, а про постановку.
//
// ПОРОГИ ЗДЕСЬ ОПИСЫВАЮТ ИЗМЕРЕННОЕ, А НЕ ЖЕЛАЕМОЕ. Батарея заводится как
// регрессионная мерка: она обязана краснеть, когда устойчивость УХУДШИЛАСЬ
// против записанного, а не когда модель не дотягивает до идеала. Идеала здесь
// пока нет, и придумывать его до работы над устойчивостью нечестно.
//
// Известные источники самой неустойчивости перечислены в docs/stability.md.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { Boat } from '../sim/physics.js';
import { FULL, modeLine } from './lib/mode.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PACK = JSON.parse(readFileSync(join(ROOT, 'out/export/physics.json'), 'utf8'));
const D = Math.PI / 180;
const DT = 1 / 30;

let failures = 0;
const check = (name, ok, detail) => {
  if (!ok) failures++;
  console.log((ok ? '  ok   ' : '  ПЛОХО') + '  ' + name + (detail ? '   ' + detail : ''));
};

// Следующее представимое число вверх. Именно ОДИН разряд, а не «маленькое
// число»: любое назначенное epsilon пришлось бы обосновывать, а один бит
// мантиссы — это наименьшее возмущение, которое вообще существует в double, и
// обосновывать его не нужно. Меньше не бывает, значит всё, что выросло из него,
// выросло из ничего.
const BUF = new ArrayBuffer(8);
const F64 = new Float64Array(BUF), U64 = new BigUint64Array(BUF);
function ulpUp(x) {
  if (x === 0) return Number.MIN_VALUE;
  F64[0] = x;
  U64[0] += (x > 0 ? 1n : -1n);
  return F64[0];
}

// --- режимы --------------------------------------------------------------------
//
// Генакер здесь не для полноты: именно на нём подозревается худшая устойчивость,
// и именно его карта немонотонна. Бейдевинд — противоположный край.
const CASES = [
  { name: 'бейдевинд',        tws: 8,  twa: 45,  sheet: 14, gen: false },
  { name: 'генакер TWA 120°', tws: 6,  twa: 120, sheet: 70, gen: true, genLen: 4.5 },
  { name: 'галфвинд',         tws: 8,  twa: 90,  sheet: 35, gen: false },
  { name: 'бакштаг',          tws: 12, twa: 140, sheet: 70, gen: false },
];

function build(c) {
  const b = new Boat(PACK);
  if (c.gen) b.setGennaker(true);
  b.o.windSpeed = c.tws; b.o.windDir = 100 * D; b.psi = 100 * D - c.twa * D;
  b.o.sheet = c.sheet * D; b.o.draft = 1.0; b.o.twist = 8 * D;
  if (c.genLen != null) b.o.genSheetLen = c.genLen;
  b.o.crewHike = -1; b.o.crewMass = 219.9; b.u = 4;
  return b;
}

const WARM = 900;                      // тридцать секунд разгона
const HOLD = FULL ? 1800 : 900;        // сколько идём после толчка

// Возмущения от наименьшего возможного и вверх по порядкам. Один разряд — это
// то, чем отличаются две КОРРЕКТНЫЕ реализации одной формулы; 1e-9 — примерно
// то, чем отличалась бы модель, посчитанная с другим порядком суммирования;
// 1e-3 — уже физическая величина, порыв ветра.
const KICKS = [
  { name: '1 ULP', rel: null },
  { name: '1e-12', rel: 1e-12 },
  { name: '1e-9',  rel: 1e-9 },
  { name: '1e-6',  rel: 1e-6 },
];

// Прогон пары. Возвращает не только расхождение чисел, но и то, разошлись ли
// ДИСКРЕТНЫЕ состояния: сколько раз сработал предохранитель и сколько полосок
// осталось в решётке. Это добавлено после первого же замера, и вот почему.
//
// Ожидалось, что 1 ULP вырастет: в vlm.js записано, что модель усиливает
// расхождение в триста раз за полминуты. Замер этого НЕ ПОКАЗАЛ — за шестьдесят
// секунд расхождение осталось на уровне единиц последнего разряда. То есть по
// гладкой части модель сжимающая, а не хаотическая, и та запись про триста раз
// относилась к возмущению совсем другого масштаба (возраст матрицы влияния).
//
// Значит опасен не гладкий рост, а ПЕРЕКЛЮЧЕНИЕ: предохранитель, граница решётки
// по углу атаки, порог наполнения. Они разрывны и гистерезиса не имеют, поэтому
// сколь угодно малое возмущение у самого порога переводит модель на другую
// ветвь — и вот ЭТО и видно на немонотонной карте генакера. Мерить надо его.
function pair(c, kick) {
  const a = build(c), b = build(c);
  for (let i = 0; i < WARM; i++) { a.step(DT); b.step(DT); }
  b.u = kick.rel == null ? ulpUp(b.u) : b.u * (1 + kick.rel);
  a.rig.fuseTrips = 0; b.rig.fuseTrips = 0;
  let maxDu = 0, flip = 0;
  for (let i = 1; i <= HOLD; i++) {
    a.step(DT); b.step(DT);
    const d = Math.abs(a.u - b.u);
    if (d > maxDu) maxDu = d;
    const la = (a.rig.latOn || []).reduce((s, v) => s + (v ? 1 : 0), 0);
    const lb = (b.rig.latOn || []).reduce((s, v) => s + (v ? 1 : 0), 0);
    if (la !== lb) flip++;
  }
  return {
    maxDu, flip,
    dFuse: Math.abs((a.rig.fuseTrips || 0) - (b.rig.fuseTrips || 0)),
    fuse: a.rig.fuseTrips || 0,
    u: a.u, dEnd: Math.abs(a.u - b.u),
  };
}

console.log('\n' + modeLine());
console.log('\nТолчок по `u` после тридцати секунд разгона, горизонт ' +
            (HOLD * DT).toFixed(0) + ' с.');
console.log('«шагов врозь» — на скольких шагах у копий РАЗНОЕ число полосок в решётке.\n');

const cases = FULL ? CASES : CASES.slice(0, 2);
const rows = [];
for (const c of cases) {
  console.log('  ' + c.name + ':');
  console.log('      толчок      max |Δu|, м/с    |Δu| в конце   шагов врозь   Δ срабатываний');
  for (const k of KICKS) {
    const r = pair(c, k);
    rows.push({ c, k, r });
    console.log('    %s %s %s %s %s',
      k.name.padEnd(10),
      r.maxDu.toExponential(2).padStart(14),
      r.dEnd.toExponential(2).padStart(15),
      String(r.flip).padStart(12),
      String(r.dFuse).padStart(16));
  }
  console.log('');
}

// --- что из этого следует -------------------------------------------------------

const byKick = (name) => rows.filter((x) => x.k.name === name);
const ulpRows = byKick('1 ULP');

// Порог здесь описывает ИЗМЕРЕННОЕ. Один разряд не должен вырастать до величины,
// которую видит хоть одна батарея: самый мелкий допуск в них — сотые узла, то
// есть около 5e-3 м/с. Запас на два порядка.
const ULP_LIMIT = 5e-5;
check('один разряд не вырастает до наблюдаемого',
      ulpRows.every((x) => x.r.maxDu < ULP_LIMIT),
      'худшее ' + Math.max(...ulpRows.map((x) => x.r.maxDu)).toExponential(2) +
      ' м/с при пороге ' + ULP_LIMIT.toExponential(0));

// Это и есть условие приёмки порта счёта. Пока оно держится, побитовое
// расхождение реализаций не может изменить поведение, и сверять порт можно по
// допуску, а не по золотым записям.
check('дискретные состояния не расходятся от одного разряда',
      ulpRows.every((x) => x.r.flip === 0 && x.r.dFuse === 0),
      ulpRows.map((x) => x.c.name + ': ' + x.r.flip + ' / ' + x.r.dFuse).join(',  '));

console.log('');
console.log(failures ? failures + ' проверок провалено' : 'все проверки прошли');
console.log('');
process.exit(failures ? 1 : 0);
