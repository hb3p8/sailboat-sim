// Свободная пелена на лодке: node tests/wake.test.mjs
//
// Пелена ВХОДИТ В СИЛЫ: она заменила прямые лучи в матрице влияния, кривую
// запаздывания и подогнанный фильтр `alphaLag`. Здесь проверяется, как она ведёт
// себя на лодке; чистая постановка — без второго паруса, воды и поляры — стоит
// отдельно, в `tests/wing.test.mjs`.
//
// Первой идёт единственная проверка, оставшаяся от той поры, когда пелена в силы
// не входила: включённый отладочный ВИД не двигает лодку ни на разряд. Она
// успела стать тождественной и была переписана — подробности у неё же.
//
// Остальное — свойства самой пелены: сходит с кромки, уносится по потоку,
// суммарная завихренность паруса равна нулю, сброс её чистит; нити знают свой
// парус, пелена висит в мире и за лодкой не поворачивается; за срывом лист с
// кромки не сходит, и счёт на полных курсах от этого не разносится.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { Boat } from '../sim/physics.js';
import { FreeWake } from '../sim/vlm.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PACK = JSON.parse(readFileSync(join(ROOT, 'out/export/physics.json'), 'utf8'));
const D = Math.PI / 180;

let failures = 0;
const check = (name, ok, detail) => {
  if (!ok) failures++;
  console.log((ok ? '  ok   ' : '  ПЛОХО') + '  ' + name + (detail ? '   ' + detail : ''));
};

function run(wake, steps, drive, forces) {
  const b = new Boat(PACK);
  b.o.freeWake = wake;
  if (forces !== undefined) b.o.wakeForces = forces;
  b.o.windSpeed = 8; b.o.windDir = 100 * D; b.psi = 55 * D;
  b.o.sheet = 14 * D; b.o.twist = 8 * D;
  b.o.crewHike = -1; b.o.crewMass = 219.9; b.u = 4;
  b.wind.o.gust = 0.2; b.wind.o.shift = 9 * D;
  for (let i = 0; i < steps; i++) {
    if (drive) drive(b, i / 30);
    b.step(1 / 30);
  }
  return b;
}

// --- выключенная из сил пелена не трогает силы ----------------------------------
//
// Проверка старая, но с поднятым `wakeForces` она успела стать тождественной и
// перестала что-либо доказывать: `freeWake` в силовом пути не участвует вовсе,
// пелена считается по `wakeForces`, и оба прогона были попросту одним и тем же.
// Зелёная тождественная проверка хуже отсутствующей — она создаёт уверенность.
//
// Поэтому здесь `wakeForces` СНЯТ у обоих, и различаются прогоны только тем,
// считается ли пелена для картинки. Это и есть настоящий контракт: включённый
// отладочный вид не двигает физику ни на разряд — а он делает и снос, и
// выталкивание узлов, и держит своё состояние.
console.log('\nЛодка с пеленой для картинки и без неё (в силы не входит),' +
            ' 45 секунд с порывами и перекладкой руля:\n');
{
  const drive = (b, t) => { b.o.rudderTarget = 12 * D * Math.sin(t / 5); };
  const a = run(false, 45 * 30, drive, false), c = run(true, 45 * 30, drive, false);
  const F = ['x', 'y', 'psi', 'u', 'v', 'r', 'phi', 'p_', 'zc', 'w', 'th', 'q', 'hike'];
  let worst = 0, who = '';
  for (const k of F) {
    const d = Math.abs(a[k] - c[k]);
    if (d > worst) { worst = d; who = k; }
  }
  console.log('  ход  %s против %s уз', a.telemetry.speedKn.toFixed(9), c.telemetry.speedKn.toFixed(9));
  console.log('  крен %s против %s°', (a.phi / D).toFixed(9), (c.phi / D).toFixed(9));
  console.log('  наибольшее расхождение по состоянию: %s (%s)\n', worst.toExponential(1), who);
  check('пелена не меняет ни одного разряда в состоянии лодки', worst === 0,
    worst === 0 ? 'ровно ноль' : worst.toExponential(1) + ' по ' + who);
  check('и ни одного в показаниях',
    a.telemetry.driveN === c.telemetry.driveN && a.telemetry.sideN === c.telemetry.sideN,
    a.telemetry.driveN.toFixed(9) + ' против ' + c.telemetry.driveN.toFixed(9));

  // И то же самое с поднятым выключателем — там, где симулятор и живёт.
  // Проверка тождественна по построению (в силовом пути `freeWake` не
  // спрашивается нигде), и держится ровно за это: если его туда однажды заведут,
  // отладочный вид начнёт двигать лодку, и узнать об этом лучше здесь.
  const a2 = run(false, 20 * 30, drive), c2 = run(true, 20 * 30, drive);
  let w2 = 0;
  for (const k of F) w2 = Math.max(w2, Math.abs(a2[k] - c2[k]));
  check('и с пеленой в силах переключение вида тоже ничего не двигает', w2 === 0,
    w2 === 0 ? 'ровно ноль' : w2.toExponential(1));
}

// --- свойства самой пелены -----------------------------------------------------
{
  const b = run(true, 20 * 30);
  const w = b.rig.wake;
  const L = w.len;
  console.log('Пелена: %d нитей по %d узлов, сошло %d\n', w.fil, w.len, w.n);
  check('пелена завелась и заполнилась', w && w.n === w.len, w ? String(w.n) : 'нет');

  // Узел тем дальше от кромки, чем он старше: пелена уносится, а не стоит.
  let mono = true, far = 0;
  for (let f = 0; f < w.fil; f++) {
    if (!w.g[f]) continue;
    const bi = f * L;
    let prev = -1;
    for (let i = 0; i < w.n; i++) {
      const dx = w.x[bi + i] - w.x[bi], dy = w.y[bi + i] - w.y[bi];
      const d = Math.hypot(dx, dy);
      if (d < prev - 1e-9) mono = false;
      prev = d; far = Math.max(far, d);
    }
  }
  check('узлы уходят от кромки монотонно с возрастом', mono);
  // Сорок узлов при тридцати герцах — это 1.3 секунды, а не три: узел сходит
  // каждый шаг.
  check('за секунду с небольшим пелена уходит на несколько длин лодки',
    far > 6 && far < 60, far.toFixed(1) + ' м');

  // Суммарная сходящая завихренность паруса равна нулю: сколько циркуляции
  // набралось к топу, столько и сошло. Это не подгонка, а тождество — если
  // нарушится, значит нити расставлены не по границам полосок.
  let sum = 0;
  for (let f = 0; f < w.fil; f++) sum += w.g[f];
  check('суммарная сила нитей равна нулю', Math.abs(sum) < 1e-9, sum.toExponential(1));

  // Пелена вся под ветром от паруса и вся ниже топа: если полезла на наветренную
  // сторону или вверх, значит снос считается не тем полем.
  let above = 0, zmin = 1e9;
  for (let f = 0; f < w.fil; f++) {
    for (let i = 0; i < w.n; i++) {
      above = Math.max(above, w.z[f * L + i]);
      zmin = Math.min(zmin, w.z[f * L + i]);
    }
  }
  check('пелена не поднимается выше топа', above < 11, above.toFixed(1) + ' м');
  check('и не уходит под воду', zmin > -0.5, zmin.toFixed(1) + ' м');
}

// --- нити знают свой парус -----------------------------------------------------
//
// Нить сидит на границе полосок, но на стыке грота со стакселем их две подряд:
// конец одного набора и начало другого. С этого места номер нити и номер
// полоски разъезжаются на единицу, и всякий, кто позже полезет от нити к
// полоске, ошибётся — полотно пелены натянется через щель между парусами.
// Поэтому парус пишется при построении нитей, а не восстанавливается по номеру.
{
  const b = run(true, 5 * 30);
  const S = b.rig.wakeSail, w = b.rig.wake;
  let flips = 0, mixed = 0, used = 0;
  for (let f = 0; f < w.fil; f++) {
    if (S[f] < 0) continue;
    used++;
    if (S[f + 1] >= 0 && S[f] !== S[f + 1]) flips++;
  }
  for (let f = 0; f + 1 < w.fil; f++) if (S[f] >= 0 && S[f + 1] >= 0 && S[f] !== S[f + 1]) mixed++;
  // Нитей на одну больше, чем границ полосок: на стыке парусов их две подряд.
  check('парус записан у каждой рабочей нити', used === b.rig.strips.length + 2,
    used + ' из ' + (b.rig.strips.length + 2));
  check('паруса идут двумя сплошными кусками, а не вперемешку', flips === 1,
    String(flips));
  check('через щель между парусами полотно не натягивается', mixed === 1,
    String(mixed));

  // И ровно тот промах, ради которого это записывается: номер нити на стыке уже
  // не равен номеру полоски. Считать парус по `strips[f]` — ошибиться на одну.
  let stripFlip = -1, filFlip = -1;
  for (let i = 0; i + 1 < b.rig.strips.length; i++) {
    if (b.rig.strips[i].jib !== b.rig.strips[i + 1].jib) stripFlip = i;
  }
  for (let f = 0; f + 1 < w.fil; f++) if (S[f] >= 0 && S[f + 1] >= 0 && S[f] !== S[f + 1]) filFlip = f;
  check('стык нитей смещён относительно стыка полосок', filFlip === stripFlip + 1,
    'полоски ' + stripFlip + ', нити ' + filFlip);
}

// --- снос не зависит от порядка нитей ------------------------------------------
//
// Скорость узла зависит от всей пелены, включая соседние нити. Двигай узлы по
// ходу дела — и второй нити достанется поле, в котором первая уже сдвинулась, а
// третья ещё нет. Пелена свернётся в жгут по-разному в зависимости от того, как
// нити пронумерованы, а нумерация не физика. Проверяется прямо: тот же лист,
// пронумерованный с другого конца, обязан дать тот же ответ.
//
// Переворот у КОЛЕЦ не тот, что был бы у отдельных нитей: кольцо сидит между
// нитями f и f+1, при перевороте оно оказывается между F-2-f и F-1-f, а обход
// его меняет сторону — значит и знак циркуляции. Не поменять знак значит
// перевернуть лист наизнанку и сравнивать разные задачи.
{
  const FIL = 4, LEN = 12, DT = 1 / 30;
  const gr = [0.9, -0.4, 0.6, 0];            // последняя нить кольца не замыкает
  const start = (f, i) => [0.3 * i, 0.8 * f - 1.2, 3 + 0.05 * i * (f - 1.5)];

  const grow = (rev) => {
    const w = new FreeWake(FIL, LEN);
    w.core = 0.05;
    w.dirx = 1; w.diry = 0; w.dirz = 0;
    const g = rev ? gr.map((_, f) => (f < FIL - 1 ? -gr[FIL - 2 - f] : 0)) : gr.slice();
    const V = [0, 0, 0];
    const vel = (x, y, z, out) => {
      w.induced(x, y, z, true, V);
      out[0] = 6 + V[0]; out[1] = V[1]; out[2] = V[2];
    };
    const seed = (f, out) => {
      const p = start(rev ? FIL - 1 - f : f, 0);
      out[0] = p[0]; out[1] = p[1]; out[2] = p[2];
    };
    for (let s = 0; s < LEN + 6; s++) w.step(DT, seed, vel, g);
    return w;
  };

  const a = grow(false);
  const c = grow(true);                      // тот же лист, нумерация с конца
  let worst = 0;
  for (let f = 0; f < FIL; f++) {
    const ia = f * LEN, ic = (FIL - 1 - f) * LEN;
    for (let i = 0; i < a.n; i++) {
      worst = Math.max(worst,
        Math.abs(a.x[ia + i] - c.x[ic + i]),
        Math.abs(a.y[ia + i] - c.y[ic + i]),
        Math.abs(a.z[ia + i] - c.z[ic + i]));
    }
  }
  // Ровного нуля тут не будет и не должно быть: суммы Био — Савара складываются
  // по нитям, а сложение чисел с плавающей точкой неассоциативно. Порог на
  // двенадцати порядках ниже самого сноса, а промах с одним проходом стоил бы
  // сантиметров — разница между тем и другим не в порядке, а в природе.
  console.log('\nПереставленные нити: наибольшее расхождение %s м\n', worst.toExponential(1));
  check('снос не зависит от порядка нитей в массиве', worst < 1e-12,
    worst.toExponential(1) + ' м');
}

// --- пелена висит в мире, а не за кормой ---------------------------------------
//
// Ради этого маршевая схема и берётся: после поворота старая пелена остаётся
// там, где была, и лодка идёт по собственному старому следу. Если хранить узлы
// в связанных с лодкой осях, весь след поворачивается вместе с ней, и попасть в
// него становится невозможно в принципе.
//
// Проверяется грубо и прямо: лодке ВРУЧНУЮ доворачивается курс на сорок
// градусов между шагами. Узел в дюжине метров за кормой, будь он приколочен к
// лодке, проехал бы на этом полдюжины метров вбок. Живущий в воздухе сдвинется
// на снос за шаг, то есть на десяток сантиметров.
{
  const b = run(true, 20 * 30);
  const w = b.rig.wake, L = w.len;
  const X = Float64Array.from(w.x), Y = Float64Array.from(w.y);
  const turn = 40 * D;
  b.psi += turn;
  b.step(1 / 30);
  // Узел стареет на позицию: то, что было i-м, стало (i+1)-м.
  let moved = 0, asIfBody = 0;
  for (let f = 0; f < w.fil; f++) {
    if (!w.g[f]) continue;
    for (let i = 0; i + 1 < w.n; i++) {
      const o = f * L + i;
      moved = Math.max(moved, Math.hypot(w.x[o + 1] - X[o], w.y[o + 1] - Y[o]));
      // Столько тот же узел проехал бы, будь он приколочен к лодке: хорда
      // поворота на том же радиусе.
      const R = Math.hypot(X[o] - b.x, Y[o] - b.y);
      asIfBody = Math.max(asIfBody, 2 * R * Math.sin(turn / 2));
    }
  }
  console.log('Доворот на %d°: узел сдвинулся на %s м, за лодкой уехал бы на %s м\n',
    Math.round(turn / D), moved.toFixed(2), asIfBody.toFixed(2));
  check('поворот лодки утащил бы пелену заметно', asIfBody > 3, asIfBody.toFixed(2) + ' м');
  check('но она остаётся там, где висела', moved < 0.2 * asIfBody,
    moved.toFixed(2) + ' против ' + asIfBody.toFixed(2) + ' м');
}

// --- полный курс: пелена не должна разносить счёт -------------------------------
//
// Здесь она разносилась, и это была не физика. Ядро вихря стояло на четырёх
// сантиметрах, а нити на полном курсе сходились до семи: внутри ядра Био — Савар
// тем быстрее, чем ближе подошли, явный шаг швыряет узел дальше, тот подходит
// ещё ближе. Узел ехал 2000 м/с при кажущемся ветре 4.5 — в четыреста раз
// быстрее воздуха, который его несёт.
//
// Полный курс попадает под это первым по двум причинам сразу: кажущийся ветер
// там самый слабый, узлы почти не уносит от паруса и они висят в самом сильном
// наведённом поле; а циркуляции за срывом большие и неровные по высоте, и силы
// нитей — их разности — выходят большими и шумными.
//
// Мерится это не «на глаз по картинке», а изломом: углом между соседними
// звеньями нити. У гладкой пелены это единицы градусов, у разнесённой — шесть
// десятков, и она именно так и выглядит — рваной.
{
  const b = new Boat(PACK);
  b.o.freeWake = true;
  b.o.windSpeed = 8; b.o.windDir = 100 * D; b.psi = -75 * D;   // TWA 175°
  b.o.sheet = 80 * D; b.o.jibSheet = 80 * D;
  b.o.crewHike = 0; b.o.crewMass = 219.9; b.u = 3;
  b.wind.o.gust = 0.2; b.wind.o.shift = 9 * D;
  for (let i = 0; i < 20 * 30; i++) b.step(1 / 30);

  const w = b.rig.wake, L = w.len;
  const air = b.apparentWind().speed;
  let sum = 0, cnt = 0, fast = 0, seg = 0;
  for (let f = 0; f < w.fil; f++) {
    if (!w.g[f]) continue;
    for (let k = 1; k < w.n; k++) {
      const a = f * L + k - 1, m = f * L + k;
      const ax = w.x[m] - w.x[a], ay = w.y[m] - w.y[a], az = w.z[m] - w.z[a];
      const la = Math.hypot(ax, ay, az);
      seg++;
      if (la * 30 > 4 * air) fast++;
      if (k + 1 >= w.n || la < 1e-9) continue;
      const c = f * L + k + 1;
      const bx = w.x[c] - w.x[m], by = w.y[c] - w.y[m], bz = w.z[c] - w.z[m];
      const lb = Math.hypot(bx, by, bz);
      if (lb < 1e-9) continue;
      const cs = Math.max(-1, Math.min(1, (ax * bx + ay * by + az * bz) / (la * lb)));
      sum += Math.acos(cs) / D; cnt++;
    }
  }
  const kink = sum / cnt;
  console.log('\nПолный курс, кажущийся %s м/с: излом %s° на узел, быстрее ' +
              'четверного ветра %d звеньев из %d\n',
              air.toFixed(1), kink.toFixed(1), fast, seg);
  // Порог 15, а не 6, и вот почему он вырос. Пока пелена в силы не входила,
  // излом на полном курсе был 5.4° на узел; с обратной связью — 10.3°. Это не
  // ухудшение счёта, а появившаяся физика: парус отзывается на собственный след,
  // и сходит с него уже другая завихренность. Ловить надо разнос, а он выглядит
  // совсем иначе — 65° на узел и узлы, летящие в сотни раз быстрее воздуха.
  check('на полном курсе пелена гладкая, а не рваная', kink < 15,
    kink.toFixed(1) + '° на узел');
  check('узлы плывут с воздухом, а не летят', fast < 0.02 * seg,
    fast + ' из ' + seg);

  // Оба средства против разноса — на месте и работают.
  let rcYoung = 0, rcOld = 0;
  for (let f = 0; f < w.fil; f++) {
    rcYoung = Math.max(rcYoung, w.rc[f * L]);
    rcOld = Math.max(rcOld, w.rc[f * L + w.n - 1]);
  }
  check('ядро расплывается с возрастом узла', rcOld > 3 * w.core,
    (100 * w.core).toFixed(1) + ' см у свежего, ' + (100 * rcOld).toFixed(0) + ' у старого');
  // Пол по расстоянию до соседа: у каждого узла ядро не меньше половины
  // расстояния до БЛИЖАЙШЕЙ соседней нити того же возраста. Ближайшей, а не
  // любой: пол ставится по тесноте, а тесно бывает с одной стороны.
  //
  // Проверяется `rcSp` — то ядро, которым пелена видит САМУ СЕБЯ. У паруса своё,
  // `rc`, и оно намеренно МЕНЬШЕ: пол по соседу съедал бы разгонный вихрь у
  // кромки, от которого зависит весь нестационарный отклик.
  // Сосед берётся по ТОПОЛОГИИ (`ring`), как и в самом ограничителе, а не по
  // сегодняшней силе нити. Проверка когда-то повторяла старую, уже исправленную
  // в коде ошибку: нить с нулевой разностью циркуляций из соседей выпадала, и
  // требование выходило строже кода — пол ставился по БЛИЖНЕМУ соседу, а
  // мерилось расстояние до дальнего. Поймалось это не сразу: пока экипаж
  // откренивал автоматически, лодка на полном курсе шла ровнее и такие пары не
  // сходились. Тринадцать нарушений из трёхсот, и все — на миллиметр.
  const sheet = (f, nf) => (nf < f ? w.ring[nf] : w.ring[f]);
  let tight = 0;
  for (let f = 0; f < w.fil; f++) {
    if (!(f > 0 && w.ring[f - 1]) && !w.ring[f]) continue;
    for (let k = 0; k < w.n; k++) {
      const a = f * L + k;
      let d = Infinity;
      for (const nf of [f - 1, f + 1]) {
        if (nf < 0 || nf >= w.fil || !sheet(f, nf)) continue;
        const c = nf * L + k;
        d = Math.min(d, Math.hypot(w.x[c] - w.x[a], w.y[c] - w.y[a], w.z[c] - w.z[a]));
      }
      if (d < Infinity && 2 * w.rcSp[a] < d - 1e-9) tight++;
    }
  }
  check('ядро не меньше полурасстояния до ближайшей нити', tight === 0, String(tight));
  // И два ядра действительно разные: одно на двоих гасило бы разгонный вихрь.
  let spread = 0;
  for (let k = 0; k < w.rc.length; k++) spread = Math.max(spread, w.rcSp[k] - w.rc[k]);
  check('парус видит пелену не тем ядром, что она сама', spread > 0.1,
    'разница до ' + spread.toFixed(2) + ' м');
  rcYoung;
}

// --- за срывом пелена не сбрасывает того, во что модель не верит ----------------
//
// Прошлая проверка мерила ГЕОМЕТРИЮ пелены и на этом успокаивалась. Пелена
// оставалась гладкой, узлы плыли с воздухом — а счёт при этом разносился, и
// разносился в другом месте: в самой циркуляции.
//
// Выглядело так. Грот на полном курсе вытравлен, поток подходит к нему почти
// под прямым углом (α по полоскам 59° через три секунды на 160° по ветру, 90°
// на чистом фордевинде), и вся хорда стоит на ОДНОЙ станции по потоку: точки
// и задняя кромка оказываются рядом поперёк потока, а не друг за другом вдоль
// него. Свежий ряд, сошедший с кромки, проходит в трёх-десяти сантиметрах от
// контрольных точек — при ядре в пять. Дальше петля: скос от свежего кольца
// поднимает Γ, большая Γ сходит в пелену, назавтра то же кольцо наводит ещё
// больше. За две секунды Γ шла 20 → 120 → 650 → 3200 → 11000, скос в
// контрольных точках доходил до 1200 м/с при кажущемся ветре 4.7, а боковая
// сила на чистом фордевинде выходила −206 Н вместо нуля.
//
// Ловится это сравнением с прямыми лучами — моделью, которую пелена заменила.
// Там на тех же курсах Γ около двадцати, и никакого разноса нет. Порог сброса
// и то, как он искался, — у `Rig.wakeShed`.
{
  const set = (b, twa) => {
    b.o.windSpeed = 8; b.o.windDir = 100 * D; b.psi = (100 - twa) * D;
    b.o.sheet = 85 * D; b.o.jibSheet = 85 * D; b.o.twist = 8 * D;
    b.o.crewHike = 0; b.o.crewMass = 219.9; b.u = 3;
    b.wind.o.gust = 0; b.wind.o.shift = 0;    // разнос ищем, а не порывы
    return b;
  };
  const sail = (twa, wake, sec) => {
    const b = set(new Boat(PACK), twa);
    b.o.freeWake = wake; b.o.wakeForces = wake;
    for (let i = 0; i < sec * 30; i++) b.step(1 / 30);
    return b;
  };
  const maxG = b => {
    let g = 0;
    for (let j = 0; j < b.rig.lattice.n; j++)
      g = Math.max(g, Math.abs(b.rig.lattice.gamma[j]));
    return g;
  };
  console.log('\nЦиркуляция на полных курсах, 25 с:\n');
  let worst = 0;
  for (const twa of [160, 170, 180]) {
    const wk = sail(twa, true, 25), ray = sail(twa, false, 25);
    const gw = maxG(wk), gr = maxG(ray);
    console.log('  TWA %s°: пелена max|Γ| %s, прямые лучи %s; боковая %s Н против %s',
      String(twa).padStart(3), gw.toFixed(1), gr.toFixed(1),
      wk.telemetry.sideN.toFixed(0), ray.telemetry.sideN.toFixed(0));
    worst = Math.max(worst, gw / gr);
    if (twa === 180)
      // На чистом фордевинде боковой силе взяться неоткуда: ветер строго с
      // кормы, парус стоит поперёк. Прямые лучи дают единицы ньютонов.
      check('на чистом фордевинде боковой силы нет', Math.abs(wk.telemetry.sideN) < 60,
        wk.telemetry.sideN.toFixed(0) + ' Н');
  }
  console.log('');
  check('на полных курсах пелена не раздувает циркуляцию', worst < 2,
    'до ' + worst.toFixed(2) + ' от прямых лучей');

  // Поворот через фордевинд: курс проходит все углы насквозь, и если гашение
  // где-то прыгает, видно это здесь.
  //
  // Экипаж в манёвре ПЕРЕСАЖИВАЕТСЯ: он больше не переходит сам (physics.js,
  // `crewHike` знаковый), а поворот с экипажем, оставшимся под ветром, — это
  // проверка не гашения, а того, как лодка ложится. Пересадка идёт по борту, с
  // которого дует, и занимает своё время.
  {
    const b = set(new Boat(PACK), 150);
    b.o.freeWake = true; b.o.wakeForces = true;
    b.o.sheet = 80 * D; b.o.jibSheet = 80 * D;
    b.o.crewHike = -1;                  // наветренный борт первого галса
    let g = 0;
    for (let i = 0; i < 40 * 30; i++) {
      const t = i / 30;
      b.o.rudderTarget = (t > 5 && t < 13) ? 10 * D : 0;
      const twa = ((b.o.windDir - b.psi) / D % 360 + 360) % 360;
      b.o.crewHike = twa < 180 ? -1 : 1;
      b.step(1 / 30);
      g = Math.max(g, maxG(b));
    }
    console.log('Поворот через фордевинд: наибольшая |Γ| за манёвр %s\n', g.toFixed(1));
    check('на повороте через фордевинд счёт держится', g < 60, g.toFixed(1));
  }

  // И главное: на рабочих курсах гашение не трогает НИЧЕГО. Оно начинается с
  // тридцати пяти градусов, а на лавировке углы атаки девять-десять. Проверка
  // стоит здесь ровно затем, чтобы порог нельзя было незаметно сдвинуть вниз:
  // гашение, доехавшее до рабочих углов, работает усилителем, а не тормозом.
  {
    const b = new Boat(PACK);
    b.o.freeWake = true; b.o.wakeForces = true;
    b.o.windSpeed = 8; b.o.windDir = 100 * D; b.psi = 55 * D;
    b.o.sheet = 14 * D; b.o.twist = 8 * D;
    b.o.crewHike = -1; b.o.crewMass = 219.9; b.u = 4;
    b.wind.o.gust = 0; b.wind.o.shift = 0;
    for (let i = 0; i < 20 * 30; i++) b.step(1 / 30);
    let full = 0, live = 0, aMax = 0;
    for (let s = 0; s < b.rig.strips.length; s++) {
      const g = b.rig.stripCalc[s];
      if (!g.live) continue;
      live++;
      if (b.rig.wakeShed(s) === 1) full++;
      aMax = Math.max(aMax, Math.abs(g.alpha) / D);
    }
    console.log('Бейдевинд: наибольший угол атаки %s°, полностью сбрасывают %d полосок из %d\n',
      aMax.toFixed(1), full, live);
    check('на бейдевинде пелена сбрасывает всю циркуляцию', full === live,
      full + ' из ' + live);
  }
}

// --- пелена помнит, а не переписывается ----------------------------------------
//
// Ради этого маршевая схема и берётся. Раньше у нити была ОДНА сила на всю
// длину, и она переписывалась каждый шаг: потрави шкот — и весь след, включая
// сошедший секунду назад, мгновенно менял силу. Такая пелена не помнит ничего.
//
// Теперь состояние — циркуляции колец, и кольцо равно связанной циркуляции
// полоски в момент схода. Проверяется прямым опытом: резко потравить шкот и
// посмотреть, что стало со старыми кольцами. Ответ обязан быть — ничего, только
// уехали на позицию вглубь.
{
  const b = run(true, 10 * 30);
  const w = b.rig.wake, L = w.len;
  const was = Float64Array.from(w.gr);
  const g0 = Float64Array.from(w.g);
  b.o.sheet = 45 * D; b.o.jibSheet = 45 * D;   // рвануть шкот
  b.step(1 / 30);

  let moved = 0, worst = 0;
  for (let f = 0; f < w.fil; f++) {
    for (let i = 0; i + 1 < w.n; i++) {
      const d = Math.abs(w.gr[f * L + i + 1] - was[f * L + i]);
      worst = Math.max(worst, d); moved++;
    }
  }
  let fresh = 0;
  for (let f = 0; f < w.fil; f++) fresh = Math.max(fresh, Math.abs(w.g[f] - g0[f]));
  console.log('\nШкот с %d° на 45°: старые кольца сдвинулись на %s, свежая нить на %s\n',
    14, worst.toExponential(1), fresh.toFixed(2));
  check('сошедшие кольца шкотом не переписываются', worst === 0,
    worst === 0 ? 'ровно ноль в ' + moved + ' кольцах' : worst.toExponential(1));
  check('а свежее — отзывается сразу', fresh > 0.5, fresh.toFixed(2));

  // Гельмгольц в каждом узле: сколько завихренности втекло, столько и вытекло.
  // Для колец это тождество, но именно поэтому его и стоит держать проверкой —
  // оно ловит перепутанный знак разности быстрее, чем любая картинка.
  let leak = 0;
  for (let f = 1; f + 1 < w.fil; f++) {
    for (let i = 1; i + 1 < w.n; i++) {
      const k = f * L + i;
      leak = Math.max(leak, Math.abs(w.et[k - 1] - w.et[k] + w.es[k - L] - w.es[k]));
    }
  }
  check('вихревой лист замкнут: в узле ничего не теряется', leak < 1e-12,
    leak.toExponential(1));

  // Дальний ряд не обрывается: у него ненулевая сила, и она уходит хвостом.
  let tailG = 0;
  for (let f = 0; f < w.fil; f++) tailG = Math.max(tailG, Math.abs(w.et[f * L + w.n - 1]));
  check('дальний ряд продолжен хвостом, а не обрублен', tailG > 0.1 &&
    Math.abs(Math.hypot(w.tdx[w.n - 1], w.tdy[w.n - 1], w.tdz[w.n - 1]) - 1) < 1e-9,
    tailG.toFixed(2));
}

// --- пелена наводит то же, что прямые лучи, которые она заменяет ---------------
//
// Главная проверка перед тем, как пускать пелену в силы, и единственная, где
// есть с чем сравнивать. Прямой сходящий луч решётки — это и есть пелена,
// выпрямленная по потоку. Значит на установившемся ходу и небольших углах, где
// сворачивается она слабо, скос в контрольных точках обязан выйти почти тем же.
//
// «Почти» тут не отговорка: свободная пелена сворачивается и отклоняется, и
// наводит поэтому НЕМНОГО меньше. А вот знак обязан совпадать точно, и именно
// на нём всё и ловилось: у решётки верхний конец присоединённого вихря — `a`,
// то есть +Г висит на нижнем луче, а пелена вешала +Г на верхний. Отношение
// выходило -0.92 вместо +0.92 — та же величина наоборот. На картинке такую
// ошибку не видно вовсе: жёлтое с синим меняются местами, и только.
{
  const b = run(true, 25 * 30);
  const lat = b.rig.lattice, w = b.rig.wake;
  const aw = b.apparentWind(), sp = Math.hypot(aw.x, aw.y) || 1;
  const c = Math.cos(b.psi), sn = Math.sin(b.psi);
  const All = [0, 0, 0], Bnd = [0, 0, 0], V = [0, 0, 0];
  let straight = 0, free = 0;
  for (let i = 0; i < lat.n; i++) {
    const P = lat.panels[i], p = P.c, nr = P.nrm;
    lat.induced(p[0], p[1], p[2], aw.x / sp, aw.y / sp, 0, true, All, false);
    lat.induced(p[0], p[1], p[2], aw.x / sp, aw.y / sp, 0, true, Bnd, true);
    straight += (All[0] - Bnd[0]) * nr[0] + (All[1] - Bnd[1]) * nr[1] +
                (All[2] - Bnd[2]) * nr[2];
    const X = b.x + p[0] * c - p[1] * sn, Y = b.y + p[0] * sn + p[1] * c;
    w.induced(X, Y, p[2], true, V);
    free += (V[0] * c + V[1] * sn) * nr[0] + (-V[0] * sn + V[1] * c) * nr[1] +
            V[2] * nr[2];
  }
  straight /= lat.n; free /= lat.n;
  const ratio = free / straight;
  console.log('\nСкос в контрольных точках: прямые лучи %s м/с, пелена %s (%s)\n',
    straight.toFixed(3), free.toFixed(3), ratio.toFixed(2));
  check('пелена наводит скос в ту же сторону, что и прямые лучи', ratio > 0,
    ratio.toFixed(2));
  // Отношение теперь 1.24, а не 0.93, и уехало в нём НЕ то, что мерится.
  // Скос от пелены как был -0.53 м/с, так и остался (-0.534 без сил, -0.524 в
  // силах). Уехал эталон сравнения: циркуляции решаются уже с пеленой, и прямые
  // лучи на них дают -0.42 вместо -0.58. Сравнивать поэтому имеет смысл порядок
  // величины и знак, а не десятые: прямой луч больше не часть модели.
  check('и того же порядка', ratio > 0.6 && ratio < 1.6, ratio.toFixed(2));
}

// --- задача Вагнера ------------------------------------------------------------
//
// То, ради чего пелена в силы и заводится. Смена угла атаки не даёт новой
// подъёмной силы сразу: с задней шкаторины должен сойти разгонный вихрь, и пока
// он рядом, его скос держит циркуляцию. Классика с 1925 года:
//
//     Ф(s) = 1 - 0.165 e^(-0.0455 s) - 0.335 e^(-0.3 s),
//
// где s — путь в полухордах. Ф(0) = 0.5, Ф(∞) = 1.
//
// Прямые сходящие лучи этого не знают вовсе: они мгновенно перестраиваются под
// новую циркуляцию, и Ф у них тождественно единица. Запаздывание в модели
// поэтому и стояло назначенным — фильтром `alphaLag` с подобранной постоянной.
// Здесь проверяется, что пелена даёт его сама.
{
  const wag = (x) => 1 - 0.165 * Math.exp(-0.0455 * x) - 0.335 * Math.exp(-0.3 * x);
  // Ступенькой меняется ВЕТЕР, а не шкот. Разница принципиальная: поворот шкота
  // двигает саму хорду, то есть меняет геометрию, а Вагнер — про смену условия
  // при неподвижном крыле. На ступеньке шкота кривая выходит другой, и сверять
  // её с классикой нельзя.
  const run2 = (wf) => {
    const b = new Boat(PACK);
    b.o.wakeForces = wf; b.o.freeWake = wf;
    b.wind.o.gradient = false;
    b.o.windSpeed = 8; b.o.windDir = 60 * D; b.o.sheet = 14 * D; b.o.twist = 0;
    // Лодка замораживается: мерить надо парус, а не разгон корпуса.
    const hold = (n) => {
      for (let i = 0; i < n; i++) {
        b.u = 6; b.v = 0; b.r = 0; b.phi = 0; b.p_ = 0; b.psi = 0;
        b.step(1 / 30);
      }
    };
    // Циркуляция полоски прямо из решётки: сечение с его потолком и пузом тут
    // ни при чём, проверяется постановка.
    const G = () => { const l = b.rig.lattice; return l.gamma[6] + l.gamma[7] + l.gamma[8]; };
    hold(900);
    const g0 = G();
    b.o.windDir = 64 * D;
    const tr = [];
    for (let i = 0; i < 300; i++) { hold(1); tr.push(G()); }
    hold(1200);
    const gInf = G();
    const ve = b.rig.stripCalc[2].ve, ch = b.rig.strips[2].chord;
    const phi = tr.map((g) => (g - g0) / (gInf - g0));
    // Путь в полухордах -> номер шага.
    return (x) => {
      const i = Math.round(x * ch / 2 / ve * 30) - 1;
      return i >= 0 && i < phi.length ? phi[i] : NaN;
    };
  };

  const straight = run2(false), free = run2(true);
  console.log('\n       путь, полухорд      2      6     12');
  console.log('  Вагнер                %s   %s   %s',
    wag(2).toFixed(2), wag(6).toFixed(2), wag(12).toFixed(2));
  console.log('  прямые лучи           %s   %s   %s',
    straight(2).toFixed(2), straight(6).toFixed(2), straight(12).toFixed(2));
  console.log('  свободная пелена      %s   %s   %s\n',
    free(2).toFixed(2), free(6).toFixed(2), free(12).toFixed(2));

  check('прямые лучи запаздывания не дают вовсе', Math.abs(straight(6) - 1) < 0.02,
    straight(6).toFixed(2));
  // Мерится со ВТОРОЙ полухорды. Самый первый отсчёт в этой схеме Вагнера не
  // воспроизводит и не может: свежее кольцо несёт новую циркуляцию всего на
  // длину одного сноса, а в установившемся состоянии она тянется на всю пелену,
  // и стабилизирующий скос на первом шаге недопредставлен. Это разрешение схемы
  // по времени. Проверено и то, что укорочение первого звена (совет Каца и
  // Плоткина) дела не исправляет, а портит: 1.32 при полном звене против 1.96
  // при десятой доле — в этой постановке стабилизатор не разгонный вихрь, а
  // ножки ближнего кольца. Подробности в docs/wake.md.
  //
  // Допуск ±0.15 к плоской классике: размах у нас конечный, парусов два, снизу
  // зеркало от воды. Строгая сверка требует отдельного стенда с жёстким
  // прямоугольным крылом — она в списке открытого.
  check('пелена держит циркуляцию, пока разгонный вихрь рядом',
    Math.abs(free(2) - wag(2)) < 0.15, free(2).toFixed(2) + ' против ' + wag(2).toFixed(2));
  check('и отпускает её по Вагнеру',
    Math.abs(free(6) - wag(6)) < 0.15 && Math.abs(free(12) - wag(12)) < 0.15,
    free(6).toFixed(2) + '/' + free(12).toFixed(2) + ' против ' +
    wag(6).toFixed(2) + '/' + wag(12).toFixed(2));
}

// --- хвост помнит, куда шла лодка ----------------------------------------------
//
// Дальний конец пелены продолжается полубесконечным лучом вдоль потока. Куда
// именно — по потоку ТОГО момента, когда этот ряд сходил, а не сегодняшнему.
// Направление было одно на всю пелену и переписывалось каждый шаг: после
// поворота весь дальний след разом менял направление, хотя ближние узлы стояли
// на месте. Памяти о том, куда шла лодка, не было никакой.
//
// Заодно здесь записано, СКОЛЬКО этой памяти стоит хотеть. Пелена длиной в
// десять секунд (300 рядов) и оверштаг: вклад старой её части — той, что
// старше 1.3 с, — в скос на парусе не превышает 0.45% кажущегося ветра, а
// обычно держится сотых долей процента. Ближе пяти метров собственный старый
// след к лодке не подходит. То есть длинная память для ОДНОЙ лодки не окупается
// ничем, и редкая дальняя пелена, которую стоило бы городить ради неё, не
// нужна. Чужой след — другая задача, и он не моделируется вовсе.
{
  const b = run(true, 12 * 30);
  const w = b.rig.wake;
  const was = [w.tdx[w.n - 1], w.tdy[w.n - 1]];
  // Крутой поворот: за пять секунд курс уходит на десятки градусов.
  b.o.rudderTarget = 25 * D;
  for (let i = 0; i < 5 * 30; i++) b.step(1 / 30);
  const now = [w.dirx, w.diry];
  const tail = [w.tdx[w.n - 1], w.tdy[w.n - 1]];
  const ang = (a, c) => Math.acos(Math.max(-1, Math.min(1, a[0] * c[0] + a[1] * c[1]))) / D;
  console.log('\nПосле поворота: поток сейчас против хвоста %s°, хвост сдвинулся на %s°\n',
    ang(now, tail).toFixed(1), ang(was, tail).toFixed(1));
  // Отставание невелико — около двух градусов, — и это тоже измерение, а не
  // недоделка. Узлы живут в МИРОВЫХ осях, и сносит их кажущийся ветер в мире,
  // то есть истинный ветер минус скорость лодки. Истинный никуда не девается, а
  // лодка на трёх метрах в секунду против восьми ветра может повернуть его
  // разве что на полтора десятка градусов, да и то не мгновенно. Ловится этой
  // проверкой ровно то, ради чего она писалась: направление, переписываемое
  // каждый шаг, дало бы здесь тождественный ноль.
  check('хвост помнит поток, а не берёт сегодняшний', ang(now, tail) > 0.5,
    ang(now, tail).toFixed(1) + '°');
  check('и это память, а не заклинивание', ang(was, tail) > 0.5 && ang(now, tail) < 90,
    'сдвинулся на ' + ang(was, tail).toFixed(1) + '°');
}

// --- выталкивание из паруса: что оно делает с геометрией -------------------------
//
// Оно телепортирует узел, а телепортация — приём опасный: ею легко нарисовать
// излом, которого в потоке не было, или перебросить узел на другую сторону
// полотна. Поэтому здесь мерится не «работает ли», а СКОЛЬКО оно делает.
//
// На силы оно при этом не влияет вовсе (та же циркуляция с ним и без него на
// шести курсах), и стоит там потому, что узел на полотне — заведомо неверная
// геометрия. Числа отсюда: три-четыре узла за шаг, перенос до 17 см при шаге
// сноса около 40 см.
{
  const b = new Boat(PACK);
  b.o.windSpeed = 8; b.o.windDir = 100 * D; b.psi = 55 * D;
  b.o.sheet = 16 * D; b.o.jibSheet = 16 * D; b.o.twist = 8 * D;
  b.o.crewHike = -1; b.o.crewMass = 219.9; b.u = 4;
  b.wind.o.gust = 0.2; b.wind.o.shift = 9 * D;
  const rig = b.rig, orig = rig.keepWakeOut.bind(rig);
  let pushed = 0, steps = 0, maxPush = 0, kinkBefore = 0, kinkAfter = 0;
  const angle = (w, L) => {
    let sum = 0, cnt = 0;
    for (let f = 0; f < w.fil; f++) {
      if (!w.g[f]) continue;
      for (let k = 1; k + 1 < w.n; k++) {
        const a = f * L + k - 1, m = f * L + k, c = f * L + k + 1;
        const ax = w.x[m] - w.x[a], ay = w.y[m] - w.y[a], az = w.z[m] - w.z[a];
        const bx = w.x[c] - w.x[m], by = w.y[c] - w.y[m], bz = w.z[c] - w.z[m];
        const la = Math.hypot(ax, ay, az), lb = Math.hypot(bx, by, bz);
        if (la < 1e-9 || lb < 1e-9) continue;
        sum += Math.acos(Math.max(-1, Math.min(1, (ax * bx + ay * by + az * bz) / (la * lb))));
        cnt++;
      }
    }
    return cnt ? sum / cnt / D : 0;
  };
  rig.keepWakeOut = (bb) => {
    const w = rig.wake, L = w.len;
    const X = Float64Array.from(w.x), Y = Float64Array.from(w.y), Z = Float64Array.from(w.z);
    const k0 = angle(w, L);
    orig(bb);
    steps++;
    kinkBefore = Math.max(kinkBefore, k0);
    kinkAfter = Math.max(kinkAfter, angle(w, L));
    for (let k = 0; k < w.x.length; k++) {
      const d = Math.hypot(w.x[k] - X[k], w.y[k] - Y[k], w.z[k] - Z[k]);
      if (d > 1e-9) { pushed++; maxPush = Math.max(maxPush, d); }
    }
  };
  for (let i = 0; i < 30 * 30; i++) b.step(1 / 30);
  console.log('\nВыталкивание из паруса за %d шагов: %d узлов (%s за шаг), ' +
    'наибольший перенос %s м\n  излом до %s°, после %s°\n',
    steps, pushed, (pushed / steps).toFixed(1), maxPush.toFixed(3),
    kinkBefore.toFixed(1), kinkAfter.toFixed(1));
  check('выталкивает единицы узлов, а не всю пелену', pushed / steps < 20,
    (pushed / steps).toFixed(1) + ' за шаг');
  check('переносит меньше, чем узел проходит за шаг', maxPush < 0.35,
    maxPush.toFixed(3) + ' м');
  check('и не рисует излома, которого не было', kinkAfter < kinkBefore + 2,
    kinkBefore.toFixed(1) + '° -> ' + kinkAfter.toFixed(1) + '°');
}

// --- пелена сквозь корпус не проходит -------------------------------------------
//
// Проверка и правка зовут ОДНУ И ТУ ЖЕ `hullProbe`, и это здесь главное.
// Прошлый заход на корпус провалился именно на том, что правка считала его с
// креном, а замер без, и спорить им было не о чем.
//
// Мерится по РЁБРАМ: внутрь корпуса попадают не узлы. Шкотовый угол стакселя
// сидит в восьмидесяти сантиметрах над водой, палуба у борта — в семидесяти
// пяти, и поперечные рёбра скользят по ней, проходя сквозь обшивку между
// узлами. Узловая проверка на этом молчала — ноль срабатываний за тысячу
// восемьсот шагов, при том что рёбер внутри было под сотню.
{
  const b = new Boat(PACK);
  b.o.windSpeed = 8; b.o.windDir = 100 * D; b.psi = 55 * D;
  b.o.sheet = 16 * D; b.o.jibSheet = 16 * D; b.o.twist = 8 * D;
  b.o.crewHike = -1; b.o.crewMass = 219.9; b.u = 4;
  b.wind.o.gust = 0.2;
  let inside = 0, checked = 0;
  const o = [0, 0, 0];
  for (let i = 0; i < 40 * 30; i++) {
    // Уваливание до фордевинда и обратно: там пелена и заворачивается к борту.
    b.o.rudderTarget = (i / 30) < 20 ? 18 * D : 0;
    b.step(1 / 30);
    if (i % 30) continue;
    const w = b.rig.wake, L = w.len;
    const probe = (p, q) => {
      checked++;
      if (b.rig.hullProbe(b, (w.x[p] + w.x[q]) / 2, (w.y[p] + w.y[q]) / 2,
                          (w.z[p] + w.z[q]) / 2, o)) inside++;
    };
    for (let f = 0; f < w.fil; f++) {
      const b0 = f * L;
      for (let k = 0; k + 1 < w.n; k++) probe(b0 + k, b0 + k + 1);
      if (f + 1 < w.fil && w.ring[f]) for (let k = 1; k < w.n; k++) probe(b0 + k, b0 + k + L);
    }
  }
  console.log('\nРёбер пелены с серединой внутри обшивки: %d из %d\n', inside, checked);
  // Ноль тут недостижим: выталкивание отрабатывает в начале шага, а лодка за
  // шаг ещё и кренится с рысканьем. Единицы из десятков тысяч — это оно и есть.
  check('пелена сквозь корпус не проходит', inside < checked / 5000,
    inside + ' из ' + checked);
}

// --- поле пелены: пачкой и по точке — одно и то же -----------------------------
//
// У `FreeWake` два способа спросить поле: `induced()` по одной точке и `field()`
// сразу по набору. Второй вывернут наизнанку ради скорости (снаружи рёбра,
// внутри точки), и повторяет он первый построчно — то есть ровно то место, где
// расхождение никто не заметит.
//
// И оно там было: `field()` добавлял зеркало от воды НЕ СПРАШИВАЯ `ground`.
// В симуляторе вода есть всегда, поэтому в лодке это не проявлялось никак; а вот
// стенд на чистом крыле (`tests/wing.test.mjs`) стоит без воды, весь лежит в
// плоскости z = 0, и там зеркальный хвост совпадал с настоящим и вычитался
// ровно — в самоиндукции стенда хвостов не оставалось вовсе. Проверялась,
// выходит, не та модель, которую обосновывали.
//
// Проверка прогнана на коде С ОШИБКОЙ: без воды расхождение 0.12 м/с, с водой
// ноль. То есть поймала бы, и поймала бы именно там, где ошибка и жила.
{
  const w = new FreeWake(5, 8);
  w.core = 0.05;
  for (let f = 0; f + 1 < w.fil; f++) w.ring[f] = 1;
  const G = new Float64Array(w.fil);
  for (let f = 0; f < w.fil; f++) G[f] = 1 + 0.3 * f;
  w.dirx = 1; w.diry = 0; w.dirz = 0;
  // Пелена не плоская и не в нулевой плоскости: иначе зеркало не проверить.
  for (let k = 0; k < 8; k++)
    w.step(1 / 30, (f, out) => { out[0] = 0; out[1] = f * 0.4; out[2] = 1 + 0.1 * f; },
      (x, y, z, out) => { out[0] = 6; out[1] = 0.2 * z; out[2] = 0.1; }, G);
  const qx = [1.0, 2.5, -0.5, 0.3], qy = [0.7, 0.2, 1.1, -0.4], qz = [1.4, 0.9, 2.0, 0.6];
  const ox = new Float64Array(4), oy = new Float64Array(4), oz = new Float64Array(4);
  const one = [0, 0, 0];
  for (const ground of [true, false]) {
    w.ground = ground;
    w.edges(); w.pack(true);
    w.field(qx, qy, qz, 4, ox, oy, oz);
    let worst = 0;
    for (let j = 0; j < 4; j++) {
      w.induced(qx[j], qy[j], qz[j], ground, one);
      worst = Math.max(worst, Math.abs(one[0] - ox[j]), Math.abs(one[1] - oy[j]),
                       Math.abs(one[2] - oz[j]));
    }
    check('поле пачкой и по точке совпадает, вода ' + (ground ? 'есть' : 'нет'),
      worst < 1e-12, worst.toExponential(1) + ' м/с');
  }
  w.ground = true;
}

// --- выключение и сброс --------------------------------------------------------
{
  const b = run(true, 5 * 30);
  b.o.freeWake = false; b.o.wakeForces = false;   // оба, иначе пелена нужна силам
  b.step(1 / 30);
  check('выключенная пелена стирается', b.rig.wake.n === 0, String(b.rig.wake.n));
}

