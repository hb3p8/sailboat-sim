// --- центр свёрнутой пелены: π/4 размаха ----------------------------------------
//
// Классика, которую видно ЧИСЛОМ, а не «на картинке закрутилось». У крыла с
// эллиптической нагрузкой сходящая завихренность сворачивается в две нити, и
// расстояние между ними выходит π/4 ≈ 0.785 размаха.
//
// Число это берётся не из формы жгута, а из сохранения: центр тяжести
// завихренности каждой половины у эллиптической нагрузки стоит на π/8 размаха от
// середины, а свёртывание его не двигает — вихри друг друга не создают и не
// уничтожают. Значит проверка на самом деле такая: СНОС ПЕЛЕНЫ СОХРАНЯЕТ ЦЕНТР
// ТЯЖЕСТИ ЗАВИХРЕННОСТИ. Если он поехал, значит поле считается не тем.
//
// Нагрузка задаётся прямо, без решения: проверяется здесь снос, а не решатель.
{
  // Циркуляция взята покрупнее, а пелена подлиннее нарочно: время сворачивания
  // порядка b²/Γ, и на слабой нагрузке за отведённый путь не свернётся ничего.
  const n = 40, b = 2, len = 150, dt = 1 / 30, U = 1, G0 = 1;
  const w = new FreeWake(n + 1, len);
  w.ground = false;
  w.core = 0.02;
  w.dirx = 1; w.diry = 0; w.dirz = 0;
  for (let f = 0; f + 1 < w.fil; f++) w.ring[f] = 1;
  // Границы полосок и эллиптическая циркуляция на каждой.
  const yb = [];
  for (let i = 0; i <= n; i++) yb.push(-b / 2 + b * i / n);
  const G = new Float64Array(w.fil);
  for (let i = 0; i < n; i++) {
    const y = (yb[i] + yb[i + 1]) / 2;
    G[i] = G0 * Math.sqrt(Math.max(0, 1 - (2 * y / b) ** 2)); // Γ(y), эллипс
  }
  // Центр тяжести сходящей завихренности одной половины.
  const centroid = () => {
    let m = 0, s = 0;
    for (let f = 0; f < w.fil; f++) {
      const g = w.et[f * len];                 // сила нити у кромки
      if (g <= 0) continue;                    // одна половина: один знак
      const y = w.y[f * len + 0];
      m += g; s += g * y;
    }
    return s / m;
  };
  // Тот же центр, но по УЖЕ СНЕСЁННОМУ ряду: он и должен стоять на месте.
  const centroidAt = (row) => {
    let m = 0, s = 0;
    for (let f = 0; f < w.fil; f++) {
      const g = w.et[f * len + row];
      if (g <= 0) continue;
      m += g; s += g * w.y[f * len + row];
    }
    return s / m;
  };
  const V = [0, 0, 0];
  for (let k = 0; k < len; k++) {
    w.step(dt, (f, out) => { out[0] = 0; out[1] = yb[f]; out[2] = 0; },
      (x, y, z, out) => { out[0] = U; out[1] = 0; out[2] = 0; }, G);
  }
  const want = Math.PI / 8 * b;
  const atShed = centroid(), atFar = centroidAt(len - 1);
  // Свернулась пелена или просто съехала — считается по ЗАВОРОТУ, а не по
  // разлёту.
  //
  // Разлёт крайних нитей тут стоял раньше, с порогом «уже 0.95 размаха», и был
  // неверной меркой дважды.
  //
  // Во-первых, по существу: сворачивается пелена в СПИРАЛЬ вокруг концевой
  // нити, и внешний виток спирали заходит СНАРУЖИ прежнего конца. Разлёт от
  // этого растёт, а не падает, — свёрнутая пелена шире плоской, и порог «стало
  // уже» требовал ровно обратного тому, что должно происходить.
  //
  // Во-вторых, по месту замера: мерилось в ПОСЛЕДНЕМ ряду, а там начинается
  // прямой хвост, и ряд этот жил не как все. Пока `field()` не спрашивал `ground`
  // (см. `sim/vlm.js`), хвосты в самоиндукции взаимно уничтожались, последний ряд
  // не чувствовал ничего и честно «сужался» до 0.91 — на этом проверка и
  // проходила. Замер на том же сносе, но подальше от конца цепочки, давал 1.18
  // и тогда, и теперь: числа сходятся, а порог был подогнан под артефакт.
  //
  // Заворот виден прямо: сколько нитей оказалось СНАРУЖИ концевой. У плоского
  // листа таких нет по построению; у свернувшегося их дюжина.
  const outside = (row) => {
    const hi = w.y[(w.fil - 2) * len + row], lo = w.y[0 * len + row];
    let over = 0, zmax = 0;
    for (let f = 0; f + 1 < w.fil; f++) {
      const y = w.y[f * len + row];
      if (y > hi + 1e-9 || y < lo - 1e-9) over++;
      zmax = Math.max(zmax, Math.abs(w.z[f * len + row]));
    }
    return [over, zmax];
  };
  const [overShed] = outside(0), [overFar, zFar] = outside(len - 1);
  console.log('\nЭллиптическая нагрузка, пелена снесена на %s хорд:', (len * dt * U * 2).toFixed(0));
  console.log('  центр тяжести завихренности: у кромки %s, в дальнем ряду %s',
    atShed.toFixed(4), atFar.toFixed(4));
  console.log('  теория π/8 размаха = %s, то есть между нитями π/4 = %s',
    want.toFixed(4), (2 * want / b).toFixed(3));
  console.log('  снаружи концевой нити: у кромки %d нитей, в дальнем ряду %d из %d',
    overShed, overFar, w.fil - 1);
  console.log('  лист ушёл из своей плоскости на %s размаха\n', (zFar / b).toFixed(2));
  // Знак говорит лишь о том, какая половина попала в выборку.
  check('центр завихренности у кромки — π/8 размаха',
    Math.abs(Math.abs(atShed) - want) < 0.02 * b,
    Math.abs(atShed).toFixed(4) + ' против ' + want.toFixed(4));
  check('снос его не двигает — значит сохраняет завихренность',
    Math.abs(Math.abs(atFar) - Math.abs(atShed)) < 0.03 * b,
    'уехал на ' + Math.abs(Math.abs(atFar) - Math.abs(atShed)).toFixed(4) +
    ' при размахе ' + b);
  check('у кромки лист плоский: снаружи концевой нити никого', overShed === 0,
    String(overShed));
  check('а дальше сворачивается: нити заворачиваются за концевую',
    overFar > 5 && zFar > 0.2 * b,
    overFar + ' нитей снаружи, лист ушёл на ' + (zFar / b).toFixed(2) + ' размаха');
  V;
}

// --- свободная пелена против прямых лучей ---------------------------------------
//
// На большом удлинении и малом угле сворачивание слабое, и свободная пелена
// обязана дать почти то же, что прямая. Это проверка не «похоже», а с допуском:
// расхождение больше нескольких процентов на Λ = 20 — признак ошибки в
// постановке, а не физики.
{
  const AR = 20, n = 24, alpha = 3 * D;
  // Прямые лучи: обычная стационарная решётка, безо всякой пелены.
  const s0 = stand({ AR, n, len: 20, hz: 30 });
  s0.lat.build(1, 0, 0, true, false, false);          // с лучами
  const rhs = new Float64Array(s0.lat.n);
  for (let i = 0; i < s0.lat.n; i++) rhs[i] = -Math.sin(alpha);
  s0.lat.solveLinear(rhs);
  let Lstraight = 0;
  const span = AR;
  for (let i = 0; i < n; i++) {
    let g = 0;
    for (let k = 0; k < 3; k++) g += s0.lat.gamma[i * 3 + k];
    Lstraight += g * (span / n);
  }
  // Свободная пелена: тот же стенд, доведённый до установившегося.
  const s1 = stand({ AR, n, len: 120, hz: 30 });
  for (let i = 0; i < 400; i++) s1.step(alpha);
  const Lfree = s1.total();
  const rel = Lfree / Lstraight;
  console.log('Λ=%d, угол %s°: циркуляция по размаху %s (прямые лучи) против %s (пелена)',
    AR, (alpha / D).toFixed(0), Lstraight.toFixed(4), Lfree.toFixed(4));
  console.log('  отношение %s\n', rel.toFixed(3));
  check('на большом удлинении пелена даёт почти то же, что прямые лучи',
    Math.abs(rel - 1) < 0.05, rel.toFixed(3));
}

