// Постановка на чистом крыле: node tests/wing.test.mjs
//
// Три проверки самой постановки — БЕЗ лодки: нестационарный отклик по Вагнеру,
// свёрнутая пелена против π/4 размаха и свободная пелена против прямых лучей на
// большом удлинении, где сворачивание слабое.
//
// Всё это — то, ради чего заводилась свободная пелена. На лодке в одном опыте смешаны конечное
// удлинение, два паруса, зеркало от воды, нелинейная поправка, измеренная
// поляра и мягкое полотно, которое при перекладке ещё и меняет форму. Сверять
// такое с классикой можно только на глаз.
//
// Здесь вместо этого — плоское прямоугольное крыло в свободном потоке: жёсткое,
// одно, без воды, без поляр, без корпуса. Меняется РОВНО ОДНО: граничное
// условие, то есть угол атаки, и то ступенькой. Всё остальное стоит.
//
// Классика (Вагнер, 1925): после ступеньки угла атаки циркуляция выходит на
// новую величину не сразу, потому что с задней кромки сходит разгонный вихрь и,
// пока он рядом, его скос держит подъёмную силу.
//
//     Ф(s) = 1 − 0.165·e^(−0.0455 s) − 0.335·e^(−0.3 s),   s — путь в полухордах
//
// Ф(0) = 0.5, Ф(∞) = 1. Формула плоская, поэтому крыло здесь берётся большого
// удлинения: у конечного размаха завихренность уходит ещё и вбок, и на новую
// подъёмную силу оно выходит быстрее.

import { Lattice, FreeWake } from '../sim/vlm.js';

const D = Math.PI / 180;
let failures = 0;
const check = (name, ok, detail) => {
  if (!ok) failures++;
  console.log((ok ? '  ok   ' : '  ПЛОХО') + '  ' + name + (detail ? '   ' + detail : ''));
};

const wagner = (s) => 1 - 0.165 * Math.exp(-0.0455 * s) - 0.335 * Math.exp(-0.3 * s);

// --- стенд ---------------------------------------------------------------------
//
// Постановка Вайссингера: присоединённый вихрь на четверти хорды, условие
// непротекания на трёх четвертях, свободные вихри уходят от ЗАДНЕЙ КРОМКИ — то
// есть ровно та же, что в симуляторе, и с той же связкой: сошедшие кольца в
// правой части, свежее в матрице тремя отрезками.
// `nc` — панелей ПО ХОРДЕ. Три, как в симуляторе, и это не мелочь: с одной
// панелью связанная завихренность вырождается в один вихрь на четверти хорды, а
// отклик Вагнера зависит от того, как она распределена вдоль хорды и как
// разговаривает с ближней пеленой. Стенд с одной панелью даёт систематический
// сдвиг вверх.
function stand({ AR = 20, n = 24, nc = 3, len = 40, hz = 30, U = 1, c = 1 }) {
  const span = AR * c;
  const lat = new Lattice(n * nc);
  const te = [];                        // точки схода: задняя кромка, по границам полосок
  for (let i = 0; i <= n; i++) te.push(-span / 2 + span * i / n);
  for (let i = 0; i < n; i++) {
    for (let k = 0; k < nc; k++) {
      const p = lat.panels[i * nc + k];
      const xb = (k + 0.25) / nc * c, xc = (k + 0.75) / nc * c;
      p.a[0] = xb; p.a[1] = te[i + 1]; p.a[2] = 0;       // a — «верхний» конец
      p.b[0] = xb; p.b[1] = te[i]; p.b[2] = 0;
      // Ножки вдоль хорды идут к задней кромке — как в симуляторе со свободной
      // пеленой. С прямыми лучами они были бы вырождены в точку.
      p.ta[0] = c; p.ta[1] = te[i + 1]; p.ta[2] = 0;
      p.tb[0] = c; p.tb[1] = te[i]; p.tb[2] = 0;
      p.c[0] = xc; p.c[1] = (te[i] + te[i + 1]) / 2; p.c[2] = 0;
      p.nrm[0] = 0; p.nrm[1] = 0; p.nrm[2] = 1;
      p.chord = c / nc; p.speed = U;
    }
  }
  lat.core = 0.02 * c;

  const w = new FreeWake(n + 1, len);
  w.ground = false;                     // воды нет: крыло в свободном потоке
  w.core = lat.core;
  w.dirx = 1; w.diry = 0; w.dirz = 0;   // поток вдоль +x
  for (let f = 0; f + 1 < w.fil; f++) w.ring[f] = 1;   // полотно между всеми парами

  const dt = 1 / hz;
  const N = n * nc;
  const rhs = new Float64Array(N);
  const G = new Float64Array(n);        // циркуляции полосок
  const V = [0, 0, 0];
  const qx = new Float64Array(w.fil * len), qy = new Float64Array(w.fil * len),
        qz = new Float64Array(w.fil * len);
  const vx = new Float64Array(w.fil * len), vy = new Float64Array(w.fil * len),
        vz = new Float64Array(w.fil * len);

  // Один шаг: снос и посадка ряда, потом решение. Порядок тот же, что в
  // симуляторе, и он существенный — свежее кольцо обязано соединять СЕГОДНЯШНЮЮ
  // кромку с последним сошедшим рядом.
  const step = (alpha) => {
    if (w.n > 0) {
      lat.packBound(false);
      lat.fieldBound(w.x, w.y, w.z, 0, vx, vy, vz);    // размер задаётся ниже
    }
    // Поле решётки во всех узлах — одним заходом.
    const P = w.fil * w.n;
    for (let f = 0; f < w.fil; f++) {
      for (let i = 0; i < w.n; i++) {
        const k = f * len + i, j = f * w.n + i;
        qx[j] = w.x[k]; qy[j] = w.y[k]; qz[j] = w.z[k];
      }
    }
    if (P > 0) { lat.packBound(false); lat.fieldBound(qx, qy, qz, P, vx, vy, vz); }
    w.step(dt, (f, out) => { out[0] = c; out[1] = te[f]; out[2] = 0; },
      (x, y, z, out, j) => { out[0] = U + vx[j]; out[1] = vy[j]; out[2] = vz[j]; },
      G);

    // Правая часть: набегающий поток плюс известная пелена.
    //
    // Ядро при упаковке — то, которым пелену видит КРЫЛО (`pack(false)`), и
    // обратно на своё, `pack(true)`, она переупаковывается после решения:
    // самоиндукция считается по другому ядру. В симуляторе ровно так же.
    w.hold = true; w.edges(); w.pack(false);
    const WF = w.n > 1;
    lat.build(1, 0, 0, true, false, WF);
    for (let i = 0; i < N; i++) {
      const p = lat.panels[i];
      let wn = 0;
      if (WF) {
        w.induced(p.c[0], p.c[1], p.c[2], false, V);
        wn = V[0] * p.nrm[0] + V[1] * p.nrm[1] + V[2] * p.nrm[2];
      }
      rhs[i] = -U * Math.sin(alpha) - wn;
    }
    // Свежее кольцо — в матрицу. Циркуляция кольца равна циркуляции ПОЛОСКИ,
    // то есть сумме по её панелям, поэтому коэффициент идёт во все её столбцы.
    if (WF) {
      for (let f = 0; f + 1 < w.fil; f++) {
        for (let i = 0; i < N; i++) {
          const p = lat.panels[i];
          w.nearInfluence(f, p.c[0], p.c[1], p.c[2], false, V);
          const kk = V[0] * p.nrm[0] + V[1] * p.nrm[1] + V[2] * p.nrm[2];
          for (let k = 0; k < nc; k++) lat.k[i * N + f * nc + k] += kk;
        }
      }
    }
    lat.solveLinear(rhs);
    // Найденная циркуляция полоски — в свежий ряд.
    for (let i = 0; i < n; i++) {
      let g = 0;
      for (let k = 0; k < nc; k++) g += lat.gamma[i * nc + k];
      G[i] = g;
      w.gr[i * len] = g;
    }
    w.gr[(w.fil - 1) * len] = 0;
    w.hold = false; w.edges(); w.pack(true);
  };

  const total = () => {
    let s = 0;
    for (let i = 0; i < n; i++) s += G[i] * Math.abs(te[i + 1] - te[i]);
    return s;
  };
  return { lat, w, step, total, mid: () => G[n >> 1], c, U, dt };
}

// --- ступенька угла атаки ------------------------------------------------------

function indicial(opts) {
  const s = stand(opts);
  const L = opts.len || 40;
  const a0 = 2 * D, a1 = 4 * D;
  // Прогрев: пелене хватает заполниться и ещё столько же на устаканивание.
  for (let i = 0; i < 2 * L; i++) s.step(a0);
  const g0 = s.total(), m0 = s.mid();
  // Запись: столько шагов, чтобы покрыть двенадцать полухорд с запасом.
  const need = Math.ceil(14 * s.c / 2 / (s.U * s.dt));
  const tr = [], mid = [];
  for (let i = 0; i < need; i++) { s.step(a1); tr.push(s.total()); mid.push(s.mid()); }
  // Установившееся: ещё длина пелены, чтобы она вся сменилась.
  for (let i = 0; i < 2 * L; i++) s.step(a1);
  const gInf = s.total(), mInf = s.mid();
  // Путь в полухордах -> номер отсчёта.
  const at = (arr, a, b) => (x) => {
    const k = Math.round(x * s.c / 2 / (s.U * s.dt)) - 1;
    return k >= 0 && k < arr.length ? (arr[k] - a) / (b - a) : NaN;
  };
  return { phi: at(tr, g0, gInf), mid: at(mid, m0, mInf) };
}

